"""Цепочка фильтров ffmpeg: один ролик, ОДНО кодирование.

Здесь собирается вся картинка — своя рамка на каждом плане, два режима
кадра, слой субтитров. Ни один кадр не проходит через кодировщик дважды.

**Почему это отдельный файл.** Цепочка — самая сложная вещь в проекте,
и её надо уметь читать глазами, не запуская ffmpeg. Здесь только
строки: на входе числа монтажа, на выходе текст фильтра. Ни диска,
ни процессов. Значит, её можно закрепить автотестами — единственный
способ поймать поломку до того, как она станет файлом.

**Почему не резать ролик на куски и не склеивать.** Разный кроп
на разных планах соблазняет собрать каждый план отдельно и склеить.
Так делать нельзя: каждое кодирование добавляет артефакты, а ролик
и без того пересжимается площадкой.

    [0:v] ─┬─ crop(x = выражение от времени) ─ scale ─┬─ [cropped] ───┐
           │                                          └─ размыть [blurred]
           └─ вписать целиком ────────────────── [strip]              │
                                [blurred]+[strip] = [full] ───────────┤
                                         [cropped] + [full] по enable ┤
                                                           [frame] ───┤
                                       [N:v] субтитры [subs] ─────────┘
                                                            [video]

**Границы отрезков пишутся как `gte(t,a)*lt(t,b)`, а не `between`.**
`between` включает оба конца, и на стыке двух отрезков оба условия
истинны разом: один кадр не из той ветки, и найти его потом нельзя
ничем.
"""

from __future__ import annotations

from . import plans, tuning
from .errors import VertcutError


def порог(t: float, fps: float) -> float:
    """Порог `enable`/`gte` посреди между кадрами, а не на самом кадре.

    Кадр номер n показывается во время n/fps, и написать `gte(t, n/fps)`
    значит сравнить два числа с плавающей точкой на точное равенство.
    Сойдётся оно или нет — зависит от того, как ffmpeg посчитал время
    кадра из своей временной базы. Это монетка, и подбрасывается она
    на каждой склейке.

    Полкадра ниже — и монетки нет. Точность не теряется: между кадрами
    показывать нечего.
    """
    return round(t - 0.5 / fps, 4)


def окно(width: int, height: int) -> dict:
    """Самое широкое окно 9:16, какое влезает в кадр, по центру.

    Общий случай, а не «1920 пополам»: видео однажды приедет в 4K или
    в 4:3, и подгонка под один размер даст кривой кадр молча.

    Ширина и высота округляются до чётного — h264 нечётных не берёт.
    """
    if width <= 0 or height <= 0:
        raise VertcutError(f"The video has an impossible frame size: "
                           f"{width}×{height}")
    чёт_ш, чёт_в = width // 2 * 2, height // 2 * 2
    if width * tuning.VERTICAL_H > height * tuning.VERTICAL_W:
        # Кадр шире вертикали — режем по бокам, высота вся.
        рез_в = чёт_в
        рез_ш = round(рез_в * tuning.VERTICAL_W / tuning.VERTICAL_H / 2) * 2
    else:
        # Кадр уже вертикали — режем сверху и снизу.
        рез_ш = чёт_ш
        рез_в = round(рез_ш * tuning.VERTICAL_H / tuning.VERTICAL_W / 2) * 2
    рез_ш, рез_в = min(рез_ш, чёт_ш), min(рез_в, чёт_в)
    return {"w": рез_ш, "h": рез_в,
            "x": (width - рез_ш) // 2 // 2 * 2,
            "y": (height - рез_в) // 2 // 2 * 2}


def окно_для(width: int, height: int, cx: float) -> dict:
    """То же окно, но с центром в доле `cx` ширины кадра.

    Окно не свисает за край: лицо у самого края даёт окно, прижатое
    к краю, и это правильно — оно всё равно попадёт в вертикаль, просто
    не по центру.

    Левый край округляется до чётного: у yuv420p цветность вдвое реже
    яркости, и нечётный сдвиг красит кадр мимо своих же пикселей.
    """
    рамка = окно(width, height)
    хочу = round(cx * width - рамка["w"] / 2)
    предел = width - рамка["w"]
    рамка["x"] = min(max(хочу, 0), предел) // 2 * 2
    return рамка


def коробка_окна(width: int, height: int, cx: float | None,
                 масштаб: float = 1.0) -> tuple[int, int, int, int]:
    """Окно колонки прямоугольником в пикселях кадра исходника.

    Заведено ради правила «одна геометрия — одно место». Этот
    прямоугольник нужен трём: цепочке фильтров (там он превращается
    в строку), сверке готового файла и предпросмотру на настоящем
    кадре. Три раза посчитать «x, y, ширина, высота» — три шанса
    разойтись, и разойдутся они молча.

    `масштаб` — во сколько раз кадр, из которого режут, крупнее того,
    для которого посчитано окно. Кадр из ffmpeg приезжает то полного
    размера, то уменьшенным, и подгонять окно на месте — это опять
    своя арифметика.
    """
    рамка = окно_для(width, height, 0.5 if cx is None else float(cx))
    return (int(рамка["x"] * масштаб), int(рамка["y"] * масштаб),
            int((рамка["x"] + рамка["w"]) * масштаб),
            int((рамка["y"] + рамка["h"]) * масштаб))


def crop_x(rows: list[dict], width: int, height: int,
           fps: float = 25.0) -> str:
    """Выражение положения колонки от времени ролика.

    **Колонка — выражение, а не число.** Фильтр `crop` считает свой `x`
    на каждом кадре, и достаточно написать ему, какое число брать
    когда. Склейки при этом стоят ровно там же, где стояли в видео:
    колонка перепрыгивает на монтажном стыке, где картинка и так
    меняется целиком.
    """
    if not rows:
        raise VertcutError(
            "This clip has no shots left, so there's nothing to export",
            hint="its boundaries seem to run past the end of the video; "
                 "delete the clip and make it again")

    точки = []
    for ряд in rows:
        cx = 0.5 if ряд["cx"] is None else float(ряд["cx"])
        точки.append((ряд["at"], окно_для(width, height, cx)["x"]))

    # Все колонки на одном месте — выражение ни к чему. Это не только
    # экономия: ролик из одного плана должен давать простую строку,
    # по которой видно, что ничего не двигается.
    if len({x for _, x in точки}) == 1:
        return str(точки[0][1])

    куски = []
    for n, (at, x) in enumerate(точки):
        свой = порог(at, fps)
        следом = порог(точки[n + 1][0], fps) if n + 1 < len(точки) else None
        if n == 0:
            куски.append(f"{x}*lt(t,{следом:.4f})")
        elif n == len(точки) - 1:
            куски.append(f"{x}*gte(t,{свой:.4f})")
        else:
            куски.append(f"{x}*(gte(t,{свой:.4f})*lt(t,{следом:.4f}))")
    return "+".join(куски)


def полный_кадр_когда(rows: list[dict], fps: float = 25.0) -> str | None:
    """Когда включён полный кадр. None — ни на одном плане не выбран."""
    куски = [f"gte(t,{порог(r['at'], fps):.4f})"
             f"*lt(t,{порог(r['till'], fps):.4f})"
             for r in rows if r["mode"] == plans.РЕЖИМ_ПОЛНЫЙ]
    return "+".join(куски) if куски else None


def _колонка(x: str, width: int, height: int) -> str:
    """Вырезать вертикальную колонку и растянуть её в кадр ролика."""
    рамка = окно(width, height)
    return (f"crop={рамка['w']}:{рамка['h']}:'{x}':{рамка['y']},"
            f"scale={tuning.VERTICAL_W}:{tuning.VERTICAL_H}:flags=lanczos,"
            "setsar=1")


def _размыть(вход: str, выход: str) -> str:
    """Фон полей: размытая копия колонки.

    Размывается УМЕНЬШЕННАЯ копия, а не полный кадр. Размытие
    по большому радиусу считается в квадрате радиуса: на 1080×1920
    честная гауссиана стоила бы секунды на кадр, через уменьшение —
    доли миллисекунды. На глаз разницы нет: размытие тем и занято,
    что стирает подробности.
    """
    мал_в = tuning.BLUR_HEIGHT
    мал_ш = round(tuning.VERTICAL_W * мал_в / tuning.VERTICAL_H / 2) * 2
    return (f"[{вход}]scale={мал_ш}:{мал_в},gblur=sigma={tuning.BLUR_SIGMA},"
            f"scale={tuning.VERTICAL_W}:{tuning.VERTICAL_H}:flags=bilinear,"
            f"setsar=1[{выход}]")


def размытие_долей_кадра() -> float:
    """Радиус размытия полей — долей ВЫСОТЫ кадра ролика.

    Заведено для будущего экрана: он рисует те же поля браузером, чтобы
    предпросмотр показывал не чёрные полосы, а то, что будет в файле.
    Написать там своё число значило бы завести второе место для одного.
    """
    return tuning.BLUR_SIGMA / tuning.BLUR_HEIGHT


def _лента(вход: str, выход: str) -> str:
    """Кадр целиком, вписанный по ширине.

    `decrease` — чтобы кадр, который окажется уже 9:16, не вылез
    за высоту.
    """
    return (f"[{вход}]scale={tuning.VERTICAL_W}:{tuning.VERTICAL_H}:"
            f"force_original_aspect_ratio=decrease,setsar=1[{выход}]")


def куски_видео(кадров: list[int]) -> tuple[list[str], str]:
    """Куски видео, сшитые в одну ленту ролика.

    **Сшивается ДО фильтров, а не после кодирования.** Кодирование
    по-прежнему одно: `concat` — это фильтр, он работает с кадрами
    в памяти, а не с готовыми файлами.

    **Число кадров у куска ЗАДАЁТСЯ, а не получается.** `-t` у входа
    отмерил бы секунды, а секунда на границе кадра — монетка: кусок
    вышел бы то на кадр длиннее, то на кадр короче, и стыки поехали бы
    относительно звука. `trim=end_frame` отмеряет ровно столько кадров,
    сколько посчитано.
    """
    звенья, метки = [], []
    for n, сколько in enumerate(кадров):
        звенья.append(f"[{n}:v]trim=end_frame={сколько},"
                      f"setpts=PTS-STARTPTS[part{n}]")
        метки.append(f"[part{n}]")
    звенья.append(f"{''.join(метки)}concat=n={len(кадров)}:v=1:a=0[joined]")
    return звенья, "joined"


def video(rows: list[dict], width: int, height: int,
          вход_субтитров: int | None = None, fps: float = 25.0,
          кадров: list[int] | None = None,
          вход_плашки: int | None = None,
          плашка_с: float | None = None) -> str:
    """Вся видеочасть цепочки. На выходе поток `[video]`.

    Имена звеньев — латиницей: их видно человеку в хвосте ошибки
    ffmpeg, а экран говорит по-английски.

    Входы идут так: по входу на каждый кусок видео (обычно один),
    следом плашка в конце, если она есть, последним — слой субтитров.
    Порядок важен и повторяется в команде — там же, где `-ss` и `-t`
    каждого из них.

    **Плашка ЗАМЕЩАЕТ картинку, а не приклеивается к ролику.** Она
    ложится звеном поверх кадра на последние секунды, внутри той же
    цепочки: кодирование остаётся одно. Длина файла от неё не меняется
    ни на кадр, и звук она не трогает вовсе — он доигрывает под ней
    целиком.
    """
    x = crop_x(rows, width, height, fps)
    полный = полный_кадр_когда(rows, fps)
    колонка = _колонка(x, width, height)
    кусков = len(кадров) if кадров else 1

    звенья = []
    if кусков > 1:
        сшивка, начало = куски_видео(кадров)
        звенья += сшивка
    else:
        # Времена сбрасываются ЯВНО, а не «ffmpeg сделает сам».
        #
        # Это замер, и он стоил половины стадии. Предок замерял на своей
        # версии ffmpeg: спросил ffprobe у собранного ролика — первый
        # кадр лежал ровно на 0.000000, — и записал, что `-ss` перед
        # входом сдвигает времена сам.
        #
        # На ffmpeg 8 это уже не так. Перемотка на 38.255 честно отдаёт
        # кадр 957 (38.28), но его время в выходе — 0.025, а не ноль:
        # остаток от того, что запрошенное время не лежало на сетке
        # кадров. Полкадра сдвига хватает, чтобы содержимое уехало
        # на кадр, и колонка переключалась на кадр позже КАЖДОЙ склейки
        # — ровно та беда, которую предок ловил глазами в пятой сессии.
        #
        # `setpts=PTS-STARTPTS` делает это явным: чем бы ни кончилась
        # перемотка, первый кадр ролика стоит на нуле. У звука тот же
        # сброс стоял всегда (`asetpts`).
        звенья.append("[0:v]setpts=PTS-STARTPTS[start]")
        начало = "start"

    if полный is None:
        # Ветка полного кадра строится, только если она кому-то нужна:
        # размытие даром никому не сдалось.
        звенья.append(f"[{начало}]{колонка}[frame]")
    else:
        звенья += [
            f"[{начало}]split=2[main][whole]",
            f"[main]{колонка}[column]",
            "[column]split=2[cropped][toblur]",
            _размыть("toblur", "blurred"),
            _лента("whole", "strip"),
            "[blurred][strip]overlay=(W-w)/2:(H-h)/2[full]",
            f"[cropped][full]overlay=0:0:enable='{полный}'[frame]",
        ]

    # Плашка в конце — ДО субтитров, и порядок здесь часть смысла:
    # положи её после — и она накрыла бы субтитр своей картинкой,
    # а полоса в её середине держится пустой ровно затем, чтобы
    # субтитр был виден и на ней.
    #
    # **Диапазон яркости назван вслух.** Картинка плашки полного
    # диапазона, видеодорожка — телевизионного, и смешивать их в одном
    # потоке молча нельзя: плашка выцвела бы относительно картинки.
    # Сегодня swscale приводит их так же и сам — у предка это замерено
    # и совпало до пикселя, — но молчаливое совпадение это не договор.
    #
    # **Порог стоит ПОСЕРЕДИНЕ между кадрами**, как и все пороги этой
    # цепочки: `gte(t, n/fps)` сравнивает два числа с плавающей точкой
    # на точное равенство, а это монетка.
    метка = "frame"
    if вход_плашки is not None:
        звенья.append(f"[{вход_плашки}:v]scale=in_range=full:out_range=tv,"
                      f"format=yuv420p[endcard]")
        звенья.append(f"[frame][endcard]overlay=0:0:"
                      f"enable='gte(t,{порог(плашка_с, fps):.4f})'[withcard]")
        метка = "withcard"

    if вход_субтитров is None:
        звенья.append(f"[{метка}]copy[video]")
        return ";".join(звенья)

    # Субтитры ложатся ПОСЛЕДНИМ звеном.
    #
    # Диапазон яркости назван вслух: слой рисуется полного диапазона,
    # видеодорожка телевизионного, и смешивать их молча нельзя. Альфа
    # при этом сохраняется — в ней весь смысл слоя.
    звенья.append(f"[{вход_субтитров}:v]scale=in_range=full:out_range=tv,"
                  f"format=yuva420p[subs]")
    звенья.append(f"[{метка}][subs]overlay=0:0:eof_action=pass[video]")
    return ";".join(звенья)


def audio(таблица: dict) -> tuple[list[str], str]:
    """Звук ролика: куски встык, шторки на краях, кресты на стыках.

    **Кресты, а не встык.** На стыке конец одного куска гаснет, начало
    другого разгорается, и делают они это ОДНОВРЕМЕННО, поверх одного
    и того же куска времени. Иначе стык стоил бы двух шторок подряд:
    сперва тишина наплывает, потом уходит, — и это слышно как провал.

    Померить это нечем. Слушать.
    """
    куски = таблица["куски"]
    кривая = tuning.EDGE_FADE_CURVE
    звенья = []
    # Каждый вход обрезается по СВОЕЙ длине звука.
    for n, кусок in enumerate(куски):
        звенья.append(f"[{n}:a]atrim=0:{кусок['звук']['длина']:.3f},"
                      f"asetpts=N/SR/TB[audio{n}]")
    метка = "audio0"
    for n in range(1, len(куски)):
        крест = куски[n - 1]["trail"]
        новая = f"joined{n}"
        звенья.append(f"[{метка}][audio{n}]acrossfade=d={крест:.3f}:"
                      f"c1={кривая}:c2={кривая}[{новая}]")
        метка = новая

    края = []
    if куски[0]["lead"] > 0:
        края.append(f"afade=t=in:st=0:d={куски[0]['lead']:.3f}:curve={кривая}")
    if куски[-1]["trail"] > 0:
        начало = max(таблица["всего"] - куски[-1]["trail"], 0)
        края.append(f"afade=t=out:st={начало:.3f}:"
                    f"d={куски[-1]['trail']:.3f}:curve={кривая}")
    if края:
        звенья.append(f"[{метка}]{','.join(края)}[audio]")
        метка = "audio"
    return звенья, метка
