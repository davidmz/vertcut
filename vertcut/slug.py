"""Имя папки разбора из имени файла — латиницей и без пробелов.

Папка живёт в пути, который уезжает в команды ffmpeg, в имена готовых
файлов и в ссылки будущей страницы. Кириллица там работает, но каждый
раз по-своему, и однажды перестаёт.

Здесь у этого правила есть вторая причина, которой у Нарезатора не было.
Тот жил на одной машине; этот раздаётся. Готовый ролик человек утащит
на флешке в Windows, а Windows не создаст файл, в имени которого стоит
`? : " < > | *` — и упадёт это на чужой машине, а не здесь. Таблица ниже
не оставляет от таких знаков ничего.
"""

from __future__ import annotations

import re

# Таблица одна и составлена под русский. Не «универсальная
# транслитерация»: универсальной не бывает, а для одного языка таблица
# проверяема глазами.
#
# Что делать с языками, у которых своя таблица (украинский «ї», сербский
# «ђ»), — открытый вопрос раздачи, он записан в TODO.md. Сегодня такие
# буквы просто выпадут, и имя папки станет короче: это видно сразу,
# в отличие от молчаливой замены.
_TABLE = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e",
    "ж": "zh", "з": "z", "и": "i", "й": "y", "к": "k", "л": "l", "м": "m",
    "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
    "ф": "f", "х": "h", "ц": "c", "ч": "ch", "ш": "sh", "щ": "sch",
    "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
}

# Длиннее этого имя папки не становится: путь целиком уезжает в команды,
# а у файловой системы предел на длину имени.
LIMIT = 48


def make(name: str) -> str:
    text = "".join(_TABLE.get(ch, ch) for ch in name.lower())
    # Всё, что не латиница и не цифра, становится дефисом. Отсюда же
    # берётся безопасность имени на чужой файловой системе: запрещённых
    # знаков после этой строки не остаётся ни одного.
    text = re.sub(r"[^a-z0-9]+", "-", text).strip("-")
    if len(text) > LIMIT:
        text = text[:LIMIT].rstrip("-")
    if not text:
        raise ValueError(f"can't make a folder name out of {name!r}")
    return text
