"""Сегментация фраз: поток слов → фразы.

**Фраза — это одновременно три вещи:** субтитр, монтажный слот
и единица, которой человек выбирает кусок. Поэтому своя сегментация,
а не та, что отдаёт распознавание: та режет по своей логике, а нужны
смысловые швы — конец предложения, конец оборота, вдох.

Все пороги — в `tuning.py`, и там же про них написано главное:
они единственные во всём проекте, которые Нарезатор не мерил сам.
"""

from __future__ import annotations

from dataclasses import dataclass, field

from . import tuning


@dataclass
class Phrase:
    idx: int
    start: float
    end: float
    text: str
    # Слова с временами, из которых фраза собрана. Нужны субтитрам:
    # слова там появляются по одному, и когда — знает только укладка.
    words: list[dict] = field(default_factory=list)


def отпечаток() -> str:
    """Отпечаток правил нарезки: числа И сам код правил.

    Зачем. Стадии переступаются по штампу, а штамп говорит только
    «сделано». Поменяли порог паузы — стадия по-прежнему «сделана»,
    и новый порог не доехал бы никуда, молча. Отпечаток кладётся
    в штамп, и разошедшийся отпечаток значит «посчитано по другим
    правилам».

    **Код правил входит наравне с числами.** Главная правка второй
    сессии — не число, а правило: конец предложения перестал
    отменяться порогом длины. Отпечаток из одних чисел такую правку
    не заметил бы. Цена — лишний пересчёт после правки комментария
    в этом файле; он стоит доли секунды, а тихо разъехавшиеся фразы
    стоят ролика.
    """
    import hashlib
    import inspect
    import json

    числа = {имя: getattr(tuning, имя) for имя in (
        "PAUSE_SPLIT", "MIN_PHRASE", "COMMA_AFTER", "MAX_PHRASE",
        "SENTENCE_END", "CLAUSE_END")}
    try:
        код = "".join(inspect.getsource(f)
                      for f in (split, backoff_point, last_mark))
    except Exception:
        # ЛОВИТСЯ ВСЁ, И ЭТО ПОЧИНКА НАСТОЯЩЕЙ ПОЛОМКИ. Ловилось
        # OSError и TypeError — «файла нет» и «это не функция».
        # На деле чтение исходника роняет и другое: файл, переписанный
        # под работающим процессом, читается по прежним номерам строк
        # и рассыпается разбором. Разбор упал с трассировкой посреди
        # девятиминутной работы — из-за отпечатка, который всего лишь
        # отвечает на вопрос «не устарело ли».
        #
        # Правило общее: подсказка не имеет права ронять то, что она
        # стережёт. Не прочиталось — отпечаток честно называет себя
        # неполным и остаётся на одних числах.
        код = "без исходников"   # не для человека: кусок отпечатка
    что = json.dumps(числа, ensure_ascii=False, sort_keys=True) + код
    return hashlib.sha1(что.encode()).hexdigest()[:16]


def join_words(tokens) -> str:
    """Склейка слов в текст.

    Распознавание отдаёт «наконец» и «-то» разными словами, и обычный
    пробел между ними превращает их в «наконец -то».
    """
    out = ""
    for t in tokens:
        if not out:
            out = t
        elif t.startswith("-") or out.endswith("-"):
            out += t
        else:
            out += " " + t
    return out


def last_mark(token: str) -> str:
    """Последний значащий символ слова: закрывающие кавычки не в счёт."""
    t = token.rstrip("\"»)'")
    return t[-1:] if t else ""


def backoff_point(buf: list[dict]) -> int:
    """Куда отступить, когда фраза упёрлась в потолок посреди оборота:
    сразу за последним знаком препинания. 0 — отступать некуда."""
    for j in range(len(buf) - 2, 0, -1):
        mark = last_mark(buf[j]["w"])
        if (mark and mark in tuning.SENTENCE_END + tuning.CLAUSE_END
                and buf[j]["e"] - buf[0]["s"] >= tuning.MIN_PHRASE):
            return j + 1
    return 0


def split(words: list[dict]) -> list[Phrase]:
    """Нарезать поток слов на фразы по смысловым швам.

    Потолок длины — последнее средство, и даже он сначала отступает
    назад до ближайшего знака: фраза, оборванная посреди оборота,
    читается как оборванная и в субтитре, и в списке.
    """
    out: list[Phrase] = []
    buf: list[dict] = []

    def выпустить(chunk: list[dict]) -> None:
        if not chunk:
            return
        text = join_words(x["w"] for x in chunk)
        out.append(Phrase(len(out) + 1, chunk[0]["s"], chunk[-1]["e"],
                          text, [dict(x) for x in chunk]))

    for i, w in enumerate(words):
        buf.append(w)
        span = buf[-1]["e"] - buf[0]["s"]
        gap = words[i + 1]["s"] - w["e"] if i + 1 < len(words) else 99.0
        mark = last_mark(w["w"])

        # Потолок ТОЛЬКО по времени. Знаков в правиле нет вовсе, и это
        # главное решение второй сессии: см. `wrap` ниже и `tuning`.
        полная = span >= tuning.MAX_PHRASE
        # Конец предложения — самый сильный шов, и он не отменяется
        # порогом длины. Замер: с порогом на разговорном материале
        # каждая четвёртая фраза оказывалась сшита из конца одного
        # предложения и начала следующего («стол. Ну и все такое.»),
        # без порога — ни одной. Числа в `tuning.MIN_PHRASE`.
        предложение = bool(mark) and mark in tuning.SENTENCE_END
        оборот = (bool(mark) and mark in tuning.CLAUSE_END
                  and span >= tuning.COMMA_AFTER)
        вдох = gap >= tuning.PAUSE_SPLIT and span >= tuning.MIN_PHRASE

        if полная and not (предложение or оборот):
            назад = backoff_point(buf)
            if назад:
                выпустить(buf[:назад])
                buf = buf[назад:]
                continue

        if полная or предложение or оборот or вдох:
            выпустить(buf)
            buf = []

    выпустить(buf)
    return out


# ЧЕРНОВОЙ РАЗБИВКИ НА СТРОКИ ЗДЕСЬ НЕТ, И ЕЁ ОТСУТСТВИЕ — РЕШЕНИЕ.
#
# Была: фраза делилась на строки по числу знаков, и результат лежал
# в разборе рядом с текстом. Убрана целиком вместе с числом знаков
# в строке.
#
# Причина. В момент разбора стиля ещё нет: ни шрифта, ни кегля, ни
# полей — их человек настраивает потом и под себя. Значит любое число
# знаков в строке здесь — выдумка, которая выглядит как ответ. Один
# и тот же текст в разных шрифтах даёт разную ширину, и на пределе это
# решает.
#
# Настоящую разбивку делает рисование субтитра: там есть шрифт, и там
# меряется ширина КРАСКИ, а не количество знаков. Владелец у этого
# вопроса теперь один, и разъехаться ему не с чем.
#
# Читал эту разбивку никто: она лежала в `align.json` полем `lines`
# и ждала, когда в неё поверят.
