"""Детектор лиц: где на кадре лицо.

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
ПОЧЕМУ ДЕТЕКТОР ЗДЕСЬ ДРУГОЙ, ЧЕМ У СОСЕДА

Нарезатор ищет лица моделью `yolov8_animeface` поверх библиотеки
ultralytics. Она под AGPL-3.0, а эта лицензия заразная: раздача
программы с ней, скорее всего, обязывает открыть под той же лицензией
всё остальное. От детектора нужна одна вещь — где на кадре лицо, —
и платить за неё лицензией всего проекта нельзя.

Здесь YuNet: 230 КБ весов под MIT, лежит в поставке. Он же избавил
проект от полутора гигабайт torch и ultralytics — то есть от установки,
которую чужой человек не осилит.

ЧЕМ ПЛАТИМ. Тот детектор обучен на рисованных лицах, этот — на живых.
Замер расхождения на настоящем материале — в private/docs/sessions.md.
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

**Модель запускается движком, который уже стоит ради распознавания.**
Тот же YuNet умеет запускать opencv — одной строкой, — и сначала так
и было сделано. От opencv отказались после замера: свой разбор ответа
сошёлся с его разбором до 0.00 пикселя на всех проверенных кадрах,
а сам opencv весит 120 МБ поставки и печатает при каждом запуске два
предупреждения, которые чужой человек прочтёт как поломку. Сотня строк
здесь дешевле.

**Ответ модели разбирается так же, как его разбирает opencv**, и это
не догадка: числа сверены. Модель отдаёт три сетки — на каждый восьмой,
шестнадцатый и тридцать второй пиксель, — а в них на каждую клетку своя
уверенность и своя рамка от центра клетки.
"""

from __future__ import annotations

import threading
from pathlib import Path

from . import layout
from .errors import VertcutError

# Сетки, на которых модель ищет: каждый 8-й, 16-й и 32-й пиксель.
# Не настройка — устройство самой модели.
ШАГИ = (8, 16, 32)

# Насколько две рамки должны налезать друг на друга, чтобы считаться
# одним лицом. Значение из поставки модели, не наш замер.
НМС = 0.3

# Сессия одна на процесс: загрузка модели стоит десятые доли секунды,
# а планов бывают сотни. Замок — потому что стадии могут считаться
# в нескольких потоках (очередь сборки), а сессия у движка одна.
_сессия = None
_замок = threading.Lock()


def модель() -> Path:
    путь = layout.assets() / "models" / "yunet.onnx"
    if not путь.exists():
        raise VertcutError(
            f"The face detector file is missing: {путь}",
            hint="it ships with Vertcut — the install looks incomplete",
        )
    return путь


def _движок():
    global _сессия
    with _замок:
        if _сессия is None:
            try:
                import onnxruntime as ort
            except ImportError:
                raise VertcutError(
                    "onnxruntime is not installed — cannot look for faces",
                    hint="install the dependencies: pip install -e . -c constraints.txt",
                ) from None
            # Движок печатает предупреждения о своих внутренностях,
            # человеку они не говорят ничего.
            настройки = ort.SessionOptions()
            настройки.log_severity_level = 3
            _сессия = ort.InferenceSession(
                str(модель()), настройки, providers=["CPUExecutionProvider"])
        return _сессия


def найти(кадр_bgr, порог: float) -> list[dict]:
    """Лица на кадре: список рамок с уверенностью.

    `кадр_bgr` — картинка как массив: строки, столбцы, три цвета
    в порядке синий-зелёный-красный. Порядок цветов именно такой,
    потому что на таком порядке модель обучена; перепутать их — значит
    показать ей другое изображение.
    """
    import numpy as np

    в, ш = кадр_bgr.shape[:2]

    # Сетка модели делится на 32, а кадры бывают любой высоты. Кадр
    # добивается нулями СПРАВА И СНИЗУ — тогда координаты рамок
    # остаются координатами исходного кадра и пересчитывать нечего.
    # Дополнение слева сдвинуло бы все лица, и сдвинуло бы молча.
    нш, нв = (ш + 31) // 32 * 32, (в + 31) // 32 * 32
    if (нш, нв) != (ш, в):
        поле = np.zeros((нв, нш, 3), кадр_bgr.dtype)
        поле[:в, :ш] = кадр_bgr
        кадр_bgr = поле

    вход = кадр_bgr.astype(np.float32).transpose(2, 0, 1)[None]
    сессия = _движок()
    выходы = сессия.run(None, {"input": вход})
    как = dict(zip([o.name for o in сессия.get_outputs()], выходы))

    рамки, баллы = [], []
    столбцов_всего = нш
    for шаг in ШАГИ:
        уверенность = как[f"cls_{шаг}"][0].reshape(-1)
        объект = как[f"obj_{шаг}"][0].reshape(-1)
        рамка = как[f"bbox_{шаг}"][0]
        столбцов = столбцов_всего // шаг
        # Балл — среднее геометрическое двух уверенностей модели:
        # «здесь вообще что-то есть» и «это лицо». Так же считает
        # opencv, и числа сверены с ним.
        балл = np.sqrt(np.clip(уверенность, 0, 1) * np.clip(объект, 0, 1))
        for i in np.where(балл >= порог)[0]:
            стб, ряд = i % столбцов, i // столбцов
            cx = (стб + рамка[i, 0]) * шаг
            cy = (ряд + рамка[i, 1]) * шаг
            w = np.exp(рамка[i, 2]) * шаг
            h = np.exp(рамка[i, 3]) * шаг
            рамки.append([cx - w / 2, cy - h / 2, w, h])
            баллы.append(float(балл[i]))

    if not рамки:
        return []
    оставшиеся = _отсеять_повторы(np.array(рамки, np.float32),
                                  np.array(баллы, np.float32), НМС)
    return [{"x": float(x), "y": float(y), "w": float(w), "h": float(h),
             "балл": float(б)} for x, y, w, h, б in оставшиеся]


def _отсеять_повторы(рамки, баллы, порог: float):
    """Одно лицо модель находит несколькими рамками сразу.

    Оставляем самую уверенную и выбрасываем те, что сильно на неё
    налезают. Без этого одно лицо считалось бы за пять, и «самое
    крупное лицо» выбиралось бы из повторов одного и того же.
    """
    import numpy as np

    x1, y1 = рамки[:, 0], рамки[:, 1]
    x2, y2 = x1 + рамки[:, 2], y1 + рамки[:, 3]
    площадь = рамки[:, 2] * рамки[:, 3]
    порядок = баллы.argsort()[::-1]
    оставить = []
    while порядок.size:
        i = порядок[0]
        оставить.append(i)
        xx1 = np.maximum(x1[i], x1[порядок[1:]])
        yy1 = np.maximum(y1[i], y1[порядок[1:]])
        xx2 = np.minimum(x2[i], x2[порядок[1:]])
        yy2 = np.minimum(y2[i], y2[порядок[1:]])
        общее = np.maximum(0, xx2 - xx1) * np.maximum(0, yy2 - yy1)
        доля = общее / (площадь[i] + площадь[порядок[1:]] - общее)
        порядок = порядок[1:][доля <= порог]
    return np.column_stack([рамки[np.array(оставить)], баллы[np.array(оставить)]])


def прочитать(путь: Path):
    """Картинка с диска как массив в порядке синий-зелёный-красный.

    Читает Pillow, а не opencv. Проверено на настоящих кадрах: те же
    файлы обе библиотеки раскладывают в одни и те же пиксели, разница
    ноль, и детектор отвечает одинаково.
    """
    import numpy as np
    from PIL import Image

    with Image.open(путь) as картинка:
        return np.asarray(картинка.convert("RGB"))[:, :, ::-1].copy()


def самое_крупное(лица: list[dict], ширина: int) -> float | None:
    """Центр самого крупного лица, долей ширины кадра. None — лиц нет.

    Крупное лицо — это ближний план и, как правило, тот, кто говорит.
    Мелкие в глубине кадра тянуть окно на себя не должны.
    """
    if not лица:
        return None
    крупнейшее = max(лица, key=lambda f: f["w"] * f["h"])
    return float((крупнейшее["x"] + крупнейшее["w"] / 2) / ширина)
