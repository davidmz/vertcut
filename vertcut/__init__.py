import os as _os

# ТЕЛЕМЕТРИЯ ONNXRUNTIME ВЫКЛЮЧАЕТСЯ ЗДЕСЬ, ДО ВСЯКОГО ИМПОРТА.
#
# Найдено в 26-й сессии агентом, который ставил сервис по INSTALL.md
# в чистый дом: после `vertcut check` в нём появилась папка
# `~/Library/Application Support/Microsoft/DeveloperTools/.onnxruntime/`
# — идентификатор устройства и очередь событий. onnxruntime 1.31
# на macOS везёт телеметрию Microsoft (1DS, адрес
# `mobile.events.data.microsoft.com/OneCollector`) и при одном лишь
# `import onnxruntime` пишет событие: модель Mac, процессор, версия
# системы, тип сети, хэш устройства. Что оно уходит, проверено опытом:
# за 25 секунд жизни процесса очередь пустеет, а с запрещённой сетью
# (`sandbox-exec`) событие остаётся в ней. Короткий процесс оставляет
# событие в очереди — до следующего запуска.
#
# README обещает: в сеть уходит только модель и текст для кнопок AI.
# Поэтому — выключатель самой библиотеки, `ORT_DISABLE_TELEMETRY`.
# Он действует, только если выставлен ДО импорта: вызов
# `onnxruntime.disable_telemetry_events()` после импорта опаздывает —
# папка уже заведена (проверено). Отсюда место: пакет импортируется
# первым при любом входе — команда, экран, проверки. `setdefault` —
# чтобы человек, который нарочно поставил своё значение, его сохранил.
# Установщик зовёт питон без пакета — у него своя такая же строка
# (`install/installer.py`, `download_model`).
_os.environ.setdefault("ORT_DISABLE_TELEMETRY", "1")

# ТЕЛЕМЕТРИЯ HUGGING FACE — тем же порядком и по той же причине.
# Найдено замером в 27-й сессии (`nettop` во время разбора): раз в сутки
# huggingface_hub шлёт `GET /api/agent-harnesses` — в его коде это
# названо «best-effort telemetry» — и дописывает в User-Agent, каким
# ИИ-агентом запущен процесс. Выключатель библиотеки —
# `HF_HUB_DISABLE_TELEMETRY`. Проверку «не вышла ли модель новее»
# при каждом разборе снимает другое место: распознавание берёт
# модель сперва только из кэша (`align.transcribe`).
_os.environ.setdefault("HF_HUB_DISABLE_TELEMETRY", "1")
