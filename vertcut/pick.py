"""Границы ролика: какой кусок видео режем.

**Границы считаются в СЛОВАХ, а не в секундах.** Слово — единственная
единица, у которой в разборе есть измеренное время. Три дороги сводятся
к одной паре номеров слов, и дальше всё считается из неё:

- `--text` — вставленный кусок текста разбора (сценария, а у кого его
  нет — расшифровки), ищется по уложенному тексту;
- `--range 13-31` — номера фраз, целыми фразами;
- `--start` / `--end` — время, прилипает к ближайшей границе слова.

**Ключ ролика — номера слов его кусков**, он же имя папки. Не номера
фраз: пересегментация фраз (она в долгах) перенумерует их целиком,
и старый ключ станет показывать на другое место видео — папка та же,
файл открывается, внутри чужое. Слова берутся из уложенного текста,
а он от перенарезки фраз не меняется.

**Ключ и название — разные работы.** Ключ обязан НЕ меняться: по нему
находят папку и сверяют штамп сборки. Название обязано меняться, когда
человек передумал. Одно поле не может делать и то, и другое.

**Посреди слова не режем никогда** — обрубок звука слышен всегда.
**Посреди фразы — режем**: начать ролик с середины фразы человек
вправе, сервис предупреждает, но не запрещает.
"""

from __future__ import annotations

import json
from datetime import datetime
from pathlib import Path

from . import align, layout, script as сценарий, speech, tuning
from . import report
from .errors import VertcutError

# Сколько раскладок показывать, прежде чем сказать «слишком много».
# Не замер: список из двух десятков строк человек всё равно не читает.
ПРЕДЕЛ_РАСКЛАДОК = 12


# Как называть текст разбора в сообщениях. Сценарий и расшифровка —
# разные вещи, и «the script doesn't have this» человеку без сценария
# читается как поломка. Падежей у английского нет — хватает одного
# слова на каждый.
def _зовут(laid: dict) -> str:
    откуда = speech.чей_текст(laid)
    return "the transcript" if откуда == speech.РАСШИФРОВКА else "the script"


def parse_time(raw: str) -> float:
    """«1:25.0», «85.0» или «1:02:03» → секунды."""
    куски = str(raw).strip().split(":")
    try:
        числа = [float(x) for x in куски]
    except ValueError:
        raise VertcutError(f"Cannot read the time: {raw!r}",
                           hint="write it like this: 1:25.0 or 85.0") from None
    итог = 0.0
    for ч in числа:
        итог = итог * 60 + ч
    return итог


def show_time(at: float) -> str:
    return f"{int(at // 60)}:{at % 60:04.1f}"


# ─────────────────────────────────────────────────────────────────────
# Дорога первая: вставленный текст
# ─────────────────────────────────────────────────────────────────────

def _слова_разбора(laid: dict) -> list[str]:
    """Слова уложенного текста в том виде, в каком их считает укладка."""
    вышло = []
    for w in laid["words"]:
        было = align.words(w["w"])
        if len(было) != 1:
            raise VertcutError(
                f"The word “{w['w']}” in the analysis splits into {len(было)} parts",
                hint="analyze again: vertcut ingest … --again")
        вышло.append(было[0])
    return вышло


def _слова_вставки(вставлено: str) -> list[str]:
    """Слова вставленного куска.

    Непроизносимые строки выбрасываются тем же правилом, что и на
    разборе: заголовки капсом в уложенный текст не попали, и кусок,
    скопированный поперёк заголовка, иначе не нашёлся бы никогда.
    """
    строки = [с for с in (вставлено or "").splitlines()
              if сценарий.is_spoken(с)]
    return align.words("\n".join(строки))


def by_text(laid: dict, вставлено: str) -> list[list[tuple[int, int]]]:
    """Уложить вставленный текст на текст разбора. Пусто не возвращает.

    Возвращает РАСКЛАДКИ: каждая — список кусков видео, из которых
    вставленный текст складывается по порядку. Одна раскладка из одного
    куска — обычный случай.

    Раскладок бывает несколько: человек повторил формулировку, и текст
    ложится не одним способом. Выбирать за него нельзя — возвращаются
    все, решает он.

    **Разрыв разрешён только на границе фразы.** Это единственный способ
    отличить нарочный разрыв от опечатки: порога в словах не выйдет —
    фразы бывают и из одного слова, и из пятнадцати. А сама фраза —
    готовая единица, и в ней человек и работает.
    """
    надо = _слова_вставки(вставлено)
    if not надо:
        raise VertcutError(
            "The pasted text has no spoken words",
            hint="paste text that is spoken in the video, not a heading")
    стог = _слова_разбора(laid)
    if len(надо) > len(стог):
        raise VertcutError(
            f"The pasted text has {report.счёт(len(надо), 'word', 'words')}, "
            f"but the whole video has {len(стог)} — it is not from this video")
    места = speech.spans(laid)
    начала = {первое for первое, _ in места}
    концы = {последнее for _, последнее in места}

    нашлось = _раскладки(стог, надо, начала, концы)
    if нашлось:
        return нашлось
    raise _не_нашлось(laid, стог, надо,
                      _докуда(стог, надо, начала, концы), начала)


def _полосы(стог: list[str], надо: list[str], p: int,
            начала: set[int], концы: set[int]) -> list[tuple[int, int, int]]:
    """Чем может быть кусок, начинающийся со слова `p` вставленного текста.

    Начало куска обязано попасть на начало фразы — кроме самого первого:
    там край ролика, и посреди фразы начинать можно. Конец — на конец
    фразы, кроме последнего куска, где та же поблажка.
    """
    вышло: list[tuple[int, int, int]] = []
    n = len(надо)
    for i in range(len(стог)):
        if стог[i] != надо[p] or (p > 0 and i not in начала):
            continue
        сколько = 0
        while (p + сколько < n and i + сколько < len(стог)
               and стог[i + сколько] == надо[p + сколько]):
            сколько += 1
        for длина in range(1, сколько + 1):
            q, j = p + длина, i + длина - 1
            if q == n or j in концы:
                вышло.append((q, i, j))
    return вышло


def _раскладки(стог: list[str], надо: list[str], начала: set[int],
               концы: set[int]) -> list[list[tuple[int, int]]]:
    """Все раскладки с наименьшим числом кусков.

    **Меньше стыков — лучше**, и это не вкус: текст, легший одной
    полосой, и он же, покрошенный на семь огрызков, — не два равных
    прочтения.
    """
    n = len(надо)
    память: dict[int, int] = {}
    много = n + 1

    def мера(p: int) -> int:
        if p == n:
            return 0
        if p in память:
            return память[p]
        лучшее = много
        for q, _, _ in _полосы(стог, надо, p, начала, концы):
            лучшее = min(лучшее, мера(q) + 1)
        память[p] = лучшее
        return лучшее

    предел = мера(0)
    if предел >= много:
        return []

    готово: list[list[tuple[int, int]]] = []

    def собрать(p: int, осталось: int, набрано: list[tuple[int, int]]) -> None:
        if len(готово) >= ПРЕДЕЛ_РАСКЛАДОК:
            return
        if p == n:
            готово.append(list(набрано))
            return
        for q, i, j in _полосы(стог, надо, p, начала, концы):
            if мера(q) == осталось - 1:
                набрано.append((i, j))
                собрать(q, осталось - 1, набрано)
                набрано.pop()

    собрать(0, предел, [])
    return готово


def _докуда(стог: list[str], надо: list[str], начала: set[int],
            концы: set[int]) -> int:
    """До какого слова вставленный текст вообще доложился.

    Без этого числа сообщение про опечатку в конце длинного куска
    показывало бы на первый стык — то есть на исправное место, —
    и человек чинил бы не то.
    """
    дошли = {0}
    дальше = 0
    сюда = [0]
    while сюда:
        p = сюда.pop()
        дальше = max(дальше, p)
        for q, _, _ in _полосы(стог, надо, p, начала, концы):
            if q not in дошли:
                дошли.add(q)
                сюда.append(q)
    return дальше


def _не_нашлось(laid: dict, стог: list[str], надо: list[str],
                с_слова: int = 0,
                начала: set[int] | None = None) -> VertcutError:
    """Почему не нашлось. ДИАГНОЗ, а не «ничего не найдено».

    Ищется самое длинное совпадение с начала куска. По нему видно, где
    именно текст разошёлся с текстом разбора, — обычно это опечатка при
    перепечатке или правка, которая в запись не попала.
    """
    хвост = надо[с_слова:]
    лучшее_где, лучшее_сколько = -1, 0
    for начало in range(len(стог)):
        if стог[начало] != хвост[0]:
            continue
        if с_слова > 0 and начала is not None and начало not in начала:
            continue
        сколько = 0
        while (сколько < len(хвост) and начало + сколько < len(стог)
               and стог[начало + сколько] == хвост[сколько]):
            сколько += 1
        if сколько > лучшее_сколько:
            лучшее_где, лучшее_сколько = начало, сколько
    вступление = ("" if с_слова == 0 else
                  f"The first {report.счёт(с_слова, 'word', 'words')} matched {_зовут(laid)}, "
                  "the rest did not.\n  ")
    if лучшее_сколько == 0:
        подсказка = ("check that the text is from this video" if с_слова == 0
                     else "a clip can only jump at a phrase boundary — "
                          "this looks like a typo")
        return VertcutError(
            f"{вступление}This text is not in {_зовут(laid)}: "
            f"the word “{хвост[0]}” does not appear"
            + ("" if с_слова == 0 else " at the start of a phrase") + ".",
            hint=подсказка)
    слова = laid["words"]
    сломалось = лучшее_где + лучшее_сколько
    где = show_time(слова[лучшее_где]["s"])
    ваше = хвост[лучшее_сколько] if лучшее_сколько < len(хвост) else "—"
    наше = (слова[сломалось]["w"] if сломалось < len(слова)
            else f"the end of {_зовут(laid)}")
    return VertcutError(
        f"{вступление}Only part of the text was found: {лучшее_сколько} of "
        f"{report.счёт(len(хвост), 'word', 'words')} matched, starting at {где}.\n"
        f"  Then they differ: you have “{ваше}”, "
        f"{_зовут(laid)} has “{наше}”.",
        hint="the text was probably edited after recording — "
             "paste it the way it sounds in the video")


