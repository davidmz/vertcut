def by_phrases(laid: dict, первая: int, последняя: int) -> tuple[int, int]:
    """Целые фразы с номера по номер."""
    всего = len(laid["phrases"])
    if первая < 1 or последняя > всего:
        raise VertcutError(
            f"There are no phrases {первая}–{последняя}: the video has {всего}",
            hint="to see the list: vertcut phrases VIDEO_ID")
    if первая > последняя:
        raise VertcutError(f"The start ({первая}) is after the end ({последняя})")
    места = speech.spans(laid)
    return места[первая - 1][0], места[последняя - 1][1]


def parse_ranges(raw: str) -> list[tuple[int, int]]:
    """«21-22,25-30» → пары номеров фраз. Запятая значит разрыв."""
    пары = []
    for кусок in str(raw).split(","):
        кусок = кусок.strip()
        if not кусок:
            continue
        части = кусок.split("-")
        try:
            если_одна = int(части[0])
            пары.append((если_одна, int(части[-1])))
        except ValueError:
            raise VertcutError(
                f"Cannot read the phrase range: {кусок!r}",
                hint="write it like this: 13-31 or 21-22,25-30") from None
    if not пары:
        raise VertcutError("The phrase range is empty")
    return пары


def by_ranges(laid: dict, пары: list[tuple[int, int]]) -> list[tuple[int, int]]:
    return [by_phrases(laid, a, b) for a, b in пары]


def snap(laid: dict, at: float, край: str) -> int:
    """Номер слова, к границе которого прилипает названное время.

    Посреди слова не режем никогда: обрубок звука слышен всегда.
    """
    слова = laid["words"]
    if край == "start":
        for n, w in enumerate(слова):
            if w["e"] > at - 1e-6:
                return n
        return len(слова) - 1
    for n in range(len(слова) - 1, -1, -1):
        if слова[n]["s"] < at + 1e-6:
            return n
    return 0


# ─────────────────────────────────────────────────────────────────────
# Описание куска: ключ, название, границы, края
# ─────────────────────────────────────────────────────────────────────

def _запас(пауза: float) -> float:
    """Запас, который граница отъедает у соседней паузы.

    Половина паузы, но не больше потолка. Половина — чтобы никогда
    не заехать в чужое слово. Там, где паузы нет (рез посреди фразы),
    запас сам собой равен нулю.
    """
    return round(min(max(пауза, 0.0) / 2, tuning.EDGE_PAD), 3)


def _край(laid: dict, места: list[tuple[int, int]], далеко: list[int],
          слово: int, сторона: str) -> dict:
    """Насколько надёжна граница: на чём стоит время этого слова.

    **Числом, а не флажком.** Замер: из 72 прикидочных границ 64 стоят
    в одном слове от опоры — промах в сотые доли, — и только четыре
    лежат глубже трёх слов. Одинаковый флажок утопил бы эти четыре
    в шуме.
    """
    w = laid["words"][слово]
    номер = 1
    for n, (первое, последнее) in enumerate(места, 1):
        if первое <= слово <= последнее:
            номер = n
            break
    return {
        "phrase": номер,
        "at": w["s"] if сторона == "start" else w["e"],
        "word": слово,
        "measured": "a" not in w,
        "far": далеко[слово],
    }


def _кусок(laid: dict, места, далеко, первое: int, последнее: int,
           duration: float, n: int) -> dict:
    слова = laid["words"]
    if первое > последнее:
        raise VertcutError(
            f"The start ({show_time(слова[первое]['s'])}) is after the end "
            f"({show_time(слова[последнее]['e'])})")
    до = слова[первое]["s"] - (слова[первое - 1]["e"] if первое > 0 else 0.0)
    после = ((слова[последнее + 1]["s"] if последнее + 1 < len(слова)
              else duration) - слова[последнее]["e"])
    запас_до, запас_после = _запас(до), _запас(после)
    начало = max(round(слова[первое]["s"] - запас_до, 3), 0.0)
    конец = min(round(слова[последнее]["e"] + запас_после, 3), duration)
    голова = _край(laid, места, далеко, первое, "start")
    хвост = _край(laid, места, далеко, последнее, "end")
    return {
        "n": n,
        "words": {"first": первое, "last": последнее,
                  "count": последнее - первое + 1},
        "phrases": {"first": голова["phrase"], "last": хвост["phrase"],
                    "count": хвост["phrase"] - голова["phrase"] + 1},
        "start": начало, "end": конец, "duration": round(конец - начало, 3),
        "pad": {"start": запас_до, "end": запас_после},
        "edges": {"start": голова, "end": хвост},
        "text": " ".join(w["w"] for w in слова[первое:последнее + 1]),
    }


def ключ(куски: list[dict]) -> str:
    """Ключ ролика — номера слов каждого куска.

    Четыре цифры, чтобы сортировка по имени совпадала с порядком
    в видео. Разрывный кусок пишется через `+`, по звену на кусок:
    `0076-0113+1150-1200`. Соврать такой ключ не может — по нему видно
    и то, что кусков два, и то, чего между ними нет.
    """
    return "+".join(f"{к['words']['first']:04d}-{к['words']['last']:04d}"
                    for к in куски)


# Знаки, на которых название кончаться не должно.
#
# Точка, вопрос и кавычка что-то ЗАКРЫВАЮТ и потому остаются. А запятая
# и тире ведут дальше, в слова, которых в названии уже нет, и висят
# обещанием продолжения, которого не будет.
_ХВОСТ = " ,;:—–-…"


def название(куски: list[dict]) -> str:
    """Название по умолчанию — первые слова, которые услышит зритель.

    Берётся начало текста ПЕРВОГО куска, а не первой фразы целиком.
    Разница видна там, где ролик начинается посреди фразы, и она
    нарочная. Отсюда побочная польза, ради которой это и стоит держать
    именно так: **невнятное название в списке значит невнятный крючок**,
    и список заодно становится проверкой. Возьми название откуда-нибудь
    ещё — и эта проверка сломается.
    """
    текст = " ".join((куски[0].get("text") or "").split())
    if not текст:
        raise VertcutError(
            "The segment has no text — nothing to make a title from")
    if len(текст) <= tuning.TITLE_LIMIT:
        return текст.rstrip(_ХВОСТ) or текст
    кусок = текст[:tuning.TITLE_LIMIT + 1]
    пробел = кусок.rfind(" ")
    # Пробела нет вовсе — одно слово длиннее предела. Режем посреди:
    # выбор между обрубком и пустотой, а пустота хуже.
    кусок = кусок[:пробел] if пробел > 0 else кусок[:tuning.TITLE_LIMIT]
    return кусок.rstrip(_ХВОСТ) or кусок


def зовут(cut: dict) -> str:
    """Как ролик зовут: своё название, если дано, иначе расчётное.

    **Названия нет вовсе — им становится ключ.** Такое бывает у ролика,
    записанного не до конца. Ронять здесь нельзя: `зовут` читают списки
    и развеска имён, то есть работа ВСЕГО видео, и один битый ролик
    запретил бы сохранять всех остальных.
    """
    готовое = (cut.get("название") or "").strip()
    if готовое:
        return готовое
    try:
        return название(pieces(cut))
    except VertcutError:
        return cut["id"]


def describe(laid: dict, куски: list[tuple[int, int]], как: str,
             duration: float) -> dict:
    """Полное описание ролика по кускам видео."""
    if not куски:
        raise VertcutError("A clip needs at least one segment of video")
    # Один и тот же кусок дважды в одном ролике — брак, который слышно
    # только на публикации: фраза звучит второй раз, а зритель думает,
    # что ролик подвис.
    for n, (a1, b1) in enumerate(куски):
        for m, (a2, b2) in enumerate(куски[:n]):
            if a1 <= b2 and a2 <= b1:
                raise VertcutError(
                    f"Segments {m + 1} and {n + 1} overlap: "
                    f"words {a2}–{b2} and {a1}–{b1}.\n"
                    "  The same words would play twice.",
                    hint="check the pasted text: part of it seems to be "
                         "repeated")
    места = speech.spans(laid)
    далеко = speech.anchor_distance(laid)
    собрано = [_кусок(laid, места, далеко, первое, последнее, duration, n)
               for n, (первое, последнее) in enumerate(куски, 1)]

    return {
        "id": ключ(собрано),
        # Ключ и название считаются РЯДОМ, по одним и тем же кускам,
        # за один проход. Развести их по стадиям значит однажды
        # записать название от другого куска.
        "название": название(собрано),
        "how": как,
        "made": datetime.now().astimezone().isoformat(timespec="seconds"),
        "куски": собрано,
        "words": {"first": собрано[0]["words"]["first"],
                  "last": собрано[-1]["words"]["last"],
                  "count": sum(к["words"]["count"] for к in собрано)},
        "phrases": {"first": собрано[0]["phrases"]["first"],
                    "last": собрано[-1]["phrases"]["last"],
                    "count": sum(к["phrases"]["count"] for к in собрано)},
        "start": собрано[0]["start"],
        "end": собрано[-1]["end"],
        "duration": round(sum(к["duration"] for к in собрано), 3),
        "pad": {"start": собрано[0]["pad"]["start"],
                "end": собрано[-1]["pad"]["end"]},
        "fade": tuning.EDGE_FADE,
        "edges": {"start": собрано[0]["edges"]["start"],
                  "end": собрано[-1]["edges"]["end"]},
        "text": " ".join(к["text"] for к in собрано),
    }


def pieces(cut: dict) -> list[dict]:
    """Куски видео, из которых состоит ролик. Всегда хотя бы один."""
    готовые = cut.get("куски")
    if готовые:
        return готовые
    один = {"n": 1}
    for ключ_ in ("words", "phrases", "start", "end", "duration", "pad",
                  "edges", "text"):
        if ключ_ in cut:
            один[ключ_] = cut[ключ_]
    return [один]


def ranges(cut: dict) -> list[list[int]]:
    """Номера слов каждого куска. По ним сверяется, тот ли файл лежит рядом.

    Отдельно от `words`: у разрывного ролика верхние `words` говорят
    про весь размах, а внутри него дыры. Сравнивать надо куски.
    """
    return [[к["words"]["first"], к["words"]["last"]] for к in pieces(cut)]


def порог_длины(хвост: float = 0.0) -> float:
    """Короче этого ролик не заводится. Растёт вместе с плашкой.

    **Плашка в конце ЗАМЕЩАЕТ картинку**, а не добавляется к ролику:
    три секунды плашки от пятнадцатисекундного ролика — это плашка
    с предисловием. Поэтому порог считается ОТ её длительности,
    а не совпадает с ней числом: поменяли длительность — порог поехал
    за ней сам. У предка эти два числа лежали врозь, и он записал,
    что однажды они разъедутся.

    `хвост` — сколько секунд занимает плашка; ноль, когда её нет.
    Спрашивает его тот, кто зовёт: `pick` не читает профиля и не должен
    — «что уже выбрано» обязано работать на голом json.
    """
    return tuning.MIN_CLIP + max(0.0, float(хвост))


def не_хватает_длины(cut: dict, хвост: float = 0.0) -> float | None:
    """Сколько секунд не добирает кусок до порога. `None` — добирает.

    **Отдельно от отказа, и это понадобилось экрану.** В терминале
    вопрос один: заводить ролик или нет. На экране их два — человек
    ещё только водит мышью по списку фраз, и полоса «выбрано» обязана
    сказать «пока коротко», не мешая ему выбирать дальше. Отказ
    остаётся там, где он и был: в момент создания.

    Считается ЗДЕСЬ, а не там, где спрашивают. Порог `MIN_CLIP` —
    единственное число проекта, которое не мерялось ни разу, и второе
    место, где с ним сравнивают, однажды разъедется с первым.
    """
    если = float(cut["duration"])
    порог = порог_длины(хвост)
    if если + 1e-6 >= порог:
        return None
    return round(порог - если, 1)


def коротко_словами(секунд: float, хвост: float = 0.0) -> str | None:
    """«12 с — короче порога 15 с», или `None`, если длины хватает.

    Заведено для кандидатов модели: им нужно СКАЗАТЬ человеку, почему
    предложение негодно, а не отказать. Сравнение при этом остаётся
    здесь — `MIN_CLIP` единственное число проекта, которое не мерялось
    ни разу, и второе место, где с ним сравнивают, разъедется с первым.
    """
    не_хватает = не_хватает_длины({"duration": секунд}, хвост)
    if не_хватает is None:
        return None
    return (f"{секунд:.0f} s — shorter than the minimum "
            f"{порог_длины(хвост):.0f} s")


def короче_порога(хвост: float = 0.0) -> str:
    """«shorter than 15 seconds» — словами, для просьбы к модели."""
    # Часть запроса к модели: переводится вместе с инструкциями модели.
    return f"shorter than {порог_длины(хвост):.0f} seconds"


def check_length(cut: dict, хвост: float = 0.0) -> None:
    """Ролик короче порога не заводится.

    Порог и замер — в `tuning.MIN_CLIP`, там же написано, почему он тут
    другой по причине, чем у предка. Плашка в конце его поднимает —
    см. `порог_длины`.
    """
    если = float(cut["duration"])
    не_хватает = не_хватает_длины(cut, хвост)
    if не_хватает is not None:
        подпись = ("" if хвост <= 0 else
                   f", {хвост:.0f} s of which is the end card")
        raise VertcutError(
            f"Too short: {если:.1f} s, needs at least "
            f"{порог_длины(хвост):.0f} s{подпись}. "
            f"{не_хватает:.1f} s more.",
            hint="add a phrase or two")


def save(project: Path, cut: dict, заново: bool = False) -> Path:
    """Положить `cut.json`. Чужой ролик под тем же ключом не затирается."""
    путь = layout.cut_json(project, cut["id"])
    if путь.exists():
        старое = json.loads(путь.read_text(encoding="utf-8"))
        # Штамп сборки переносится, а не теряется: он говорит, из каких
        # слов собран лежащий рядом файл. Потеряв его, сервис не отличит
        # готовое от устаревшего и пересоберёт всё подряд.
        #
        # Переносится ТОЛЬКО то, чего в записываемом ролике нет. Иначе
        # лежащее на диске всегда сильнее нового, и команда, которая
        # как раз меняет правку, молча пишет обратно старую.
        if старое.get("render") and not cut.get("render"):
            cut["render"] = старое["render"]
        # Имя лежащего рядом файла — по той же причине: `describe` его
        # не знает, оно решается по всему видео разом. Потеряв его,
        # сервис оставит готовый файл под прежним именем и объявит
        # ролик несобранным: файл цел, а собирают заново.
        if старое.get("файл") and not cut.get("файл"):
            cut["файл"] = старое["файл"]
        # Название, данное рукой, сильнее расчётного — и переносится
        # НЕ по правилу «чего в новом нет»: в новом название есть
        # всегда, его считает `describe`. Правило другое: тронутое рукой
        # не пересчитывается, нетронутое пересчитывается.
        if старое.get("своё_название"):
            cut["название"] = старое.get("название", cut.get("название"))
            cut["своё_название"] = True
        # Монтаж кадра — авторская правка, и переживает перевыбор
        # границ: рамки привязаны к номерам планов ВИДЕО, а не к
        # секундам ролика.
        if старое.get("edit") and not cut.get("edit"):
            cut["edit"] = dict(старое["edit"])
        поехало = ranges(старое) != ranges(cut)
        if not заново and поехало:
            raise VertcutError(
                f"Clip “{cut['id']}” already exists with different edges: "
                f"{show_time(старое['start'])}–{show_time(старое['end'])} "
                f"instead of {show_time(cut['start'])}–{show_time(cut['end'])}.",
                hint="to overwrite it: --again")
    путь.parent.mkdir(parents=True, exist_ok=True)
    путь.write_text(json.dumps(cut, ensure_ascii=False, indent=1) + "\n",
                    encoding="utf-8")
    # Имя готового файла — свойство ВСЕГО видео, а не этого ролика:
    # новый кусок может начаться той же фразой, что и старый, и тогда
    # ключ понадобится обоим.
    from . import rename
    rename.развесить(project)
    return путь


def update(project: Path, cut: dict) -> Path:
    """Переписать существующий ролик целиком, без переносов.

    Отдельно от `save`, и это починка настоящей ошибки, а не порядок
    ради порядка. `save` кладёт ТОЛЬКО ЧТО ВЫБРАННЫЙ кусок и потому
    переносит то, чего в свежем описании быть не может. А команды
    правки читают ролик, меняют и кладут обратно: для них лежащий
    на диске блок правок — не «то, чего нет в новом», а ровно то, что
    они только что убрали. Снятая единственная правка возвращалась бы
    с диска обратно, и команда говорила бы «снято», а рамка оставалась.
    """
    путь = layout.cut_json(project, cut["id"])
    путь.parent.mkdir(parents=True, exist_ok=True)
    путь.write_text(json.dumps(cut, ensure_ascii=False, indent=1) + "\n",
                    encoding="utf-8")
    return путь


def load(project: Path, ident: str) -> dict:
    путь = layout.cut_json(project, ident)
    if not путь.exists():
        raise VertcutError(f"No such clip: {ident}",
                           hint="to see your clips: vertcut cuts VIDEO_ID")
    return json.loads(путь.read_text(encoding="utf-8"))


def listing(project: Path) -> list[dict]:
    """Все выбранные ролики, по порядку в видео.

    Читает голый json: ровно тот момент, когда с окружением может быть
    что-то не так, а человеку надо посмотреть, что у него нарезано.
    """
    корень = layout.cuts(project)
    if not корень.exists():
        return []
    вышло = []
    for папка in sorted(корень.iterdir()):
        if not папка.is_dir():
            continue
        файл = layout.cut_json(project, папка.name)
        if файл.exists():
            вышло.append(json.loads(файл.read_text(encoding="utf-8")))
    вышло.sort(key=lambda c: c.get("words", {}).get("first", 0))
    return вышло
