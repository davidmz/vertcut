"""Слой субтитров: прозрачное видео, которое ляжет поверх кадра.

Отдельным файлом от `subs.py` по той же причине, по которой цепочка
фильтров будет жить в своём: у него одна работа, и её видно целиком.
Здесь диск и ffmpeg; что рисовать и когда — в `subs.py`, а как это
выглядит — в `assets/subtitles.yaml`.

## Почему слоем, а не звеном цепочки

Субтитр меняется на каждом слове: на восемнадцатисекундном ролике это
под сорок состояний, на сорокасекундном — за полсотни. Написать их
наложениями с `enable` нельзя: цепочка распухнет до полусотни звеньев
и станет нечитаемой, а читаемость цепочки — единственный способ
поймать её поломку до того, как она станет файлом.

Поэтому состояния рисуются картинками, склеиваются в одно видео
с прозрачностью и накладываются ОДНИМ звеном. **Кодирование при этом
по-прежнему одно:** слой — отдельный вход, а не второй проход.

## Почему qtrle

Сжатие без потерь с альфой. Альфа тут не роскошь, а весь смысл файла:
всё, кроме плашек строк, обязано остаться прозрачным до последнего
пикселя.

## Почему слой не остаётся лежать

Его надо смотреть в движении, а не картинкой, и весит он больше
половины самого ролика. Поэтому он живёт во временной папке и умирает
вместе со сборкой. Посмотреть раскладку глазами до сборки можно листом.
"""

from __future__ import annotations

from pathlib import Path

from . import subs
from .errors import VertcutError
from .run import FFMPEG, FFPROBE, run, run_с_ходом

# Кодек слоя: сжатие без потерь с альфой.
КОДЕК = ["-c:v", "qtrle", "-pix_fmt", "argb"]


def кадров_в(всего: float, fps: float) -> int:
    """Сколько кадров в ролике такой длины.

    Слой обязан быть НЕ КОРОЧЕ картинки: наложение просто перестанет
    накладывать, и последние субтитры пропадут молча. Поэтому кадр
    в запас — он всё равно прозрачный.
    """
    return int(round(всего * fps)) + 1


def собрать(раскл: dict, prof: dict, font, fps: float, работа: Path,
            ход=None) -> Path:
    """Собрать слой субтитров ролика. Возвращает путь к файлу.

    `работа` — своя временная папка на этот счёт. Общей быть не должно:
    два счёта разом это обычное дело, и общая папка стирается из-под
    соседа.

    `ход` — кому рассказывать, сколько уже сделано. Работы тут
    на восьмую часть сборки, и обе её половины считаются
    по-настоящему: нарисованные состояния и записанные кадры.
    """
    ход = ход or (lambda *_а, **_к: None)
    показы = раскл["показы"]
    if not показы:
        raise VertcutError(
            "This clip has no subtitles, so there's no subtitle layer "
            "to make")

    кадров = кадров_в(раскл["total"], fps)
    работа.mkdir(parents=True, exist_ok=True)

    # Границы состояний считаются в КАДРАХ по абсолютным позициям,
    # а не по длительностям. Округляй каждую длительность по отдельности
    # — и к концу сорокасекундного ролика субтитр уедет от голоса
    # на несколько кадров.
    метки, состояния, прошлый = [], [], 0
    for показ in показы:
        начало = max(прошлый, min(кадров, int(round(показ["at"] * fps))))
        if начало > прошлый:
            # Между фразами субтитра нет: пустой кадр, а не висящая
            # плашка.
            метки.append(прошлый)
            состояния.append(None)
        метки.append(начало)
        состояния.append(показ)
        прошлый = max(начало, min(кадров, int(round(показ["till"] * fps))))
    if прошлый < кадров:
        метки.append(прошлый)
        состояния.append(None)

    список, последний = [], ""
    for n, показ in enumerate(состояния):
        ход("Drawing subtitles", n, len(состояния), "images")
        сколько = (метки[n + 1] if n + 1 < len(метки) else кадров) - метки[n]
        if сколько <= 0:
            continue
        последний = f"{len(список):04d}.png"
        if показ is None:
            _пусто(prof).save(работа / последний)
        else:
            subs.нарисовать(показ["страница"], показ["сказано"],
                            показ["низ"], prof, font).save(работа / последний)
        список.append(f"file '{последний}'\nduration {сколько / fps:.6f}\n")

    if not список:
        raise VertcutError("The subtitle layer came out empty")
    # Последний файл повторяется без длительности: без этого склейщик
    # роняет хвост, и слой выходит на кадр короче картинки.
    список.append(f"file '{последний}'\n")
    (работа / "list.txt").write_text("".join(список), encoding="utf-8")

    куда = работа / "subtitles.mov"
    run_с_ходом([
        FFMPEG, "-v", "error", "-y",
        "-f", "concat", "-safe", "0", "-i", str(работа / "list.txt"),
        # `tpad` клонирует хвост: после приведения к сетке кадров их
        # может выйти на один меньше, чем в картинке. Лишнее срежет
        # `-frames:v`.
        "-vf", f"fps={fps},format=rgba,tpad=stop_mode=clone:stop_duration=1",
        "-frames:v", str(кадров), "-an", *КОДЕК, str(куда),
    ], кадров, lambda с, в: ход("Preparing subtitles", с, в, "frames"),
        считать="кадры")
    вышло = сколько_кадров(куда)
    if вышло != кадров:
        raise VertcutError(
            f"The subtitle layer came out {вышло} frames long instead of "
            f"{кадров}. On top of the video it would drift away from "
            "the voice.",
            hint="export again; if it repeats, see Not working?")
    return куда


def _пусто(prof: dict):
    from PIL import Image
    return Image.new("RGBA", (prof["width"], prof["height"]), (0, 0, 0, 0))


def сколько_кадров(путь: Path) -> int:
    вышло = run([FFPROBE, "-v", "error", "-select_streams", "v:0",
                 "-count_packets", "-show_entries", "stream=nb_read_packets",
                 "-of", "csv=p=0", str(путь)]).strip()
    return int(вышло) if вышло.isdigit() else 0
