"""Плашка в конце ролика: фон, обложка выпуска, надпись.

Последние секунды ролика идут картинкой вместо видео. Звук при этом
доигрывает под ней ЦЕЛИКОМ — **плашка замещает картинку, а не
приклеивается к ролику**, и длина файла от неё не меняется ни на кадр.

**По умолчанию её нет, и это решение спеки.** У чужого человека нет
ни обложки выпуска, ни канала, ни фона; плашка — возможность, а не
часть пути. Выключенная, она не стоит ничего и не меняет ничего:
ролик, собранный без неё, собирается ровно тем же, чем собирался
до её появления.

**Собирается КАРТИНКОЙ, а не звеньями цепочки.** Композиция статичная,
а перенос строк и подбор кегля — работа для сборщика картинки:
в фильтрах ffmpeg нет ни того, ни другого. Собранная `плашка.png`
остаётся лежать рядом с роликом, и по ней видно, что уехало, ещё
до сборки.

**Все числа — из профиля, блок `end_card`.** В коде нет ни кегля,
ни полей, ни базового текста: расходится код с настройками —
правится профиль.

**Полоса под субтитр СЧИТАЕТСЯ, а не лежит здесь числом.** Правило
предка: субтитр не двигается, расступается плашка. У него полоса
замерена под один кегль; здесь кегль меняет человек, и полосу считает
`subs.полоса` — то самое измерение, которое уже есть. Второго тут
не заводится: разъедься они, обложка налезла бы на субтитр молча.

**Обложка вписывается, а не обрезается.** Она уже скомпонована
автором; кроп под 16:9 однажды срежет с неё половину заголовка.

**Надпись переносится только по авторским разрывам строк.** Своего
переноса по ширине нет намеренно: две строки — это ритм, и машина,
ломающая строку в своём месте, его рушит. Не влезло — уменьшается
кегль, до предела; дальше отказ с числами.
"""

from __future__ import annotations

from pathlib import Path

from . import layout, report, subs
from .errors import VertcutError

# Сторона кадра словами. Ключи «слева»/«справа» — имена в json зазоров,
# их читает экран; в жалобу человеку они идут по-английски.
_СТОРОНА = {"слева": "on the left", "справа": "on the right"}

# «Фона нет» — сплошной цвет. Не поломка и не недостача: человек
# с обложкой, но без фона, обязан получить плашку, а не отказ.
БЕЗ_ФОНА = "none"


# ─────────────────────────────────────────────────────────────────────
# Настройки
# ─────────────────────────────────────────────────────────────────────

def сырые(project: Path | None = None, ident: str | None = None) -> dict:
    """Блок `end_card` профиля как он лежит в файле.

    Профиль читается тем же `subs.settings` — со всеми четырьмя
    уровнями, с достройкой недостающего из образца и с отказом
    на незнакомый ключ. Второго читателя настроек в проекте нет.
    """
    return subs.settings(project, ident).get("end_card") or {}


def включена(это: dict) -> bool:
    """Показывать плашку или нет. Принимает сырой блок `end_card`."""
    return subs.да_или_нет(это.get("show", False), "end_card.show")


def секунды(это: dict) -> float:
    """Сколько секунд ролика занимает плашка. Выключена — ноль.

    Ноль у выключенной не оговорка, а то, на чём держатся двое:
    порог длины ролика (он растёт вместе с плашкой) и отсчёт её
    начала. Спрашивать «а включена ли» им обоим не приходится.
    """
    if not включена(это):
        return 0.0
    сколько = float(это.get("duration", 0.0))
    if сколько <= 0:
        raise VertcutError(
            f"The end card length in the subtitle style is {сколько} s, "
            "but it must be more than zero",
            hint="fix it: vertcut style … --set end_card.duration=3.0")
    return сколько


def секунд_у(project: Path | None = None,
             ident: str | None = None) -> float:
    """Сколько секунд плашка забирает у роликов ЭТОГО видео.

    Короткая дорога для тех, кому нужно одно число: порога длины
    ролика, экрана, просьбы к модели. Читать профиль ради него
    у каждого из них — три места, знающих, где лежит плашка.
    """
    return секунды(сырые(project, ident))


def начало(всего: float, это: dict) -> float:
    """С какой секунды файла идёт плашка.

    **Отсчитывается от конца ФАЙЛА, а не от конца речи.** Файл длиннее
    речи на звуковые шторки: они работают наружу, и восемнадцати-
    секундный ролик лежит на диске длиной 18.4. Считать от конца речи
    значит оставить после плашки висеть две десятых картинки — она
    мигнёт обратно перед самым концом. Тянуть от конца речи до конца
    файла значит получить 3.2 секунды вместо трёх.

    Замер предка, три отсчёта перебраны; от конца файла — единственный,
    при котором и длительность ровная, и после плашки ничего не висит.

    Плашки нет — возвращается длина файла, то есть «плашка начинается
    там, где ролик кончился». Так у всех, кто спрашивает, не заводится
    развилки.
    """
    сколько = секунды(это)
    if сколько <= 0:
        return всего
    return round(max(всего - сколько, 0.0), 3)


def числа(prof: dict, это: dict, project: Path | None = None) -> dict:
    """Числа плашки в пикселях ЭТОГО кадра.

    Принимает готовый профиль субтитров (`prof`) и сырой блок `end_card`.
    Профиль нужен не для красоты: из него берутся безопасные зоны
    и полоса под субтитр, и брать их вторым числом здесь нельзя —
    они уже посчитаны там, где живут.
    """
    from . import fonts

    width, height = int(prof["width"]), int(prof["height"])
    надпись = это.get("text") or {}
    обложка = это.get("thumbnail") or {}

    имя_фона = str(это.get("image", БЕЗ_ФОНА)).strip()
    фон_файл = None if имя_фона in ("", БЕЗ_ФОНА) else найти_фон(имя_фона)

    поле = round(width * float(обложка["side_margin"]))
    верх = round(height * float(обложка["top"]))
    низ = round(height * float(обложка["bottom"]))
    if width - 2 * поле <= 0 or низ - верх <= 0:
        raise VertcutError(
            "The thumbnail box in the subtitle style is inside out: "
            f"{width - 2 * поле}×{низ - верх}",
            hint="its numbers are under «end_card.thumbnail» in the style")

    кегль = max(8, round(width * float(надпись["size"])))
    предел_кегля = max(4, round(width * float(надпись["min_size"])))
    if предел_кегля > кегль:
        raise VertcutError(
            f"The end card text size {кегль} is smaller than its own "
            f"minimum {предел_кегля}",
            hint="its numbers are under «end_card.text» in the style")

    полоса = subs.полоса(prof)
    return {
        "показывать": включена(это),
        "секунды": секунды(это),
        "width": width, "height": height,
        "фон": фон_файл,
        "фон_имя": имя_фона,
        "цвет": str(это["color"]),
        "коробка": {"x": поле, "y": верх,
                    "w": width - 2 * поле, "h": низ - верх},
        "шрифт": fonts.найти(надпись["font"], project),
        "вес": int(надпись["weight"]),
        "кегль": кегль,
        "кегль_предел": предел_кегля,
        "шаг_долей": float(надпись["line_spacing"]),
        "первая_базовая": round(height * float(надпись["first_baseline"])),
        "цвет_надписи": str(надпись["color"]),
        # Предельная ширина строки и нижний предел — ИЗ БЕЗОПАСНЫХ ЗОН
        # субтитров, а не свои. Два числа на один вопрос однажды
        # разъезжаются, и разъедутся они на готовом ролике.
        "предел_ширины": (width - 2 * prof["зона_сбоку"]
                          if prof["беречь_зоны"] else width),
        "предел_низа": prof["предел_низа"],
        "поле_сбоку": prof["зона_сбоку"] if prof["беречь_зоны"] else 0,
        "зона_сверху": prof["предел_верха"],
        "беречь_зоны": prof["беречь_зоны"],
        "столбик_верх": prof["столбик_верх"],
        # Полоса, которую плашка держит пустой под субтитр. Считается
        # профилем субтитров, а не лежит здесь: у предка она была
        # замерена под один кегль, а здесь кегль меняет человек.
        "полоса": {"верх": полоса["верх"], "низ": полоса["низ"],
                   "строк": полоса["строк"]},
    }


def настройки(prof: dict, project: Path | None = None,
              ident: str | None = None) -> dict:
    """Всё про плашку одним куском: сырое прочитано, числа посчитаны."""
    return числа(prof, сырые(project, ident), project)


# ─────────────────────────────────────────────────────────────────────
# Фон: свой файл человека
# ─────────────────────────────────────────────────────────────────────

def набор_фонов() -> list[dict]:
    """Какие фоны у человека есть. Поставляемых нет вовсе."""
    папка = layout.фоны()
    if not папка.exists():
        return []
    вышло = []
    for путь in sorted(папка.iterdir()):
        if путь.is_file() and not путь.name.startswith("."):
            вышло.append({"имя": путь.name, "путь": путь,
                          "мегабайт": round(путь.stat().st_size / 1048576, 2)})
    return вышло


def найти_фон(имя: str) -> Path:
    """Файл фона по имени из профиля.

    Имя с разделителем пути берётся как путь: человек вправе указать
    файл где угодно. Голое имя ищется у него в `~/.vertcut/фоны/` —
    поставляемых фонов нет и быть не может.
    """
    сырое = str(имя).strip()
    прямой = Path(сырое).expanduser()
    if len(прямой.parts) > 1:
        if прямой.exists():
            return прямой
        raise VertcutError(f"The end card background file isn't there: "
                           f"{прямой}")
    путь = layout.фоны() / сырое
    if путь.exists():
        return путь
    raise VertcutError(
        f"The end card background “{сырое}” isn't where Vertcut looks for "
        f"it: {layout.фоны()}",
        hint="choose the background again in the subtitle editor, "
             "or turn the background off there")


def поставить_фон(файл: Path) -> Path:
    """Положить свой фон к себе — в `~/.vertcut/фоны/`.

    **Копируется, а не запоминается путём.** Ровно та же причина, что
    у шрифта: путь на рабочий стол через месяц ведёт в пустоту,
    и плашка соберётся сплошным цветом.

    **Копируется содержимое, без прав и меток файла** — тот же замер,
    что у шрифтов: файлы, помеченные системой, `copy2` тащить
    отказывается.
    """
    import shutil

    файл = Path(файл).expanduser()
    if not файл.exists():
        raise VertcutError(f"No such file: {файл}")
    _это_картинка(файл, "End card background")
    куда = layout.фоны() / файл.name
    куда.parent.mkdir(parents=True, exist_ok=True)
    if файл.resolve() != куда.resolve():
        shutil.copyfile(файл, куда)
    return куда


# ─────────────────────────────────────────────────────────────────────
# Обложка выпуска
# ─────────────────────────────────────────────────────────────────────

def _это_картинка(файл: Path, что: str):
    """Открыть и убедиться, что это правда картинка. Возвращает размер."""
    from PIL import Image, UnidentifiedImageError

    try:
        with Image.open(файл) as картинка:
            картинка.load()
            return картинка.size
    except UnidentifiedImageError as bad:
        raise VertcutError(
            f"{что}: this isn't an image — {файл.name}") from bad
    except OSError as bad:
        raise VertcutError(f"{что}: can't read the file — {файл}\n  {bad}")


def поставить_обложку(project: Path, файл: Path) -> dict:
    """Положить обложку выпуска в папку разбора.

    **Отдельно, а не стадией разбора.** Разбор стоит минуты, обложка
    меняется чаще всего остального и не влияет на него ничем — её
    видит одна плашка. Ни один штамп разбора здесь не трогается.

    **Кладётся в jpeg БЕЗ прореживания цвета.** На обложке крупный
    текст, а обычное для jpeg прореживание 4:2:0 размывает именно его
    края. Файл маленький, экономить не на чем.
    """
    from PIL import Image

    файл = Path(файл).expanduser()
    if not файл.exists():
        raise VertcutError(f"No such file: {файл}")
    размер = _это_картинка(файл, "Thumbnail")

    куда = layout.обложка_выпуска(project)
    было = None
    if куда.exists():
        with Image.open(куда) as старая:
            было = {"размер": list(старая.size),
                    "мегабайт": round(куда.stat().st_size / 1048576, 2)}
    куда.parent.mkdir(parents=True, exist_ok=True)
    with Image.open(файл) as картинка:
        картинка.convert("RGB").save(куда, "JPEG", quality=95,
                                     subsampling=0, optimize=True)
    return {"файл": куда, "источник": файл, "размер": list(размер),
            "мегабайт": round(куда.stat().st_size / 1048576, 2),
            "было": было, "отпечаток": отпечаток(куда)}


def убрать_обложку(project: Path) -> bool:
    """Снять обложку выпуска. Не было — просто «нет»."""
    путь = layout.обложка_выпуска(project)
    if not путь.exists():
        return False
    путь.unlink()
    return True


def обложка(project: Path) -> Path | None:
    """Обложка выпуска или ничего.

    **Ничего — законный ответ, а не недостача.** Плашка без обложки
    это фон и надпись: годная концовка. Сервис говорит об этом словами
    (см. `собрать`), но не отказывает: отказ здесь означал бы, что
    человек, которому обложка не нужна, не может включить плашку вовсе.
    """
    путь = layout.обложка_выпуска(project)
    return путь if путь.exists() else None


def отпечаток(путь: Path) -> str:
    """Отпечаток картинки. По нему видно, что обложку заменили."""
    import hashlib

    сумма = hashlib.sha256()
    with путь.open("rb") as файл:
        while кусок := файл.read(1 << 20):
            сумма.update(кусок)
    return сумма.hexdigest()[:16]


