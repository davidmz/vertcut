def базовый_текст(это: dict) -> str:
    """Базовая надпись. В коде её нет — только в профиле."""
    return str((это.get("text") or {}).get("content") or "")


def текст_у(cut: dict, это: dict) -> str:
    """Надпись ЭТОЙ вертикалки: своя, а нет своей — базовая.

    **Базовая в `cut.json` не оседает.** Осела бы — вертикалка тихо
    отвязалась бы от настроек: поправили базовую надпись, а плашка
    осталась со старой, и молча.
    """
    своя = (cut.get("хвост") or {}).get("текст")
    return своя if своя else базовый_текст(это)


def задать_текст(cut: dict, текст: str | None) -> None:
    """Своя надпись вертикалке. Пусто — обратно на базовую."""
    свой = (текст or "").strip()
    хвост = cut.setdefault("хвост", {})
    if свой:
        хвост["текст"] = свой
    else:
        хвост.pop("текст", None)
    if not хвост:
        cut.pop("хвост", None)


def _строки(текст: str) -> list[str]:
    """Строки надписи. Только авторские разрывы, своих нет."""
    вышло = [строка.strip()
             for строка in текст.replace("\r\n", "\n").split("\n")]
    return [строка for строка in вышло if строка]


def уложить(текст: str, это: dict) -> dict:
    """Кегль и место каждой строки. Не влезло — кегль вниз, потом отказ.

    **Меряется по КРАСКЕ, а не по габариту строки.** Надпись стоит
    по центру, и центрировать её надо по тому, что видно.

    **Промах называется на самом мелком кегле, а не на исходном.**
    Сказать «шире на 768» про кегль, с которого начинали, значит
    отправить человека резать текст вчетверо там, где хватит пары слов.
    """
    строки = _строки(текст)
    if not строки:
        raise VertcutError(
            "The end card text is empty — nothing to draw",
            hint="write the end card text in the subtitle editor")

    коробка = это["предел_ширины"]
    поле = (это["width"] - коробка) // 2
    низ_предел = это["предел_низа"]
    промах = None
    for кегль in range(это["кегль"], это["кегль_предел"] - 1, -1):
        шрифт, вес_выставлен = subs.открыть_шрифт(это["шрифт"], кегль,
                                                  это["вес"])
        шаг = round(кегль * это["шаг_долей"])
        места, шире, низ = [], 0, 0
        for n, строка in enumerate(строки):
            x0, y0, x1, y1 = шрифт.getbbox(строка, anchor="ls")
            краска = x1 - x0
            шире = max(шире, краска - коробка)
            базовая = это["первая_базовая"] + n * шаг
            лев = поле + (коробка - краска) // 2
            места.append({"текст": строка, "базовая": базовая,
                          "x": лев - x0, "лев": лев, "прав": лев + краска,
                          "верх": базовая + y0, "низ": базовая + y1,
                          "ширина": краска})
            низ = max(низ, базовая + y1)
        промах = (шире, низ - низ_предел)
        if шире <= 0 and низ <= низ_предел:
            return {"кегль": кегль, "шаг": шаг, "строки": места,
                    "просили": это["кегль"], "вес_выставлен": вес_выставлен,
                    "верх": min(м["верх"] for м in места), "низ": низ,
                    "лев": min(м["лев"] for м in места),
                    "прав": max(м["прав"] for м in места),
                    "коробка": коробка}

    шире, ниже = промах
    почему = []
    if шире > 0:
        почему.append(f"the longest line is {шире} px wider than the box "
                      f"(box {коробка})")
    if ниже > 0:
        почему.append(f"the last line goes {ниже} px below the limit")
    raise VertcutError(
        f"The end card text doesn't fit even at the smallest size "
        f"{это['кегль_предел']}: " + ", ".join(почему) + ".\n"
        f"  {report.счёт(len(строки), 'line', 'lines')}. Lines break only "
        "where you put a line break — Vertcut doesn't add its own.",
        hint="shorten the text or split it into more lines")


