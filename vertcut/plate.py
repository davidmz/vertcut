# Сборка картинки
# ─────────────────────────────────────────────────────────────────────

def _фон(это: dict):
    """Фон под вертикальный кадр: файл человека или сплошной цвет.

    Файл вписывается ЗАПОЛНЕНИЕМ: масштабируется до кадра по большей
    стороне и берётся середина. Обрезать фон можно — он фон; обложку
    нельзя, и в этом вся разница между ними.
    """
    from PIL import Image

    width, height = это["width"], это["height"]
    путь = это["фон"]
    if путь is None:
        return Image.new("RGB", (width, height),
                         subs.цвет(это["цвет"])[:3])
    try:
        с_диска = Image.open(путь).convert("RGB")
    except OSError as bad:
        raise VertcutError(f"Can't read the end card background: {путь}"
                           f"\n  {bad}")
    во_сколько = max(width / с_диска.width, height / с_диска.height)
    крупный = с_диска.resize(
        (max(round(с_диска.width * во_сколько), width),
         max(round(с_диска.height * во_сколько), height)), Image.LANCZOS)
    лев = (крупный.width - width) // 2
    верх = (крупный.height - height) // 2
    return крупный.crop((лев, верх, лев + width, верх + height))


def коробка_обложки(размер: tuple[int, int], это: dict) -> dict:
    """Куда встанет обложка. Вписывается целиком, не обрезается.

    **Верхний край не двигается никогда:** «обложка сверху с полями» —
    это про верхнее поле, и оно должно быть одинаковым у всех выпусков.
    Более квадратная обложка упрётся в нижний предел высотой и станет
    уже; более широкая ляжет во всю ширину коробки и не дотянется
    до низа.
    """
    коробка = это["коробка"]
    ш, в = размер
    if ш <= 0 or в <= 0:
        raise VertcutError(f"The thumbnail has an impossible size: {ш}×{в}")
    во_сколько = min(коробка["w"] / ш, коробка["h"] / в)
    новая_ш = max(round(ш * во_сколько), 1)
    новая_в = max(round(в * во_сколько), 1)
    return {"x": коробка["x"] + (коробка["w"] - новая_ш) // 2,
            "y": коробка["y"], "w": новая_ш, "h": новая_в,
            "коробка": dict(коробка)}


def зазоры(это: dict, где_обложка: dict | None, уложено: dict) -> dict:
    """Сколько остаётся до интерфейса площадки и до субтитра.

    **Ничего не двигает — говорит числами.** Числа зон не официальные,
    их снимают со скриншотов, и источники расходятся вдвое. Двигать
    по ним композицию значило бы перекладывать плашку от чужой
    неточности; поэтому проверка печатает зазоры и ругается.

    **Боковые поля спрашиваются только с того, что достаёт до столбика
    иконок.** Обложка кончается выше середины кадра, а столбик занимает
    нижние сорок процентов: ругать её за то, что она стоит к краю ближе
    поля, значит печатать жалобу на то, чего не бывает.
    """
    полоса = это["полоса"]
    поле = это["поле_сбоку"]
    жалобы = []

    вышло = {"надпись": {"слева": уложено["лев"],
                         "справа": это["width"] - уложено["прав"],
                         "снизу": это["height"] - уложено["низ"],
                         "до_полосы": уложено["верх"] - полоса["низ"]}}
    if где_обложка is not None:
        вышло["обложка"] = {
            "слева": где_обложка["x"],
            "справа": это["width"] - (где_обложка["x"] + где_обложка["w"]),
            "сверху": где_обложка["y"],
            "до_полосы": полоса["верх"] - (где_обложка["y"]
                                           + где_обложка["h"])}

    if это["беречь_зоны"]:
        if где_обложка is not None:
            if где_обложка["y"] < это["зона_сверху"]:
                жалобы.append(
                    f"the thumbnail goes under the app's top bar: "
                    f"{где_обложка['y']} px, the margin is "
                    f"{это['зона_сверху']}")
            достаёт = (где_обложка["y"] + где_обложка["h"]
                       > это["столбик_верх"])
            for сторона in ("слева", "справа"):
                if достаёт and вышло["обложка"][сторона] < поле:
                    жалобы.append(
                        f"the thumbnail reaches the column of icons "
                        f"(below {это['столбик_верх']}) and is too close "
                        f"to the edge {_СТОРОНА[сторона]}: "
                        f"{вышло['обложка'][сторона]} px, the margin is "
                        f"{поле}")
        for сторона in ("слева", "справа"):
            if вышло["надпись"][сторона] < поле:
                жалобы.append(
                    f"the end card text goes under the app's buttons "
                    f"{_СТОРОНА[сторона]}: {вышло['надпись'][сторона]} px, "
                    f"the margin is {поле}")
        если_снизу = это["height"] - это["предел_низа"]
        if вышло["надпись"]["снизу"] < если_снизу:
            жалобы.append(
                f"the end card text goes under the app's bottom bar: "
                f"{вышло['надпись']['снизу']} px, the margin is "
                f"{если_снизу}")

    # Полоса под субтитр. Она считается профилем субтитров, и если
    # человек поднял субтитр или укрупнил кегль, обложка с надписью
    # обязаны об этом узнать — а не оказаться под ним на готовом ролике.
    if где_обложка is not None and вышло["обложка"]["до_полосы"] < 0:
        жалобы.append(
            f"the thumbnail runs {-вышло['обложка']['до_полосы']} px into "
            f"the subtitle area: it ends at "
            f"{где_обложка['y'] + где_обложка['h']}, the area starts at "
            f"{полоса['верх']}")
    if вышло["надпись"]["до_полосы"] < 0:
        жалобы.append(
            f"the end card text runs {-вышло['надпись']['до_полосы']} px "
            f"into the subtitle area: the letters start at "
            f"{уложено['верх']}, the area ends at {полоса['низ']}")

    return {"зазоры": вышло, "полоса": полоса, "жалобы": жалобы}


def жалоба_на_контраст(это: dict) -> str | None:
    """Сливается ли надпись со сплошным фоном.

    **Только когда фон сплошной.** Есть картинка — сказать нечего:
    она разная в разных местах, и мера контраста к ней неприменима.
    То же решение и та же причина, что у субтитра при подложке «без».
    """
    from . import tuning

    if это["фон"] is not None:
        return None
    мера = subs.контраст(это["цвет_надписи"], это["цвет"])
    if мера >= tuning.CONTRAST_MIN:
        return None
    return (f"the end card text blends into the background: colors "
            f"{это['цвет_надписи']} and {это['цвет']}, contrast {мера:.1f}, "
            f"needs {tuning.CONTRAST_MIN}")


def собрать(куда: Path, это: dict, обложка_файл: Path | None,
            текст: str) -> dict:
    """Собрать плашку картинкой. Возвращает измеренную композицию."""
    from PIL import Image, ImageDraw

    кадр = _фон(это)
    где = None
    если = []
    if обложка_файл is None:
        если.append("this video has no thumbnail — the end card will "
                    "go without it")
    else:
        with Image.open(обложка_файл) as картинка:
            картинка = картинка.convert("RGB")
            где = коробка_обложки(картинка.size, это)
            кадр.paste(картинка.resize((где["w"], где["h"]), Image.LANCZOS),
                       (где["x"], где["y"]))
            размер_обложки = list(картинка.size)

    уложено = уложить(текст, это)
    шрифт, _ = subs.открыть_шрифт(это["шрифт"], уложено["кегль"], это["вес"])
    рисуем = ImageDraw.Draw(кадр)
    for строка in уложено["строки"]:
        рисуем.text((строка["x"], строка["базовая"]), строка["текст"],
                    font=шрифт, fill=это["цвет_надписи"], anchor="ls")

    куда.parent.mkdir(parents=True, exist_ok=True)
    кадр.save(куда)

    проверка = зазоры(это, где, уложено)
    беда_с_цветом = жалоба_на_контраст(это)
    if беда_с_цветом:
        если.append(беда_с_цветом)
    if not уложено["вес_выставлен"]:
        если.append(f"weight {это['вес']} didn't apply to the end card "
                    "font: it has no weight axis, so the file's own weight "
                    "is used")

    return {
        "файл": куда,
        "кадр": {"w": это["width"], "h": это["height"]},
        "фон": (str(это["фон"]) if это["фон"] is not None
                else f"solid {это['цвет']}"),
        "обложка": (None if где is None else
                    {"источник": str(обложка_файл), "размер": размер_обложки,
                     **{k: где[k] for k in ("x", "y", "w", "h")}}),
        "надпись": {
            "текст": текст, "кегль": уложено["кегль"],
            "просили": уложено["просили"], "шаг": уложено["шаг"],
            "верх": уложено["верх"], "низ": уложено["низ"],
            "лев": уложено["лев"], "прав": уложено["прав"],
            "строки": [{k: с[k] for k in ("текст", "базовая", "лев", "прав",
                                          "верх", "низ", "ширина")}
                       for с in уложено["строки"]],
        },
        "просвет": (None if где is None
                    else уложено["верх"] - (где["y"] + где["h"])),
        **проверка,
        "жалобы": если + проверка["жалобы"],
    }


def собрать_у(project: Path, cut: dict, prof: dict) -> dict:
    """Плашка одной вертикалки: прочитать настройки и собрать картинку.

    Одно место на всех, кто её просит: сборка, экран, команда. Второе
    разъехалось бы с первым — и человек увидел бы на экране одно,
    а в файле другое.
    """
    это = сырые(project, cut["id"])
    if not включена(это):
        raise VertcutError(
            "The end card is off — nothing to make",
            hint="turn it on in the subtitle editor")
    сделано = собрать(layout.плашка(project, cut["id"]),
                      числа(prof, это, project), обложка(project),
                      текст_у(cut, это))
    сделано["штамп"] = штамп_сейчас(project, cut, это)
    return сделано


# ─────────────────────────────────────────────────────────────────────
# Штамп: из чего собрана плашка лежащего рядом файла
# ─────────────────────────────────────────────────────────────────────

def штамп_сейчас(project: Path, cut: dict, это: dict) -> dict:
    """Всё, от чего плашка зависит, одним словарём.

    **Отдельно от отпечатка профиля субтитров, и это нарочно.** Числа
    плашки в профиле лежат и в его отпечаток входят сами; а обложка —
    файл в папке разбора, и надпись может быть своя у вертикалки.
    Ни того ни другого профиль не видит вовсе, и заменённая обложка
    доехала бы не до всех роликов — молча.

    **Выключенная плашка — это ОДНО слово и больше ничего.** Не «ноль
    секунд и такая-то обложка»: тогда человек, у которого плашка
    выключена, устаревал бы все свои ролики от замены обложки, которой
    в них нет ни пикселем. Включение возможности не имеет права трогать
    тех, кто ею не пользуется, и здесь это записано ровно один раз.
    """
    if not включена(это):
        return {"показывать": False}
    картинка = обложка(project)
    return {
        "показывать": True,
        "секунды": секунды(это),
        "текст": текст_у(cut, это),
        "обложка": отпечаток(картинка) if картинка is not None else "",
    }
