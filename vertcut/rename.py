"""Имена готовых файлов: по названию ролика, а не по ключу.

**Зачем это вообще.** Пока ролик смотрят на экране, имя файла незаметно.
При публикации пачкой человек перетаскивает в загрузчик площадки
двадцать файлов — и если все они зовутся одинаково, он их
переименовывает руками.

**Чистка берётся у имени папки разбора.** Второе такое же правило
однажды разъедется с первым, и молча: обе половины продолжат работать,
просто по-разному отвечая, как пишется «ж».

**Столкнулись два названия — ключ приписывается ОБОИМ.** Не одному
«второму»: второй — это тот, кто попался позже при обходе папки,
а после переименования соседа он окажется первым. Имя файла, зависящее
от порядка обхода, меняется само по себе.

**Имя файла — свойство всего ВИДЕО, а не ролика.** Глядя на один ролик,
столкновения не увидишь. Поэтому имена развешиваются по видео разом.
"""

from __future__ import annotations

import json
from pathlib import Path

from . import layout, pick, slug
from .errors import VertcutError


def чисто(название: str) -> str:
    """Название → имя файла. Режется по границе слова, а не посреди.

    У чистки имени папки свой предел, и режет она посреди слова.
    Своего правила здесь не заводится: вместо этого отбрасывается
    последнее слово названия, и чистка зовётся снова.
    """
    слова = название.split()
    while слова:
        try:
            вышло = slug.make(" ".join(слова))
        except ValueError:
            слова = слова[:-1]
            continue
        if len(вышло) <= slug.LIMIT:
            return вышло
        слова = слова[:-1]
    return ""


def как_назовутся(project: Path, ролики: list[dict] | None = None) -> dict:
    """Как будут называться файлы роликов. Диска не трогает.

    **Отдельно от самого переименования, и это не украшение.** Имя
    файла надо ПОКАЗАТЬ — на экране описаний оно стоит техничкой под
    подписью, — а показ не имеет права ничего переименовывать. Считает
    их одно место: второе разошлось бы с первым молча, и человек видел
    бы на экране одно имя, а на диске другое.
    """
    ролики = pick.listing(project) if ролики is None else ролики
    хотят: dict[str, str] = {}
    сколько: dict[str, int] = {}
    for cut in ролики:
        имя = чисто(pick.зовут(cut)) or slug.make(cut["id"].replace("+", "-"))
        хотят[cut["id"]] = имя
        сколько[имя] = сколько.get(имя, 0) + 1

    вышло = {}
    for cut in ролики:
        имя = хотят[cut["id"]]
        if сколько[имя] > 1:
            # Столкновение: ключ приписывается ОБОИМ. Не одному
            # «второму»: второй — это тот, кто попался позже при обходе
            # папки, а после переименования соседа он окажется первым.
            имя = f"{имя}--{cut['id']}"
        вышло[cut["id"]] = f"{имя}.mp4"
    return вышло


def развесить(project: Path) -> list[dict]:
    """Раздать всем роликам видео имена файлов. Переименовывает готовые.

    **Смена названия не пересобирает ролик**, а переименовывает лежащий
    файл: имя не меняет ни одного числа, из которых он собран.
    """
    ролики = pick.listing(project)
    if not ролики:
        return []

    как = как_назовутся(project, ролики)
    изменения = []
    for cut in ролики:
        новое = как[cut["id"]]
        старое = cut.get("файл")
        if старое == новое:
            continue
        папка = layout.cut(project, cut["id"])
        если_лежит = папка / старое if старое else None
        if если_лежит is not None and если_лежит.exists():
            если_лежит.rename(папка / новое)
            изменения.append({"id": cut["id"], "было": старое, "стало": новое,
                              "файл_переехал": True})
        else:
            изменения.append({"id": cut["id"], "было": старое, "стало": новое,
                              "файл_переехал": False})
        cut["файл"] = новое
        pick.update(project, cut)
    return изменения


def set_title(project: Path, ident: str, название: str | None) -> dict:
    """Задать своё название или вернуть расчётное.

    **Тронутое рукой не пересчитывается** — иначе человек, подвинувший
    границы на одно слово, теряет придуманное им название молча.
    Пустое значит «вернуть расчётное», и это отдельное решение,
    а не забывчивость.
    """
    cut = pick.load(project, ident)
    if название and название.strip():
        cut["название"] = " ".join(название.split())
        cut["своё_название"] = True
    else:
        cut.pop("своё_название", None)
        cut["название"] = pick.название(pick.pieces(cut))
    pick.update(project, cut)
    развесить(project)
    return pick.load(project, ident)
