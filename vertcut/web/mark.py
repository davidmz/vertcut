"""Отметка файла: не тронул ли его кто-то, пока человек правил.

## Зачем

Экран и терминал правят ОДНИ И ТЕ ЖЕ файлы. У долгой работы — разбора
и сборки — есть хозяин по номеру процесса (`works.py`), и второй
запуск получает отказ. У быстрых правок — название, рамка, текст
фразы, стиль — хозяина нет и не надо: они занимают миллисекунды.

Беда у них другая, и она тише. Экран прочитал `cut.json`, человек
минуту думал, тем временем из терминала в тот же файл легла правка,
экран записал своё — и чужая правка исчезла молча. У предка это
стоило потерянного монтажа: человек двигал рамки мышью, пока сессия
работала.

## Как

Экран запоминает отметку файла в тот момент, когда прочитал его,
и присылает её обратно вместе с правкой. Разошлась — отказ словами,
а не тихая перезапись.

**В отметку входят и время правки, и размер.** Одного времени мало:
у файловых систем оно бывает грубым (секунда), и две правки внутри
одной секунды выглядели бы одной. Размер не ловит правку «поменять
цифру на цифру», зато ловит почти всё остальное; вместе они ловят
заметно больше, чем каждый по себе.

**Это НЕ замок.** Двое одновременно записать по-прежнему могут — если
попадут в одну миллисекунду. Замок здесь был бы дороже беды: файлы
правятся за миллисекунды, а брошенный замок пришлось бы снимать
руками. Работа отметки в другом: не дать потерять правку, которую
человек СДЕЛАЛ и увидел на экране.

**Отметка не выдумывается для файла, которого нет.** «Нет файла» —
это своя отметка, и она честная: если файл за это время завёлся,
значит его кто-то завёл, и это тоже потерянная правка.
"""

from __future__ import annotations

from pathlib import Path

from ..errors import VertcutError

НЕТ_ФАЙЛА = "нет"


def снять(путь: Path) -> str:
    """Отметка файла на сейчас."""
    путь = Path(путь)
    if not путь.exists():
        return НЕТ_ФАЙЛА
    сведения = путь.stat()
    return f"{сведения.st_mtime_ns}-{сведения.st_size}"


def сверить(путь: Path, была: str | None, зовут: str) -> None:
    """Упасть словами, если файл тронули с тех пор, как его прочитали.

    `была` пустая — сверка не делается вовсе. Это не дыра, а решение:
    команда в терминале отметок не присылает, и требовать их от неё
    значило бы завести правило, которое половина сервиса не соблюдает.
    Отметку присылает тот, кто её получил, — экран.
    """
    if не_надо(была):
        return
    стало = снять(путь)
    if стало == была:
        return
    # Отметки «было/стало» человеку не показываются: это время
    # и размер файла числами, и ни на один его вопрос они не отвечают.
    raise VertcutError(
        f"{зовут} changed while you were editing.",
        hint=("it was probably edited in the terminal or in another tab. "
              "Reload the page and make your change again — saving over "
              "it would lose the other edit"))


def не_надо(была: str | None) -> bool:
    return была is None or была == ""
