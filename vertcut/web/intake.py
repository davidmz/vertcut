# Показать в папке
# ─────────────────────────────────────────────────────────────────────

# Спека называет эту кнопку прямо: «показать в папке». Дизайн рисует
# вместо неё «Скачать всё готовое», и это здесь не делается —
# по той же причине, по которой брошенный файл называет свою цену:
# готовые ролики УЖЕ лежат на диске этой машины, и «скачать» означало
# бы сложить рядом их вторую копию. Отдельный ролик скачать можно —
# там это одна кнопка на одну строку и человек знает, что берёт.

_ПОКАЗАТЬ = {"darwin": ["open", "-R"], "win32": ["explorer", "/select,"]}


def показать_в_папке(путь) -> dict:
    """Открыть папку в проводнике системы и подсветить в ней файл."""
    цель = Path(путь)
    if not цель.exists():
        raise VertcutError(f"Nothing to show: {цель} does not exist")

    если_маковский = _ПОКАЗАТЬ.get(sys.platform)
    if если_маковский:
        команда = [*если_маковский, str(цель)]
    elif shutil.which("xdg-open"):
        # У xdg-open нет «подсветить файл» — открывается сама папка.
        команда = ["xdg-open", str(цель if цель.is_dir() else цель.parent)]
    else:
        raise VertcutError(
            "Vertcut does not know how to open a folder on this system",
            hint=f"here is the path, open it yourself: {цель}")
    subprocess.run(команда, capture_output=True)
    return {"показано": str(цель)}
