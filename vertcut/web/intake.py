"""Как видео попадает в сервис. Два входа, и они стоят разного.

## Почему их два

**Браузер не отдаёт путь к файлу, только содержимое.** Это не наша
причуда и не обходится: так устроена всякая страница во всяком
браузере, и спека говорит об этом прямо. Отсюда развилка, у которой
нет правильной стороны:

**Бросить в окно** — привычно, работает везде, но файл КОПИРУЕТСЯ.
Двухчасовой подкаст на три гигабайта займёт на диске второй раз.
Молча удвоить занятое место — плохой сюрприз, поэтому цена называется
числом до того, как копирование началось.

**Выбрать на диске** — системный диалог открывает САМ СЕРВИС, и копии
нет: видео остаётся лежать где лежало. Дешевле, но диалог сервис умеет
открыть не везде — сегодня только на macOS, встроенным `osascript`.
Заводить ради него зависимость нельзя: она была бы оконной, а сервис
окон не рисует вовсе.

**Третий вход достался даром** — папка «Входящие». Она заводится для
брошенных файлов, а заодно отвечает на вопрос «где мои прошлые видео»
и служит запасной дорогой там, где системного диалога нет.

## Чего здесь нет

Ссылок. Дизайн рисует поле «или ссылкой» и кнопку «Забрать» — это
скачивание с площадок, то есть ещё одна зависимость и отдельный
разговор про правила площадок. В спеке ссылок нет; мёртвого поля
на экране тоже нет.
"""

from __future__ import annotations

import shutil
import subprocess
import sys
from pathlib import Path

from .. import layout
from ..errors import VertcutError

# Расширения, которые сервис знает в лицо. Список НЕ запрещающий:
# судит о видео `ffprobe`, а не имя файла, и отказ у него честный —
# «нет видеодорожки». Список нужен, чтобы предупредить ДО того, как
# человек скопирует три гигабайта чего-то не того, и чтобы системному
# диалогу было что показывать.
ЗНАКОМЫЕ = {".mp4", ".mov", ".mkv", ".m4v", ".avi", ".webm", ".mpg",
            ".mpeg", ".ts", ".wmv", ".flv"}

# Кусок, которым файл переливается на диск. Гигабайты в память
# не читаются: сервис должен работать на машине, где памяти четыре
# гигабайта, а видео — три.
КУСОК = 4 * 1024 * 1024

# Запас, который сервис требует сверх самого файла. Разбор кладёт рядом
# дорожку, уменьшенную копию и кадры планов; на двадцатиминутном видео
# это около полутора гигабайт. Число не замерено на чужом материале
# и намеренно грубое: его работа — не пустить человека в ситуацию,
# когда диск кончился посреди девятиминутного разбора.
ЗАПАС = 2 * 1024 * 1024 * 1024


def имя_файла(сырое: str) -> str:
    """Только имя, без единого шага в сторону.

    Имя приходит из браузера, то есть снаружи. `../../` в нём положило
    бы файл куда угодно на диске; пустое имя положило бы его в саму
    папку. Берётся последняя часть пути и ничего больше.
    """
    чистое = Path(str(сырое or "").replace("\\", "/")).name.strip()
    if not чистое or чистое in (".", ".."):
        raise VertcutError("The file has no name — Vertcut could not tell what was dropped")
    return чистое


def место(имя: str, размер: int) -> dict:
    """Что будет стоить принять этот файл — до того, как это началось.

    Отвечает на три вопроса разом: сколько свободно, хватит ли, и не
    лежит ли такой файл уже во «Входящих». Третий вопрос дороже, чем
    кажется: человек, бросивший то же видео второй раз, не должен
    копировать три гигабайта повторно.
    """
    чистое = имя_файла(имя)
    входящие = layout.inbox()
    входящие.mkdir(parents=True, exist_ok=True)
    свободно = shutil.disk_usage(входящие).free

    уже = входящие / чистое
    то_же_самое = уже.exists() and уже.stat().st_size == int(размер or 0)

    return {
        "имя": чистое,
        "размер": int(размер or 0),
        "свободно": свободно,
        "хватит": свободно >= int(размер or 0) + ЗАПАС,
        "запас": ЗАПАС,
        "уже_лежит": str(уже) if то_же_самое else None,
        "занято_другим": bool(уже.exists() and not то_же_самое),
        "знакомое": Path(чистое).suffix.lower() in ЗНАКОМЫЕ,
        "куда": str(входящие),
    }


def положить(имя: str, читать, сколько: int) -> Path:
    """Перелить брошенный файл во «Входящие». Возвращает путь.

    **Через времянку с переименованием.** Копирование трёх гигабайт
    идёт минуту, и оборванное на середине оставило бы обрезанный файл
    с настоящим именем — а такой файл выглядит целым. Готовое имя
    появляется только тогда, когда всё дошло.

    **Считаются байты.** Браузер обещает длину заранее; если пришло
    меньше, значит связь оборвалась, и молча принять огрызок значит
    отдать его разбору, который упадёт девятью минутами позже
    на чём-нибудь непонятном.
    """
    чистое = имя_файла(имя)
    входящие = layout.inbox()
    входящие.mkdir(parents=True, exist_ok=True)
    цель = входящие / чистое
    времянка = входящие / (чистое + ".part")

    пришло = 0
    try:
        with времянка.open("wb") as куда:
            while пришло < сколько:
                кусок = читать(min(КУСОК, сколько - пришло))
                if not кусок:
                    break
                куда.write(кусок)
                пришло += len(кусок)
        if пришло != сколько:
            raise VertcutError(
                f"Only part of the file arrived: {пришло} of {сколько} bytes",
                hint="the copy was probably interrupted — drop the file again")
        времянка.replace(цель)
    except BaseException:
        времянка.unlink(missing_ok=True)
        raise
    return цель


def входящие() -> list[dict]:
    """Что лежит во «Входящих». Отвечает на «а где мои прошлые видео»."""
    папка = layout.inbox()
    if not папка.exists():
        return []
    вышло = []
    for файл in sorted(папка.iterdir()):
        if not файл.is_file() or файл.name.startswith("."):
            continue
        if файл.suffix == ".part":
            continue          # копирование не доехало, файл обрезанный
        вышло.append({"имя": файл.name, "путь": str(файл),
                      "размер": файл.stat().st_size,
                      "знакомое": файл.suffix.lower() in ЗНАКОМЫЕ})
    return вышло


