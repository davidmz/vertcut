# Системный диалог
# ─────────────────────────────────────────────────────────────────────

ОТМЕНЁН = "отменён"

# Диалог просит именно у системы, а не у страницы. Причина в спеке:
# страница отдала бы содержимое, а нам нужен путь — файл должен
# остаться лежать где лежит.
#
# **Имена внутри — латиницей, и это не наш выбор.** AppleScript
# не понимает русских имён вовсе: `set выбранное to …` он отвергает
# на разборе, «Expected expression but found unknown token». Поймано
# проверкой скрипта на сборку до того, как он открыл первый диалог.
# Подпись при этом обычными словами — её читает человек, а не разборщик.
#
# `activate` отдельной строкой и ДО диалога: без него окно выбора
# открывается позади браузера, и человек решает, что кнопка не сработала.
# не для человека: в фигурных скобках — имена подстановок.
_ЯБЛОЧНЫЙ = '''tell application "System Events" to activate
set chosen to choose file with prompt "{подпись}" of type {{"{тип}"}}
POSIX path of chosen'''


def диалог_умеем() -> bool:
    return sys.platform == "darwin" and bool(shutil.which("osascript"))


def почему_не_умеем() -> str:
    """Отказ словами — и с дорогой, которая работает вместо этой."""
    if sys.platform != "darwin":
        return ("Choose file only works on macOS for now: the file picker "
                "is built into the system there, so nothing extra has to "
                "be installed.")
    return ("osascript was not found — Vertcut uses it to open the "
            "file picker.")


def выбрать_на_диске(подпись: str = "Choose a long video",
                     тип: str = "public.movie") -> str | None:
    """Открыть системный диалог. Путь, или `None`, если человек передумал.

    **Отмена — это не отказ.** Человек нажал «Отмена» ровно потому,
    что передумал; показывать ему после этого красную полосу значило бы
    ругать его за то, что он вправе сделать.
    """
    if not диалог_умеем():
        raise VertcutError(
            почему_не_умеем(),
            hint="drop the file into the window — it will be copied to "
                 "Inbox; or put it there yourself and it will show up "
                 "in the list")
    дело = subprocess.run(
        ["osascript", "-e", _ЯБЛОЧНЫЙ.format(подпись=подпись, тип=тип)],
        capture_output=True, text=True)
    if дело.returncode != 0:
        # 1 — «Отмена» в диалоге. Всё остальное — настоящая беда,
        # и её слова человеку показать надо.
        если_передумал = "User canceled" in (дело.stderr or "")
        if дело.returncode == 1 and если_передумал:
            return None
        raise VertcutError(
            "The file picker did not open",
            hint=(дело.stderr or "").strip() or "the system did not say why")
    путь = (дело.stdout or "").strip()
    if not путь:
        return None
    if not Path(путь).exists():
        raise VertcutError(f"The chosen file is not there anymore: {путь}")
    return путь


