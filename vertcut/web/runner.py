"""Долгая работа, запущенная с экрана: разбор и сборка.

## Отдельным процессом, а не потоком внутри сервера

Это главное решение файла, и причина в обещании: **разбор и сборка
переживают закрытую вкладку.** Потоком внутри сервера они пережили бы
её тоже — сервер-то работает. Но не пережили бы закрытый терминал,
а закрыть его человек вправе: девять минут — это время сходить
пообедать, а не сидеть и смотреть.

Своя группа процессов у каждой работы — не мелочь исполнения.
Разбор запускает ffmpeg детьми, и «остановить» без группы погасило бы
питон, оставив ffmpeg дожёвывать трёхгигабайтный файл.

## Состояние — на диске, и не здесь

Этот файл не помнит ничего. Кто сейчас работает — написано
в `работа.json`, и написал это сам работающий процесс, изнутри стадии.
Спроси мы у себя, а не у диска, — и работа, запущенная из терминала,
для экрана бы не существовала.

## Вывод уходит в файл

У запущенного отсюда процесса нет терминала. Его вывод — это ход
работы и, если она упадёт, причина падения. Терять её нельзя, и потому
она пишется рядом с разбором файлом, а экран показывает хвост.
"""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

from .. import layout, works
from ..errors import VertcutError

РАЗБОР = "разбор"
СБОРКА = "сборка"

# Сколько последних строк показывать человеку. Хвост, а не всё:
# у разбора вывод длинный, и причина падения лежит в конце — то же
# правило, по которому показывается хвост от ffmpeg.
ХВОСТ = 40


def файл_работы(project: Path, что: str) -> Path:
    """Где лежит состояние этой работы.

    Разбор и сборка не мешают друг другу: у сборки своё состояние —
    в очереди, потому что очередь и есть её состояние.
    """
    return layout.work(project) if что == РАЗБОР else layout.queue(project)


def идёт(project: Path, что: str = РАЗБОР) -> dict:
    """Что с этой работой прямо сейчас. Читается с диска, а не из памяти."""
    файл = файл_работы(project, что)
    состояние = works.прочитать(файл)
    хозяин = состояние.get("хозяин") or {}
    pid = int(хозяин.get("pid") or 0)
    жив = works.жив(pid)
    return {
        **{к: з for к, з in состояние.items() if к != "хозяин"},
        "идёт_сейчас": жив,
        "запускается": not жив and works.запускается(состояние),
        "не_запустилась": not жив and works.не_запустилась(состояние),
        # Хозяин, который умер, не соврав: работа была, её убили или
        # она упала. Показать это надо, а не притвориться, что ничего
        # не было.
        "брошено": bool(хозяин) and not жив,
        "pid": pid if жив else None,
        "хвост": хвост(project, что),
    }


def хвост(project: Path, что: str) -> list[str]:
    путь = layout.log(project, что)
    if not путь.exists():
        return []
    строки = путь.read_text(encoding="utf-8", errors="replace").splitlines()
    return строки[-ХВОСТ:]


def запустить(project: Path, что: str, слова: list[str]) -> dict:
    """Пустить работу своим процессом. Возвращает её номер.

    Хозяина ставит НЕ здесь, а сама стадия — изнутри. Поставь его тут,
    и работа из терминала прошла бы поверх идущей с экрана: между
    «проверили» и «начали» помещается целая чужая команда.
    """
    файл = файл_работы(project, что)
    состояние = works.прочитать(файл)
    хозяин = состояние.get("хозяин") or {}
    if хозяин and works.жив(int(хозяин.get("pid") or 0)):
        raise VertcutError(
            f"Already running: {хозяин.get('что')} — process {хозяин['pid']}, "
            f"since {хозяин.get('когда')}",
            hint="wait for it to finish, or stop it — the stop button is next to it")

    # Отмечаем ДО запуска: между «пустили» и «взялась» проходит время
    # — процессу надо подняться и посчитать отпечаток исходника, —
    # и всё это время экран обязан показывать, что работа пошла.
    works.пуск(файл, что)

    лог = layout.log(project, что)
    лог.parent.mkdir(parents=True, exist_ok=True)
    поток = лог.open("ab")
    try:
        процесс = subprocess.Popen(
            [sys.executable, "-m", "vertcut", *слова],
            stdout=поток, stderr=subprocess.STDOUT, stdin=subprocess.DEVNULL,
            # Своя группа процессов. Ради неё всё и затевалось:
            # «остановить» гасит работу вместе с её ffmpeg, а не только
            # питон, который его ждёт.
            start_new_session=True,
            # **`VERTCUT_HOME` здесь НЕ ВЫСТАВЛЯЕТСЯ, и это починка.**
            #
            # Раньше сюда клалось `VERTCUT_HOME = layout.root()` — ради
            # того, чтобы работа из песочницы проверки не ушла в живую
            # папку человека. Толку от этого не было никакого: когда
            # песочница есть, переменная уже стоит в окружении и едет
            # с ним сама; когда её нет, `layout.root()` отвечает тем же
            # самым «~/vertcut».
            #
            # А вред был, и он молчал полторы сессии. Эта переменная
            # перебивает НЕ ТОЛЬКО корень разборов: от неё же считается
            # папка настроек — `$VERTCUT_HOME/.настройки`. Выставив её
            # там, где её не было, сервис отправлял свою же сборку
            # искать настройки в `~/vertcut/.настройки` вместо
            # `~/.vertcut`. Туда же уехали бы и свои шрифты человека,
            # и его личный образец профиля.
            #
            # Вылезло это на фоне плашки — автор положил фон, экран его
            # показывал, а сборка падала словами «фона нет там, где
            # сервис его ищет», и путь в отказе был не тот, что на
            # экране. Спасибо отказу, который печатает ПУТЬ, а не
            # «файл не найден».
            env={**os.environ, "PYTHONUNBUFFERED": "1"},
        )
    finally:
        поток.close()
    return {"pid": процесс.pid, "что": что, "лог": str(лог)}


def остановить(project: Path, что: str) -> dict:
    """Погасить работу вместе с её детьми."""
    return works.остановить(файл_работы(project, что))
