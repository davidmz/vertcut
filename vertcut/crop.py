"""Предложение рамки на каждый план.

Из горизонтального кадра в вертикаль полной высоты идёт колонка около
трети ширины. Что в неё попало, решает качество ролика сильнее всего
остального, поэтому центр колонки предлагает машина, а последнее слово
за человеком.

**Машина предлагает, рука сильнее.** Предложенное лежит в `shots.json`
и пересчитывается свободно; правка руки живёт в самом ролике
(`cut.json`). Слить их в одно поле значило бы стереть правку при первом
пересчёте — молча и через месяц.

**Кадры берутся из исходника, а не из уменьшенной копии, и это замер.**
Копия в семь раз быстрее, но у каждого двенадцатого плана ставит
колонку совсем не туда, а у каждого двадцать пятого меняет само
решение «лицо или центр». Копия не врёт детектору СКЛЕЕК — это разные
задачи: склейка это «насколько кадр непохож на предыдущий», и мелочь
на неё не влияет; лицо — это мелочь и есть.

**Считается по ролику, а не по всему видео.** Это самая дорогая работа
в сервисе. В видео сотни планов, в ролик попадают десятки — кто открыл
ролик, тот и платит за его планы.

**Лиц нет — окно встаёт по центру, и это записывается.** Умнее здесь
не делается намеренно: план уже выбран автором видео, машина отвечает
только за то, какая его полоса попадёт в вертикаль.
"""

from __future__ import annotations

import shutil
import tempfile
from pathlib import Path

from . import faces, layout, media, report, tuning


def половина_окна(ширина: int, высота: int) -> float:
    """Половина ширины вертикального окна, долей кадра."""
    return высота * tuning.VERTICAL / 2 / ширина


def прижать(cx: float, ширина: int, высота: int) -> float:
    """Центр ОКНА, а не центр лица: окно не может свисать за край кадра.

    Лицо у самого края даёт окно, прижатое к краю, и это правильно —
    оно всё равно попадёт в вертикаль, просто не по центру.
    """
    половина = половина_окна(ширина, высота)
    return round(min(max(cx, половина), 1 - половина), 4)


def на_кадре(путь: Path) -> tuple[float | None, int]:
    """Центр самого крупного лица на одном кадре и ширина кадра."""
    кадр = faces.прочитать(путь)
    высота, ширина = кадр.shape[:2]
    найденные = faces.найти(кадр, tuning.FACE_CONF)
    return faces.самое_крупное(найденные, ширина), ширина


def compute(source: Path, found: list[dict], project: Path,
            только: set[int] | None = None, говорить=report.скажи,
            ход=None) -> dict:
    """Проставить рамку планам. Меняет `found` на месте."""
    дела = [s for s in found if только is None or s["idx"] in только]
    if not дела:
        return {"shots": 0, "by_face": 0, "by_center": 0, "panning": 0}

    # Своя временная папка на каждый счёт, а не общая. Рамки считаются
    # по ролику, и два счёта могут идти разом. Общая папка в таком
    # случае стирается из-под соседа, и он падает на «ffmpeg не отдал
    # кадр»: сообщение правдивое и совершенно бесполезное.
    layout.frames(project).mkdir(parents=True, exist_ok=True)
    работа = Path(tempfile.mkdtemp(prefix="crop-", dir=layout.frames(project)))

    try:
        # Времена всех кадров разом: один проход по тяжёлому исходнику
        # вместо трёх поисков на каждый план.
        времена, хозяин = [], []
        for план in дела:
            for доля in tuning.FRAMES_AT:
                при = план["start"] + план["duration"] * доля
                # Шаг от конца плана — чтобы кадр был ЭТОГО плана.
                # Конец картинки, который бывает раньше конца файла,
                # стережёт `media.grab_frames`.
                времена.append(min(при, max(план["end"] - 0.04, план["start"])))
                хозяин.append(план["idx"])

        говорить(f"  taking {len(времена)} frames from the original "
                 f"(about {len(времена) * 0.3:.0f} s)")
        вышло = media.grab_frames(
            source, времена, работа, tuning.CROP_FRAME_WIDTH,
            on_tick=lambda n, всего: говорить(f"    frames: {n} of {всего}"))
        if len(вышло) != len(времена):
            from .errors import VertcutError
            raise VertcutError(
                f"Got {len(вышло)} frames, expected {len(времена)} — "
                "they would not match their shots, and a crop would "
                "come from the wrong frame")

        по_планам: dict[int, list[Path]] = {}
        for idx, путь in zip(хозяин, вышло):
            по_планам.setdefault(idx, []).append(путь)

        говорить(f"  looking for faces in {len(дела)} shots")
        с_лицом = 0
        for n, план in enumerate(дела, 1):
            центры, ширина, высота = [], 0, 0
            for путь in по_планам.get(план["idx"], []):
                кадр = faces.прочитать(путь)
                высота, ширина = кадр.shape[:2]
                центр = faces.самое_крупное(
                    faces.найти(кадр, tuning.FACE_CONF), ширина)
                if центр is not None:
                    центры.append(центр)
            if центры:
                с_лицом += 1
                разброс = (round(max(центры) - min(центры), 3)
                           if len(центры) > 1 else 0.0)
                план["crop_cx"] = прижать(sum(центры) / len(центры),
                                          ширина, высота)
                план["crop_by"] = "face"
                план["crop_spread"] = разброс
            else:
                план["crop_cx"] = 0.5
                план["crop_by"] = "center"
                план["crop_spread"] = 0.0
            if ход:
                ход(n, len(дела), "shots")
            if n % 50 == 0:
                говорить(f"    {n} of {len(дела)}")
    finally:
        shutil.rmtree(работа, ignore_errors=True)

    панорам = sum(1 for s in дела
                  if (s.get("crop_spread") or 0) >= tuning.PAN_SPREAD)
    return {"shots": len(дела), "by_face": с_лицом,
            "by_center": len(дела) - с_лицом, "panning": панорам}


def посчитать(source: Path, project: Path, только: set[int] | None = None,
              говорить=report.скажи, ход=None) -> dict:
    """Посчитать рамки и записать их. Одно место на стадию и на команду.

    **Заведено потому, что мест стало два.** Рамка кадра — теперь пятая
    стадия разбора, и она же осталась отдельной командой: перемерить
    рамки на части планов надо уметь, не переделывая разбор. Две копии
    «посчитать и записать» разошлись бы в том, записывается ли
    результат, — и разошлись бы молча.
    """
    from . import shots as планы

    найдено = планы.read(project)
    итог = compute(source, найдено, project, только, говорить, ход)
    планы.write(найдено, project)
    return итог
