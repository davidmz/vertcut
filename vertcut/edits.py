"""Правка фраз рукой: разделить, склеить, поправить текст.

**Правка живёт у РОЛИКА, а не у видео.** Расшифровка остаётся такой,
какой её услышала машина; меняется только субтитр. Отсюда прямое
следствие, и оно нарочное: два ролика из одного видео могут иметь
разные правки, и это нормально. Один и тот же кусок в одном ролике
может быть подписан подробно, а в другом коротко.

**Правка привязана к НОМЕРАМ СЛОВ, а не к номерам фраз.** Причина
та же, по которой в словах считается ключ ролика: номера фраз
переезжают. Перенарезали видео другими правилами, поправили сценарий —
и правка, записанная на «фразу 247», молча легла бы на другое место.
Номера слов не двигаются: слова — это то, из чего посчитано всё
остальное.

**Правка текста не двигает границ ролика.** Новый текст раскладывается
внутри прежнего окна фразы, по длине слов. Субтитр от этого может
встать на десятую секунды иначе — это видно и это правда; молча
растянуть окно значило бы поменять длину ролика от того, что человек
исправил букву.

Три правки, и все три выражены через одно — через шов между словами:

- **разделить** — поставить шов после слова N;
- **склеить** — снять шов после слова N;
- **текст** — заменить слова с N по M на другие.
"""

from __future__ import annotations

from . import align
from .errors import VertcutError

# Где правки лежат в `cut.json`.
КЛЮЧ = "правки_фраз"

РАЗДЕЛИТЬ, СКЛЕИТЬ, ТЕКСТ = "разделить", "склеить", "текст"


def список(cut: dict) -> list[dict]:
    return list(cut.get(КЛЮЧ) or [])


def положить(cut: dict, правки: list[dict]) -> None:
    """Записать правки в ролик. Пусто — ключа нет вовсе.

    Пустой список в файле означал бы «правок нет, но кто-то тут был»,
    а это разные вещи только для человека, читающего файл. Для сервиса
    они одно, и лишний ключ через полгода читается как забытый долг.
    """
    if правки:
        cut[КЛЮЧ] = sorted(правки, key=_порядок)
    else:
        cut.pop(КЛЮЧ, None)


def _порядок(правка: dict):
    return (int(правка.get("с", правка.get("после", 0))),
            str(правка.get("что", "")))


def описать(правка: dict) -> str:
    что = правка.get("что")
    if что == РАЗДЕЛИТЬ:
        return f"split after word {правка['после']}"
    if что == СКЛЕИТЬ:
        return f"merge with the next phrase at word {правка['после']}"
    if что == ТЕКСТ:
        return (f"text of words {правка['с']}–{правка['по']}: "
                f"“{правка['текст']}”")
    return str(правка)


# ─────────────────────────────────────────────────────────────────────
# Наложение
# ─────────────────────────────────────────────────────────────────────

def наложить(фразы: list[dict], правки: list[dict] | None) -> list[dict]:
    """Фразы ролика с наложенными правками.

    **Порядок нарочный: сперва швы, потом текст.** Причина в том, как
    правка записывается: человек называет фразу, которую ВИДИТ, а видит
    он её уже разделённой или склеенной. Наложи текст первым — и правка,
    записанная на половину разделённой фразы, легла бы в пустоту.

    Обратный случай тоже возможен: поправили текст целой фразы, а потом
    её разделили. Тогда правка текста не ляжет и об этом будет сказано
    словами — записать её заново на нужную половину дешевле, чем гадать,
    какой половине она предназначалась.

    **Не легло — падаем словами, а не молчим.** Правка, записанная
    на слова, которых в ролике больше нет, значит, что границы куска
    переехали. Молча её потерять — это субтитр не тот, и увидит это
    зритель.
    """
    вышло = [dict(ф) for ф in фразы]
    if not правки:
        return вышло
    швы = [п for п in правки if п.get("что") in (РАЗДЕЛИТЬ, СКЛЕИТЬ)]
    тексты = [п for п in правки if п.get("что") == ТЕКСТ]
    чужие = [п for п in правки
             if п.get("что") not in (РАЗДЕЛИТЬ, СКЛЕИТЬ, ТЕКСТ)]
    if чужие:
        raise VertcutError(f"Unknown phrase edit: {чужие[0]}")

    for правка in sorted(швы, key=_порядок):
        if правка["что"] == РАЗДЕЛИТЬ:
            вышло = _разделить(вышло, правка)
        else:
            вышло = _склеить(вышло, правка)
    for правка in sorted(тексты, key=_порядок):
        вышло = _поправить_текст(вышло, правка)
    вышло.sort(key=lambda ф: ф["at"])
    return вышло


def _найти(фразы: list[dict], слово: int) -> int:
    for n, ф in enumerate(фразы):
        if ф["с"] <= слово <= ф["по"]:
            return n
    raise VertcutError(
        f"A phrase edit no longer fits: word {слово} isn't in this clip "
        "any more.",
        hint="the segment boundaries moved — reset the phrase edits in the "
             "subtitle editor")


def _поправить_текст(фразы: list[dict], правка: dict) -> list[dict]:
    n = _найти(фразы, int(правка["с"]))
    ф = фразы[n]
    if (ф["с"], ф["по"]) != (int(правка["с"]), int(правка["по"])):
        raise VertcutError(
            f"A text edit no longer fits: it was made for words "
            f"{правка['с']}–{правка['по']}, but the phrase here runs "
            f"from word {ф['с']} to {ф['по']}.",
            hint="the phrase was split or merged since — reset the edit "
                 "and type it again in the subtitle editor")
    новые = разложить(str(правка["текст"]), ф["at"], ф["till"])
    if not новые:
        raise VertcutError("The text edit has no words in it")
    фразы[n] = {**ф, "words": новые, "правлено": True,
                "at": новые[0]["s"], "till": новые[-1]["e"]}
    return фразы


def разложить(текст: str, при: float, до: float) -> list[dict]:
    """Слова нового текста внутри прежнего окна фразы.

    Время делится пропорционально длине слов — тем же правилом, каким
    укладка делит спорный участок между словами сценария. Это прикидка,
    и она называется прикидкой: у слов стоит пометка `a`.

    Ровнее не сделать: где именно в этих двух секундах человек сказал
    исправленное слово, не знает никто. Мерить нечего — исходное слово
    было расслышано неверно.
    """
    формы = align.surfaces(текст)
    if not формы:
        return []
    веса = [max(len(align.words(ф)[0]) if align.words(ф) else 1, 1)
            for ф in формы]
    всего = sum(веса) or 1
    длина = max(float(до) - float(при), 0.0)
    вышло, курсор = [], float(при)
    for форма, вес in zip(формы, веса):
        шаг = длина * вес / всего
        вышло.append({"w": форма, "s": round(курсор, 3),
                      "e": round(курсор + шаг, 3), "a": "правка"})
        курсор += шаг
    вышло[-1]["e"] = round(float(до), 3)
    return вышло


def _разделить(фразы: list[dict], правка: dict) -> list[dict]:
    после = int(правка["после"])
    n = _найти(фразы, после)
    ф = фразы[n]
    if после >= ф["по"]:
        raise VertcutError(
            f"Can't split after word {после}: the phrase already ends "
            "there.",
            hint="the split goes AFTER the word you name")
    сколько = после - ф["с"] + 1
    слева, справа = ф["words"][:сколько], ф["words"][сколько:]
    if not слева or not справа:
        raise VertcutError(
            f"Can't split after word {после}: one half would be empty")
    фразы[n:n + 1] = [
        {**ф, "по": после, "words": слева,
         "at": слева[0]["s"], "till": слева[-1]["e"], "целая": False},
        {**ф, "с": после + 1, "words": справа,
         "at": справа[0]["s"], "till": справа[-1]["e"], "целая": False},
    ]
    return фразы


def _склеить(фразы: list[dict], правка: dict) -> list[dict]:
    после = int(правка["после"])
    n = _найти(фразы, после)
    ф = фразы[n]
    if после != ф["по"]:
        raise VertcutError(
            f"Can't merge at word {после}: the phrase ends at word "
            f"{ф['по']}.",
            hint="Merge joins a phrase with the next one, at its end")
    if n + 1 >= len(фразы):
        raise VertcutError(
            "Nothing to merge with: this is the clip's last phrase")
    сосед = фразы[n + 1]
    if сосед["с"] != после + 1:
        raise VertcutError(
            "Can't merge across a gap: the next phrase starts at word "
            f"{сосед['с']}, and this one ends at {после}.",
            hint="part of the video between them was left out — "
                 "a merged subtitle would hang over the cut")
    if сосед.get("кусок") != ф.get("кусок"):
        raise VertcutError(
            "Can't merge phrases from different segments of the clip: "
            "there's a cut between them, and the subtitle would hang "
            "across it")
    фразы[n:n + 2] = [{**ф, "по": сосед["по"],
                       "words": [*ф["words"], *сосед["words"]],
                       "at": ф["at"], "till": сосед["till"],
                       "целая": False}]
    return фразы


# ─────────────────────────────────────────────────────────────────────
# Запись правки
# ─────────────────────────────────────────────────────────────────────
#
# **Правка адресуется НОМЕРАМИ СЛОВ, и на экране это оказалось не
# лишней строчкой, а единственной дорогой.** В терминале человек
# называет номер фразы по списку видео, и перевод в слова делает
# команда. На экране он тыкает в строку субтитра — то есть во фразу
# УЖЕ разделённую или склеенную, которой в разборе нет вовсе, и номера
# у неё нет. Зато у неё есть номера слов: `с` и `по` лежат в каждой
# фразе раскладки ролика.
#
# Отсюда и вид этих функций: они принимают слова, а не фразы. Команда
# переводит номер фразы в слова у себя и зовёт их же.

def записать(cut: dict, правка: dict) -> dict:
    """Положить правку в ролик. Та же правка второй раз — замена.

    Иначе на одну фразу легли бы два текста, и который из них
    победит, решал бы порядок в списке.
    """
    правки = [п for п in список(cut)
              if not (п.get("что") == правка.get("что")
                      and п.get("с", п.get("после")) ==
                      правка.get("с", правка.get("после")))]
    правки.append(правка)
    положить(cut, правки)
    return правка


def поправить_текст(cut: dict, с: int, по: int, текст: str) -> dict:
    """Заменить текст фразы. Границ ролика это не двигает.

    Новый текст раскладывается внутри прежнего окна фразы по длине
    слов, и у этих слов стоит пометка «прикидка». Ровнее не сделать:
    где именно человек сказал исправленное слово, не знает никто —
    исходное расслышано неверно, мерить нечего.
    """
    if not str(текст).strip():
        raise VertcutError(
            "The subtitle text is empty",
            hint="to get rid of a phrase, merge it with the one next to "
                 "it, or reset the text edits")
    return записать(cut, {"что": ТЕКСТ, "с": int(с), "по": int(по),
                          "текст": str(текст)})


def разделить_после(cut: dict, слово: int) -> dict:
    """Разрезать фразу после этого слова."""
    return записать(cut, {"что": РАЗДЕЛИТЬ, "после": int(слово)})


def склеить_после(cut: dict, слово: int) -> dict:
    """Склеить фразу, кончающуюся этим словом, со следующей."""
    return записать(cut, {"что": СКЛЕИТЬ, "после": int(слово)})


def снять(cut: dict, с: int | None = None, по: int | None = None) -> int:
    """Снять правки. Без границ — все. Возвращает, сколько сняли."""
    было = список(cut)
    if с is None:
        положить(cut, [])
        return len(было)
    осталось = [п for п in было
                if not (int(с) <= int(п.get("с", п.get("после", -1)))
                        <= int(по if по is not None else с))]
    положить(cut, осталось)
    return len(было) - len(осталось)
