"""Ошибка, которую видно человеку без трейсбека.

Тип свой. Причина записана в спеке прямо: чужой тип ошибки — это
зависимость, которая ничего не делает. Здесь она была бы вдвойне
бессмысленной: чужого проекта рядом нет вовсе, и в этом весь замысел.

`hint` — что именно сделать, чтобы починить. Обычно команда.
Разделение нарочное: первая строка говорит, ЧТО случилось, подсказка —
что нажать. Слепив их в одну строку, теряешь подсказку в потоке слов,
а она самое нужное в отказе.
"""

from __future__ import annotations


class VertcutError(Exception):
    def __init__(self, message: str, hint: str | None = None):
        super().__init__(message)
        self.message = message
        self.hint = hint
