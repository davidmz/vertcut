// Разговор с сервисом.
//
// Одно место на все просьбы, и заведено оно из-за отказов. У сервиса
// отказ устроен по правилу: первая строка — что случилось, вторая —
// что делать. Разбирай это в каждой кнопке по отдельности — и половина
// кнопок однажды покажет «ошибка», проглотив подсказку, которая
// и есть самое нужное.
//
// ПРОПУСК запуска лежит в адресе страницы и прикладывается к каждой
// просьбе заголовком. Без него сервис не отвечает: любая другая
// страница, открытая в том же браузере, тоже может постучаться
// на 127.0.0.1, и браузер послушно приложит её запрос.
//
// **Пропуск, а не «ключ».** Слово «ключ» тут занято ключом ролика,
// и пока оба звались одинаково, они затирали друг друга в одном
// адресе: у картинки вертикалки пропуск подменялся ключом ролика,
// и сервис отвечал отказом на каждый кадр.
//
// Имя заголовка латиницей нарочно: имена заголовков в HTTP обязаны
// быть видимой латиницей, русское браузер отправлять откажется.

const ПРОПУСК = 'pass';
const пропуск = new URLSearchParams(location.search).get(ПРОПУСК) || '';

export class Беда extends Error {
  // `вид` приезжает с сервера словом, а не угадывается по тексту.
  // Сегодня видов два: обычная беда и «дорого» — вопрос про деньги,
  // который экран показывает полосой с кнопкой, а не красным.
  // не для человека: «беда» — значение договора с сервером, а не слово.
  constructor(что, подсказка, вид = 'беда', ещё = {}) {
    super(что);
    this.что = что;
    this.подсказка = подсказка || '';
    this.вид = вид;
    Object.assign(this, ещё);
  }

  get дорого() { return this.вид === 'дорого'; }
}

// Сервис погашен кнопкой «Quit Vertcut» — дальше страница молчит.
//
// Экраны разбора, вертикалки и сборки спрашивают сервис по часам,
// и каждый такой вопрос после выхода кончился бы полосой «Vertcut is
// not responding» — а то и перерисовкой поверх последнего экрана
// «Vertcut has stopped». Просьбы после выхода не уходят и не кончаются
// ничем: ответа на них нет и не будет, и сказать об этом уже сказано.
let молчим = false;

export function замолчать() { молчим = true; }

const никогда = () => new Promise(() => {});

export async function взять(имя, параметры = {}) {
  if (молчим) return никогда();
  const адрес = new URL('/апи/' + имя, location.origin);
  for (const [к, з] of Object.entries(параметры)) {
    if (з !== null && з !== undefined && з !== '') адрес.searchParams.set(к, з);
  }
  return await разобрать(fetch(адрес, { headers: { 'X-Vertcut-Pass': пропуск } }));
}

export async function послать(имя, тело = {}) {
  if (молчим) return никогда();
  return await разобрать(fetch('/апи/' + имя, {
    method: 'POST',
    headers: { 'X-Vertcut-Pass': пропуск, 'Content-Type': 'application/json' },
    body: JSON.stringify(тело),
  }));
}

// Адрес картинки или файла, который отдаёт сервис. Здесь пропуск идёт
// в самом адресе, а не заголовком: <img>, <audio> и <a download>
// заголовков не носят вовсе.
export function адрес(имя, параметры = {}) {
  const у = new URL('/апи/' + имя, location.origin);
  for (const [к, з] of Object.entries(параметры)) {
    if (з !== null && з !== undefined && з !== '') у.searchParams.set(к, з);
  }
  // Пропуск ставится ПОСЛЕДНИМ и своим именем: затереть его чужим
  // значением больше нечем.
  у.searchParams.set(ПРОПУСК, пропуск);
  return у.pathname + у.search;
}

async function разобрать(обещание) {
  let ответ;
  try {
    ответ = await обещание;
  } catch (е) {
    // Сюда попадаем, когда сервиса на том конце нет вовсе: человек
    // закрыл терминал, где запущен экран. Сказать это надо прямо,
    // а не «не удалось выполнить запрос».
    throw new Беда(
      'Vertcut is not responding.',
      'It looks like it has stopped. Start it again with the Vertcut ' +
      'icon, or with vertcut screen in a terminal.');
  }
  const тип = ответ.headers.get('Content-Type') || '';
  if (!тип.includes('application/json')) {
    const текст = await ответ.text();
    throw new Беда(текст || `Vertcut sent an unexpected answer (${ответ.status}).`, '');
  }
  const это = await ответ.json();
  if (!ответ.ok) {
    throw new Беда(это.беда || 'That did not work.', это.подсказка, это.вид,
                   { сколько: это.сколько, порог: это.порог,
                     слаг: это.слаг, ключ: это.ключ });
  }
  return это;
}
