// Вход страницы: кто что показывает и как между этим ходят.
//
// **Экран не держит состояние.** Всё, что он показывает, читается
// с диска в момент показа; всё, что человек меняет, ложится на диск
// сразу. Закрыл вкладку — не потерялось ничего, потому что терять
// нечего: разбор и сборка идут своими процессами и пишут своё
// состояние сами.
//
// Отсюда и устройство переходов: адрес страницы — это и есть всё
// состояние экрана. Обновил страницу — оказался ровно там же.

import { ждём, сказать_беду, убрать_полосы, запомнить_ai } from './shell.js';
import * as адрес from './route.js';
import * as связь from './api.js';
import * as видео from './screens/videos.js';
import * as разбор from './screens/ingest.js';
import * as фрагменты from './screens/picks.js';
import * as вертикалка from './screens/cut.js';
import * as сборка from './screens/render.js';
import * as субтитры from './screens/subs.js';
import * as описания from './screens/notes.js';
import * as настройки from './screens/settings.js';
import * as помощь from './screens/help.js';

// Куда ведёт какой адрес. Ключ — первое слово после решётки,
// остальное отдаётся экрану как есть.
const ЭКРАНЫ = {
  'videos': видео.показать,
  'analysis': разбор.показать,
  'segments': фрагменты.показать,
  'clip': вертикалка.показать,
  'export': сборка.показать,
  'subtitles': субтитры.показать,
  'descriptions': описания.показать,
  'settings': настройки.показать,
  'help': помощь.показать,
};

const НАЧАЛЬНЫЙ = 'videos';

// Маршрутизатор отдаётся наружу нарочно: его зовёт проба экрана
// (`tests/screen-probe.mjs`). Проверять маршрут её собственной копией
// разбора адреса — значит проверять копию, а не маршрут.

export async function куда_идти() {
  const [имя, ...хвост] = адрес.части();
  const показать = ЭКРАНЫ[имя || НАЧАЛЬНЫЙ];
  if (!показать) {
    адрес.идти(НАЧАЛЬНЫЙ);
    return;
  }
  // Полосы — про то, что ТОЛЬКО ЧТО случилось. Ушёл человек с экрана
  // — они своё отработали: «вертикалка создана» на экране сборки
  // читается как «создана прямо сейчас», а она создана десять минут
  // назад и на другом шаге.
  убрать_полосы();
  try {
    // Состояние ключа освежается перед КАЖДЫМ показом: подвал колонки
    // стоит на всех экранах, и показывать там вчерашнее значило бы
    // врать про то, за что человек платит.
    //
    // Отказ здесь не должен рушить переход: без ключа сервис работает
    // целиком, и экран, не открывшийся из-за подвала, — это ровно
    // то, чего в этой сессии допускать нельзя.
    try { запомнить_ai(await связь.взять('ai')); }
    catch (беда) { сказать_беду(беда); }
    await показать(хвост);
  } catch (беда) {
    // Отказ на переходе не оставляет человека перед пустым экраном:
    // рисуется тот экран, куда всегда можно вернуться, а поверх него
    // — полоса с тем, что случилось.
    if (имя && имя !== НАЧАЛЬНЫЙ) {
      try { await ЭКРАНЫ[НАЧАЛЬНЫЙ]([]); } catch (_) { /* скажем ниже */ }
    }
    сказать_беду(беда);
  }
}

// Проверка окружения — отдельно и потом. Она поднимает каждую
// библиотеку по имени, а это секунды; ждать их, глядя в пустой экран,
// человек не должен. Молчит, пока всё на месте.
async function проверить_окружение() {
  try {
    const это = await связь.взять('окружение');
    if (это.всё_на_месте) return;
    const { сказать } = await import('./shell.js');
    сказать({
      вид: 'bad',
      что: 'Something Vertcut needs is missing — videos cannot be analyzed.',
      // Что именно не хватает, говорит СЕРВИС. Раньше эта строка
      // собиралась здесь: взять отчёт и оставить строки, в которых
      // есть буквы «НЕ». Беда, назвавшаяся иначе, пропадала молча —
      // а таких в проекте сразу две: «ЕСТЬ, но сервис его не видит»
      // и «ПОСТАВЛЕНА, но не загружается».
      делать: (это.не_хватает || []).join('; ')
        || 'for details, run vertcut check in a terminal',
    });
  } catch (беда) {
    сказать_беду(беда);
  }
}

// Незнакомая поломка не оставляет человека перед пустым экраном.
//
// Правило проекта — никаких заглушек, молча возвращающих пустоту —
// на странице работает так же, как в сервисе. Всё, что мы поймали
// сами, приезжает полосой; всё, чего не поймали, приезжает этой.
function поломка(что) {
  сказать_беду({
    что: 'The page broke: ' + (что && что.message ? что.message : что),
    подсказка: 'This is not Vertcut refusing — the page itself broke. ' +
               'Details are in the browser console: Cmd+Option+J.',
  });
}

window.addEventListener('error', (е) => поломка(е.error || е.message));
window.addEventListener('unhandledrejection', (е) => поломка(е.reason));

window.addEventListener('hashchange', куда_идти);

ждём('loading your videos…');
куда_идти().then(проверить_окружение);
