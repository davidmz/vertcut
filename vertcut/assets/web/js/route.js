// Адрес экрана — одно место на всю страницу.
//
// **Заведено потому, что мест было тридцать, и все они ошибались
// одинаково.** Имена экранов тогда были русскими (`#разбор/{слаг}`;
// с 22-й сессии — `#analysis/{слаг}`).
// Записать такой адрес браузер даёт, а вот читает его обратно
// В ПРОЦЕНТАХ: `location.hash` возвращает
// `#%D1%80%D0%B0%D0%B7%D0%B1%D0%BE%D1%80/…`.
//
// Отсюда две беды подряд, и обе выглядели как «сервис не слушается»:
//
//   · маршрутизатор не узнавал экран и молча уводил на начальный —
//     щелчок по видео не открывал ничего;
//   · часы, которые обновляют идущую работу, спрашивали «мы ещё
//     на этом экране?» через `startsWith('#разбор')`, получали «нет»
//     и умирали на первом же тике. Разбор шёл, а экран стоял
//     на «запускается» до обновления страницы.
//
// Ни одна из них не давала ни поломки, ни отказа. Поэтому адрес
// читается и пишется здесь, и больше нигде — то же правило, по
// которому все пути на диске собирает `layout.py`.

export function читать() {
  const сырой = location.hash.replace(/^#/, '');
  try {
    return decodeURIComponent(сырой);
  } catch (_) {
    // Битые проценты — это не наш адрес. Пусть маршрутизатор отправит
    // человека на начальный экран, а не упадёт здесь.
    return сырой;
  }
}

export function части() {
  return читать().split('/').filter(Boolean);
}

// На каком экране мы сейчас. Спрашивают это часы, которые обновляют
// идущую работу: ушёл человек с экрана — часам конец.
export function на_экране(имя) {
  return части()[0] === имя;
}

// Пойти на экран. Части склеиваются здесь, чтобы никто не собирал
// адрес руками: одна забытая косая — и переход ведёт в пустоту.
export function идти(...куда) {
  location.hash = '#' + куда.filter(Boolean).join('/');
}
