// Экраны 01 · Первый вход и 02 · Видео.
//
// Это один экран в двух состояниях, а не два разных. Пусто — сервис
// показывает одно поле и одну кнопку, ничего не объясняя абзацем;
// появилось хоть одно видео — та же работа переезжает в колонку
// и футбар, а середину занимает список.
//
// Чего здесь нет и почему:
//
//   · **поля «или ссылкой»** — это скачивание с площадок: ещё одна
//     зависимость и отдельный разговор про их правила. В спеке ссылок
//     нет, а мёртвое поле — первое, на что человек нажмёт;
//   · **карточки «AI — по желанию»** с кнопкой «Подключить ключ» —
//     ключ это пятая сессия, а кнопка, которая ничего не делает,
//     хуже её отсутствия.

import {
  нарисовать, лого, блок, эл, моно, метка, положить, растяжка, сказать,
  сказать_беду, убрать_полосы, подвал, выйти_кнопкой,
} from '../shell.js';
import * as связь from '../api.js';
import * as слова from '../words.js';
import * as приём from '../intake.js';
import * as адрес from '../route.js';

export async function показать() {
  // Читается заново на каждом заходе. Экран не помнит ничего: список
  // обязан совпадать с тем, что лежит на диске, даже если видео
  // добавили из другой вкладки или из терминала.
  const это = await связь.взять('начало');
  const лежит = await связь.взять('входящие');
  // Принятое видео ведёт прямо к разбору: следующий шаг у него один,
  // и заставлять человека искать только что добавленное видео
  // в списке — работа, которой не должно быть.
  приём.куда_после((слаг) => { адрес.идти('analysis', слаг); });

  if (!это.видео.length && !лежит.файлы.length) первый_вход(это);
  else список(это, лежит);
}

// ── 01 · Первый вход ──────────────────────────────────────────────────

function первый_вход(это) {
  const зона = зона_броска(это);
  положить(document.getElementById('экран'), эл('div', { класс: 'в-вход' }, [
    эл('div', { класс: 'в-вход__верх' }, [
      лого('cuts wide videos into vertical clips'),
      растяжка(),
      // Колонки с подвалом здесь ещё нет — выход встаёт в верхнюю полосу.
      выйти_кнопкой('vc-link vc-link--muted'),
    ]),
    эл('div', { класс: 'в-вход__середина' }, [
      эл('div', { класс: 'в-вход__колонка' }, [
        эл('div', { класс: 'в-полосы', id: 'полосы' }),
        эл('div', { класс: 'в-блок' }, [
          эл('h1', { класс: 'vc-h1' }, [
            'One long video — ',
            эл('em', { текст: 'many vertical clips' }),
          ]),
          эл('p', {
            класс: 'vc-lede',
            текст: 'Transcript, segments, subtitles and export — all on your ' +
                   'computer. Nothing is uploaded, and there is no account ' +
                   'to sign in to.',
          }),
        ]),
        эл('div', { класс: 'vc-card' }, [зона, две_дороги(это)]),
      ]),
    ]),
  ]));
  приём.ловить_броски(зона);
}

// ── 02 · Видео ────────────────────────────────────────────────────────

function список(это, лежит) {
  const зона = зона_броска(это);
  нарисовать({
    колонка: [
      лого(),
      блок('videos', [
        добавить_кнопкой(это, 'в-пунктиром'),
        ...это.видео.map(строка_колонки),
      ]),
      растяжка(),
      подвал(адрес.идти),
    ],
    заголовок: эл('h1', { класс: 'vc-h1' }, ['Videos']),
    лид: 'Each video is analyzed once. Cut as many clips from it ' +
         'as you like.',
    мета: [моно(слова.счёт(это.видео.length, 'video', 'videos'))],
    тело: [
      это.видео.length
        ? эл('div', { класс: 'в-сетка' }, [
            ...это.видео.map(карточка),
            карточка_добавить(это),
          ])
        : эл('div', { класс: 'vc-card' }, [зона, две_дороги(это)]),
      входящие(лежит),
    ],
    футбар: {
      главное: {
        зовут: 'Add video',
        подпись: 'analysis takes about ten minutes and happens once',
        делать: () => начать_приём(это),
      },
    },
  });
  if (!это.видео.length) приём.ловить_броски(зона);
  // Бросить файл можно куда угодно в окно, а не только в пунктирную
  // рамку: когда список уже не пуст, рамки на экране нет вовсе,
  // а привычка бросать осталась.
  приём.ловить_броски(document.getElementById('экран'));
}

// ── Общее ─────────────────────────────────────────────────────────────

function зона_броска(это) {
  return эл('div', {
    класс: 'vc-drop',
    на: { click: () => начать_приём(это) },
  }, [
    эл('b', { текст: 'Drop a video here' }),
    эл('span', { текст: 'mp4, mov, mkv · up to four hours' }),
  ]);
}

// Два входа названы словами, потому что стоят они разного, и разницу
// человек обязан узнать ДО того, как заплатит.
function две_дороги(это) {
  return эл('div', { класс: 'в-блок' }, [
    эл('div', { класс: 'vc-card__hr' }),
    эл('p', {
      класс: 'в-подпись',
      стиль: { margin: '0' },
      текст: 'A file dropped into the window is COPIED into the Vertcut ' +
             'folder, so it takes up disk space twice. That is how ' +
             'browsers work: they hand over the file, not where it lives.',
    }),
    это.диалог_умеем
      ? эл('div', { класс: 'в-ряд' }, [
          эл('button', {
            класс: 'vc-btn vc-btn--sm',
            текст: 'Choose file',
            на: { click: () => приём.выбрать_на_диске() },
          }),
          эл('span', {
            класс: 'в-подпись',
            текст: 'no copy: the video stays where it is',
          }),
        ])
      : эл('p', {
          класс: 'в-подпись',
          стиль: { margin: '0' },
          текст: (это.почему_нет_диалога || '') +
                 ' Put the video into the Inbox folder yourself — it will ' +
                 'show up in the list below, with no copy.',
        }),
    // Путь к «Входящим» показывается ТОЛЬКО там, где без него нельзя.
    //
    // Он стоял тут всегда, и автор увидел его первым же взглядом: три
    // строки моноширинного пути посреди первого экрана читаются как
    // адресная строка, попавшая внутрь страницы. На машине, где
    // системный диалог работает, человеку эта папка не нужна вовсе:
    // он нажимает «Choose file».
    //
    // А там, где диалога нет (Windows, Linux), выше стоит «положите
    // видео в папку сами» — и вот там путь и есть ответ на вопрос,
    // который только что задан.
    //
    // Где эта папка лежит, теперь написано и на экране «Если
    // не работает», рядом со всеми остальными путями.
    это.диалог_умеем ? null : моно(это.входящие, 'в-подпись'),
  ].filter(Boolean));
}

function начать_приём(это) {
  if (это.диалог_умеем) return приём.выбрать_на_диске();
  // Диалога нет — бросить файл всё равно можно, и сказать об этом
  // надо там, где человек нажал.
  сказать({
    вид: 'warn',
    что: 'Choose file does not work on this computer.',
    делать: 'Drop the video into this window — it will be copied to ' +
            'Inbox. Or put it into Inbox yourself.',
  });
}

function добавить_кнопкой(это, класс) {
  return эл('button', {
    класс, на: { click: () => начать_приём(это) },
  }, [эл('span', { текст: '+' }), 'Add video']);
}

function карточка_добавить(это) {
  return эл('button', {
    класс: 'в-видео в-видео--добавить',
    на: { click: () => начать_приём(это) },
  }, [
    эл('b', { стиль: { fontSize: '15.5px', fontWeight: '600' },
              текст: 'Add video' }),
    эл('span', { класс: 'в-подпись',
                 текст: 'drop it here or choose a file' }),
  ]);
}

// ── Одно видео ────────────────────────────────────────────────────────

function имя(видео) {
  return видео.журнал ? видео.источник : видео.слаг;
}

// Метка состояния — В ОДНУ СТРОКУ, и слова подобраны под это.
// «разбор не доделан» переносилось на две и ломало ряд; смысл
// от «in progress» не теряется — рядом стоит число вертикалок,
// а подробности про стадии живут на экране разбора.
function состояние(видео) {
  if (!видео.журнал) return { что: 'no data', вид: 'bad' };
  if (видео.разобрано) return { что: 'analyzed', вид: 'good' };
  if (!видео.стадии.length) return { что: 'not analyzed', вид: 'dim' };
  return { что: 'in progress', вид: 'warn' };
}

// Мета в ДВЕ строки, и делятся они по смыслу: сверху про само видео
// (сколько идёт, какого кадра), снизу про то, что из него нарезано.
// Одной строкой это читалось как перечисление четырёх равных чисел,
// хотя первые два про исходник, а вторые два — про работу.
function мета(видео) {
  if (!видео.журнал) return видео.беда || 'analysis data is missing';
  return `${слова.минут(видео.duration)} · ${видео.width}×${видео.height}`;
}

function про_вертикалки(видео) {
  if (!видео.журнал) return null;
  if (!видео.вертикалок) return 'no clips yet';
  return `${видео.собрано} of ${видео.вертикалок} exported`;
}

// Карточка видео.
//
// **Она `div`, а не кнопка, и это вынужденно.** Внутри у неё живёт
// «Delete», а кнопку в кнопку класть нельзя — браузер разбирает
// такую разметку как попало. Поэтому щелчок ловится на карточке,
// а всё, что само по себе нажимается, из него исключается: иначе
// «Delete» сперва спрашивал бы, а потом уводил на экран разбора,
// с которого человек только что ушёл.
//
// С клавиатуры до карточки ведёт НАЗВАНИЕ — оно кнопка. Само собой
// это не получается: `div` в обход клавиш, а карточка была кнопкой
// и работала. Убрать кнопку и не завести другой дороги значило бы
// потерять её молча.
function карточка(видео) {
  const сост = состояние(видео);
  return эл('div', {
    класс: 'в-видео в-видео--живая',
    на: { click: (е) => {
      if (е.target.closest('button, a, input, label')) return;
      адрес.идти('analysis', видео.слаг);
    } },
  }, [
    обложка(видео),
    эл('div', { класс: 'в-видео__низ' }, [
      // Название с заголовком целиком в подсказке: две строки —
      // это решение про раскладку, а не про то, сколько человеку
      // можно знать.
      эл('button', { класс: 'в-видео__имя', текст: имя(видео),
                     title: имя(видео),
                     на: { click: () => адрес.идти('analysis', видео.слаг) } }),
      эл('div', { класс: 'в-видео__ряд' }, [
        метка(сост.что, сост.вид),
        эл('div', { класс: 'в-видео__числа' }, [
          моно(мета(видео), 'vc-rail-row__meta'),
          про_вертикалки(видео)
            ? моно(про_вертикалки(видео), 'vc-rail-row__meta')
            : null,
        ]),
      ]),
      // Удаление — здесь, на карточке самого видео, и это правка
      // после первого взгляда автора. Сперва оно стояло свёрнутым
      // блоком на экране разбора и читалось как техническое
      // пояснение, а не как действие: экран разбора — про то, как
      // идёт работа, а удаление там оказывалось сноской к ней.
      //
      // Приглушённой ссылкой, а не красной кнопкой: карточек в сетке
      // десяток, и красное на каждой кричало бы с экрана, который
      // человек открывает всякий раз. Красным становится сама
      // полоса подтверждения — там это и к месту.
      эл('button', {
        класс: 'vc-link vc-link--muted в-видео__убрать', текст: 'Delete',
        на: { click: () => спросить_удаление(видео) },
      }),
    ]),
  ]);
}

// Что именно уйдёт, спрашивается В МОМЕНТ НАЖАТИЯ, а не вместе
// со списком: счёт занятого места — обход всей папки разбора,
// и платить за него на каждой отрисовке списка не за что.
//
// **Полоса собирается ПОСЛЕ ответа, а не до.** Спросить «удалить?»
// и дописать числа потом значило бы дать человеку нажать «Delete
// permanently» раньше, чем он узнал, чего лишится.
async function спросить_удаление(видео) {
  убрать_полосы();
  let у;
  try {
    у = await связь.взять('что-уйдёт', { слаг: видео.слаг });
  } catch (беда) { return сказать_беду(беда); }

  if (у.идёт) {
    return сказать({
      вид: 'warn', что: `This video's ${у.идёт} is running right now.`,
      делать: 'Stop it and try again: a folder cannot be deleted ' +
              'while something is writing to it.',
    });
  }

  // Галочка живёт ровно столько, сколько висит полоса. На диске ей
  // не место: она про это нажатие и про эту минуту.
  let с_видео = false;
  const галочка = эл('input', { type: 'checkbox' });
  галочка.addEventListener('change', () => { с_видео = галочка.checked; });

  сказать({
    вид: 'bad',
    что: `Delete “${имя(видео)}” and its analysis?`,
    // Ролики называются, только когда они есть: «and 0 clips» читается
    // как поломка счёта, а не как «терять нечего».
    делать: `This frees ${слова.гигабайт(у.занято)}: the transcript, ` +
            `shot frames, crop and subtitle edits` +
            (у.вертикалок
              ? `, and ${слова.счёт(у.вертикалок, 'clip', 'clips')}` +
                (у.собрано ? ` (${у.собрано} exported)` : '')
              : '') +
            '. This is PERMANENT — nothing goes to the Trash.',
    действия: [
      // Про сам файл видео говорится РАЗНОЕ, и разница настоящая:
      // копию во «Входящих» делал сервис и вправе её унести, а файл
      // в папке человека он не создавал и не тронет, даже если его
      // об этом попросить. Правило это живёт в `ingest.наша_копия`,
      // здесь только слова.
      у.наша_копия
        ? эл('label', { класс: 'в-ряд' }, [
            галочка,
            эл('span', { класс: 'в-подпись',
                         текст: 'and the video itself — it is a copy in Inbox' }),
          ])
        : эл('span', { класс: 'в-подпись',
                       текст: `the video itself stays: ${у.источник}` }),
      эл('button', {
        класс: 'vc-btn vc-btn--sm vc-btn--danger', текст: 'Delete permanently',
        на: { click: () => удалить(видео.слаг, с_видео) },
      }),
      эл('button', {
        класс: 'vc-btn vc-btn--sm', текст: 'Cancel',
        на: { click: убрать_полосы },
      }),
    ],
  });
}

async function удалить(слаг, с_видео) {
  // Полоса с вопросом снимается ДО перерисовки: полосы её переживают
  // нарочно («Останавливаю…» обязана висеть, пока работа не встала),
  // и красный вопрос «удалить?» остался бы висеть над уже удалённым.
  убрать_полосы();
  try {
    const ушло = await связь.послать('удалить-видео',
                                     { слаг, с_видео: с_видео ? '1' : '' });
    await показать();          // список читается с диска заново
    сказать({
      вид: 'warn', что: `Deleted: ${слаг}`,
      делать: `Analysis folder deleted` +
              (ушло.видео ? `, along with ${ушло.видео}.` : '.'),
    });
  } catch (беда) { сказать_беду(беда); }
}

// Кадр из настоящего видео. Не отдался — на его месте полосатая
// заглушка из пакета дизайна: она честно говорит «кадра пока нет»,
// а чёрный прямоугольник читался бы как «видео чёрное».
function обложка(видео) {
  const кадр = эл('img', {
    класс: 'в-видео__кадр',
    alt: '',
    src: связь.адрес('обложка', { слаг: видео.слаг }),
  });
  const место = эл('div', { класс: 'в-видео__кадр vc-stripe' });
  кадр.addEventListener('error', () => кадр.replaceWith(место));
  return кадр;
}

// В колонке у видео кадра нет, и это не экономия.
//
// Кадр 26×46 — форма 9:16, то есть форма ВЕРТИКАЛКИ. У видео форма
// другая, горизонтальная, и втиснутый в вертикальную рамку кадр
// говорит про него неправду. А различать четыре своих видео человек
// и так умеет — по названию.
function строка_колонки(видео) {
  const сост = состояние(видео);
  return эл('button', {
    класс: 'vc-rail-row',
    на: { click: () => { адрес.идти('analysis', видео.слаг); } },
  }, [
    эл('span', { стиль: { minWidth: 0 } }, [
      эл('b', { класс: 'vc-rail-row__title', текст: имя(видео) }),
      эл('span', { класс: 'vc-rail-row__meta',
                   текст: `${слова.минут(видео.duration)} · ${сост.что}` }),
    ]),
  ]);
}

// ── «Входящие» ────────────────────────────────────────────────────────
//
// Спека заводит эту папку не только для брошенных файлов: она же
// отвечает на вопрос «а где мои прошлые видео». И она же — запасная
// дорога там, где системного диалога нет.

function входящие(лежит) {
  const ждут = лежит.файлы.filter((ф) => !ф.разобрано);
  if (!ждут.length) return null;
  return эл('div', { класс: 'vc-card' }, [
    эл('div', { класс: 'в-ряд' }, [
      эл('b', { класс: 'vc-card__title', текст: 'In Inbox' }),
      растяжка(),
      моно(лежит.папка, 'в-подпись'),
    ]),
    эл('p', {
      класс: 'в-подпись', стиль: { margin: '0' },
      текст: 'These files are in the Vertcut folder but not added yet. ' +
             'Adding reads the video and creates its analysis folder; ' +
             'nothing is copied.',
    }),
    ...ждут.map((файл) => эл('div', { класс: 'в-ряд' }, [
      моно(файл.имя),
      моно(слова.гигабайт(файл.размер), 'в-подпись'),
      !файл.знакомое ? метка('unknown file type', 'warn') : null,
      растяжка(),
      эл('button', {
        класс: 'vc-btn vc-btn--xs',
        текст: 'Add',
        на: { click: () => приём.по_пути(файл.путь) },
      }),
    ])),
  ]);
}
