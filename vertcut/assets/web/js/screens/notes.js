// Экран 06 · Описания.
//
// Текст, который человек скопирует при публикации. Правится там же,
// где читается: карточка превращается в поле — отдельного экрана
// правки нет, это правило пакета дизайна.
//
// С ключом внизу — «Write missing descriptions» и «Rewrite all»,
// у карточки — «Ask AI» или «Rewrite with AI»; метка авторства
// говорит «AI», «yours» или «editing».
//
// И нет **счётчика «64 / 150»**. Число 150 брать неоткуда: у каждой
// площадки свой предел, они разные и меняются. Счётчик знаков остался
// — он говорит правду, которая от площадки не зависит.

import {
  нарисовать, лого, блок, маршрут, вертикалки, эл, моно, метка, растяжка,
  карандаш,
  сказать, сказать_беду, убрать_полосы, подвал,
} from '../shell.js';
import * as связь from '../api.js';
import * as слова from '../words.js';
import * as адрес from '../route.js';

let это = null;
let правим = null;
let пишем = false;      // ключ ролика, чьё описание сейчас в поле

export async function показать([слаг]) {
  if (!слаг) throw new связь.Беда('No video named for descriptions', '');
  правим = null;
  это = await связь.взять('описания', { слаг });
  это.куски = (await связь.взять('куски', { слаг })).куски;
  рисовать();
}

function рисовать() {
  нарисовать({
    колонка: колонка(),
    заголовок: эл('h1', { класс: 'vc-h1' }, ['Descriptions']),
    лид: 'The text you paste into the platform\'s form when you post. ' +
         'Click a description to edit it right here.',
    мета: [моно(`${это.написано} of ${это.описания.length} written`)],
    тело: [
      приглашение(),
      одинаковые(),
      это.описания.length
        ? эл('div', { класс: 'в-описания' }, это.описания.map(карточка))
        : пусто(),
    ],
    футбар: футбар(),
  });
}

// Приглашение стоит СВЕРХУ и только пока ключа нет.
//
// Оно не заглушка и не реклама: описания — одна из двух работ, ради
// которых ключ вообще нужен, и человек, впервые попавший на этот
// экран, должен узнать об этом здесь, а не искать в настройках.
// Появится ключ — приглашение уйдёт, а у каждой карточки встанет
// кнопка «Попросить AI». Это пятая сессия; кнопки, которая сегодня
// ничего не сделает, тут нет.
function приглашение() {
  if (это.ai_подключён) return null;
  return эл('div', { класс: 'vc-card vc-card--empty' }, [
    эл('b', { класс: 'vc-card__title', текст: 'AI could write these for you' }),
    эл('p', {
      класс: 'в-подпись', стиль: { margin: '0' },
      текст: 'With your own API key, AI reads what is said in each clip ' +
             'and writes a description — in your voice, if you add your ' +
             'samples in Settings. Without a key you write descriptions ' +
             'yourself, and that doesn\'t stop you from exporting or ' +
             'posting.',
    }),
    эл('button', {
      класс: 'vc-btn vc-btn--sm', текст: 'Add API key',
      на: { click: () => адрес.идти('settings', 'ai') },
    }),
  ]);
}

// Полоса ловит механическое: судить о качестве описания сервису
// нечем, а заметить, что три подписи подряд начинаются одинаково,
// можно счётом.
function одинаковые() {
  if (!это.одинаковые.length) return null;
  const пары = это.одинаковые.map((п) => `“${п.начало}…”`).join(', ');
  return эл('div', { класс: 'vc-bar vc-bar--warn' }, [
    эл('div', { класс: 'vc-bar__what' }, [
      эл('b', { текст: `These descriptions start the same way: ${пары}` }),
      эл('span', { текст: 'In a feed they\'ll sit next to each other and ' +
                          'read as one. Vertcut only counts the matches — ' +
                          'what to do about them is up to you.' }),
    ]),
  ]);
}

function пусто() {
  return эл('div', { класс: 'в-пусто' }, [
    эл('div', { класс: 'vc-empty__title', текст: 'Nothing to describe yet' }),
    эл('p', {
      класс: 'vc-lede',
      текст: 'Descriptions belong to clips. Pick a segment and create ' +
             'a clip — it will show up here.',
    }),
    эл('button', {
      класс: 'vc-btn vc-btn--sm', текст: 'Go to segments',
      на: { click: () => { адрес.идти('segments', это.слаг); } },
    }),
  ]);
}

// Карточка описания.
//
// **Главное здесь — сама подпись, а не название вертикалки.** Сперва
// было наоборот: название стояло заголовком, крупным и чёрным,
// а подпись под ним — серой строкой. Но название вертикалки это
// её первые слова, техническая примета; человек пришёл сюда за тем,
// что он СДЕЛАЛ, — за подписью, которую скопирует в форму площадки.
//
// Поэтому подпись стоит первой и набрана крупно, а вся техника —
// имя файла, номера фраз, счёт знаков, метка авторства — уехала
// в одну мелкую строку под ней.
function карточка(о) {
  if (правим === о.id) return правка(о);
  const пусто_ = !о.текст;
  if (пусто_) return карточка_пустая(о);
  return эл('div', { класс: 'vc-card в-описание' }, [
    // Карандаш в конце подписи, а не подсказка `title`: подсказка
    // молчит, пока на неё не наткнулись мышью, а на ощупь по тексту
    // не щёлкают. Подсказка при этом осталась — она говорит словами
    // то, на что карандаш только намекает.
    эл('p', {
      класс: 'в-описание__текст',
      title: 'click to edit',
      на: { click: () => { правим = о.id; рисовать(); } },
    }, [о.текст, карандаш()]),
    эл('div', { класс: 'в-описание__низ' }, [
      о.кто === 'моделью' ? метка('AI', 'busy') : метка('yours', 'good'),
      моно(о.файл, 'в-подпись'),
      моно(`phrases ${о.фразы.first}–${о.фразы.last} · ` +
           слова.счёт(о.знаков, 'character', 'characters'), 'в-подпись'),
      растяжка(),
      // Кнопка копирования — то, ради чего экран вообще есть:
      // подпись отсюда уезжает в форму площадки, и уезжает руками.
      кнопка_копировать(о.текст),
      // Той же кнопкой, что и «Copy», а не ссылкой: они стоят
      // в одной строке и делают одно и то же по весу — действие над
      // этой карточкой. Разный вид у соседей читается как разный
      // смысл, а смысл тут один.
      это.ai_подключён ? эл('button', {
        класс: 'vc-btn vc-btn--xs', текст: 'Rewrite with AI',
        disabled: пишем,
        на: { click: () => написать({ ключ: о.id }) },
      }) : null,
    ]),
  ]);
}

// Пустая карточка той же формы, что и остальные: строка сверху,
// техника и действия снизу. Кнопки стоят справа — там же, где
// «Скопировать» у соседей. Разное место у одинаковых по смыслу
// кнопок заставляет искать их глазами в каждой карточке заново.
function карточка_пустая(о) {
  return эл('div', { класс: 'vc-card в-описание в-описание--пусто' }, [
    эл('p', { класс: 'в-описание__текст в-описание__нет',
              текст: 'no description' }),
    эл('div', { класс: 'в-описание__низ' }, [
      моно(о.файл, 'в-подпись'),
      моно(`phrases ${о.фразы.first}–${о.фразы.last} · ` +
           слова.длина(о.duration), 'в-подпись'),
      растяжка(),
      эл('button', {
        класс: 'vc-btn vc-btn--xs', текст: 'Write it yourself',
        на: { click: () => { правим = о.id; рисовать(); } },
      }),
      это.ai_подключён ? эл('button', {
        класс: 'vc-btn vc-btn--xs', текст: 'Ask AI',
        disabled: пишем,
        на: { click: () => написать({ ключ: о.id }) },
      }) : null,
    ]),
  ]);
}

// Копирование в буфер. Не вышло — говорим словами и показываем,
// что скопировать: браузер может запретить буфер, и молча ничего
// не сделать в этом месте хуже всего — человек уйдёт публиковать
// пустоту.
function кнопка_копировать(текст) {
  const кнопка = эл('button', {
    класс: 'vc-btn vc-btn--xs', текст: 'Copy',
    на: { click: async () => {
      try {
        await navigator.clipboard.writeText(текст);
        кнопка.textContent = 'Copied';
        setTimeout(() => { кнопка.textContent = 'Copy'; }, 1500);
      } catch (_) {
        сказать({
          вид: 'warn',
          что: 'The browser didn\'t allow copying.',
          делать: 'Select the description text and copy it yourself.',
        });
      }
    } },
  });
  return кнопка;
}

function правка(о) {
  const поле = эл('textarea', {
    класс: 'vc-textarea', rows: '4',
    свойства: { value: о.текст },
    placeholder: 'what this clip is about — the way a viewer will read it',
  });
  const счётчик = моно(слова.счёт(о.знаков, 'character', 'characters'),
                      'в-подпись');
  поле.addEventListener('input', () => {
    счётчик.textContent = слова.счёт(поле.value.length, 'character',
                                     'characters');
  });
  return эл('div', { класс: 'vc-card в-описание',
                     стиль: { borderColor: 'var(--accent)' } }, [
    эл('div', { класс: 'в-описание__низ' }, [
      метка('editing'),
      моно(о.файл, 'в-подпись'),
      моно(`phrases ${о.фразы.first}–${о.фразы.last}`, 'в-подпись'),
    ]),
    поле,
    эл('div', { класс: 'в-ряд' }, [
      счётчик,
      растяжка(),
      эл('button', {
        класс: 'vc-btn vc-btn--sm vc-btn--primary', текст: 'Save',
        на: { click: () => сохранить(о.id, поле.value) },
      }),
      эл('button', {
        класс: 'vc-link vc-link--muted', текст: 'Cancel',
        на: { click: () => { правим = null; рисовать(); } },
      }),
    ]),
    эл('p', {
      класс: 'в-подпись', стиль: { margin: '0' },
      текст: 'The description isn\'t part of the video file, so editing ' +
             'it doesn\'t make an exported clip out of date.',
    }),
  ]);
  }

async function сохранить(ключ, текст) {
  убрать_полосы();
  try {
    const куски = это.куски;
    это = await связь.послать('описание',
                              { слаг: это.слаг, ключ, текст });
    это.куски = куски;
    правим = null;
    рисовать();
  } catch (беда) { сказать_беду(беда); }
}

function колонка() {
  return [
    лого(это.источник),
    блок('steps', маршрут({
      слаг: это.слаг, сейчас: 'descriptions', идти: адрес.идти,  // имя шага — для маршрута, не для человека
      разобрано: true, вертикалок: это.описания.length,
      состояния: {
        descriptions: `${это.написано} of ${это.описания.length}`,
      },
    })),
    вертикалки({ слаг: это.слаг, куски: это.куски, идти: адрес.идти }),
    растяжка(),
    подвал(адрес.идти),
  ];
}

// Нижняя полоса — как в макете: главная кнопка «Write missing
// descriptions» с ценой, справа опасная ссылка «Rewrite all».
//
// **Без ключа главной остаётся «Next: export».** Одна главная
// кнопка на экран — правило пакета; какая именно, решает то, есть ли
// кому нажимать на первую.
function футбар() {
  const нет_у = это.описания.length - это.написано;
  if (!это.ai_подключён || !это.описания.length) {
    return {
      главное: {
        зовут: 'Next: export',
        подпись: нет_у
          ? `${слова.счёт(нет_у, 'clip has', 'clips have')} no description ` +
            '— you can still export'
          : 'every clip has a description',
        делать: () => { адрес.идти('export', это.слаг); },
      },
    };
  }
  const справа = это.написано ? [эл('button', {
    класс: 'vc-link vc-link--danger', текст: 'Rewrite all',
    на: { click: переписать_все },
  })] : null;
  if (!нет_у) {
    return {
      справа,
      главное: {
        зовут: 'Next: export',
        подпись: 'every clip has a description',
        делать: () => { адрес.идти('export', это.слаг); },
      },
    };
  }
  const ц = это.цена && это.цена.без_описания;
  return {
    справа,
    главное: {
      зовут: пишем ? 'Writing…' : 'Write missing descriptions',
      подпись: `${слова.счёт(нет_у, 'clip', 'clips')} · ${цена_словами(ц)}`,
      делать: пишем ? null : () => написать({}),
    },
  };
}


// ── Просьба к модели ──────────────────────────────────────────────────

// Одно место на все три кнопки: у карточки, «Write missing
// descriptions» и «Rewrite all». Разница между ними — ровно в том, кого просят,
// и она уезжает словом в просьбе, а не тремя копиями этой функции.
async function написать(кого) {
  убрать_полосы();
  пишем = true;
  рисовать();
  сказать({ вид: 'ask', что: 'Asking AI…',
            делать: 'This takes a few seconds to a minute.' });
  try {
    const ответ = await связь.послать('описания-написать',
                                      { слаг: это.слаг, ...кого });
    // Вертикалки колонки в этом ответе не приезжают — их спрашивают
    // отдельной ручкой. Не перенеси их сюда, и колонка слева пропадёт
    // молча: список вертикалок это то, ради чего человек тут вообще
    // ходит.
    const куски = это.куски;
    это = ответ;
    это.куски = куски;
    убрать_полосы();
    сказали(ответ.ответ);
  } catch (беда) {
    убрать_полосы();
    if (беда.дорого) спросить_разрешения(беда, кого);
    else сказать_беду(беда);
  } finally {
    пишем = false;
    рисовать();
  }
}

function сказали(н) {
  // Сервис ответил не тем, чего у него просили. Молча ничего
  // не показать тут нельзя: деньги уже потрачены, и человек обязан
  // узнать, что ответ пришёл, а прочитать его не вышло.
  if (!н || !н.записано) {
    return сказать({
      вид: 'bad',
      что: 'The AI answer arrived, but Vertcut couldn\'t report on it.',
      делать: 'The full answer is saved in the video\'s analysis ' +
              'folder, in “descriptions.answer.txt”. The request is paid for.',
    });
  }
  const сколько = слова.счёт(н.записано.length, 'description',
                            'descriptions');
  сказать({
    вид: н.записано.length ? 'good' : 'warn',
    что: н.записано.length ? `${сколько} written` : 'AI wrote nothing',
    делать: `${слова.деньги(н.деньги)} · ${н.вошло} + ${н.вышло} tokens ` +
            `in ${слова.длина(н.секунд)}`,
  });
  if (н.язык_разошёлся) {
    сказать({ вид: 'warn',
              что: 'The descriptions came back in a different language ' +
                   'from the video.',
              делать: 'Ask again. If it keeps happening and all your ' +
                      'videos are in one language, name it in the ' +
                      'prompt: Settings → AI and API key.' });
  }
  if (н.не_ответила.length) {
    сказать({ вид: 'warn',
              что: `AI skipped ${слова.счёт(н.не_ответила.length, 'clip',
                                            'clips')}.`,
              делать: 'The whole request is paid for. Try again — or ' +
                      'write those descriptions yourself.' });
  }
}

function спросить_разрешения(беда, кого) {
  сказать({
    вид: 'ask', что: беда.что, делать: беда.подсказка,
    действия: [
      эл('button', {
        класс: 'vc-btn vc-btn--sm vc-btn--primary', текст: 'Yes, write',
        на: { click: () => { убрать_полосы();
                             написать({ ...кого, согласен: true }); } },
      }),
      эл('button', {
        класс: 'vc-btn vc-btn--sm', текст: 'Cancel', на: { click: убрать_полосы },
      }),
    ],
  });
}

function переписать_все() {
  убрать_полосы();
  const ц = это.цена && это.цена.всем;
  сказать({
    вид: 'ask',
    что: 'Rewrite all descriptions?',
    делать: 'The ones you wrote yourself too: they will be replaced. ' +
            `${цена_словами(ц)} for ` +
            слова.счёт(это.описания.length, 'clip', 'clips') + '.',
    действия: [
      эл('button', {
        класс: 'vc-btn vc-btn--sm vc-btn--danger', текст: 'Rewrite all',
        на: { click: () => { убрать_полосы(); написать({ всем: true }); } },
      }),
      эл('button', {
        класс: 'vc-btn vc-btn--sm', текст: 'Cancel', на: { click: убрать_полосы },
      }),
    ],
  });
}

// Деньги словами — те же, что на экране фрагментов: четыре знака
// после точки читаются как шум.
// Своей арифметики тут нет: и размер, и деньги посчитал сервис.
// Цена неизвестна — говорится размер запроса, как у фрагментов.
function цена_словами(о) {
  if (!о) return '';
  if (о.деньги === null) return `${о.вошло} tokens · price unknown`;
  return `≈ ${слова.деньги(о.деньги)}`;
}
