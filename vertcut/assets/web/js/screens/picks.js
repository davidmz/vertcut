// Негодные СВОРАЧИВАЮТСЯ, а не прячутся и не стоят наравне с годными.
//
// Дизайн говорит «негодные не скрываются: причина часто интереснее
// самого предложения», и это правда — но правдой оказалось и обратное:
// автор увидел колонку, где половина карточек занимает место и
// не годится ни на что. Три из шести — это не «интересная причина»,
// это шум.
//
// Свёрнутая строка со словами — то же правило дизайна номер 10:
// молчаливый обрез читается как поломка, а «3 предложения не годятся»
// не читается никак, кроме как самим собой. Раскрыл — там причины,
// все до одной.
function список_кандидатов(было) {
  const годные = было.предложения.filter((к) => к.годен);
  const негодные = было.предложения.filter((к) => !к.годен);
  return эл('div', { класс: 'в-кандидаты__ряд' }, [
    ...годные.map(карточка_кандидата),
    негодные.length ? свёрнутые_негодные(негодные) : null,
  ]);
}

function свёрнутые_негодные(негодные) {
  const узел = эл('details', {
    класс: 'в-раскрывашка', open: негодные_раскрыты,
  }, [
    эл('summary', {
      текст: `${слова.счёт(негодные.length, 'suggestion', 'suggestions')} ` +
             'not usable',
    }),
    эл('div', { класс: 'в-кандидаты__ряд' },
       негодные.map(карточка_кандидата)),
  ]);
  узел.addEventListener('toggle', () => { негодные_раскрыты = узел.open; });
  return узел;
}

// Выбран ли этот кандидат. Одно определение: по нему и рисуется
// подложка, и решается, что делает щелчок. Разойдись они — карточка
// выглядела бы выбранной, а щелчок по ней выбирал бы её заново.
function это_выбран(к) {
  return Boolean(к.годен && выбор.length === 1
                 && выбор[0][0] === к.с && выбор[0][1] === к.по);
}

function карточка_кандидата(к) {
  const выбран = это_выбран(к);
  const классы = ['в-кандидат'];
  if (!к.годен) классы.push('в-кандидат--негоден');
  // Вертикалка по этому совету уже создана — карточка зелёная.
  // Иначе пятнадцать карточек выглядят одинаково, и человек
  // не помнит, какие из них уже отработаны. Выбор при этом главнее:
  // он говорит про то, что происходит прямо сейчас.
  if (к.есть_ключ && !выбран) классы.push('в-кандидат--есть');
  if (выбран) классы.push('в-кандидат--выбран');
  return эл(к.годен ? 'button' : 'div', {
    класс: классы.join(' '),
    ...(к.годен ? { на: { click: () => взять_кандидата(к) } } : {}),
  }, [
    эл('div', { класс: 'в-ряд' }, [
      моно(`#${к.н}`, 'в-кандидат__н'),
      эл('b', { текст: к.название || '(untitled)' }),
      растяжка(),
      // Метки «выбрано» нет: выбор виден подложкой и рамкой, а слово
      // рядом с ними — это второй раз про одно и то же. Метка «есть»
      // остаётся: она говорит про то, чего в карточке не видно вовсе.
      к.есть_ключ ? метка('clip exists', 'good') : null,
      // Убрать одно. Не «спрятать»: предложение стирается с диска,
      // и остальные после этого ПРОВЕРЯЮТСЯ ЗАНОВО — негодность
      // бывает относительной, и «пересекается с предложением выше»
      // перестаёт быть правдой, как только того не стало.
      эл('span', {
        класс: 'в-кандидат__убрать', текст: '×', title: 'remove this',
        на: { click: (е) => { е.stopPropagation(); убрать_одно(к); } },
      }),
    ]),
    к.с ? моно(`phrases ${к.с}–${к.по}` +
               (к.duration ? ` · ${слова.длина(к.duration)}` : ''),
               'в-подпись') : null,
    к.почему
      ? эл('span', { класс: 'в-подпись в-жалоба',
                     текст: `not usable: ${к.почему}` })
      : к.о_чём ? эл('span', { класс: 'в-подпись', текст: к.о_чём }) : null,
  ]);
}

// Щелчок по кандидату = два щелчка по списку фраз. Ни больше ни меньше.
//
// **Щелчок по УЖЕ выбранному снимает выбор.** Иначе выбранная карточка
// — единственное место на экране, где щелчок не делает ничего: она
// выглядит нажимаемой, нажимается и не отвечает. Снимается тем же
// самым, чем снимает ссылка «снять» в полосе выбора.
async function взять_кандидата(к) {
  убрать_полосы();
  if (это_выбран(к)) return снять_выбор();
  выбор = [[к.с, к.по]];
  ждём = null;
  await прикинуть();
  const первая = document.getElementById(`фраза-${к.с}`);
  if (первая) {
    первая.scrollIntoView({ block: 'center' });
    const список = document.querySelector('.в-фразы');
    if (список) прокрутка = список.scrollTop;
  }
}

async function убрать_одно(к) {
  убрать_полосы();
  try {
    предложения = await связь.послать('предложение-убрать',
                                      { слаг: это.слаг, н: к.н });
    рисовать();
  } catch (беда) { сказать_беду(беда); }
}

async function спросить_модель(согласен) {
  убрать_полосы();
  спрашиваю = true;
  рисовать();
  сказать({ вид: 'ask', что: 'Asking AI…',
            делать: 'This takes ten seconds to a minute. You can close ' +
                    'the tab: the answer is saved to disk.' });
  try {
    предложения = await связь.послать('предложения-спросить',
                                      { слаг: это.слаг, согласен });
    убрать_полосы();
    const б = предложения.было;
    сказать({
      вид: 'good',
      что: `${б.годных} of ${б.предложения.length} usable`,
      делать: `${слова.деньги(б.деньги)} · ${б.вошло} + ${б.вышло} tokens ` +
              `in ${слова.длина(б.секунд)}`,
    });
  } catch (беда) {
    убрать_полосы();
    // «Дорого» — вопрос, а не поломка, и вид его приезжает словом
    // с сервера, а не угадывается по тексту сообщения.
    if (беда.дорого) спросить_разрешения(беда);
    else сказать_беду(беда);
  } finally {
    спрашиваю = false;
    рисовать();
  }
}

function спросить_разрешения(беда) {
  сказать({
    вид: 'ask', что: беда.что, делать: беда.подсказка,
    действия: [
      эл('button', {
        класс: 'vc-btn vc-btn--sm vc-btn--primary', текст: 'Yes, ask',
        на: { click: () => { убрать_полосы(); спросить_модель(true); } },
      }),
      эл('button', {
        класс: 'vc-btn vc-btn--sm', текст: 'Cancel',
        на: { click: убрать_полосы },
      }),
    ],
  });
}

async function убрать_предложения() {
  убрать_полосы();
  сказать({
    вид: 'ask',
    что: 'Remove all suggestions?',
    делать: 'Asking again costs the same as the first time.',
    действия: [
      эл('button', {
        класс: 'vc-btn vc-btn--sm vc-btn--danger', текст: 'Remove',
        на: { click: async () => {
          убрать_полосы();
          try {
            предложения = await связь.послать('предложения-убрать',
                                              { слаг: это.слаг });
            рисовать();
          } catch (беда) { сказать_беду(беда); }
        } },
      }),
      эл('button', {
        класс: 'vc-btn vc-btn--sm', текст: 'Cancel', на: { click: убрать_полосы },
      }),
    ],
  });
}

