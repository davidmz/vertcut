// Экран 04 · Фрагменты, в варианте без AI (экран 05).
//
// **Главный элемент — список фраз.** Дизайн переставил логику именно
// так: фразами фрагмент отмечают всегда, и без ключа тоже. Правая
// колонка не исчезает и не превращается в заглушку во весь экран —
// она сжимается до приглашения и уступает место фразам.
//
// «Примерить» здесь нет: выбранное показано полосой сверху, и главная
// кнопка сразу называет результат — «Создать вертикалку».
//
// Управление: щелчок — начало, второй щелчок — конец. Shift на первом
// щелчке пары — приклеить вторым куском. Разрыв разрешён только
// на границе фразы, и по-другому его тут и не сделать: щёлкают
// по фразам.

import {
  нарисовать, лого, блок, маршрут, вертикалки, эл, моно, метка, растяжка,
  сказать, сказать_беду, убрать_полосы, подвал,
} from '../shell.js';
import * as связь from '../api.js';
import * as слова from '../words.js';
import * as адрес from '../route.js';

let это = null;          // всё, что прочитано с диска на этом заходе
let выбор = [];          // пары номеров фраз: [[10, 20], [40, 45]]
let ждём = null;         // начало пары, у которой ещё нет конца
let прикидка = null;     // что сервис ответил про этот выбор
let искать = '';
let звук = null;
let прокрутка = 0;     // где человек стоял в списке фраз
let предложения = null;  // что ответил сервис про кандидатов
let спрашиваю = false;   // обращение к модели идёт прямо сейчас
// Показывать ли карточку «Свой текст». Без ключа она стоит всегда;
// с ключом её место занимает колонка предложений, а сама она
// приходит по ссылке в нижней полосе — как в макете.
let свой_текст_открыт = false;
// Раскрыты ли негодные. Экран рисуется заново на каждом щелчке,
// и `<details>` рождался бы закрытым: раскрыл причины, щёлкнул
// по годному — и они схлопнулись сами.
let негодные_раскрыты = false;

export async function показать([слаг]) {
  if (!слаг) throw new связь.Беда('No video given', '');
  выбор = []; ждём = null; прикидка = null; искать = '';
  это = {
    слаг,
    разбор: await связь.взять('разбор', { слаг }),
    фразы: await связь.взять('фразы', { слаг }),
    куски: (await связь.взять('куски', { слаг })).куски,
  };
  предложения = await связь.взять('предложения', { слаг });
  свой_текст_открыт = !предложения.подключён;
  рисовать();
}

// ── Рисование ─────────────────────────────────────────────────────────

function рисовать() {
  нарисовать({
    колонка: колонка(),
    заголовок: эл('h1', { класс: 'vc-h1' }, ['Segments']),
    // Лид НЕ МЕНЯЕТСЯ по ходу выбора, и это не лень.
    //
    // Он менялся — и на первом же щелчке становился длиннее на строку.
    // Всё, что ниже, съезжало вниз: список фраз уходил из-под курсора,
    // и место в тексте приходилось искать заново. А сказано в нём было
    // ровно то же, что говорит полоса выбора двумя строками ниже.
    лид: 'Click the phrase where the segment starts, then the one ' +
         'where it ends.',
    мета: [
      моно(слова.счёт(это.фразы.фразы.length, 'phrase', 'phrases')),
      моно(слова.длина(это.фразы.duration)),
    ],
    тело: [
      полоса_выбора(),
      эл('div', { класс: 'в-фрагменты' }, [
        список_фраз(),
        эл('div', { класс: 'в-блок' }, [
          предложения && предложения.подключён ? колонка_предложений() : null,
          предложения && предложения.подключён ? null : приглашение(),
          свой_текст_открыт ? свой_текст() : null,
        ]),
      ]),
    ],
    футбар: футбар(),
  });
}

// ── Полоса «выбрано» ──────────────────────────────────────────────────

function полоса_выбора() {
  if (!выбор.length && !ждём) return null;
  if (!прикидка) {
    return эл('div', { класс: 'vc-bar vc-bar--ask в-выбор' }, [
      эл('div', { класс: 'vc-bar__what' }, [
        эл('b', { текст: ждём
          ? `Start: phrase ${ждём}. Now click where it ends.`
          : 'Checking…' }),
        эл('span', { текст: ждём
          ? 'Click the same phrase again to use just that one.'
          : '' }),
      ]),
      эл('div', { класс: 'vc-bar__acts' }, [кнопка_снять()]),
    ]);
  }
  const п = прикидка;
  const где = п.куски.map((к) =>
    `${слова.время(к.start)} → ${слова.время(к.end)}`).join(' + ');
  const края = [
    п.edges.start.measured ? 'starts on a heard word'
      : `start is estimated: the nearest heard word is ` +
        `${слова.счёт(п.edges.start.far, 'word', 'words')} away`,
    п.с_начала_фразы ? null : 'starts MID-phrase',
  ].filter(Boolean).join(' · ');

  return эл('div', {
    класс: 'в-выбор vc-bar '
           + (п.не_хватает ? 'vc-bar--warn' : 'vc-bar--ask'),
  }, [
    эл('div', { класс: 'vc-bar__what' }, [
      эл('b', { текст: `Selected: ${назвать_выбор()} · ${слова.длина(п.duration)}` }),
      эл('span', { текст: `${где} · ${края}` }),
    ]),
    эл('div', { класс: 'vc-bar__acts' }, [
      эл('button', {
        класс: 'vc-btn vc-btn--sm',
        текст: звук ? 'Stop' : 'Listen',
        на: { click: слушать },
      }),
      кнопка_снять(),
    ]),
  ]);
}

function назвать_выбор() {
  return выбор.map(([a, b]) => a === b ? `phrase ${a}` : `phrases ${a}–${b}`)
    .join(' + ');
}

function кнопка_снять() {
  return эл('button', {
    класс: 'vc-link vc-link--muted', текст: 'clear',
    на: { click: снять_выбор },
  });
}

// Снятие выбора — ОДНО место. Снимают его отсюда трое: ссылка «снять»
// в полосе, повторный щелчок по выбранному предложению и повторный
// щелчок по той же фразе. Три копии этих четырёх строк однажды
// разошлись бы в том, что именно осталось на экране.
function снять_выбор() {
  выбор = [];
  ждём = null;
  прикидка = null;
  замолчать();
  рисовать();
}

// ── Список фраз ───────────────────────────────────────────────────────

// Столбцы: номер, время, длина, текст.
//
// **Надёжности здесь нет, и это решение автора.** Она никуда не делась
// — её по-прежнему показывает `vertcut phrases`, одним столбцом
// с двумя смыслами. Но на этом экране человек занят другим: он ищет,
// где мысль начинается и где кончается, и лишний столбец цифр ему
// в этом мешает.
function столбцы() {
  return эл('div', { класс: 'vc-list__cols' }, [
    эл('span', { стиль: { width: '34px' }, текст: '#' }),
    эл('span', { стиль: { width: '58px' }, текст: 'start' }),
    эл('span', { стиль: { width: '46px' }, текст: 'length' }),
    эл('span', { стиль: { flex: '1' }, текст: 'phrase' }),
  ]);
}

function список_фраз() {
  const узел = эл('div', { класс: 'vc-list в-фразы',
                           'data-ждём-конец': ждём ? '1' : null }, [
    эл('div', { класс: 'в-фразы__верх' }, [шапка(), столбцы()]),
    ...строки(),
  ]);
  // Где человек стоял в списке — восстанавливается после перерисовки.
  //
  // **Это не удобство, а починка.** Экран рисуется заново на каждом
  // щелчке, и список рождался прокрученным в начало: человек отмечал
  // начало фрагмента на трёхсотой фразе и оказывался на первой.
  узел.addEventListener('scroll', () => { прокрутка = узел.scrollTop; });
  queueMicrotask(() => { узел.scrollTop = прокрутка; });
  return узел;
}

function шапка() {
  return эл('div', { класс: 'vc-list__head' }, [
    эл('b', { класс: 'vc-card__title', текст: 'Phrases' }),
    эл('input', {
      класс: 'в-поиск', type: 'search', placeholder: 'search the text',
      value: искать,
      на: { input: (е) => { искать = е.target.value; перерисовать_список(); } },
    }),
    эл('input', {
      класс: 'в-поиск в-поиск--номер', type: 'text', placeholder: 'go to #',
      на: { change: (е) => к_номеру(е.target.value) },
    }),
    растяжка(),
    эл('span', { класс: 'в-подпись' }, [
      'pick a start and an end; to add another segment, hold ',
      эл('span', { класс: 'в-клавиша', текст: 'Shift' }),
    ]),
  ]);
}

// Какие строки показывать: ВСЕ, а под поиском — найденные.
//
// **Середина больше не сворачивается, и это правка по слову автора.**
// Пока она сворачивалась, второй щелчок — тот, которым отмечают конец
// фрагмента, — сжимал список до окрестностей выбора: всё, что было
// выше, становилось одной строкой «ещё 240 фраз», и выбранная фраза
// оказывалась в начале списка. Человек, отметивший кусок на трёхсотой
// фразе, терял место, где он работал, ровно в тот миг, когда выбор
// сложился. Отмечать следующий кусок после этого некуда: соседних
// фраз на экране нет.
//
// Правило пакета «свёрнутая середина всегда со словами, сколько
// спрятано» никуда не делось — по нему свёрнуты негодные предложения
// AI. Но там сворачивается то, что человеку НЕ нужно, а здесь
// сворачивалось ровно то, за чем он на экран пришёл.
//
// Платим отрисовкой всех строк на каждом щелчке. Замер автора:
// 478 фраз, и это тот же самый список, который уже рисуется целиком
// под поиском.
function строки() {
  const все = это.фразы.фразы;
  if (!искать.trim()) return все.map(строка);
  const найдено = все.filter(
    (ф) => ф.text.toLowerCase().includes(искать.trim().toLowerCase()));
  return найдено.length
    ? найдено.map(строка)
    : [эл('div', { класс: 'vc-fold', текст: 'nothing found' })];
}

function строка(ф) {
  const где = место_в_выборе(ф.idx);
  return эл('div', {
    класс: 'vc-row в-фраза',
    id: `фраза-${ф.idx}`,
    'data-in-range': где ? '' : null,
    'data-край': где === 'начало' || где === 'конец' ? где : null,
    на: { click: (е) => щёлкнули(ф.idx, е.shiftKey) },
  }, [
    эл('span', { класс: 'vc-row__n', текст: String(ф.idx) }),
    эл('span', { класс: 'vc-row__at', текст: слова.время(ф.start) }),
    эл('span', { класс: 'vc-row__len', текст: слова.длина(ф.duration) }),
    эл('span', { класс: 'vc-row__text', текст: ф.text }),
    где === 'начало' || где === 'конец'
      ? эл('span', { класс: 'vc-row__edge', текст: КРАЙ[где] }) : null,
  ]);
}

// Слова у края строки. Значения `место_в_выборе` — внутренние
// (по ним же стоит `data-край`), а человеку показывается это.
const КРАЙ = { 'начало': 'start', 'конец': 'end' };   // не для человека: ключи

function место_в_выборе(idx) {
  for (const [a, b] of выбор) {
    if (idx === a) return 'начало';             // не для человека
    if (idx === b) return 'конец';              // не для человека
    if (idx > a && idx < b) return 'внутри';    // не для человека
  }
  if (ждём === idx) return 'начало';            // не для человека
  return null;
}

// Перерисовать ТОЛЬКО строки, шапку не трогая.
//
// **Шапка не пересобирается, и это починка, а не бережливость.**
// В ней стоит поле поиска, и зовут эту функцию с каждой буквой,
// которую в него набирают. Пока шапка собиралась заново, каждая
// буква рождала НОВОЕ поле на месте старого: набранное в нём
// восстанавливалось из `искать`, а вот фокус — нет, он у убитого
// узла. Со второй буквы человек печатал в никуда, и выглядело это
// как «поиск сбрасывает ввод».
//
// Поэтому старые строки снимаются поштучно, а шапка остаётся тем же
// самым узлом — не пересозданным и даже не переставленным: узел,
// вынутый и вложенный обратно, теряет фокус ровно так же.
function перерисовать_список() {
  const где = document.querySelector('.в-фразы');
  if (!где) return рисовать();
  const верх = где.querySelector('.в-фразы__верх');
  if (!верх) return рисовать();
  const было = где.scrollTop;
  while (верх.nextSibling) верх.nextSibling.remove();
  for (const строка_ of строки()) где.append(строка_);
  где.scrollTop = было;
}

function к_номеру(сырое) {
  const n = parseInt(сырое, 10);
  if (!n) return;
  искать = '';
  рисовать();
  const строка_ = document.getElementById(`фраза-${n}`);
  if (строка_) {
    строка_.scrollIntoView({ block: 'center' });
    const список = document.querySelector('.в-фразы');
    if (список) прокрутка = список.scrollTop;
  }
  else сказать({ вид: 'warn', что: `There is no phrase ${n}.`,
                 делать: `This video has ${слова.счёт(это.фразы.фразы.length, 'phrase', 'phrases')}.` });
}

// ── Выбор ─────────────────────────────────────────────────────────────

async function щёлкнули(idx, приклеить) {
  // Начал размечать новое — сказанное про прошлое своё отработало.
  убрать_полосы();
  замолчать();
  if (ждём === null) {
    // Первый щелчок пары. Shift — начать ВТОРОЙ кусок, не сбрасывая
    // первый; без Shift — начать выбор заново.
    if (!приклеить) выбор = [];
    ждём = idx;
    прикидка = null;
    рисовать();
    return;
  }
  const a = Math.min(ждём, idx);
  const b = Math.max(ждём, idx);
  ждём = null;
  выбор = [...выбор, [a, b]].sort((о, д) => о[0] - д[0]);
  await прикинуть();
}

async function прикинуть() {
  убрать_полосы();
  прикидка = null;
  рисовать();
  try {
    прикидка = await связь.послать('прикинуть',
                                   { слаг: это.слаг, диапазоны: выбор });
  } catch (беда) {
    // Куски налезли друг на друга или выбор пустой — это отказ
    // сервиса, и он приезжает словами. Выбор при этом откатывается:
    // держать на экране то, из чего ничего не выйдет, незачем.
    выбор = выбор.slice(0, -1);
    сказать_беду(беда);
  }
  рисовать();
}

// ── Слушать ───────────────────────────────────────────────────────────

function слушать() {
  if (звук) return замолчать(), рисовать();
  const п = прикидка;
  if (!п) return;
  // Слушается ПЕРВЫЙ кусок: у разрывного ролика между кусками
  // выброшена речь, и склеивать их тут значило бы дать послушать
  // то, чего в файле не будет.
  const к = п.куски[0];
  звук = new Audio(связь.адрес('слушать',
                               { слаг: это.слаг, с: к.start, по: к.end }));
  звук.addEventListener('ended', () => { звук = null; рисовать(); });
  звук.play().catch((е) => {
    звук = null;
    сказать({ вид: 'bad', что: 'The browser would not play the sound.',
              делать: String(е.message || е) });
  });
  рисовать();
}

function замолчать() {
  if (звук) { звук.pause(); звук = null; }
}

// ── Правая колонка ────────────────────────────────────────────────────

function приглашение() {
  return эл('div', { класс: 'vc-card vc-card--empty' }, [
    эл('b', { класс: 'vc-card__title', текст: 'AI can suggest segments' }),
    эл('p', {
      класс: 'в-подпись', стиль: { margin: '0' },
      текст: 'With your own API key, AI reads the whole transcript ' +
             'and suggests segments, each with a reason. You still ' +
             'choose. Everything else works without a key: transcript, ' +
             'shots, subtitles, export.',
    }),
    эл('button', {
      класс: 'vc-btn vc-btn--sm', текст: 'Add API key',
      на: { click: () => адрес.идти('settings', 'ai') },
    }),
  ]);
}

function свой_текст() {
  const поле = эл('textarea', {
    класс: 'vc-textarea', rows: '4',
    placeholder: 'paste part of the script — we will find it in the transcript',
  });
  return эл('div', { класс: 'vc-card' }, [
    эл('b', { класс: 'vc-card__title', текст: 'Your text' }),
    поле,
    эл('button', {
      класс: 'vc-btn vc-btn--sm', текст: 'Find in video',
      на: { click: () => найти(поле.value) },
    }),
  ]);
}

async function найти(текст) {
  убрать_полосы();
  if (!текст.trim()) {
    return сказать({ вид: 'warn', что: 'The box is empty.',
                     делать: 'Paste part of the script or transcript.' });
  }
  try {
    const ответ = await связь.послать('найти-текст',
                                      { слаг: это.слаг, текст });
    const годные = ответ.нашлось.filter((р) => р.диапазоны.every((д) => д.length));
    if (!годные.length) {
      return сказать({ вид: 'warn', что: 'Found the text, but it does not line up with phrases.',
                       делать: 'It seems to fall between them.' });
    }
    if (годные.length === 1) return лечь(годные[0]);
    // Текст лёг несколькими способами — выбирает человек, а не сервис.
    сказать({
      вид: 'ask',
      что: `This text fits in ${годные.length} places.`,
      делать: 'Pick the one you mean.',
      действия: годные.map((р, n) => эл('button', {
        класс: 'vc-btn vc-btn--sm', текст: `${n + 1}: ${назвать(р)}`,
        на: { click: () => { убрать_полосы(); лечь(р); } },
      })),
    });
  } catch (беда) { сказать_беду(беда); }
}

function назвать(раскладка) {
  return раскладка.диапазоны
    .map(([a, b]) => a === b ? `phrase ${a}` : `phrases ${a}–${b}`).join(' + ');
}

async function лечь(раскладка) {
  выбор = раскладка.диапазоны.map(([a, b]) => [a, b]);
  ждём = null;
  await прикинуть();
  const первая = document.getElementById(`фраза-${выбор[0][0]}`);
  if (первая) {
    первая.scrollIntoView({ block: 'center' });
    const список = document.querySelector('.в-фразы');
    if (список) прокрутка = список.scrollTop;
  }
}

// ── Колонка и футбар ──────────────────────────────────────────────────

function колонка() {
  return [
    лого(это.разбор.источник),
    блок('steps', маршрут({
      слаг: это.слаг, сейчас: 'segments', идти: адрес.идти,
      разобрано: это.разбор.разобрано, вертикалок: это.куски.length,
      состояния: { segments: String(это.куски.length || '') },
    })),
    вертикалки({ слаг: это.слаг, куски: это.куски, идти: адрес.идти }),
    растяжка(),
    эл('button', {
      класс: 'vc-link vc-link--muted', текст: '← all videos',
      на: { click: () => { адрес.идти('videos'); } },
    }),
    подвал(адрес.идти),
  ];
}

function футбар() {
  // «Вставить свой текст» — ссылка справа, как в макете. Она есть
  // только там, где карточку вытеснила колонка предложений: без
  // ключа карточка и так стоит на месте, и ссылка вела бы к тому,
  // что человек уже видит.
  // Списком, а не одним узлом: нижняя полоса раскладывает правую
  // сторону как список — так же, как это делают другие экраны.
  const справа = (предложения && предложения.подключён && !свой_текст_открыт)
    ? [эл('button', {
        класс: 'vc-link vc-link--muted', текст: 'paste your own text',
        на: { click: () => { свой_текст_открыт = true; рисовать(); } },
      })]
    : null;
  if (!выбор.length) {
    return { главное: { зовут: 'Create clip' }, справа,
             почему: ждём
               ? 'start marked — click where the segment ends'
               : 'nothing to create: no segment selected' };
  }
  if (!прикидка) {
    return { главное: { зовут: 'Create clip' }, справа,
             почему: 'checking…' };
  }
  if (прикидка.не_хватает) {
    // Порог назван числом, и плашка — тоже. Она поднимает его
    // на свою длину: три секунды плашки от пятнадцатисекундного
    // ролика — это плашка с предисловием. Человек, который её
    // включил, обязан понять, почему порог вдруг стал другим,
    // а не гадать.
    const из_них = прикидка.хвост
      ? ` (${слова.длина(прикидка.хвост)} of it is the end card)` : '';
    return {
      главное: { зовут: 'Create clip' }, справа,
      почему: `too short: ${слова.длина(прикидка.duration)}, needs ` +
              `${слова.длина(прикидка.порог)}${из_них} — ` +
              `${слова.длина(прикидка.не_хватает)} more`,
    };
  }
  return {
    справа,
    главное: {
      зовут: 'Create clip',
      подпись: `${слова.длина(прикидка.duration)} · goes to Export`,
      делать: создать,
    },
  };
}

async function создать() {
  убрать_полосы();
  try {
    const свежий = await связь.послать('выбрать-кусок',
                                       { слаг: это.слаг, диапазоны: выбор });
    замолчать();
    // Экран вертикалки — следующий пункт работы. Пока созданная
    // вертикалка появляется в колонке слева, и об этом говорится
    // словами: молча вернуть человека к тому же списку значило бы
    // не сказать, сработала ли кнопка.
    await показать([это.слаг]);
    сказать({
      вид: 'good',
      что: `Clip created: ${свежий.название}`,
      делать: `${слова.длина(свежий.duration)} · clip id ${свежий.id} · ` +
              `file name: ${свежий.файл}`,
    });
  } catch (беда) { сказать_беду(беда); }
}

// ── Колонка предложений (экран 04) ────────────────────────────────────
//
// Встаёт на место карточки «Свой текст», а приглашение уезжает —
// так это описано в задаче сессии и так нарисовано в макете.
//
// **Кандидат ничего не создаёт.** Щелчок по нему делает ровно то же,
// что сделали бы два щелчка по списку фраз: отмечает начало и конец.
// Дальше человек нажимает ту же самую главную кнопку. Автор
// подтверждает всегда.

function колонка_предложений() {
  const было = предложения.было;
  return эл('div', { класс: 'vc-card в-кандидаты' }, [
    шапка_предложений(было),
    кнопки_предложений(было),
    было && !предложения.свежие ? полоса_несвежести() : null,
    было ? список_кандидатов(было) : пусто_кандидатов(),
    было ? эл('div', { класс: 'в-ряд' }, [
      моно(`asked ${слова.когда(было.когда)} · ` +
           `took ${слова.длина(было.секунд)} · ${слова.деньги(было.деньги)}`,
           'в-подпись'),
    ]) : null,
    было ? эл('button', {
      класс: 'vc-link vc-link--danger', текст: 'remove all suggestions',
      на: { click: убрать_предложения },
    }) : null,
  ]);
}

function шапка_предложений(было) {
  return эл('div', { класс: 'в-ряд' }, [
    эл('b', { класс: 'vc-card__title', текст: 'AI suggestions' }),
    было ? метка(`${было.годных} of ${было.предложения.length} usable`,
                 было.годных ? 'good' : 'warn') : null,
    растяжка(),
  ]);
}

// Цена ДО нажатия — правило спеки. Печатается всегда: и когда
// предложений ещё нет, и когда спрашивают заново.
// Цена стоит У КНОПКИ, а не в общей куче чисел.
//
// Сперва под кнопками стояли две моношириные строки подряд — во что
// обойдётся спросить и во что обошлось в прошлый раз, — и читались
// они как каша: четыре числа, из которых непонятно, какое к чему.
// Числа развели: сколько будет стоить — вплотную к кнопке, которая
// это стоит; сколько ушло — внизу колонки, к итогу.
function кнопки_предложений(было) {
  const о = предложения.оценка;
  return эл('div', { класс: 'в-спросить' }, [
    эл('div', { класс: 'в-спросить__ряд' }, [
      эл('button', {
        класс: 'vc-btn vc-btn--sm',
        текст: спрашиваю ? 'Asking…' : было ? 'Ask again' : 'Ask AI',
        disabled: спрашиваю,
        на: { click: () => спросить_модель(false) },
      }),
      моно(цена_словами(о), 'в-подпись'),
      растяжка(),
      эл('button', {
        класс: 'vc-link vc-link--muted', текст: 'prompt',
        на: { click: () => адрес.идти('settings', 'ai') },
      }),
    ]),
    было && было.язык_разошёлся
      ? эл('span', { класс: 'в-подпись в-жалоба',
                     текст: 'the answer is not in the language of the ' +
                            'video — say so in the prompt' })
      : null,
    было && было.оборвался
      ? эл('span', { класс: 'в-подпись в-жалоба',
                     текст: 'the answer hit its length limit: the last ' +
                            'suggestion may be cut off' })
      : null,
  ]);
}

// Своей арифметики тут нет: и размер, и деньги, и то, дорого ли это,
// посчитал сервис. В браузере не должно быть ни одного числа про
// деньги — их место там, где написано их происхождение.
function цена_словами(о) {
  if (!о) return '';
  if (о.деньги === null) return `${о.вошло} tokens · price unknown`;
  return `≈ ${слова.деньги(о.деньги)}`;
}

