// Экран 03 · Разбор.
//
// Десять минут смотрят на СТАДИИ, а не на общий процент. У каждой свой
// штамп и своя длительность, и по ним видно, что уже нельзя потерять:
// стадия со штампом переживёт и закрытую вкладку, и убитый сервис.
//
// **Полоса хода рисуется только там, где процент известен
// по-настоящему** — правило пакета дизайна. Таких стадий две:
// распознавание знает, сколько секунд звука уже услышало, и рамки
// знают, сколько планов посчитали. Остальным полосу рисовать нечем,
// и вместо неё стоит время: сколько идёт и сколько обычно занимает.
//
// **Экран ничего не помнит.** Всё, что здесь показано, прочитано
// с диска в момент показа. Закрыл вкладку, вернулся через час, открыл
// на другой машине — то же самое.

import {
  нарисовать, лого, блок, маршрут, вертикалки, эл, моно, галка,
  метка, растяжка,
  сказать, сказать_беду, убрать_полосы, подвал,
} from '../shell.js';
import * as связь from '../api.js';
import * as слова from '../words.js';
import * as адрес from '../route.js';

// Как часто переспрашивать, пока работа идёт. Две секунды — не замер,
// а соображение: стадии длятся минутами, а человек смотрит на экран
// и ждёт движения. Чаще незачем, реже — экран выглядит замершим.
const ПЕРЕСПРАШИВАТЬ = 2000;

let часы = null;
// Полоса «Останавливаю…» держится, пока работа правда не встала.
// Работа встаёт не мгновенно — самый долгий шаг идёт внутри чужой
// библиотеки, — и человек обязан увидеть, когда она встала, а не
// остаться перед словом «останавливаю» навсегда.
let полоса_остановки = null;
// Раскрыта ли объяснялка. Экран перерисовывается целиком каждые две
// секунды, и `<details>` каждый раз рождался закрытым: человек
// раскрывал его и через секунду видел, как он схлопнулся сам.
// Помнить это состояние больше негде — на диске ему не место, оно
// про эту вкладку и про эту минуту.
let раскрыто = false;

export async function показать([слаг]) {
  if (!слаг) throw new связь.Беда('No video given to analyze', '');
  остановить_часы();
  await перерисовать(слаг);
}

function остановить_часы() {
  if (часы) { clearInterval(часы); часы = null; }
}

async function перерисовать(слаг) {
  const это = await связь.взять('разбор', { слаг });
  const куски = (await связь.взять('куски', { слаг })).куски;
  рисовать(это, куски);

  // Пока работа идёт ИЛИ ПОДНИМАЕТСЯ, экран переспрашивает сам.
  //
  // «Поднимается» — это отдельное состояние, и без него экран врал.
  // Между нажатием и первой строчкой работы проходит время: процессу
  // надо стартовать и посчитать отпечаток исходника — на трёх
  // гигабайтах это около десяти секунд. Экран смотрел сразу после
  // нажатия, видел «никто не работает» и переставал следить. Человек
  // нажимал «Продолжить разбор», разбор шёл, а экран показывал, что
  // ничего не происходит.
  остановить_часы();
  if (это.идёт_сейчас || это.запускается) {
    часы = setInterval(async () => {
      if (!адрес.на_экране('analysis')) return остановить_часы();
      try {
        const свежее = await связь.взять('разбор', { слаг });
        рисовать(свежее, куски);
        if (!свежее.идёт_сейчас && !свежее.запускается) {
          остановить_часы();
          снять_полосу_остановки();
          if (свежее.разобрано) сказать({
            вид: 'good', что: 'Analysis is done.',
            делать: 'Next: segments — mark where each clip starts ' +
                    'and ends.',
          });
        }
      } catch (беда) { остановить_часы(); сказать_беду(беда); }
    }, ПЕРЕСПРАШИВАТЬ);
  }
}

// ── Рисование ─────────────────────────────────────────────────────────

function рисовать(это, куски) {
  нарисовать({
    колонка: колонка(это, куски),
    заголовок: эл('h1', { класс: 'vc-h1' }, [это.источник]),
    лид: лид(это),
    мета: [моно(`${это.width}×${это.height}`), моно(`${это.fps} fps`)],
    тело: [
      беда_полосой(это),
      эл('div', { класс: 'в-стадии' }, это.стадии.map(стадия)),
      плитка(это.числа),
      раскрывашка(это),
    ],
    футбар: футбар(это),
  });
}

function лид(это) {
  const всего = это.стадии.reduce((с, э) => с + (э.оценка || 0), 0);
  if (это.запускается) {
    return 'Starting analysis — reading the file first. ' +
           'On a big video this takes up to ten seconds.';
  }
  if (это.разобрано) {
    const потрачено = это.стадии.reduce((с, э) => с + (э.секунд || 0), 0);
    return `Analyzed in ${слова.длина(потрачено)}. ` +
           'Cut as many clips from it as you like.';
  }
  if (это.идёт_сейчас) {
    const осталось = это.стадии
      .filter((с) => !с.сделана).reduce((с, э) => с + (э.оценка || 0), 0);
    return `${слова.минут(это.duration)} video · about ` +
           `${слова.длина(осталось)} left`;
  }
  return `${слова.минут(это.duration)} video · analysis takes about ` +
         `${слова.длина(всего)} and happens once`;
}

function стадия(с) {
  // не для человека: значения `data-как`, по ним красит screen.css.
  const как = с.сделана ? 'сделана' : (с.идёт ? 'идёт' : 'ждёт');
  return эл('div', { класс: 'в-стадия', 'data-как': как }, [
    эл('div', { класс: 'в-стадия__ряд' }, [
      с.сделана ? галка() : эл('span', { класс: 'в-точка-стадии', текст: '·' }),
      эл('span', { класс: 'в-стадия__зовут', текст: с.зовут }),
      эл('span', { класс: 'в-стадия__мета', текст: подпись_стадии(с) }),
    ]),
    полоса_хода(с),
  ]);
}

function подпись_стадии(с) {
  if (с.сделана) {
    return [слова.когда(с.когда), слова.длина(с.секунд)].filter(Boolean).join(' · ');
  }
  if (с.идёт) return 'running';
  if (с.оценка === null || с.оценка === undefined) {
    // Рамки считаются по планам, а планов до стадии склеек не знает
    // никто. Выдумать срок значило бы пообещать его из воздуха.
    return 'waiting';
  }
  // «usually 0.0 s» читается как поломка счёта, а значит «мгновенно».
  if (с.оценка < 1) return 'waiting · takes a moment';
  return `waiting · usually ${слова.длина(с.оценка)}`;
}

// Полоса ТОЛЬКО там, где процент известен по-настоящему. Правило
// пакета дизайна, и оно же честность: доля, посчитанная от ожидаемого
// времени, показывала бы 90% у стадии, которая идёт вторую минуту
// сверх плана.
function полоса_хода(с) {
  if (!с.идёт || !с.всего) return null;
  const доля = Math.max(0, Math.min(1, (с.сделано || 0) / с.всего));
  return эл('div', {}, [
    эл('div', { класс: 'vc-progress' }, [
      эл('i', { стиль: { width: `${(доля * 100).toFixed(1)}%` } }),
    ]),
    эл('div', {
      класс: 'в-стадия__мета',
      стиль: { marginLeft: '0', marginTop: '6px' },
      текст: `${Math.round(с.сделано)} of ${Math.round(с.всего)} ${с.единица}`,
    }),
  ]);
}


// ── Плитка чисел ──────────────────────────────────────────────────────

function плитка(числа) {
  const клетки = [
    [['minute of video', 'minutes of video'], числа.минут],
    [['phrase found', 'phrases found'], числа.фраз],
    [['shot', 'shots'], числа.планов],
    [['clip', 'clips'], числа.вертикалок || null],
  ];
  return эл('div', { класс: 'в-плитка' }, клетки.map(([[одна, много], сколько]) =>
    эл('div', {}, [
      // Прочерк там, где числа ещё нет. Пустая клетка читалась бы как
      // ноль, а «ноль планов» и «планы ещё не считали» — разные вещи.
      эл('b', { текст: сколько === null || сколько === undefined
                       ? '—' : String(сколько),
                'data-нет': сколько === null || сколько === undefined }),
      эл('span', { текст: слова.форма(сколько ?? 0, одна, много) }),
    ])));
}

// ── Беда и объяснение ─────────────────────────────────────────────────

function беда_полосой(это) {
  if (это.не_запустилась) {
    return эл('div', { класс: 'vc-bar vc-bar--bad' }, [
      эл('div', { класс: 'vc-bar__what' }, [
        эл('b', { текст: 'Analysis was started but never got going.' }),
        эл('span', { текст: 'Half a minute passed and nothing picked it ' +
                            'up. What Vertcut said is under “details” ' +
                            'below.' }),
      ]),
    ]);
  }
  if (это.беда) {
    return эл('div', { класс: 'vc-bar vc-bar--bad' }, [
      эл('div', { класс: 'vc-bar__what' }, [
        эл('b', { текст: это.беда }),
        эл('span', { текст: это.подсказка || '' }),
      ]),
    ]);
  }
  if (это.остановлен) {
    return эл('div', { класс: 'vc-bar vc-bar--warn' }, [
      эл('div', { класс: 'vc-bar__what' }, [
        эл('b', { текст: 'Analysis stopped.' }),
        эл('span', { текст: 'Finished stages are saved — it will pick up ' +
                            'where it stopped.' }),
      ]),
    ]);
  }
  if (это.брошено) {
    return эл('div', { класс: 'vc-bar vc-bar--warn' }, [
      эл('div', { класс: 'vc-bar__what' }, [
        эл('b', { текст: 'Analysis stopped without saying why.' }),
        эл('span', { текст: 'The process was probably killed, or the ' +
                            'computer went to sleep. Finished stages are saved.' }),
      ]),
    ]);
  }
  return null;
}

function раскрывашка(это) {
  const хвост = (это.хвост || []).join('\n');
  const узел = эл('details', { класс: 'в-раскрывашка', open: раскрыто }, [
    эл('summary', { текст: 'details' }),
    эл('p', {
      // «quit Vertcut» здесь — не «остановить разбор»: разбор идёт своим
      // процессом и переживает выход (решение шестой сессии). С 27-й
      // кнопка «Quit Vertcut» настоящая, и прежние слова «следующий
      // запуск продолжит с места» читались как «выход его обрывает».
      текст: 'Analysis happens once. Close the tab or quit Vertcut — ' +
             'the analysis keeps going on its own; open Vertcut again to ' +
             'see how it’s doing. If it is stopped, finished stages are ' +
             'kept, and the next run picks up where it stopped. The file ' +
             'is not uploaded anywhere: it stays where it is.',
    }),
    хвост ? эл('div', { класс: 'в-хвост', текст: хвост }) : null,
  ]);
  узел.addEventListener('toggle', () => { раскрыто = узел.open; });
  return узел;
}

// ── Колонка и футбар ──────────────────────────────────────────────────

function колонка(это, куски) {
  return [
    лого(это.источник),
    блок('steps', маршрут({
      слаг: это.слаг, сейчас: 'analysis', идти: адрес.идти,
      разобрано: это.разобрано, вертикалок: это.числа.вертикалок,
      состояния: {
        analysis: это.разобрано ? true
                : (это.идёт_сейчас || это.запускается ? 'running' : 'unfinished'),
      },
    })),
    вертикалки({ слаг: это.слаг, куски, идти: адрес.идти }),
    растяжка(),
    эл('p', {
      класс: 'в-подпись',
      текст: 'You can close this tab — analysis runs on its own ' +
             'and saves its progress.',
    }),
    эл('button', {
      класс: 'vc-link vc-link--muted', текст: '← all videos',
      на: { click: () => { адрес.идти('videos'); } },
    }),
    подвал(адрес.идти),
  ];
}

function футбар(это) {
  if (это.запускается) {
    return {
      главное: { зовут: 'Next: segments' },
      почему: 'starting analysis…',
    };
  }
  if (это.идёт_сейчас) {
    return {
      главное: { зовут: 'Next: segments' },
      почему: почему_нельзя(это),
      справа: [эл('button', {
        класс: 'vc-link vc-link--danger', текст: 'stop analysis',
        на: { click: () => остановить(это.слаг) },
      })],
    };
  }
  if (это.разобрано) {
    return {
      главное: {
        зовут: 'Next: segments',
        подпись: `${слова.счёт(это.числа.фраз, 'phrase', 'phrases')} to choose from`,
        делать: () => { адрес.идти('segments', это.слаг); },
      },
      справа: [эл('button', {
        класс: 'vc-link vc-link--muted', текст: 'analyze again',
        на: { click: () => спросить_заново(это.слаг) },
      })],
    };
  }
  const сделано = это.стадии.filter((с) => с.сделана).length;
  return {
    главное: {
      зовут: сделано ? 'Continue analysis' : 'Analyze',
      подпись: сделано
        ? `${сделано} of ${это.стадии.length} stages done — it picks up ` +
          'where it stopped'
        : 'happens once; you can close the tab',
      делать: () => пустить(это.слаг, false),
    },
  };
}

function почему_нельзя(это) {
  const идёт = это.стадии.find((с) => с.идёт);
  if (идёт && идёт.имя === 'crop') {
    return 'phrases are ready, crops are still being worked out';
  }
  return 'phrases are still being worked out — nothing to choose yet';
}

// ── Действия ──────────────────────────────────────────────────────────

async function пустить(слаг, заново) {
  убрать_полосы();
  try {
    await связь.послать('разобрать', { слаг, заново: заново ? '1' : '' });
    await перерисовать(слаг);
  } catch (беда) { сказать_беду(беда); }
}

function спросить_заново(слаг) {
  убрать_полосы();
  сказать({
    вид: 'ask',
    что: 'Analyzing again redoes all five stages.',
    делать: 'Transcribing is the longest of them. Your clips stay, ' +
            'but go out of date: the phrases are worked out again.',
    действия: [
      эл('button', {
        класс: 'vc-btn vc-btn--sm vc-btn--primary', текст: 'Analyze again',
        на: { click: () => пустить(слаг, true) },
      }),
      эл('button', {
        класс: 'vc-btn vc-btn--sm', текст: 'Cancel', на: { click: убрать_полосы },
      }),
    ],
  });
}

function снять_полосу_остановки() {
  if (полоса_остановки) { полоса_остановки.remove(); полоса_остановки = null; }
}

async function остановить(слаг) {
  убрать_полосы();
  try {
    const ответ = await связь.послать('остановить-разбор', { слаг });
    полоса_остановки = сказать({
      вид: 'warn',
      что: ответ.сигнал_послан ? 'Stopping…' : 'Nothing to stop.',
      делать: ответ.сигнал_послан
        // Работа встаёт не мгновенно: самый долгий шаг идёт внутри
        // чужой библиотеки, и та отдаёт управление не сразу.
        ? 'It stops in a few seconds, after finishing what it ' +
          'started. Finished stages are kept.'
        : (ответ.почему || ''),
    });
    if (!ответ.сигнал_послан) полоса_остановки = null;
    // Дальше следят часы: как только работа встала, эта полоса
    // уходит, а на её место встаёт «Разбор остановлен» — из состояния
    // на диске, а не из нашей памяти.
    await перерисовать(слаг);
  } catch (беда) { сказать_беду(беда); }
}
