// Каркас экрана: колонка маршрута, рабочая область, нижняя полоса.
//
// Собирается в одном месте, потому что правил у него ровно три, и все
// три из пакета дизайна:
//
//   · колонка — путь, а не меню: у каждого шага видно состояние;
//   · ОДНА главная кнопка на экран, и она в липкой нижней полосе;
//     погашена — рядом словами написана причина, ДО клика;
//   · опасное и сломанное говорит полосой во всю ширину, никогда
//     модальным окном: окно закрывает собой ровно то, о чём спрашивает.
//
// Разложи это по экранам — и на четвёртом появится вторая главная
// кнопка, а на пятом модальное окно.

import { эл, моно, галка, стрелка, карандаш, точка, растяжка, положить } from './draw.js';
import * as связь from './api.js';
import * as адрес from './route.js';
import * as слова from './words.js';

const корень = () => document.getElementById('экран');

// Где человек стоял, когда этот экран рисовался в прошлый раз.
//
// **Это починка, и одна на все экраны.** Рабочая область прокручивается
// сама, а перерисовка кладёт на её место НОВЫЙ узел — то есть
// прокрутку в ноль. Человек, поправивший рамку плана мышью, оказывался
// в начале экрана: кадр, по которому он только что вёл курсором, уезжал
// вверх. То же было на каждом щелчке по плану, по фразе и на каждом
// тике часов, которые обновляют идущую работу.
//
// Список фраз чинил это у себя сам, с четвёртой сессии. Здесь то же
// самое сделано ОДИН раз: второе такое место разошлось бы с первым
// молча.
//
// Помнится вместе с АДРЕСОМ, а не само по себе: адрес — это и есть
// весь экран. Ушёл человек на другой экран (или на другую вертикалку)
// — новый экран начинается с начала, как и должен.
let стояли = { адрес: null, тело: 0, колонка: 0 };

// ── Экран целиком ─────────────────────────────────────────────────────

export function нарисовать({ колонка, заголовок, лид, мета, тело, футбар }) {
  const полосы = эл('div', { класс: 'в-полосы', id: 'полосы' });
  const шапка = заголовок
    ? эл('header', { класс: 'в-блок' }, [
        эл('div', { класс: 'в-ряд в-ряд--широко' }, [
          заголовок instanceof Node ? заголовок : эл('h1', { класс: 'vc-h1' }, [заголовок]),
          мета ? [растяжка(), эл('div', { класс: 'в-мета' }, мета)] : null,
        ]),
        лид ? эл('p', { класс: 'vc-lede', текст: лид }) : null,
      ])
    : null;

  const рабочее = эл('div', { класс: 'vc-main__body' },
                     [полосы, шапка, тело].flat().filter(Boolean));
  const главное = эл('div', { класс: 'vc-main' }, [
    рабочее,
    футбар ? нижняя_полоса(футбар) : null,
  ]);
  const рельс = колонка ? эл('aside', { класс: 'vc-rail' }, колонка) : null;

  // Снимается прокрутка ДО того, как старая разметка ушла: после
  // `положить` спрашивать её уже не у кого.
  const сейчас = адрес.читать();
  const было_рабочее = document.querySelector('.vc-main__body');
  const было_рельс = document.querySelector('.vc-rail');
  const тот_же = стояли.адрес === сейчас && Boolean(было_рабочее);
  const где = {
    тело: тот_же ? было_рабочее.scrollTop : 0,
    колонка: тот_же && было_рельс ? было_рельс.scrollTop : 0,
  };

  // Полосы, которые уже висят, ПЕРЕЕЗЖАЮТ в новую разметку.
  //
  // Экран перерисовывается целиком на каждом тике часов, а полоса
  // живёт своей жизнью: «Останавливаю…» должна висеть, пока работа
  // не встала, и уйти сама. Сотри её вместе с разметкой — и человек
  // будет видеть её ровно две секунды до следующего тика.
  const было_ = document.getElementById('полосы');
  const жившие = было_ ? [...было_.children] : [];

  положить(корень(), эл('div', { класс: 'vc-shell' }, [рельс, главное]));
  жившие.forEach((п) => полосы.append(п));
  очередь_полос.forEach((п) => полосы.append(п));
  очередь_полос.length = 0;

  if (где.тело) рабочее.scrollTop = где.тело;
  if (где.колонка && рельс) рельс.scrollTop = где.колонка;
  стояли = { адрес: сейчас, тело: где.тело, колонка: где.колонка };
}

// ── Нижняя полоса ─────────────────────────────────────────────────────

// `почему` — причина, по которой главная кнопка погашена. Она не
// украшение: правило 2 пакета требует называть причину ДО клика,
// и поэтому кнопка гасится не флажком, а самой причиной. Есть
// причина — кнопка погашена, и человек читает, чего не хватает.
export function нижняя_полоса({ главное, почему, справа }) {
  const кнопка = главное
    ? эл('button', {
        класс: 'vc-btn vc-btn--primary',
        текст: главное.зовут,
        disabled: !!почему,
        на: почему ? {} : { click: главное.делать },
      })
    : null;
  return эл('div', { класс: 'vc-footbar' }, [
    кнопка,
    (почему || главное?.подпись)
      ? эл('span', { класс: 'vc-footbar__why', текст: почему || главное.подпись })
      : null,
    эл('span', { класс: 'vc-footbar__spacer' }),
    ...(справа || []),
  ]);
}

