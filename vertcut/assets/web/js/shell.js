// Что известно про AI. Заполняется маршрутизатором перед КАЖДЫМ
// показом экрана, а не запоминается навсегда: правило проекта —
// экран ничего не помнит, всё читается с диска в момент показа.
//
// Лежит здесь, потому что подвал колонки один на все экраны. Пусть
// каждый экран спрашивает это сам — и через полгода половина будет
// показывать «без AI» у человека с ключом.
let про_ai = null;

export function запомнить_ai(это) { про_ai = это; }

// Подвал колонки: «Настройки» строкой с меткой состояния AI,
// «Если не работает» и «Поддержать».
//
// **Одно место на все экраны** — по тому же правилу, по которому
// в одном месте собран маршрут. Пока каждый экран рисовал его сам,
// «Настройки» были простой ссылкой без всякой метки, и понять,
// подключён ли ключ, можно было, только зайдя в настройки.
//
// Строкой, а не ссылкой: в макете это ряд с меткой справа. Метка
// говорит состояние — «без AI», пока ключа нет, и имя модели, когда
// он есть. Имя модели тут не украшение: платит человек по ней.
export function подвал(идти) {
  return эл('div', {}, [
    эл('button', {
      класс: 'в-подвал', на: { click: () => идти('settings') },
    }, [
      эл('span', { текст: 'Settings' }),
      растяжка(),
      про_ai === null ? null
        : про_ai.подключён
          ? эл('span', { класс: 'в-подвал__метка' }, [
              точка('в-точка--good'), моно(про_ai.модель)])
          : метка('no AI', 'off'),
    ]),
    // «Если не работает» стоит рядом с настройками и на КАЖДОМ экране.
    //
    // Не в углу и не в меню: её ищут в ту минуту, когда всё сломалось,
    // и искать в этот момент человек не станет — он закроет сервис.
    эл('button', {
      класс: 'в-подвал', на: { click: () => идти('help') },
    }, [
      эл('span', { текст: 'Not working?' }),
    ]),
    // «Поддержать» — ссылка НАРУЖУ, а не экран сервиса. Открывается
    // новой вкладкой, чтобы не уводить человека с его работы. Подписи
    // «куда ведёт» справа нет — так решил автор.
    //
    // `rel` — не украшение: без него открытая вкладка получает ссылку
    // на нашу страницу через `window.opener`.
    эл('a', {
      класс: 'в-подвал', href: ПОДДЕРЖАТЬ,
      target: '_blank', rel: 'noopener noreferrer',
    }, [
      эл('span', { текст: 'Support' }),
    ]),
    // «Quit Vertcut» — последней строкой подвала, тише прочих.
    //
    // До 27-й сессии сервис, поднятый иконкой, жил до выхода из
    // системы: окна у иконки нет, места в Dock тоже, а экран помощи
    // советовал «Quit Vertcut», не говоря, чем. Последней — потому что
    // это конец работы, а не её часть; тише — потому что нажимают её
    // раз за вечер.
    выйти_кнопкой('в-подвал в-подвал--тихо'),
  ]);
}

// Кнопка выхода. Своя функция, а не строка подвала: на первом входе
// подвала нет вовсе (колонки ещё нет), и там она встаёт в верхнюю
// полосу — той же самой кнопкой.
export function выйти_кнопкой(класс) {
  return эл('button', { класс, на: { click: спросить_выход } }, [
    эл('span', { текст: 'Quit Vertcut' }),
  ]);
}

// Что будет, говорится ДО нажатия, и узнаётся у сервиса в момент
// нажатия: идёт ли разбор или сборка. Они НЕ обрываются — решение
// шестой сессии: работа идёт своим процессом, — и человек должен
// знать это заранее, а не обнаружить потом.
//
// Полосой, а не окном браузера: окно `confirm` останавливает страницу
// целиком и выглядит чужим; правило пакета — опасное спрашивает
// полосой.
async function спросить_выход() {
  убрать_полосы();
  let у;
  try {
    у = await связь.взять('что-идёт');
  } catch (беда) { return сказать_беду(беда); }
  const идут = у.идёт || [];
  сказать({
    вид: 'warn',
    что: 'Quit Vertcut?',
    делать: идут.length
      ? `Still running: ${идут.join(', ')}. It keeps going on its own ` +
        'after Vertcut quits — open Vertcut again to see how it’s doing.'
      : 'This page stops working until you open Vertcut again. Nothing ' +
        'is lost: everything is saved on disk.',
    действия: [
      эл('button', {
        класс: 'vc-btn vc-btn--sm vc-btn--primary', текст: 'Quit',
        на: { click: выйти },
      }),
      эл('button', {
        класс: 'vc-btn vc-btn--sm', текст: 'Cancel',
        на: { click: убрать_полосы },
      }),
    ],
  });
}

async function выйти() {
  убрать_полосы();
  let у;
  try {
    у = await связь.послать('выключить');
  } catch (беда) { return сказать_беду(беда); }
  связь.замолчать();
  остановлен(у.идёт || []);
}

// Последнее, что показывает вкладка. Ни одной кнопки: нажимать здесь
// нечего — сервиса нет, а кнопка, которая ничего не делает, хуже её
// отсутствия. Как открыть снова, сказано словами.
function остановлен(идут) {
  положить(корень(), эл('div', { класс: 'в-вход' }, [
    эл('div', { класс: 'в-вход__верх' }, [лого()]),
    эл('div', { класс: 'в-вход__середина' }, [
      эл('div', { класс: 'в-вход__колонка' }, [
        эл('div', { класс: 'в-блок' }, [
          эл('h1', { класс: 'vc-h1', текст: 'Vertcut has stopped.' }),
          эл('p', {
            класс: 'vc-lede',
            текст: 'To use it again, open the Vertcut icon, or run ' +
                   'vertcut screen in a terminal. You can close this tab.',
          }),
        ]),
        идут.length
          ? эл('div', { класс: 'vc-card' }, [
              эл('div', { класс: 'vc-card__title',
                          текст: 'Still running on its own' }),
              ...идут.map((что) => эл('div', { класс: 'в-подпись', текст: что })),
              эл('div', { класс: 'в-подпись',
                          текст: 'Open Vertcut again to see how it’s doing.' }),
            ])
          : null,
      ]),
    ]),
  ]));
}

// Куда ведёт «Поддержать». Одно место, как почта в `help.js`: адрес
// меняется вместе с тем, кто сервис раздаёт.
const ПОДДЕРЖАТЬ = 'https://ko-fi.com/tsarionov';

export function блок(метка, дети) {
  return эл('div', { класс: 'в-блок' }, [
    метка ? эл('div', { класс: 'vc-block-label', текст: метка }) : null,
    ...дети,
  ]);
}

// Шаг маршрута. Номер — курсивом антиквой, справа состояние.
//
// **Шаг, которому некуда вести, кнопкой не рисуется вовсе.** Это
// не мелочь оформления: кнопка, которая ничего не делает, — то же
// самое мёртвое поле, которое мы не рисуем нигде. Такой шаг бывает
// один — тот, на котором человек сейчас стоит.
//
// Найдено пробой, которая гоняет экраны как браузер: она считает
// кнопки, у которых нет дела.
export function шаг({ номер, зовут, состояние, сейчас, сделан, нельзя, идти }) {
  const внутри = [
    эл('span', { класс: 'vc-step__n', текст: String(номер) }),
    зовут,
    эл('span', { класс: 'vc-step__state' },
       [состояние === true ? галка() : (состояние ?? '')]),
  ];
  if (!идти) {
    return эл('div', {
      класс: 'vc-step',
      'aria-current': сейчас ? 'step' : null,
      'data-state': сделан ? 'done' : null,
      'data-некуда': сейчас ? null : '',
      title: нельзя || null,
    }, внутри);
  }
  return эл('button', {
    класс: 'vc-step',
    'aria-current': сейчас ? 'step' : null,
    'data-state': сделан ? 'done' : null,
    disabled: !!нельзя,
    title: нельзя || null,
    на: нельзя ? {} : { click: идти },
  }, внутри);
}

// ── Маршрут целиком ───────────────────────────────────────────────────
//
// **Когда какой шаг открывается — правило, и оно живёт в одном месте.**
// Пока каждый экран рисовал маршрут сам, шаги на разных экранах были
// открыты по-разному: с экрана разбора нельзя было уйти на фрагменты
// даже у разобранного видео, хотя с экрана фрагментов — можно.
// Человек это видит сразу: шаг серый там, где секунду назад был живой.
//
// Правило простое и всё целиком тут:
//
//   · разбор открыт всегда — он первый;
//   · фрагменты открыты, как только видео разобрано;
//   · описания и сборка — как только есть хоть одна вертикалка.
//
// Погашенный шаг говорит причину до клика: это правило пакета дизайна
// и правило проекта разом.

// `внутри` — мы на шаге, но не на его экране.
//
// Экран вертикалки и редактор субтитров — это то, что делают ВНУТРИ
// четвёртого шага, а не сам шаг. Шаг при этом подсвечен (человек
// понимает, где он), но остаётся живой ссылкой: иначе с вертикалки
// нельзя попасть на сборку, где очередь и скачивание, — а она уже
// может быть собрана.
export function маршрут({ слаг, сейчас, внутри, разобрано, вертикалок, идти,
                          состояния = {} }) {
  const есть = Number(вертикалок) > 0;
  const шаги = [
    { имя: 'analysis', зовут: 'Analyze', можно: true, сделан: разобрано },
    { имя: 'segments', зовут: 'Segments', можно: !!разобрано,
      почему: 'after analysis', сделан: есть },
    { имя: 'descriptions', зовут: 'Descriptions', можно: есть,
      почему: 'after the first clip' },
    { имя: 'export', зовут: 'Export', можно: есть,
      почему: 'after the first clip' },
  ];
  return шаги.map((с, n) => шаг({
    номер: n + 1,
    зовут: с.зовут,
    сейчас: с.имя === сейчас,
    сделан: !!с.сделан,
    нельзя: с.можно ? null : с.почему,
    состояние: состояния[с.имя] ?? (с.сделан ? true : ''),
    // Шагу, на котором стоим, идти некуда — и кнопкой он не рисуется.
    // Кроме случая «мы внутри него»: там идти как раз есть куда.
    идти: (с.можно && (внутри || с.имя !== сейчас))
      ? () => идти(с.имя, слаг) : null,
  }));
}

// ── Вертикалки в колонке ──────────────────────────────────────────────
//
// **Они показываются на КАЖДОМ экране, где есть колонка.** Список
// вертикалок — это то, ради чего человек сюда пришёл, и прятать его
// на шаге разбора значило бы сказать «этого у вас пока нет» там, где
// оно есть.
//
// Кадр 9:16 здесь на месте: у вертикалки форма именно такая. У видео
// её нет, и там кадра в колонке тоже нет — форма вертикальной рамки
// говорила бы про горизонтальное видео неправду.

export function вертикалки({ слаг, куски, выбран, идти }) {
  if (!куски || !куски.length) return null;
  return блок(`clips · ${куски.length}`, куски.map((к) => эл('button', {
    класс: 'vc-rail-row',
    'aria-current': к.id === выбран ? 'true' : null,
    на: { click: () => идти('clip', слаг, к.id) },
  }, [
    обложка_ролика(слаг, к.id),
    эл('span', { стиль: { minWidth: 0 } }, [
      // В строке стоит НАЗВАНИЕ, а описание уезжает в подсказку.
      //
      // **Сперва было наоборот, и автор сказал, что так нельзя.**
      // Описание — это текст для формы площадки, две-три строки прозы;
      // в строке колонки от него видно первые тридцать знаков
      // и многоточие, а тридцать знаков прозы («A scene from the first
      // season has been…») не различают вертикалки между собой почти
      // никогда. Название — первые слова, которые услышит зритель,
      // и в списке ролик узнаётся именно по ним.
      //
      // Описание при этом не потеряно: оно в подсказке, и весь экран
      // «Описания» — про него.
      эл('b', { класс: 'vc-rail-row__title',
                текст: к.зовут,
                title: к.описание ? `${к.зовут} — ${к.описание}` : к.зовут }),
      эл('span', { класс: 'vc-rail-row__meta', текст: подпись_ролика(к) }),
    ]),
  ])));
}

function подпись_ролика(к) {
  const длина = к.duration ? слова.длина(к.duration) : '';
  const как = !к.собрано ? 'not exported'
    : (к.устарел ? 'out of date' : 'exported');
  return [как, длина].filter(Boolean).join(' · ');
}

// Кадр не отдался — на его месте полосатая заглушка из пакета дизайна:
// она честно говорит «кадра пока нет», а чёрный прямоугольник читался
// бы как «ролик чёрный».
function обложка_ролика(слаг, ключ) {
  const кадр = эл('img', {
    класс: 'vc-rail-row__thumb', alt: '',
    стиль: { objectFit: 'cover' },
    src: связь.адрес('обложка-ролика', { слаг, ключ }),
  });
  кадр.addEventListener('error', () => кадр.classList.add('vc-stripe'));
  return кадр;
}

// ── Картинка, которую ещё рисуют ──────────────────────────────────────
//
// **Кадр вертикалки считается секунду-две, и молчать это время
// нельзя.** Сервис в этот момент делает настоящую работу: вынимает
// кадр из исходного файла (а тот бывает на три гигабайта), режет
// колонку и рисует субтитр настоящим шрифтом. Пока это идёт, место
// под картинку пустое — и человек, щёлкнувший по плану, не понимает,
// сработало ли.
//
// Место при этом НЕ ПРЫГАЕТ: у него та же форма 9:16, что у самой
// картинки, и подпись стоит поверх, а не вместо.

export function кадр_с_ожиданием({ src, alt, класс, ждём: подпись }) {
  const картинка = эл('img', { класс, alt: alt || '', src });
  const место = эл('div', {
    класс: 'в-рисуется', 'data-рисуется': '',
  }, [
    картинка,
    эл('span', { класс: 'в-рисуется__слово',
                 текст: подпись || 'drawing frame…' }),
  ]);
  const готово = () => место.removeAttribute('data-рисуется');
  картинка.addEventListener('load', готово);
  // Не отдалось — подпись тоже уходит: висеть «рисую» над пустотой
  // хуже, чем показать пустоту честно.
  картинка.addEventListener('error', готово);
  if (картинка.complete && картинка.naturalWidth) готово();
  return место;
}

// ── Полосы-сообщения ──────────────────────────────────────────────────

// Полосы, сказанные до того, как экран нарисовался, ждут здесь.
// Иначе отказ, случившийся на первой же просьбе, не показался бы
// вовсе — а это ровно тот отказ, который важнее прочих.
const очередь_полос = [];

export function сказать({ вид = 'warn', что, делать, действия = [] }) {
  const полоса = эл('div', { класс: `vc-bar vc-bar--${вид}` }, [
    эл('div', { класс: 'vc-bar__what' }, [
      эл('b', { текст: что }),
      делать ? эл('span', { текст: делать }) : null,
    ]),
    действия.length
      ? эл('div', { класс: 'vc-bar__acts' }, действия)
      : null,
  ]);
  const куда = document.getElementById('полосы');
  if (куда) куда.prepend(полоса);
  else очередь_полос.push(полоса);
  return полоса;
}

// Отказ сервиса. Первая строка — что случилось, вторая — что делать:
// то же правило, по которому он печатается в терминале.
//
// Отказ «стиль не читается» (испорчен или старого образца) несёт
// с собой видео и вертикалку — и под ним встаёт дорога в редактор,
// где стиль чинится. Без неё экран вертикалки выбрасывал на список
// видео с советом «нажмите кнопку в редакторе», а попасть в редактор
// оттуда было нельзя.
export function сказать_беду(беда) {
  // не для человека: «стиль» — вид отказа, слово договора с сервером.
  const к_стилю = беда.вид === 'стиль' && беда.слаг && беда.ключ;
  return сказать({
    вид: 'bad',
    что: беда.что || String(беда),
    делать: беда.подсказка || '',
    действия: к_стилю ? [эл('button', {
      класс: 'vc-btn vc-btn--sm vc-btn--primary', текст: 'Fix the style',
      на: { click: () => адрес.идти('subtitles', беда.слаг, беда.ключ) },
    })] : [],
  });
}

export function убрать_полосы() {
  const куда = document.getElementById('полосы');
  if (куда) куда.replaceChildren();
}

