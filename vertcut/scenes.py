"""Метрика склеек: насколько кадр непохож на предыдущий.

## Зачем она своя

До шестой сессии это считала библиотека `scenedetect`, а та на первом
же импорте тянет `opencv` — 119 МБ поставки. Пользовался им ОДИН
детектор склеек: детектор лиц от него отвязали ещё в первой сессии.

Уйти было нельзя, пока метрика чужая: **порог 35 замерен ИМЕННО
на ней**, глазами, по шестнадцати спорным границам во второй сессии.
Своя метрика, дающая другие числа, обесценила бы этот замер вместе
с порогом.

Поэтому здесь не «своя метрика», а **та же самая, пересчитанная без
opencv**, и доказывается это единственным способом, который что-то
значит: прогоном по тем же видео с требованием тех же границ.

## Что померено

| видео | кадров | склеек у библиотеки | у нас | разошлось |
|---|---|---|---|---|
| эссе (анимация) | 29198 | 424 | 424 | **0** |
| интервью (камера) | 24775 | 211 | 211 | **0** |
| английское видео | 9567 | 45 | 45 | **0** |
| книга (1080p) | 6000 | 5 | 5 | **0** |

Ни одной разошедшейся границы на семидесяти тысячах кадров.

## Как считается

На каждом кадре: уменьшить до 256 точек в ширину, перевести в HSV,
сложить средние отличия трёх каналов от предыдущего кадра и поделить
на три. Вышло больше порога — склейка. Дальше короткие склейки
сливаются (см. `_слить_короткие`).

## Где мы совпали точно, а где нет, и почему

**Уменьшение кадра сошлось с opencv ДО НУЛЯ** — с его точным режимом
(`INTER_LINEAR_EXACT`): ни одного расхождения на 10 463 463 значениях,
это семь разных соотношений сторон плюс восемьдесят живых кадров.
От его же БЫСТРОГО режима оно отличается на единицу на 12% точек,
и это не наша неточность: быстрый путь внутри opencv теряет точность
ради скорости, а какой именно ответ он даст, зависит ещё и от того,
какие команды умеет процессор. Библиотека склеек звала как раз быстрый
— на живом материале эта единица границ не сдвинула ни одной.

**Перевод в HSV сошёлся почти точно:** на 138 240 000 значений живого
видео разошлось 13 628 (0.0099%), всегда на единицу и **всегда
в насыщенности** — тон и яркость сошлись до нуля. Причина — округление
в таблице деления, и оно внутри opencv менялось от версии к версии.
Влияние на счёт: около одной десятитысячной.

**Декодирование сойтись не может, и это названо вслух.** Один и тот же
файл ffmpeg и opencv разбирают в разные числа: у них разный перевод
из телевизионного цвета в экранный. Подбором флагов расхождение сжато
до 0.085 из 255 в среднем (было 1.88), дальше не идёт — opencv
переводит цвет своим кодом. Именно поэтому доказательством служат
границы, а не пиксели.

## Цена

Стадия склеек стала медленнее: на девятнадцатиминутном эссе 37 секунд
против 7 у библиотеки. Внутри девятиминутного разбора это плюс пять
процентов. Получено за это: 121 МБ поставки, две зависимости и две
строки чужой ложной тревоги при каждом запуске.

Заодно перестал плавать замер цены стадии. Прежние 0.022 держались
на двух числах, расходившихся втрое, и там честно стояло «разброс
не объяснён». Четыре новых замера сходятся в пределах десятой доли
(0.031…0.034): разброс был не в материале, а в чужом коде.

Быстрее numpy тут не сделать: три четверти времени уходит на уменьшение
кадра, и оно упирается в память, а не в счёт.
"""

from __future__ import annotations

import numpy as np

from . import media, tuning

# ─── уменьшение кадра ────────────────────────────────────────────────

# Доли считаются целыми числами с восемью двоичными знаками после
# запятой, и округление делается ОДНО, в самом конце.
#
# **Оба числа подобраны замером, а не взяты из головы.** Сперва стояло
# одиннадцать знаков — и сходилось до нуля, пока проверялось на кадре
# 640×360, где множитель ровно 2.5 и доли выражаются точно любым
# способом. Первый же кадр с другим соотношением сторон разошёлся
# на единицу.
#
# Перебор на шести разных соотношениях, 818 тысяч значений:
#
#   8 знаков, одно округление  — разошлось 0
#   8 знаков, два округления   — 169 959
#   11 знаков, одно округление — 29 158
#   11 знаков, два округления  — 182 159
#
# Меняете — сверка с точным режимом opencv перестанет давать ноль,
# а вместе с ней поедет метрика и смысл замеренного порога.
_БИТ = 8
_ШКАЛА = 1 << _БИТ


def _ось(было: int, стало: int) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Откуда брать и с какими долями — на одну сторону кадра.

    **Доли округляются каждая своя**, а не «вторая как остаток
    от первой»: так это сделано в opencv.
    """
    масштаб = было / стало
    fx = (np.arange(стало) + 0.5) * масштаб - 0.5
    sx = np.floor(fx).astype(np.int64)
    доля = fx - sx
    # Края: за первую и последнюю точку не выходим, а долю прижимаем
    # к ближнему краю — иначе пришлось бы читать соседа, которого нет.
    мало = sx < 0
    sx = np.where(мало, 0, sx)
    доля = np.where(мало, 0.0, доля)
    много = sx + 1 >= было
    sx = np.where(много, было - 2, sx)
    доля = np.where(много, 1.0, доля)
    a0 = np.rint((1.0 - доля) * _ШКАЛА).astype(np.int32)
    a1 = np.rint(доля * _ШКАЛА).astype(np.int32)
    return sx, a0, a1


def уменьшить(кадр: np.ndarray, ш: int, в: int) -> np.ndarray:
    """Кадр поменьше, теми же числами, какими это делает opencv.

    **Сперва по высоте, потом по ширине.** Порядок выбран не на глаз:
    строки лежат в памяти подряд, и выборка строк — это копирование
    кусками, а выборка столбцов — прыжки. Сделав сперва высоту, дальше
    работаем на вдвое меньшем кадре. На ответ порядок не влияет вовсе:
    округление одно и делается в самом конце.

    Числа 32-битные: наибольшее возможное 255 · 256 · 256 — это
    16.7 миллиона, а влезает 2.1 миллиарда. Шире брать незачем,
    а лишняя память здесь и есть лишнее время.
    """
    sy, ay0, ay1 = _ось(кадр.shape[0], в)
    sx, ax0, ax1 = _ось(кадр.shape[1], ш)
    верт = кадр[sy] * ay0[:, None, None]
    верт += кадр[sy + 1] * ay1[:, None, None]
    гор = верт[:, sx] * ax0[None, :, None]
    гор += верт[:, sx + 1] * ax1[None, :, None]
    гор += 1 << (2 * _БИТ - 1)
    гор >>= 2 * _БИТ
    return np.clip(гор, 0, 255).astype(np.uint8)


# ─── цвет ────────────────────────────────────────────────────────────

# Таблицы деления. Тот же приём, что в opencv: деление на каждое
# возможное значение посчитано заранее, а на кадре остаётся умножение.
_ЦВЕТ_БИТ = 12
_ДЕЛИТЕЛЬ_S = np.zeros(256, np.int32)
_ДЕЛИТЕЛЬ_H = np.zeros(256, np.int32)
for _i in range(1, 256):
    _ДЕЛИТЕЛЬ_S[_i] = round((255 << _ЦВЕТ_БИТ) / _i)
    _ДЕЛИТЕЛЬ_H[_i] = round((180 << _ЦВЕТ_БИТ) / (6.0 * _i))


def в_цвета(кадр: np.ndarray) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Тон, насыщенность, яркость — как их считает opencv.

    Тон лежит в 0…179, а не в 0…359: он должен помещаться в байт,
    и так же поступает opencv. Числа тут не подобранные, а взятые
    из его же кода: своя формула дала бы другой счёт и обесценила
    замеренный порог.
    """
    b = кадр[:, :, 0].astype(np.int32)
    g = кадр[:, :, 1].astype(np.int32)
    r = кадр[:, :, 2].astype(np.int32)
    ярк = np.maximum(np.maximum(b, g), r)
    тень = np.minimum(np.minimum(b, g), r)
    размах = ярк - тень
    нас = (размах * _ДЕЛИТЕЛЬ_S[ярк] + (1 << (_ЦВЕТ_БИТ - 1))) >> _ЦВЕТ_БИТ
    тон = np.where(ярк == r, g - b,
                   np.where(ярк == g, b - r + 2 * размах,
                            r - g + 4 * размах))
    тон = (тон * _ДЕЛИТЕЛЬ_H[размах] + (1 << (_ЦВЕТ_БИТ - 1))) >> _ЦВЕТ_БИТ
    тон = np.where(тон < 0, тон + 180, тон)
    return тон, нас, ярк


# ─── сама метрика ────────────────────────────────────────────────────

def оценки(proxy, on_tick=None) -> list[float]:
    """Насколько каждый кадр непохож на предыдущий. У первого — ноль.

    Считается по уменьшенной копии, а не по исходнику: замер первой
    сессии — проход по копии 33 секунды, по исходнику 341, и связь
    метрик 0.995.
    """
    ш, в = media.размер_кадра(proxy)
    делитель = (ш / tuning.ШИРИНА_СЧЁТА_СКЛЕЕК
                if ш >= tuning.ШИРИНА_СЧЁТА_СКЛЕЕК else 1.0)
    сш = max(1, round(ш / делитель))
    св = max(1, round(в / делитель))

    прошлый = None
    из = []
    for сырьё in media.поток_кадров(proxy, ш, в):
        кадр = np.frombuffer(сырьё, np.uint8).reshape(в, ш, 3)
        if делитель > 1.0:
            кадр = уменьшить(кадр, сш, св)
        цвета = в_цвета(кадр)
        if прошлый is None:
            из.append(0.0)
        else:
            точек = float(цвета[0].size)
            из.append(sum(np.abs(a - b).sum() / точек
                          for a, b in zip(цвета, прошлый)) / 3.0)
        прошлый = цвета
        if on_tick and len(из) % 250 == 0:
            on_tick(len(из))
    return из


def _слить_короткие(оценки_: list[float], порог: float,
                    длина: int) -> list[int]:
    """Короткие склейки подряд считаются одной.

    Это не «убрать лишнее», а перенесённое правило библиотеки, и без
    него границы не сойдутся. Смысл такой: вспышка, быстрый наплыв или
    пара кадров мельтешения дают несколько срабатываний подряд; склейка
    там одна, и стоит она на последнем кадре, который был выше порога.

    **Правило перенесено дословно, включая то, что слив включается
    только после первой настоящей склейки.** Выглядит это странно,
    но именно так считала библиотека, а мы обязаны дать её границы.
    """
    резы: list[int] = []
    последний_выше = 0
    сливаем = False
    начало_слива = 0
    включён = False
    for n, оценка in enumerate(оценки_):
        выше = оценка >= порог
        набрана = (n - последний_выше) >= длина
        if выше:
            последний_выше = n
        if сливаем:
            if набрана and not выше and (последний_выше - начало_слива) >= длина:
                сливаем = False
                резы.append(последний_выше)
            continue
        if not выше:
            continue
        if набрана:
            включён = True
            резы.append(n)
            continue
        if включён:
            сливаем = True
            начало_слива = n
    return резы


def склейки(proxy, порог: float, минимум_кадров: int,
            on_tick=None) -> list[int]:
    """Номера кадров, на которых начинается новый план."""
    return _слить_короткие(оценки(proxy, on_tick=on_tick), порог,
                           max(1, минимум_кадров))
