РЕЖИМ_КРОП = "crop"
РЕЖИМ_ПОЛНЫЙ = "full"
РЕЖИМЫ = (РЕЖИМ_КРОП, РЕЖИМ_ПОЛНЫЙ)
РЕЖИМ_ПО_СЛОВУ = {"crop": РЕЖИМ_КРОП, "full": РЕЖИМ_ПОЛНЫЙ}
ИМЯ_РЕЖИМА = {РЕЖИМ_КРОП: "crop", РЕЖИМ_ПОЛНЫЙ: "full frame"}


def timeline(cut: dict, duration: float, shots: list[dict],
             fps: float = 25.0, плашка_с: float | None = None) -> list[dict]:
    """Планы ролика по порядку, в шкале ролика.

    Границы плана подрезаются файлом: первый и последний планы почти
    всегда входят кусками, и длина куска — это то, что увидит зритель,
    а не длина плана в исходном видео.

    **Отсчёт идёт от первого КАДРА файла, а не от начала звука.**

    **`плашка_с` гасит планы под плашкой в конце.** Этих кадров зритель
    не увидит вовсе — там картинка плашки, — и спрашивать у них рамку
    значит платить секунду счёта за кадр, который никуда не попадёт.
    План, заходящий под плашку только концом, подрезается по ней
    и считается как все.

    Подрезка здесь, а не у того, кому понадобилось, по тому же правилу,
    по которому здесь живёт вся арифметика времени ролика: второе
    место, знающее, где начинается плашка, разъехалось бы с первым.
    """
    таблица = карта(cut, duration, fps)
    вышло = []
    for строка in таблица["куски"]:
        видео = строка["видео"]
        окно_at = round(видео["с_кадра"] / fps, 6)
        окно_till = round((видео["с_кадра"] + видео["кадров"]) / fps, 6)
        if плашка_с is not None:
            окно_till = min(окно_till, round(плашка_с, 6))
            if окно_till <= окно_at:
                continue
        начало = видео["essay0"]
        for план in shots:
            at = round(план["start"] - начало + окно_at, 3)
            till = round(план["end"] - начало + окно_at, 3)
            if till <= окно_at or at >= окно_till:
                continue
            видно_at = max(at, окно_at)
            видно_till = min(till, окно_till)
            # Полкадра — та черта, ниже которой плана в файле просто нет.
            if видно_till - видно_at < 0.02:
                continue
            вышло.append({
                "idx": план["idx"],
                "кусок": строка["n"],
                "source": {"start": план["start"], "end": план["end"],
                           "duration": план["duration"]},
                # Какие секунды ИСХОДНИКА видны в ролике. Это НЕ то же,
                # что границы плана: первый и последний планы входят
                # кусками, и `source` у них шире видимого.
                #
                # Считается здесь, а не у того, кому понадобилось:
                # арифметика времени ролика живёт в одном месте, и это
                # правило проекта. Черновой просмотр на экране играет
                # исходник именно по этим числам.
                "видно": {
                    "start": round(начало + видно_at - окно_at, 3),
                    "end": round(начало + видно_till - окно_at, 3),
                },
                "at": round(видно_at, 3),
                "till": round(видно_till, 3),
                "duration": round(видно_till - видно_at, 3),
                # Привязка ко времени видео: на секунде `t0` ролика
                # стоит секунда `essay0` исходника.
                "t0": окно_at,
                "essay0": начало,
                "cx": план.get("crop_cx"),
                "by": план.get("crop_by"),
                "spread": план.get("crop_spread"),
                # Обрубок на краю: план, от которого остался огрызок.
                "clipped_head": at < окно_at - 1e-6,
                "clipped_tail": till > окно_till + 1e-6,
            })
    вышло.sort(key=lambda r: r["at"])
    if not вышло:
        from .errors import VertcutError
        raise VertcutError(
            f"Clip {cut['id']} has no shots in it — the cuts seem to "
            "belong to a different file",
            hint="analyze again: vertcut ingest … --again")
    return вышло


def hand_of(cut: dict) -> dict:
    """Всё, что человек сделал руками. Одним куском, а не по полям:
    проверка «устарел ли лежащий рядом файл» читает его голым json
    и должна ловить любую правку, а не перечисленные заранее."""
    return cut.get("edit") or {}


def frames_of(cut: dict) -> dict:
    """Поправленные рукой рамки. Ключи — номера планов, строками."""
    return hand_of(cut).get("shots") or {}


def resolve(cut: dict, rows: list[dict]) -> list[dict]:
    """Дописать каждому плану режим, рамку и то, чья она.

    **Машина предлагает, рука сильнее.** Предложенное лежит в
    `shots.json` и пересчитывается свободно; правка руки живёт в самом
    ролике. Слить их в одно поле значило бы стереть правку при первом
    пересчёте — молча и через месяц.
    """
    рука = frames_of(cut)
    for ряд in rows:
        своё = рука.get(str(ряд["idx"])) or {}
        ряд["mode"] = своё.get("mode") or РЕЖИМ_КРОП
        ряд["cx"] = своё.get("cx", ряд.get("cx"))
        ряд["hand"] = bool(своё)
        ряд["полный_кадр"] = ряд["mode"] == РЕЖИМ_ПОЛНЫЙ
    return rows


def digest(rows: list[dict]) -> str:
    """Сжатая запись всего монтажа кадра. По ней видно, что он уехал.

    Пишется в штамп сборки. Сравнивать сами числа было бы то же самое,
    но строка читается глазом в `cut.json`, а список словарей — нет.
    """
    куски = []
    for ряд in rows:
        cx = "—" if ряд["cx"] is None else f"{ряд['cx']:.4f}"
        # Кусок отпечатка монтажа: поменяй его — и все собранные
        # ролики станут «устаревшими».
        куски.append(f"{ряд['idx']}:{cx}:{ряд['mode']}"
                     + (":рука"  # не для человека
                        if ряд.get("hand") else ""))
    return " ".join(куски)


def needed(rows: list[dict]) -> list[int]:
    """Каким планам рамка ещё не посчитана."""
    return [ряд["idx"] for ряд in rows if ряд["cx"] is None]


def stubs(rows: list[dict]) -> list[dict]:
    """Огрызки: планы, от которых в ролике остался кусок короче порога.

    Ролик начинается по границе фразы, а не по склейке, поэтому
    в начале часто торчит обрубок плана: зритель успевает увидеть хвост
    сцены, начала которой не было. Сервис его ПОКАЗЫВАЕТ, а решает
    человек — правило спеки.
    """
    return [ряд for ряд in rows
            if ряд["duration"] < tuning.STUB
            and (ряд["clipped_head"] or ряд["clipped_tail"])]


def montage(project, meta: dict, cut: dict, shots: list[dict],
            говорить=None) -> list[dict]:
    """Весь монтаж кадра ролика: планы, досчитанные рамки, правки рукой.

    Одна дорога для команды и для будущего экрана: досчитать рамки тем
    планам, у которых их нет, и разложить правки. Две дороги собрали бы
    разное, и увидел бы это зритель.
    """
    from . import crop, report, shots as планы

    говорить = говорить or report.скажи
    duration = float(meta["duration"])
    fps = float(meta.get("fps") or 25)
    # Планы под плашкой в конце гасятся: там картинка плашки, а не
    # видео, и рамка этим кадрам не нужна ни для чего.
    from . import plate
    плашка_с = plate.начало(total_of(cut, duration),
                            plate.сырые(project, cut["id"]))
    ряды = timeline(cut, duration, shots, fps, плашка_с)
    надо = sorted({ряд["idx"] for ряд in ряды
                   if ряд["cx"] is None})
    if надо:
        говорить(f"  crops not worked out yet for "
                 f"{report.счёт(len(надо), 'shot', 'shots')} — working them out")
        итог = crop.compute(_исходник(meta), shots, project,
                            set(надо), говорить)
        планы.write(shots, project)
        говорить(f"    follows a face: {итог['by_face']}, centered: "
                 f"{итог['by_center']}")
        ряды = timeline(cut, duration, shots, fps, плашка_с)
    return resolve(cut, ряды)


def _исходник(meta: dict):
    from pathlib import Path
    return Path(meta["source"])


def поставить_рамку(cut: dict, план: int, *, cx: float | None = None,
                    режим: str | None = None,
                    сбросить: bool = False,
                    планов: int | None = None) -> dict:
    """Правка рамки рукой. Меняет `cut` на месте и возвращает, что стало.

    **Машина предлагает, рука сильнее** — и правка руки живёт в самом
    ролике, а не в `shots.json`. Предложенное там пересчитывается
    свободно; слей их в одно поле, и правка сотрётся при первом
    пересчёте, молча и через месяц.

    Заведено здесь, а не в команде, потому что мест стало два. В
    терминале рамка задаётся числом, на экране — мышью по кадру, и это
    единственное, чего в терминале сделать нельзя вовсе. Две копии
    разошлись бы в самом тихом месте: в том, убирается ли пустой блок
    правок.
    """
    правки = dict(hand_of(cut))
    рамки = dict(правки.get("shots") or {})
    ключ = str(int(план))
    # Плана, которого нет, нет и у рамки: до 24-й сессии `frame --shot 99`
    # молча записывал правку в пустоту и говорил, что всё сделано.
    if планов is not None and not 1 <= int(план) <= планов and not сбросить:
        raise VertcutError(f"There is no shot {план}: the video has "
                           f"shots 1 to {планов}",
                           hint="see this clip's shots: vertcut plans "
                                "VIDEO_ID CLIP_ID")

    if сбросить:
        if ключ not in рамки:
            raise VertcutError(f"Shot {план} has no crop set by hand — "
                               "nothing to reset")
        рамки.pop(ключ)
        стало = None
    else:
        своё = dict(рамки.get(ключ) or {})
        if cx is not None:
            if not 0.0 <= float(cx) <= 1.0:
                raise VertcutError(
                    f"The crop position is a share of the width from 0 "
                    f"to 1, not {cx}")
            своё["cx"] = round(float(cx), 4)
        if режим is not None:
            if режим not in РЕЖИМЫ:
                raise VertcutError(
                    f"Unknown shot mode: {режим}",
                    hint=f"there are: {', '.join(РЕЖИМЫ)}")
            своё["mode"] = режим
        if not своё:
            raise VertcutError("Nothing to change: give a crop position "
                               "or a mode")
        рамки[ключ] = своё
        стало = своё

    # Пустой блок правок УБИРАЕТСЯ целиком, а не остаётся пустым:
    # иначе «правок не было» и «правки были и сняты» выглядят
    # одинаково, а штамп сборки сравнивает именно этот блок.
    if рамки:
        правки["shots"] = рамки
    else:
        правки.pop("shots", None)
    if правки:
        cut["edit"] = правки
    else:
        cut.pop("edit", None)
    return стало or {}
