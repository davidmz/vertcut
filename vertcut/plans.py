"""Планы, попавшие в ролик, и шкала его времени.

Планы наследуются из видео как есть — их не выбирают заново, они уже
стоят под словами. Работа этого файла одна: сказать, какие планы попали
в ролик, где они лежат по его времени и какая рамка у каждого.

**Шкалу ролика считает ОДНО место — `карта()`.** Своей арифметики
времени больше нигде нет. У предка нарушение этого правила стоило кадра
на каждой склейке: сверка считала время кадра у себя, цепочка у себя,
и врала цепочка.

**У картинки и у звука нули РАЗНЫЕ, и это не придирка.** `-ss` перед
входом ставит ffmpeg на первый кадр, время которого не меньше
заданного, а заданное берётся из времён слов и на сетку кадров
не попадает почти никогда. Картинка идёт на сотые впереди звука,
и монтаж кадра считается от НЕЁ.
"""

from __future__ import annotations

import math

from . import pick, tuning
from .errors import VertcutError


def fades(cut: dict, duration: float) -> list[dict]:
    """Шторки каждого куска: сколько материала есть до и после него.

    Шторка работает НАРУЖУ — берёт секунды за границей куска и нарастает
    по ним, чтобы первое слово звучало с полной громкости. У края видео
    материала может не быть вовсе, и тогда шторка ровно настолько
    короче.

    **На внутреннем стыке шторок две, и они идут крест-накрест.** Конец
    первого куска гаснет на выброшенном материале, начало второго на нём
    же разгорается. Поэтому у стыка число одно на оба куска: меньшее
    из того, что есть с каждой стороны. Врозь эти два числа однажды
    разъедутся, и файл выйдет не той длины — молча, потому что сумма
    кусков сойдётся.

    Цена стыка названа и не прячется: **ролик длиннее суммы кусков
    ровно на одну шторку за стык**, и в эти доли секунды на экране
    материал, которого человек не выбирал. Померить это нечем. Слушать.
    """
    хочу = float(cut.get("fade", tuning.EDGE_FADE))
    куски = pick.pieces(cut)
    было = [{"до": round(min(хочу, к["start"]), 3),
             "после": round(min(хочу, max(duration - к["end"], 0.0)), 3)}
            for к in куски]
    вышло = []
    for n, _ in enumerate(куски):
        до = было[n]["до"] if n == 0 else round(
            min(было[n]["до"], было[n - 1]["после"]), 3)
        после = было[n]["после"] if n == len(куски) - 1 else round(
            min(было[n]["после"], было[n + 1]["до"]), 3)
        вышло.append({"lead": max(до, 0.0), "trail": max(после, 0.0),
                      "want": хочу})
    return вышло


def total_of(cut: dict, duration: float) -> float:
    """Длина файла: речь, обе краевые шторки и по шторке на каждый стык."""
    куски = pick.pieces(cut)
    шторки = fades(cut, duration)
    длина = sum(к["duration"] for к in куски)
    длина += шторки[0]["lead"] + шторки[-1]["trail"]
    длина += sum(ш["trail"] for ш in шторки[:-1])
    return round(длина, 3)


def карта(cut: dict, duration: float, fps: float = 25.0) -> dict:
    """Куда какая секунда ролика смотрит в исходном видео.

    У сплошного ролика в таблице одна строка, у разрывного — по строке
    на кусок: где кусок начинается по времени ролика, какому кадру видео
    отвечает его первый кадр, сколько кадров он занимает.

    У куска ДВА ряда чисел, и путать их нельзя:

    - `звук` — точные секунды, по ним раскладываются слова и субтитры;
    - `видео` — кадры, по ним считается монтаж и сверяется готовый файл.
    """
    куски = pick.pieces(cut)
    шторки = fades(cut, duration)
    всего = total_of(cut, duration)

    рубежи = [0.0]
    for n, кусок in enumerate(куски):
        конец = рубежи[-1] + шторки[n]["lead"] + кусок["duration"]
        if n == len(куски) - 1:
            конец += шторки[n]["trail"]
        рубежи.append(round(конец, 6))
    рубежи[-1] = всего

    кадры = [round(t * fps) for t in рубежи]
    строки = []
    for n, кусок in enumerate(куски):
        звук0 = round(кусок["start"] - шторки[n]["lead"], 3)
        # Первый кадр этого куска в видео: ffmpeg встаёт на кадр, время
        # которого не меньше заданного.
        кадр0 = math.ceil(звук0 * fps - 1e-6)
        строки.append({
            "n": n + 1,
            "видео_куска": {"start": кусок["start"], "end": кусок["end"]},
            "lead": шторки[n]["lead"], "trail": шторки[n]["trail"],
            "звук": {"at": рубежи[n], "till": рубежи[n + 1], "essay0": звук0,
                     "длина": round(шторки[n]["lead"] + кусок["duration"]
                                    + шторки[n]["trail"], 3)},
            "видео": {"at": round(кадры[n] / fps, 6),
                      "till": round(кадры[n + 1] / fps, 6),
                      "essay0": round(кадр0 / fps, 6),
                      "кадр0": кадр0,
                      "кадров": кадры[n + 1] - кадры[n],
                      "с_кадра": кадры[n]},
        })
    # Где стоит сетка кадров ГОТОВОГО ФАЙЛА — на нуле.
    #
    # **Это замер, а не вывод.** Выводом получалось другое: `-ss` встаёт
    # на первый кадр, чьё время не меньше заданного, и разница должна
    # была бы стать началом времён. Спросили ffprobe у собранного файла
    # — первый кадр лежит ровно на 0.000000: `-ss` перед входом
    # сдвигает времена сам.
    #
    # Число оставлено полем, а не вписано нулём по месту: если цепочка
    # однажды перестанет их сбрасывать, менять придётся здесь, а не
    # в трёх местах сверки.
    return {"куски": строки, "всего": всего, "fps": fps,
            "смещение": 0.0, "стыков": len(куски) - 1}


def стыки(cut: dict, duration: float) -> list[dict]:
    """Стыки разрывного куска: где каждый стоит и что между кусками пропало.

    Считается ЗДЕСЬ, а не по месту показа: второе сложение того же
    числа однажды разъедется с первым.
    """
    куски = pick.pieces(cut)
    if len(куски) < 2:
        return []
    строки = карта(cut, duration)["куски"]
    шторки = fades(cut, duration)
    вышло = []
    for n in range(len(куски) - 1):
        свой, следом = куски[n], куски[n + 1]
        дыра = round(следом["start"] - свой["end"], 3)
        вышло.append({
            "n": n + 1,
            "на": строки[n]["звук"]["till"],
            "дыра": дыра,
            "назад": дыра < 0,
            "пропало_фраз": (следом["phrases"]["first"]
                             - свой["phrases"]["last"] - 1),
            "шторка": шторки[n]["trail"],
        })
    return вышло


