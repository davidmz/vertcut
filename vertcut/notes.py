"""Описания вертикалок — текст, который человек скопирует при публикации.

## Откуда это взялось

Спека знает их как «подписи» и называет одной из двух стадий, которым
нужен ключ к модели. Дизайн рисует отдельный шаг маршрута с карточками,
меткой авторства и предупреждением про одинаковые начала — то есть
работу, которая делается и БЕЗ всякой модели: описание можно написать
руками.

Здесь сделана именно эта половина. Модель придёт пятой сессией и ляжет
рядом: она будет заполнять то же самое поле, а метка авторства скажет,
кто написал.

## Где лежит

**В `cut.json`, рядом с названием.** Не отдельным файлом: описание —
это свойство ролика, и жить оно должно там же, где границы куска
и монтаж кадра. Человек, скопировавший папку ролика на другую машину,
должен унести описание вместе с ним.

**В штамп сборки описание НЕ входит, и это решение.** Оно не попадает
в файл ни одним пикселем — его копируют руками в форму площадки.
Правка описания не должна устаревать собранный ролик: пересобирать
сорок секунд видео из-за исправленной запятой в подписи — это работа
сервиса зря.

## Чего здесь нет

**Предела в знаках.** Дизайн рисует счётчик «64 / 150». Числа 150
здесь не будет: у каждой площадки свой предел, они разные и меняются
— TikTok, Shorts и Reels не сходятся ни в одном. Вшитое число устарело
бы молча и заставляло бы человека резать текст там, где резать не надо.
Счётчик знаков остаётся: он говорит правду, которая не зависит
от площадки.
"""

from __future__ import annotations

from pathlib import Path

from . import layout, pick, tuning

# Кто написал описание. Метка авторства из дизайна: «AI» на акцентной
# подложке, «ваше» зелёная, «правится» нейтральная. Первого пока
# не бывает — он придёт вместе с ключом.
РУКОЙ = "рукой"
МОДЕЛЬЮ = "моделью"


def прочитать(cut: dict) -> dict:
    """Описание ролика и то, кто его написал."""
    это = cut.get("описание")
    if isinstance(это, dict):
        return {"текст": str(это.get("текст") or ""),
                "кто": это.get("кто") or РУКОЙ}
    return {"текст": str(это or ""), "кто": РУКОЙ}


def записать(project: Path, ident: str, текст: str,
             кто: str = РУКОЙ) -> dict:
    """Положить описание в ролик. Пустое — убрать вовсе.

    Пустое поле и отсутствующее поле должны выглядеть одинаково:
    иначе «описания нет» и «описание стёрли» — два разных состояния
    там, где смысл один.
    """
    cut = pick.load(project, ident)
    чистый = str(текст or "").strip()
    if чистый:
        cut["описание"] = {"текст": чистый, "кто": кто}
    else:
        cut.pop("описание", None)
    pick.update(project, cut)
    return прочитать(cut)


def список(project: Path) -> list[dict]:
    """Все ролики видео с их описаниями. Читает голый json."""
    from . import rename

    ролики = pick.listing(project)
    как = rename.как_назовутся(project, ролики)
    вышло = []
    for cut in ролики:
        это = прочитать(cut)
        файл = layout.out(project, cut)
        вышло.append({
            "id": cut["id"], "зовут": pick.зовут(cut),
            # Как назовётся файл. Считает `rename`, а не мы: второе
            # правило имени разошлось бы с первым молча.
            "файл": как[cut["id"]],
            "название": cut["название"],
            "фразы": cut["phrases"], "duration": cut["duration"],
            "текст": это["текст"], "кто": это["кто"],
            "знаков": len(это["текст"]),
            "есть_файл": файл.exists(),
        })
    return вышло


def одинаковые_начала(описания: list[dict]) -> list[dict]:
    """Пары описаний, которые начинаются одинаково.

    **Механическая проверка, и в этом вся её ценность.** Судить
    о качестве описания сервису нечем — это работа человека или
    модели. А вот заметить, что три подписи подряд начинаются
    «Как жить…», можно счётом, и человек об этом узнает до публикации,
    а не из ленты.
    """
    вышло = []
    для_сверки = [(о, _начало(о["текст"])) for о in описания if о["текст"]]
    for n, (один, начало_один) in enumerate(для_сверки):
        for другой, начало_другой in для_сверки[:n]:
            if начало_один and начало_один == начало_другой:
                вышло.append({"один": другой["id"], "другой": один["id"],
                              "начало": начало_один})
    return вышло


def _начало(текст: str) -> str:
    """Первые слова описания, приведённые к сравнимому виду.

    **Слова, а не знаки.** Первый вариант сравнивал двадцать первых
    знаков, и на примере из дизайна не сработал вовсе: «Как жить,
    когда мир катится» и «Как жить, когда всё случилось» расходятся
    на шестнадцатом знаке, а беда у них одна — общая формула в начале.

    Регистр и лишние пробелы не считаются: «Как жить» и «как  жить» —
    это одно и то же начало, и человек увидит их одинаковыми.
    """
    слова = str(текст).lower().split()
    return " ".join(слова[:tuning.СЛОВ_НАЧАЛА_ОПИСАНИЯ])
