// Проба экрана: гоняет все экраны так, как это делает браузер.
//
// **Она не автотест и в `pytest` не входит.** Ей нужен движок JS,
// а его в окружении сервиса нет и заводить его нельзя: сессия про
// экран начиналась с правила «никакой сборки фронтенда». Это
// инструмент замера — такой же, как перебор порогов сегментации:
// запускается руками, когда надо, и лежит рядом, чтобы не писать
// его заново.
//
// Что она нашла на первом же запуске:
//
//   · пустой экран — `shell.js` не отдавал наружу одно имя,
//     и браузер не выполнял НИ ОДНОГО модуля;
//   · два разных «ключа» под одним именем: пропуск доступа затирался
//     ключом ролика, и каждый кадр вертикалки получал отказ;
//   · кнопки без дела — шаги маршрута, которым некуда вести.
//
// Как запускать (сервис при этом должен работать):
//
//     vertcut screen --no-browser &
//     node tests/screen-probe.mjs {пропуск-из-адреса}
//
const ПРОПУСК = process.argv[2];
// Порт вторым словом: сервис берёт первый свободный за 7864, и когда
// один экран уже работает, следующий поднимается на 7865. Держать
// порт внутри пробы значило бы гонять её против ЧУЖОГО экрана
// и не понимать, почему ответы не те.
const ПОРТ = process.argv[3] || '7864';
if (!ПРОПУСК) {
  console.log('Скажите пропуск — он в адресе, который напечатал vertcut screen:');
  console.log('  node tests/screen-probe.mjs {пропуск} [порт]');
  process.exit(1);
}
// ── Заглушка браузера: ровно столько, сколько нужно нашим модулям.
const пустые = [];
class Node {
  constructor(имя) {
    this.имя = имя; this.className = ''; this.textContent = '';
    this.style = {}; this.dataset = {}; this.children = []; this.атрибуты = {};
    this.classList = { add(){}, remove(){}, contains(){ return false; } };
  }
  setAttribute(к, з) { this.атрибуты[к] = з; }
  append(...д) { this.children.push(...д); }
  prepend(...д) { this.children.unshift(...д); }
  replaceChildren(...д) { this.children = д; }
  addEventListener(что, дело) {
    // Браузер терпит undefined молча — заглушка тоже, иначе она
    // проверяла бы не сервис, а себя. Но кнопку без дела запоминаем.
    if (дело === undefined) { пустые.push(this.имя + ':' + что); return; }
    (this.слушают ||= {})[что] = дело;
  }
  removeEventListener(){}
  remove(){}
  querySelector(){ return new Node('div'); }
  querySelectorAll(){ return []; }
  getBoundingClientRect(){ return { left:0, top:0, width:312, height:554 }; }
  scrollIntoView(){}
  focus(){}
  setPointerCapture(){}
  releasePointerCapture(){}
  get value(){ return this._v || ''; }
  set value(з){ this._v = з; }
}
globalThis.Node = Node;
globalThis.document = {
  createElement: (и) => new Node(и),
  createElementNS: (нс, и) => new Node(и),
  createTextNode: (т) => { const у = new Node('#текст'); у.textContent = String(т); return у; },
  getElementById: () => new Node('div'),
  querySelector: () => new Node('div'),
  addEventListener(){},
};
globalThis.window = { addEventListener(){} };
// Адрес ведёт себя КАК БРАУЗЕР: что записали русскими буквами,
// то читается обратно в процентах. Ровно на этом стоял случай
// «нажал на видео — ничего не открылось», и заглушка, которая
// отдаёт написанное как есть, его не увидела бы никогда.
globalThis.location = {
  search: '?pass=' + ПРОПУСК,
  origin: `http://127.0.0.1:${ПОРТ}`,
  _hash: '',
  get hash() { return this._hash; },
  set hash(з) { this._hash = encodeURI(String(з)); },
  get href() { return this.origin + '/' + this._hash; },
};
globalThis.Audio = class { addEventListener(){} play(){ return Promise.resolve(); } pause(){} };
globalThis.XMLHttpRequest = class { open(){} send(){} addEventListener(){} get upload(){ return { addEventListener(){} }; } };
globalThis.setInterval = () => 0;
globalThis.clearInterval = () => {};

const { default: узел } = await import('node:http');
globalThis.fetch = async (адрес) => {
  const у = new URL(String(адрес), `http://127.0.0.1:${ПОРТ}`);
  у.searchParams.set('pass', ПРОПУСК);
  const ответ = await new Promise((готово, беда) => {
    узел.get(у.toString(), (о) => {
      let тело = '';
      о.setEncoding('utf8');
      о.on('data', (к) => { тело += к; });
      о.on('end', () => готово({ status: о.statusCode, тип: о.headers['content-type'] || '', тело }));
    }).on('error', беда);
  });
  return {
    ok: ответ.status < 400, status: ответ.status,
    headers: { get: () => ответ.тип },
    json: async () => JSON.parse(ответ.тело),
    text: async () => ответ.тело,
  };
};

function найти(узел, годится) {
  if (годится(узел)) return узел;
  for (const д of узел.children || []) {
    const нашлось = найти(д, годится);
    if (нашлось) return нашлось;
  }
  return null;
}

