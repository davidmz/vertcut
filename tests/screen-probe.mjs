// ── Черновой просмотр: какой план стоит на этой секунде.
//
// Проверяется чистая логика, без видео: браузерного плеера здесь нет
// и быть не может. Ловится ровно то, что видел автор — окно от плана,
// который давно доиграл, после перемотки ползунком.
{
  const { план_на } = await import(где + 'cut.js');
  const планы = [
    { idx: 1, видно: { start: 0, end: 2 } },
    { idx: 2, видно: { start: 2, end: 4 } },
    { idx: 3, видно: { start: 40, end: 42 } },   // за разрывом
  ];
  const случаи = [
    ['начало ролика',                 0.00, 0, { номер: 0 }],
    ['доиграли до второго плана',     2.00, 0, { номер: 1 }],
    ['перемотал НАЗАД, к первому',    0.50, 2, { номер: 0 }],
    ['перемотал ВПЕРЁД, за разрыв',  41.00, 0, { номер: 2 }],
    ['встал на выброшенное',         10.00, 1, { номер: -1, дальше: 2 }],
    ['кадр чуть раньше запрошенного', 1.99, 0, { номер: 0 }],
  ];
  console.log('\nчерновой просмотр, план на секунде:');
  for (const [что, при, от, ждём] of случаи) {
    const вышло = план_на(планы, при, от);
    const сошлось = Object.entries(ждём).every(([к, з]) => вышло[к] === з);
    console.log(`  ${что.padEnd(30)} ${сошлось ? 'ок' : 'НЕ ТО'}` +
                `  (номер ${вышло.номер}, дальше ${вышло.дальше})`);
  }
}

// ── Перевод времени: ролик ↔ исходник.
//
// **Это единственная арифметика времени в браузере**, и она повторяет
// серверную. Проверяется тем единственным способом, каким такое
// вообще проверяется: туда и обратно обязано вернуть ту же секунду,
// а полученная секунда исходника — лечь в тот план, который назовёт
// `план_на`.
//
// Своя полоса перемотки размечена ПО РОЛИКУ и держится ровно на этих
// двух функциях: ошибись они на разрыве, и ползунок повёл бы человека
// в выброшенную речь.
{
  const { в_исходник, в_ролик, план_на } = await import(где + 'cut.js');
  // Разрывная вертикалка: два куска, между ними выброшено полминуты.
  // За последним планом три секунды плашки — планов там нет вовсе.
  const планы = [
    { idx: 1, at: 0, till: 4, видно: { start: 100, end: 104 } },
    { idx: 2, at: 4, till: 9, видно: { start: 140, end: 145 } },
  ];
  const случаи = [
    ['начало ролика', 0],
    ['середина первого куска', 2.5],
    ['ровно на стыке кусков', 4],
    ['после стыка', 6],
    ['последняя секунда картинки', 8.9],
    ['уже под плашкой', 10.5],
  ];
  console.log('\nперевод времени, ролик ↔ исходник:');
  for (const [что, при] of случаи) {
    const секунда = в_исходник(планы, при);
    const обратно = в_ролик(планы, секунда, 0);
    const кругом = обратно !== null && Math.abs(обратно - при) < 0.001;
    // Секунда исходника обязана лечь в тот же план — кроме плашки:
    // там планов нет, и `план_на` честно отвечает «ни один».
    const под_плашкой = при >= планы[планы.length - 1].till;
    const где_план = план_на(планы, секунда, 0);
    const тот_план = под_плашкой
      ? где_план.номер === -1
      : (планы[где_план.номер] || {}).at !== undefined
        && при >= планы[где_план.номер].at - 0.02
        && при < планы[где_план.номер].till + 0.02;
    console.log(`  ${что.padEnd(30)} ${кругом && тот_план ? 'ок' : 'НЕ ТО'}` +
                `  (ролик ${при} → исходник ${секунда} → ${обратно})`);
  }
}
