"""Подсветка текущего слова: чем красим.

Это ВТОРОЙ слой поверх «сказано или ещё нет». Тот работал и работает —
слова темнеют по одному; здесь проверяется, что новое его не сломало
и что подсветка встаёт ровно на то слово, которое звучит.
"""

from __future__ import annotations

import pytest

from vertcut import subs
from vertcut.errors import VertcutError

ТЕКСТ = "смог ли Асано найти ответ"


def профиль(**правки):
    числа = subs.образец()
    for ключ, значение in правки.items():
        где, части = числа, ключ.split("__")
        for часть in части[:-1]:
            где[часть] = dict(где[часть])
            где = где[часть]
        где[части[-1]] = значение
    return subs.к_пикселям(числа)


def страница(prof, текст=ТЕКСТ):
    слова = [{"w": w, "s": 0.0, "e": 0.4} for w in текст.split()]
    return subs.страницы(слова, prof, subs.font_of(prof))[0]


def нарисовать(prof, сказано=1, текст=ТЕКСТ):
    return subs.нарисовать(страница(prof, текст), сказано, 1000, prof,
                           subs.font_of(prof))


def сколько_цвета(картинка, цвет: str) -> int:
    нужный = subs.цвет(цвет)[:3]
    пиксели = картинка.convert("RGBA").tobytes()
    return sum(1 for n in range(0, len(пиксели), 4)
               if tuple(пиксели[n:n + 3]) == нужный and пиксели[n + 3] > 200)


# ─── по умолчанию ничего не поменялось ───────────────────────────────

def test_по_умолчанию_подсветки_нет():
    """Из коробки субтитр выглядит ровно так, как замерено на эталоне:
    слова темнеют по одному, и ничего больше."""
    prof = профиль()
    assert prof["подсветка"] == subs.НЕТ_ПОДСВЕТКИ
    assert сколько_цвета(нарисовать(prof), prof["подсветка_цвет"]) == 0


def test_режим_без_не_трогает_картинку():
    """Даже если «чем» выставлено, при режиме «без» рисуется прежнее."""
    было = нарисовать(профиль()).tobytes()
    стало = нарисовать(профиль(karaoke__by="size")).tobytes()
    assert было == стало


# ─── кого подсвечиваем ───────────────────────────────────────────────

def test_подсвечивается_текущее_слово_а_не_весь_сказанный_кусок():
    """«Сказано или ещё нет» уже показано краской. Подсветка отвечает
    на другой вопрос — что звучит прямо сейчас."""
    prof = профиль(karaoke__mode="word")
    стр = страница(prof)
    assert subs.подсвеченные(стр[0], 3, prof) == [2]
    assert subs.подсвеченные(стр[0], 1, prof) == [0]


def test_режим_строка_берёт_всю_строку_с_текущим_словом():
    prof = профиль(karaoke__mode="line")
    стр = страница(prof)
    свои = subs.подсвеченные(стр[0], 2, prof)
    assert свои == list(range(len(стр[0].words)))


def test_чужая_строка_не_подсвечивается():
    """На двухстрочной странице подсвечена та строка, где идёт речь,
    а не обе."""
    prof = профиль(karaoke__mode="line")
    стр = страница(prof, "раз два три четыре пять шесть семь восемь "
                         "девять десять одиннадцать двенадцать")
    assert len(стр) == 2
    # Речь идёт по первой строке: вторая молчит.
    сказано = 2
    assert subs.подсвеченные(стр[0], сказано, prof)
    assert subs.подсвеченные(стр[1], сказано - len(стр[0].words), prof) == []


def test_подсветки_нет_пока_слово_не_прозвучало():
    prof = профиль(karaoke__mode="word")
    стр = страница(prof)
    assert subs.подсвеченные(стр[0], 0, prof) == []


# ─── чем красим ──────────────────────────────────────────────────────

def test_цветом_красит_слово_цветом_подсветки():
    prof = профиль(karaoke__mode="word", karaoke__by="color")
    assert сколько_цвета(нарисовать(prof), prof["подсветка_цвет"]) > 100


def test_плашкой_кладёт_плашку_под_слово():
    """Плашка идёт ПОД текст: её пикселей должно быть заметно больше,
    чем букв, — иначе она нарисована поверх и закрыла слово."""
    prof = профиль(karaoke__mode="word", karaoke__by="box")
    картинка = нарисовать(prof)
    плашки = сколько_цвета(картинка, prof["подсветка_цвет"])
    assert плашки > 1000
    # И само слово поверх неё осталось видно.
    assert сколько_цвета(картинка, prof["сказанное"]) > 100


def test_кеглем_рисует_слово_крупнее():
    # Одно слово в строке и без плашки: иначе выше всех окажется
    # соседнее слово обычного кегля, и мерить будет нечего.
    обычно = нарисовать(профиль(background="none", karaoke__mode="word",
                                karaoke__by="color"), текст="Асано")
    крупно = нарисовать(профиль(background="none", karaoke__mode="word",
                                karaoke__by="size"), текст="Асано")
    # У крупного слова буквы выше и шире.
    assert крупно.getbbox()[1] < обычно.getbbox()[1]
    assert (крупно.getbbox()[2] - крупно.getbbox()[0]
            > обычно.getbbox()[2] - обычно.getbbox()[0])


def test_кеглем_меряет_строку_крупным_кеглем():
    """Иначе строка перекладывалась бы на каждом слове и дрожала весь
    ролик, а подсвеченное слово вылезало бы за плашку."""
    обычный = subs.font_of(профиль())
    крупный = subs.font_of(профиль(karaoke__mode="word",
                                   karaoke__by="size"))
    assert крупный.мерить_крупно is True
    assert крупный.ширина(ТЕКСТ) > обычный.ширина(ТЕКСТ)


def test_кеглем_не_даёт_слову_вылезти_за_своё_место():
    """Место посчитано крупным кеглем заранее — крупное слово занимает
    его целиком и на соседа не наезжает."""
    prof = профиль(karaoke__mode="word", karaoke__by="size")
    набор = subs.font_of(prof)
    стр = страница(prof)
    места = набор.места_слов(100.0, стр[0].text, стр[0].words)
    for n, (слева, справа) in enumerate(места):
        крупное = набор.продвижение(стр[0].words[n]["w"], крупно=True)
        assert крупное <= справа - слева + 0.5


# ─── где стоят слова ─────────────────────────────────────────────────

def test_слова_не_слипаются():
    """Считать левый край слова «концом предыдущего куска» нельзя:
    между ними стоит пробел. Поймано глазами на листе — «Смог ли»
    читалось как «Смогли»."""
    prof = профиль(karaoke__mode="word")
    набор = subs.font_of(prof)
    стр = страница(prof)
    места = набор.места_слов(100.0, стр[0].text, стр[0].words)
    for (_, конец), (начало, _) in zip(места, места[1:]):
        assert начало > конец, "между словами не осталось пробела"


def test_слова_стоят_там_же_где_у_строки_одним_куском():
    """Порисовав строку по словам, буквы обязаны встать туда же, куда
    они встали бы у строки, нарисованной целиком. Иначе подсветка
    покажет не на то слово."""
    from PIL import ImageChops

    целиком = нарисовать(профиль(), сказано=5)
    # Тот же вид, но дорога другая: подсветка строкой тем же цветом,
    # что и сказанное слово, — рисуется по словам.
    по_словам = нарисовать(
        профиль(karaoke__mode="line", karaoke__by="color",
                karaoke__color=subs.образец()["text_color"]["spoken"]),
        сказано=5)
    assert целиком.getbbox() == по_словам.getbbox()
    разница = ImageChops.difference(целиком.convert("L"),
                                    по_словам.convert("L"))
    заметных = sum(1 for з in разница.tobytes() if з > 40)
    assert заметных < 200, f"буквы разъехались: {заметных} пикселей"


