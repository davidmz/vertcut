def test_в_окружении_нет_заразных_лицензий():
    """ЖИВОЙ ЗАМЕР, а не список из памяти: читаются файлы лицензий,
    которые библиотеки кладут рядом с собой.

    Заразная лицензия у зависимости, скорее всего, обязала бы открыть
    под ней и всё остальное — ровно поэтому в первой сессии меняли
    детектор лиц. Узнать об этом надо до раздачи, а не после.

    Чего проверка НЕ видит: двоичных библиотек, которые пакет везёт
    внутри. `av` — BSD по своему файлу, а внутри у него копия ffmpeg
    с x264 и x265 под GPL; это записано в `LICENSES.md` руками.
    """
    import importlib.metadata as md

    свои = {"vertcut"}
    # Кому можно и почему. Список поимённый: «ослабить правило» и
    # «знать про одно исключение» — разные вещи.
    ДВОЙНЫЕ = {"pillow": "везёт FreeType: FTL или GPLv2, берём FTL"}
    # НЕ НАШЕ: что кладёт в окружение сам питон, а не Vertcut. На 3.11
    # `python -m venv` сеет setuptools (с 3.12 — уже нет), а тот везёт
    # для себя autocommand под LGPLv3. Найдено в 28-й сессии первым же
    # прогоном проверок на 3.11. Ни сервис, ни установщик (там 3.13)
    # его не ставят и не раздают.
    НЕ_НАШИ = {"setuptools": "сеет venv питона 3.11, не Vertcut"}
    плохие = []
    for пакет in md.distributions():
        имя = (пакет.metadata["Name"] or "").lower()
        if not имя or имя in свои or имя in НЕ_НАШИ:
            continue
        for файл in пакет.files or []:
            голое = Path(str(файл)).name.upper()
            if not голое.startswith(("LICENSE", "LICENCE", "COPYING")):
                continue
            try:
                текст = (пакет.locate_file(файл)).read_text(
                    encoding="utf-8", errors="replace")[:6000]
            except OSError:
                continue
            if not re.search(r"GNU (GENERAL|LESSER|AFFERO)", текст, re.I):
                continue
            # ДВОЙНАЯ ЛИЦЕНЗИЯ — ЭТО ВЫБОР, А НЕ ОБЯЗАТЕЛЬСТВО.
            # FreeType роздан на выбор: своя лицензия (FTL,
            # разрешительная) ИЛИ GPLv2, — и берём мы первую. На Windows
            # Pillow везёт FreeType с собой, и текст приезжает целиком,
            # вместе с GPLv2; на macOS — нет, потому и всплыло это
            # только на сборочной машине.
            #
            # Записано ИСКЛЮЧЕНИЕМ, а не смягчением правила: ослабь
            # поиск — и настоящая заразная лицензия проедет молча.
            двойная = ("FTL.TXT" in текст or
                       "The FreeType Project LICENSE" in текст)
            if двойная and имя in ДВОЙНЫЕ:
                continue
            плохие.append(f"{имя}: {голое}")
    assert not плохие, ("в окружении завелась заразная лицензия:\n  "
                        + "\n  ".join(плохие))


def test_ffmpeg_не_раздаётся_а_качается():
    """Сборки ffmpeg под GPL. Наш код его GPL не задела бы и при
    раздаче — сервис зовёт ffmpeg отдельной программой, — но раздача
    обязала бы класть рядом текст лицензии и давать исходники ровно той
    сборки, на каждую систему и каждое обновление. Решение — не раздавать;
    проверка стережёт, чтобы ffmpeg не заехал в поставку молча."""
    опись = (КОРЕНЬ / "LICENSES.md").read_text(encoding="utf-8")
    assert "do NOT hand it out" in опись
    в_поставке = [ф for ф in layout.assets().rglob("*")
                  if ф.is_file() and ф.name.lower().startswith("ffmpeg")]
    assert not в_поставке, в_поставке


# ─── чего в поставке быть не должно ──────────────────────────────────

ПРИЗНАКИ_КЛЮЧА = ("sk-ant-api", "sk-ant-", "sk-proj-", "sk-or-v1")

НЕ_СМОТРИМ = {".git", ".venv", "__pycache__", ".pytest_cache",
              "vertcut.egg-info", "node_modules"}


def _файлы_проекта():
    for путь in КОРЕНЬ.rglob("*"):
        if any(часть in НЕ_СМОТРИМ for часть in путь.parts):
            continue
        if путь.is_file():
            yield путь


def test_ключа_в_папке_проекта_нет():
    """Ключ живёт в `~/.vertcut/`, и попасть в папку проекта он может
    только по ошибке — рукой, вставленным примером или забытой
    песочницей.

    Проверяется НЕ то, что мы его туда не кладём (мы и не кладём),
    а то, что его там нет. Первое — обещание, второе — счёт.
    """
    найдено = []
    for путь in _файлы_проекта():
        if путь.stat().st_size > 2_000_000:
            continue
        try:
            текст = путь.read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            continue
        for признак in ПРИЗНАКИ_КЛЮЧА:
            # Свои же проверки говорят про ключи словами, и слово
            # «sk-ant-что-то» ключом не является. Настоящий длиннее
            # и состоит из латиницы с цифрами.
            for кусок in текст.split():
                if кусок.startswith(признак) and len(кусок) > 40 \
                        and кусок[len(признак):].isascii() \
                        and "-" not in кусок[len(признак):]:
                    найдено.append(f"{путь.relative_to(КОРЕНЬ)}: {кусок[:12]}…")
    assert not найдено, "похоже на настоящий ключ в папке проекта:\n  " \
                        + "\n  ".join(найдено)


