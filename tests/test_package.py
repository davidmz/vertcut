def test_обвес_лежит_внутри_пакета():
    """Не рядом с кодом, а внутри него.

    Пока он лежал рядом, установка забирала код и оставляла обвес
    на месте — и узнать об этом можно было только на чужой машине.
    """
    пакет = Path(layout.__file__).resolve().parent
    assert layout.assets().is_relative_to(пакет), (
        f"обвес уехал наружу пакета: {layout.assets()}")


def test_каждый_файл_обвеса_объявлен_в_поставке():
    """Завели новую папку в обвесе — впишите её в pyproject.

    Иначе она молча не поедет: установка берёт только то, что названо.
    Звёздочка внутрь папок не спускается, поэтому одной строкой
    `assets/*` тут не обойтись, как ни хочется.
    """
    образцы = _описание_поставки()["tool"]["setuptools"]["package-data"]["vertcut"]
    забытые = []
    for файл in sorted(layout.assets().rglob("*")):
        if not файл.is_file() or файл.name == ".DS_Store":
            continue
        # `as_posix`: в pyproject пути записаны косой чертой,
        # а на Windows разделитель другой — проверка краснела
        # бы на всём обвесе сразу и не про то.
        относительно = "assets/" + файл.relative_to(
            layout.assets()).as_posix()
        if not any(_подходит(относительно, о) for о in образцы):
            забытые.append(относительно)
    assert not забытые, (
        "эти файлы обвеса не поедут в поставку — нет строки в pyproject:\n  "
        + "\n  ".join(забытые))


