ЛИШНЕЕ_В_РЕПОЗИТОРИИ = [
    ".venv", "__pycache__", ".pytest_cache", ".DS_Store",
    "vertcut.egg-info", "Дизайн системы Vertcut",
]


def _что_попадёт_в_репозиторий() -> list[str]:
    """Что уедет к человеку: уже записанное плюс ещё не записанное,
    но и не отброшенное правилами.

    Спрашивать одно только записанное нельзя: до первой записи оно
    пусто, и проверка была бы зелёной именно тогда, когда смотреть
    надо внимательнее всего.

    **`core.quotePath=false` — не украшение, а шестое место в проекте,
    где русские буквы не проходят.** По умолчанию git печатает
    нелатинские имена восьмеричными кодами в кавычках:
    `"\320\277\320\265..."` вместо `песочница/meta.json`. Проверка
    искала имя по концу строки и не находила его никогда — то есть была
    зелёной всегда, в том числе на подложенном разборе. Поймано ровно
    тем, что новую проверку сломали нарочно.
    """
    файлы = []
    for слова in (["ls-files"],
                  ["ls-files", "--others", "--exclude-standard"]):
        файлы += subprocess.run(["git", "-c", "core.quotePath=false", *слова],
                                cwd=КОРЕНЬ, capture_output=True,
                                text=True, check=True).stdout.splitlines()
    return файлы


def test_репозиторий_не_несёт_лишнего():
    """Окружение, кэши, песочницы и пакет дизайна в раздачу не едут.

    Пакет дизайна тут не потому, что он тайна, а потому, что он
    двадцать пять мегабайт исходников макетов: человеку, который
    скачал сервис, чтобы нарезать видео, они не нужны. Проверка,
    которая с ним сверяется, честно пропускается, когда его нет рядом.
    """
    if not (КОРЕНЬ / ".git").exists():
        pytest.skip("репозитория ещё нет")
    попало = [с for с in _что_попадёт_в_репозиторий()
              if any(плохое in с for плохое in ЛИШНЕЕ_В_РЕПОЗИТОРИИ)]
    assert not попало, "в репозиторий попало лишнее:\n  " + "\n  ".join(попало[:20])


def test_разборы_и_песочницы_в_репозиторий_не_едут():
    """Папка разбора весит сотни мегабайт и принадлежит человеку,
    а не сервису. Здесь её не должно быть ни одной."""
    if not (КОРЕНЬ / ".git").exists():
        pytest.skip("репозитория ещё нет")
    следы = [с for с in _что_попадёт_в_репозиторий()
             if с.endswith(("meta.json", "align.json", "audio.wav",
                            "proxy.mp4", "heard.json", "cut.json"))]
    assert not следы, "в репозиторий попал чужой разбор:\n  " + "\n  ".join(следы)
