"""Что уезжает к чужому человеку, а что не должно.

**Эти проверки завелись после настоящей находки, а не из аккуратности.**
Шестая сессия собрала поставку тем способом, каким её собирают обычно,
и посмотрела внутрь. Там был только код — 51 файл, и ни одного шрифта,
профиля субтитров, веса детектора или файла страницы. Сервис,
поставленный обычным путём, не нарисовал бы ни одного субтитра
и не открыл бы экрана.

У автора это не всплывало никогда: у него установка «на месте», прямо
из папки, где обвес лежит рядом с кодом и находится сам собой. Чужой
человек так не ставит.

Ни один из пятисот десяти автотестов этого не видел, и увидеть не мог:
все они гоняются в той же папке, где обвес лежит рядом. Беда была
не в коде, а в описании поставки — то есть ровно там, куда проверки
не смотрели вовсе.
"""

from __future__ import annotations

import re
import subprocess
import tomllib
from pathlib import Path

import pytest

from vertcut import deps, layout

КОРЕНЬ = Path(__file__).resolve().parent.parent


def _описание_поставки() -> dict:
    return tomllib.loads((КОРЕНЬ / "pyproject.toml").read_text(encoding="utf-8"))


def _подходит(путь: str, образец: str) -> bool:
    """Ложится ли путь под образец из описания поставки.

    Своё сравнение, а не готовое из библиотеки. Причина ровно та,
    из-за которой поставка и уехала бы неполной: готовое `fnmatch`
    считает, что звёздочка накрывает и косые черты тоже, — и
    `assets/*` у него «покрывает» `assets/web/js/screens/videos.js`.
    Проверка, согласная со всем, не значит ничего.

    Здесь звёздочка живёт внутри одной ступеньки пути, как у самой
    установки.
    """
    ч_путь = путь.split("/")
    ч_образец = образец.split("/")
    if len(ч_путь) != len(ч_образец):
        return False
    import fnmatch
    return all(fnmatch.fnmatchcase(а, б) for а, б in zip(ч_путь, ч_образец))


