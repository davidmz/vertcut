"""Удаление разбора: единственное необратимое действие над видео.

**Проверяется тщательнее прочего, и причина простая: отменить нечем.**
Корзины у сервиса нет — так и сказано человеку до нажатия, — а значит
ошибка здесь стоит не перерисованного экрана, а работы человека
и, в худшем случае, его собственного файла.

Главное свойство, ради которого эти проверки написаны: **файл, лежащий
вне «Входящих», не удаляется НИКОГДА** — даже когда удалить его прямо
просят. Такой файл сервис не копировал: человек выбрал его на диске,
и это его видео, а не наша копия.
"""

from __future__ import annotations

import json
import os
from pathlib import Path

import pytest

from vertcut import ingest, layout, works
from vertcut.errors import VertcutError


def завести(источник: Path, слаг: str = "proba") -> Path:
    """Папка разбора, какой её видит удаление: `meta.json` и немного веса."""
    папка = layout.project(слаг)
    (папка / "frames").mkdir(parents=True, exist_ok=True)
    (папка / "meta.json").write_text(
        json.dumps({"source": str(источник), "duration": 60}),
        encoding="utf-8")
    (папка / "audio.wav").write_bytes(b"y" * 500)
    return папка


def во_входящих(имя: str = "проба.mp4") -> Path:
    вх = layout.inbox()
    вх.mkdir(parents=True, exist_ok=True)
    файл = вх / имя
    файл.write_bytes(b"x" * 1000)
    return файл


def test_чужой_файл_не_удаляется_даже_когда_просят():
    """Самая дорогая ошибка, какая тут возможна.

    Видео, выбранное на диске, осталось лежать в папке человека —
    сервис его не копировал. Удалить его вместе с разбором значило бы
    унести чужой файл, и узнал бы человек об этом, когда пошёл бы его
    искать.
    """
    моё = Path(os.environ["VERTCUT_HOME"]) / "папка человека"
    моё.mkdir(parents=True)
    файл = моё / "своё.mp4"
    файл.write_bytes(b"z" * 10)
    папка = завести(файл)

    assert ingest.что_уйдёт("proba")["наша_копия"] is False
    итог = ingest.удалить("proba", с_видео=True)     # просят — не отдаём

    assert not папка.exists()
    assert файл.exists(), "удалён чужой файл — самое дорогое, что тут бывает"
    assert итог["видео"] is None


def test_своя_копия_уходит_только_по_просьбе():
    """Копию во «Входящих» делал сервис — её он вправе унести.

    Но только по отдельной просьбе: человек мог бросить видео в окно
    именно затем, чтобы оно там лежало.
    """
    видео = во_входящих()
    завести(видео)

    ingest.удалить("proba", с_видео=False)
    assert видео.exists(), "видео унесли, хотя не просили"

    завести(видео)
    итог = ingest.удалить("proba", с_видео=True)
    assert not видео.exists()
    assert итог["видео"] == str(видео)


def test_недоразобранное_видео_удаляется():
    """**Тот самый случай, ради которого удаление и заведено.**

    Распознавание упало, место кончилось, человек передумал на шестой
    минуте — и `align.json` не появился вовсе. Читать его тут нельзя:
    отказ «видео ещё не разобрано» запер бы папку ровно тогда, когда
    от неё хотят избавиться.
    """
    папка = завести(во_входящих())
    assert not (папка / "align.json").exists()

    у = ingest.что_уйдёт("proba")
    assert у["вертикалок"] == 0 and у["занято"] > 0
    ingest.удалить("proba")
    assert not папка.exists()


def test_папка_без_meta_тоже_удаляется():
    """Разбор, упавший на первой же секунде: папка есть, журнала нет."""
    папка = layout.project("proba")
    папка.mkdir(parents=True)

    assert ingest.что_уйдёт("proba")["наша_копия"] is False
    ingest.удалить("proba", с_видео=True)
    assert not папка.exists()


def test_под_работой_не_удаляется():
    """Процесс пишет в эту папку прямо сейчас.

    Убери её из-под него — и он упадёт где-то в середине, а человек
    увидит не «нельзя», а трассировку из чужой библиотеки.
    """
    папка = завести(во_входящих())
    works.записать(layout.work(папка),
                   {"хозяин": {"pid": os.getpid(), "что": "разбор"}})

    # Отказ называет, ЧТО идёт, и что удалять сейчас нельзя.
    with pytest.raises(VertcutError,
                       match="analysis is running.*cannot be deleted") as беда:
        ingest.удалить("proba")
    assert беда.value.hint, "отказ без дороги «что делать»"
    assert папка.exists()
    assert ingest.что_уйдёт("proba")["идёт"] == "analysis"


def test_нет_разбора_отказ_словами():
    # Отказ называет, ЧЕГО нет, и показывает, где посмотреть, что есть.
    with pytest.raises(VertcutError, match="No such video: нету") as беда:
        ingest.удалить("нету")
    assert "vertcut videos" in беда.value.hint


def test_веб_слой_только_переводит_просьбу():
    """Правило проекта: удалять папки веб-слой не умеет.

    Работа живёт в `ingest`, ручка её только зовёт. Второе место,
    знающее правило про чужой файл, однажды решило бы иначе.
    """
    текст = Path(__file__).parent.parent.joinpath(
        "vertcut/web/api.py").read_text(encoding="utf-8")
    ручка = текст.split('@ручка("POST", "удалить-видео")')[1].split("@ручка")[0]
    assert "rmtree" not in ручка and "unlink" not in ручка
    assert "ingest.удалить" in ручка
