def test_мёртвый_адрес_не_выдаётся_за_пропавшую_сеть(tmp_path, monkeypatch):
    """Сервер ответил 404 — сеть есть, файла нет. Совет «дождитесь сети»
    держал бы человека вечно: адрес ffmpeg уже умирал (14-я сессия).
    Поймано снимком отказа в 23-й. Оболочки делают ту же развилку."""
    import urllib.error

    def отказ(*_, **__):
        raise urllib.error.HTTPError("https://x/f.zip", 404, "Not Found", {}, None)

    monkeypatch.setattr(установщик.urllib.request, "urlopen", отказ)
    monkeypatch.setattr(установщик.time, "sleep", lambda _: None)
    with pytest.raises(установщик.InstallProblem) as беда:
        установщик.download("https://x/f.zip", tmp_path / "f.zip")
    assert "internet works" in беда.value.hint
    assert "dropped" not in беда.value.hint
    assert "%{http_code}" in (УСТАНОВКА / "install.sh").read_text(encoding="utf-8")
    assert "$_.Exception.Response" in (УСТАНОВКА / "install.ps1").read_text(
        encoding="utf-8-sig")


