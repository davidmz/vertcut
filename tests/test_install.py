@pytest.mark.skipif(not shutil.which("awk"), reason="нет awk")
def test_оболочка_и_питон_читают_одно_и_то_же():
    """ГЛАВНАЯ проверка этого файла.

    Оболочка достаёт адрес питона своим способом (awk), питон — своим.
    Разойдутся — чужая машина скачает не то, что мы проверили, и узнаем
    мы об этом от человека, а не от проверки.
    """
    for система, железо in (("darwin", "arm64"), ("darwin", "x86_64"),
                            ("windows", "x86_64")):
        через_awk = subprocess.run(
            ["awk", "-v", f"os={система}", "-v", f"arch={железо}",
             '$1=="python" && $2==os && $3==arch {print $4" "$5; exit}',
             str(УСТАНОВКА / "sources.txt")],
            capture_output=True, text=True, check=True).stdout.split()
        через_питон = next(с[3:5] for с in установщик.sources()
                           if с[0] == "python" and с[1] == система
                           and с[2] == железо)
        assert через_awk == через_питон, (система, железо)


