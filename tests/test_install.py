def test_причина_отказа_установки_не_теряется():
    """Отказ без причины — это отказ, после которого чинят наугад.

    **Найдено сборочной машиной в первую её ночь, и бед было две
    сразу.** Установка встала на первом же шаге, а журнал сказал
    ровно три слова: «установка не удалась». Почему — не сказал никто.

    Первая беда: рассказчик о беде падал сам. `Скажи-Беду` звал
    `[System.Web.HttpUtility]`, а эта сборка в PowerShell сама
    не загружается — то есть отказ ронял обработчик отказа, и вместо
    страницы с причиной человек оставался со страницей «качаю питон».

    Вторая: ярлык запускал установку БЕЗ перехвата вывода. Он запущен
    скрытым, консоли у него нет, и всё сказанное установкой пропадало.
    Маковская половина делает это с шестой сессии одной строкой
    (`exec >>"$LOG" 2>&1`) — потому там беда и не всплывала никогда.
    """
    установка = (УСТАНОВКА / "install.ps1").read_text(encoding="utf-8-sig")
    # Код, а не проза: почему System.Web звать нельзя, написано
    # примечанием в этом же файле.
    код = "\n".join(с for с in установка.splitlines()
                    if not с.lstrip().startswith("#"))
    assert "System.Web" not in код, (
        "рассказчик о беде снова зовёт сборку, которая не загружается")
    assert "[Console]::Error.WriteLine" in код, (
        "причина не уходит в поток, который ловит ярлык")
    assert "trap {" in код, (
        "неожиданная ошибка уходит в никуда: остаётся один код возврата")

    ярлык = (УСТАНОВКА / "launcher.ps1").read_text(encoding="utf-8-sig")
    assert "-RedirectStandardError" in ярлык, (
        "слова установки не доезжают до журнала")
    кусок = ярлык[ярлык.index("$Installing = Start-Process"):]
    кусок = кусок[:кусок.index("if (-not (Test-Path $Py))")]
    assert "Write-Log" in кусок, (
        "перехваченное никто не кладёт в журнал")


