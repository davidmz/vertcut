def test_установка_отпускает_порт_и_ярлык_уводит_страницу(tmp_path):
    """Сквозь обе половины: сервер установки отдаёт «Готово», уходит
    и ОТПУСКАЕТ порт, а ярлык занимает тот же порт и говорит странице
    адрес сервиса. Страница всё это время спрашивает один и тот же
    адрес — другого у неё нет."""
    import threading
    ход = ход_модуль.Progress(tmp_path, [("Шаг", "")], live=True)
    порт = ход.server.server_address[1]
    assert (tmp_path / ход_модуль.PORT_FILE).read_text() == str(порт)
    ход.finish()
    провожаем = threading.Thread(target=ход.wait_for_page)
    провожаем.start()
    assert _спросить(порт)["title"] == "Done"
    провожаем.join(10)
    assert not провожаем.is_alive(), "установка не отпустила страницу"

    итог = {}
    ярлык = threading.Thread(target=lambda: итог.update(
        дошло=ход_модуль._tell_live_page(
            tmp_path, ход_модуль._LastWord("Done", "", go_to="http://127.0.0.1:7864/"),
            10)))
    ярлык.start()
    for _ in range(50):
        try:
            ответ = _спросить(порт)
            break
        except OSError:
            time.sleep(0.1)
    ярлык.join(10)
    assert ответ["go_to"] == "http://127.0.0.1:7864/"
    assert итог["дошло"] is True
    assert not (tmp_path / ход_модуль.PORT_FILE).exists(), "порт остался записан"


