def test_у_всего_скачиваемого_есть_адрес_и_сумма():
    """Сюда приезжает то, что будет запускаться. Строка без суммы —
    это доверие к чужому серверу на слово."""
    for строка in установщик.sources():
        if строка[0] == "size":
            continue
        адрес, сумма = строка[-2], строка[-1]
        assert адрес.startswith("https://"), строка
        # Адрес обязан быть латиницей: путь запроса питон кодирует
        # в ascii и на кириллице ПАДАЕТ, а не отказывает. Девятое место
        # той же семьи; наши адреса латинские, и пусть такими и будут.
        assert адрес.isascii(), строка
        assert re.fullmatch(r"[0-9a-f]{64}", сумма), строка


