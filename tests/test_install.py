def test_обе_половины_узнают_машину_а_не_себя():
    """Под Rosetta `uname -m` и `platform.machine()` отвечают «x86_64».

    Найдено в девятой сессии, и не рассуждением: программа, запущенная
    двойным щелчком, у автора шла под Rosetta. Установка, спросившая
    про железо СЕБЯ, скачала бы на арм-машину x86_64-питон
    и x86_64-колёса — работать это будет, но через трансляцию, а самое
    долгое дело сервиса (распознавание речи) считается процессором.

    Обе половины спрашивают не флажок, а попытку: `arch -arm64`
    запускает крошечную программу. Ответила нулём — машина умеет arm64.
    """
    оболочка = (УСТАНОВКА / "install.sh").read_text(encoding="utf-8")
    голая = "\n".join(с for с in оболочка.splitlines()
                      if not с.lstrip().startswith("#"))
    начало = голая.index("which_arch()")
    конец = голая.index("OS=")
    выбор = голая[начало:конец]
    assert "/usr/bin/arch -arm64" in выбор, (
        "оболочка спрашивает про железо только себя")

    питон = (УСТАНОВКА / "installer.py").read_text(encoding="utf-8")
    assert "_can_run_arm64" in питон, "питон спрашивает про железо только себя"


@pytest.mark.skipif(sys.platform != "darwin", reason="Rosetta бывает только тут")
def test_под_rosetta_машина_всё_равно_arm64():
    """Замер, а не рассуждение: то же самое, запущенное под Rosetta.

    Пропускается там, где Rosetta нет вовсе (Intel-мак, чужая система):
    проверять там нечего, а падать на этом нельзя.
    """
    есть_arm64 = subprocess.run(["/usr/bin/arch", "-arm64", "/usr/bin/true"],
                                capture_output=True).returncode == 0
    под_rosetta = subprocess.run(["/usr/bin/arch", "-x86_64", "/usr/bin/true"],
                                 capture_output=True).returncode == 0
    if not (есть_arm64 and под_rosetta):
        pytest.skip("на этой машине нет обеих архитектур сразу")

    # Оболочка: её же функция, запущенная транслированной оболочкой.
    оболочка = (УСТАНОВКА / "install.sh").read_text(encoding="utf-8")
    кусок = оболочка[оболочка.index("which_arch()"):]
    кусок = кусок[:кусок.index("\nOS=")] + "\nwhich_arch\n"
    вышло = subprocess.run(["/usr/bin/arch", "-x86_64", "/bin/bash", "-c", кусок],
                           capture_output=True, text=True)
    assert вышло.stdout.strip() == "arm64", вышло.stderr

    # Питон: то же самое его дорогой. Только если сам питон умеет
    # x86_64: у Homebrew он собран под одну arm64, и под Rosetta его
    # не запустить вовсе («Bad CPU type in executable») — проверять
    # тогда нечего, а падать на этом нельзя. Половина оболочки выше
    # проверена в любом случае.
    if subprocess.run(["/usr/bin/arch", "-x86_64", sys.executable, "-c", "pass"],
                      capture_output=True).returncode != 0:
        pytest.skip("этот питон собран без x86_64 — под Rosetta не запускается")
    код = ("import importlib.util as u;"
           f"с=u.spec_from_file_location('у', r'{УСТАНОВКА / 'installer.py'}');"
           "м=u.module_from_spec(с);с.loader.exec_module(м);"
           "print(м.this_machine()[1])")
    вышло = subprocess.run(["/usr/bin/arch", "-x86_64", sys.executable, "-c", код],
                           capture_output=True, text=True)
    assert вышло.stdout.strip() == "arm64", вышло.stderr


