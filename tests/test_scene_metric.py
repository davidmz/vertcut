def test_уменьшение_совпадает_с_opencv():
    """До единого числа. Разошлось — метрика поехала, а вместе с ней
    и порог склеек 35, замеренный на старых числах глазами."""
    наше = scenes.уменьшить(_кадр(), 8, 5)
    assert наше.tolist() == УМЕНЬШЕННЫЙ


def test_перевод_цвета_совпадает_с_opencv():
    """Тон, насыщенность и яркость — по отдельности, чтобы при поломке
    было видно, какой из трёх поехал."""
    тон, нас, ярк = scenes.в_цвета(_кадр())
    assert тон.tolist() == ТОН, "поехал тон"
    assert нас.tolist() == НАСЫЩЕННОСТЬ, "поехала насыщенность"
    assert ярк.tolist() == ЯРКОСТЬ, "поехала яркость"


def test_тон_помещается_в_байт():
    """0…179, а не 0…359: так же поступает opencv, и от этого зависит
    вес тона в общем счёте."""
    тон, _, _ = scenes.в_цвета(_кадр())
    assert тон.min() >= 0 and тон.max() <= 179


def test_короткие_склейки_подряд_считаются_одной():
    """Вспышка или наплыв дают несколько срабатываний подряд. Склейка
    там одна, и стоит она на последнем кадре, который был выше порога.

    Правило перенесено из библиотеки дословно: без него границы
    на живом видео не сошлись бы."""
    # Ровный ряд, в середине три кадра подряд выше порога.
    оценки = [0.0] * 60
    for n in (20, 21, 22):
        оценки[n] = 99.0
    резы = scenes._слить_короткие(оценки, 35.0, 12)
    assert резы == [20], резы


def test_склейки_ближе_минимума_не_ставятся_дважды():
    """Второе срабатывание через пять кадров после первого — это
    та же склейка, размазанная сжатием на несколько кадров."""
    оценки = [0.0] * 80
    оценки[20] = 99.0
    оценки[25] = 99.0
    оценки[60] = 99.0
    резы = scenes._слить_короткие(оценки, 35.0, 12)
    assert резы == [20, 60], резы


def test_первый_кадр_не_склейка():
    """Сравнивать его не с чем, и оценка у него ноль — иначе всякое
    видео начиналось бы склейкой на нулевом кадре."""
    оценки = [0.0] * 30
    оценки[0] = 999.0
    assert scenes._слить_короткие(оценки, 35.0, 12) == []
