    это = dict(subs.образец()["end_card"], show=True, duration=3.0)
    assert plate.начало(18.4, это) == 15.4
    # Ролик короче самой плашки — плашка не вылезает за ноль.
    assert plate.начало(2.0, это) == 0.0


