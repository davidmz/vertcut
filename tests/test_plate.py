def test_обложка_ставится_не_трогая_разбора():
    """Урок предка: у него обложка ставилась стадией разбора, а разбор
    стоит минуты. Менять картинку такой ценой невозможно."""
    папка = layout.project("видео")
    папка.mkdir(parents=True)
    (папка / "meta.json").write_text('{"держись": 1}', encoding="utf-8")
    было = (папка / "meta.json").read_text(encoding="utf-8")

    сделано = plate.поставить_обложку(папка, картинка(layout.root() / "о.png"))
    assert сделано["файл"] == layout.обложка_выпуска(папка)
    assert сделано["файл"].exists()
    assert (папка / "meta.json").read_text(encoding="utf-8") == было
    assert plate.обложка(папка) == сделано["файл"]

    assert plate.убрать_обложку(папка) is True
    assert plate.обложка(папка) is None
    assert plate.убрать_обложку(папка) is False


