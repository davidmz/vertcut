"""Плашка в конце ролика.

Главное, что здесь проверяется, — не «рисуется ли картинка», а четыре
вещи, каждая из которых ломается молча:

* **выключенная плашка не стоит ничего.** Спека: у чужого человека нет
  ни обложки, ни канала, ни фона. Включение возможности не имеет права
  менять тех, кто ею не пользуется;
* **полоса под субтитр считается, а не лежит числом.** У предка она
  замерена под один кегль; здесь кегль меняет человек, и второе число
  разъехалось бы с первым на готовом ролике;
* **фона может не быть, и обложки может не быть.** И то и другое —
  законный случай, а не недостача;
* **базовая надпись в `cut.json` не оседает.** Осела бы — поправленная
  базовая молча не доехала бы до тех, кто её не менял.
"""

from __future__ import annotations

import pytest

from vertcut import layout, plate, subs
from vertcut.errors import VertcutError


@pytest.fixture(autouse=True)
def чистый_кэш():
    subs.сбросить_кэш()
    yield
    subs.сбросить_кэш()


def профиль(**правки):
    """Готовый профиль в пикселях, поверх поставляемого."""
    сырой = subs.образец()
    for ключ, значение in правки.items():
        куда = сырой
        части = ключ.split(".")
        for часть in части[:-1]:
            куда = куда[часть]
        куда[части[-1]] = значение
    return subs.к_пикселям(сырой), сырой


def картинка(куда, ширина=1280, высота=720, цвет=(200, 60, 60)):
    from PIL import Image

    куда.parent.mkdir(parents=True, exist_ok=True)
    Image.new("RGB", (ширина, высота), цвет).save(куда)
    return куда


