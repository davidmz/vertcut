# ─── планы под плашкой ───────────────────────────────────────────────

def кусок(с: float, по: float, слов: int = 40):
    return {"id": "0000-0040", "words": {"first": 0, "last": слов},
            "duration": по - с,
            "куски": [{"start": с, "end": по,
                       "words": {"first": 0, "last": слов},
                       "phrases": {"first": 1, "last": 4},
                       "duration": по - с}]}


def test_планы_под_плашкой_гасятся():
    """Этих кадров зритель не увидит вовсе — там картинка плашки.
    Рамка им не нужна ни для чего, а стоит она секунду на план."""
    from vertcut import plans

    cut = кусок(10.0, 30.0)
    склейки = [{"idx": n, "start": 10.0 + n * 5, "end": 15.0 + n * 5,
                "duration": 5.0, "crop_cx": 0.5} for n in range(4)]

    целиком = plans.timeline(cut, 100.0, склейки, 25.0)
    assert [р["idx"] for р in целиком] == [0, 1, 2, 3]

    # Плашка съедает последние три секунды файла.
    всего = plans.total_of(cut, 100.0)
    с_плашкой = plans.timeline(cut, 100.0, склейки, 25.0, всего - 3.0)
    assert [р["idx"] for р in с_плашкой] == [0, 1, 2, 3], \
        "последний план заходит под плашку только концом — он остаётся"
    assert с_плашкой[-1]["till"] < целиком[-1]["till"], "и подрезан по ней"

    # Плашка длиной в половину ролика гасит планы целиком.
    коротко = plans.timeline(cut, 100.0, склейки, 25.0, 6.0)
    assert [р["idx"] for р in коротко] == [0, 1]


def test_видимые_секунды_исходника_тоже_подрезаются():
    """`видно` — это то, что увидит зритель. Под плашкой он не видит
    исходника вовсе, и черновой просмотр на экране обязан знать то же
    самое, что знает сборка."""
    from vertcut import plans

    cut = кусок(10.0, 30.0)
    склейки = [{"idx": 0, "start": 10.0, "end": 30.0, "duration": 20.0,
                "crop_cx": 0.5}]
    всего = plans.total_of(cut, 100.0)
    ряд = plans.timeline(cut, 100.0, склейки, 25.0, всего - 3.0)[0]
    assert ряд["видно"]["end"] < 30.0


# ─── место субтитра ──────────────────────────────────────────────────

def test_под_плашкой_субтитр_встаёт_по_центру():
    """Плашка сильнее горизонтального плана: под ней плана нет вовсе,
    а полоса в её середине держится пустой затем, чтобы субтитр был
    виден. Уехав вниз, он лёг бы на надпись."""
    полный = [{"idx": 1, "at": 0.0, "till": 20.0, "cx": None,
               "mode": "full", "полный_кадр": True}]
    фраза = {"at": 16.0, "till": 18.5}

    assert subs.где_стоит(фраза, полный) == subs.НИЗ
