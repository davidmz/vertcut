def test_обложка_под_субтитром_названа_числами():
    """Человек поднял субтитр — обложка оказалась под ним. Молчать
    нельзя: увидеть это можно только на готовом ролике."""
    prof, сырой = профиль(**{"end_card.show": True,
                             "position.from_bottom": 0.62})
    это = plate.числа(prof, сырой["end_card"])
    где = plate.коробка_обложки((1280, 720), это)
    проверка = plate.зазоры(это, где, plate.уложить("раз\nдва", это))
