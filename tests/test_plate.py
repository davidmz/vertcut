def собранный(слаг: str):
    """Папка разбора с одним ролик��м, у которого в штампе всё сходится.

    Всё, кроме плашки, в порядке нарочно: значит любая причина
    пересобрать, которую назовёт сервис, придёт ровно от неё.
    """
    import json

    from vertcut import edits, speech

    папка = layout.project(слаг)
    папка.mkdir(parents=True, exist_ok=True)
    (папка / "meta.json").write_text("{}", encoding="utf-8")
    слова = [{"w": f"слово{n}", "s": n * 0.5, "e": n * 0.5 + 0.4}
             for n in range(6)]
    (папка / "align.json").write_text(json.dumps(
        {"words": слова, "sentences": [],
         "phrases": [{"idx": 1, "start": 0.0, "end": слова[-1]["e"],
                      "text": " ".join(с["w"] for с in слова),
                      "words": слова}]}), encoding="utf-8")
    subs.завести(папка)
    subs.сбросить_кэш()
    cut = {"id": "0000-0005", "файл": "ролик.mp4",
           "words": {"first": 0, "last": 5, "count": 6},
           "render": {"куски": [[0, 5]], "montage": {"hand": {}},
                      "subs": {}}}
    файл = layout.out(папка, cut)
    файл.parent.mkdir(parents=True, exist_ok=True)
    файл.write_text("не пусто", encoding="utf-8")
    cut["render"]["subs"]["профиль"] = subs.отпечаток(project=папка)
    cut["render"]["subs"]["фразы"] = subs.отпечаток_фраз(
        speech.read(папка), [[0, 5]], edits.список(cut))
    cut["render"]["хвост"] = plate.штамп_сейчас(папка, cut,
                                                plate.сырые(папка))
    return папка, cut


