def test_субтитр_выбрасывается_из_сверки_плашки():
    """Субтитр ложится ПОВЕРХ плашки, и спрашивать про эти пиксели
    надо у четвёртого заслона — того, который на них и смотрит."""
    import numpy

    from vertcut import verify

    пусто = verify._прямоугольник(None, (100, 60))
    assert пусто is None
    маска = verify._прямоугольник((10, 20, 30, 40), (100, 60))
    assert маска.shape == (100, 60)
    assert маска[25, 15] and not маска[5, 5]
    assert маска.sum() == 20 * 20

    # Выброшенные пиксели не участвуют в связи вовсе.
    a = numpy.zeros((100, 60)); b = numpy.zeros((100, 60))
    a[:50] = 1.0; b[:50] = 1.0
    a[20:40, 10:30] = 99.0          # «субтитр» в одной из картинок
    assert verify.связь(a, b, маска) == pytest.approx(1.0)
    assert verify.связь(a, b) < 1.0


