# ─── полоса под субтитр ──────────────────────────────────────────────

def test_полоса_берётся_у_субтитров_и_едет_за_кеглем():
    """Второго измерения полосы нет. Подвинули кегль — полоса поехала,
    и плашка обязана поехать за ней."""
    prof, сырой = профиль(**{"end_card.show": True})
    было = plate.числа(prof, сырой["end_card"])["полоса"]
    assert было == {"верх": subs.полоса(prof)["верх"],
                    "низ": subs.полоса(prof)["низ"],
                    "строк": subs.полоса(prof)["строк"]}

    крупнее, сырой2 = профиль(**{"end_card.show": True, "size": 0.06})
    стало = plate.числа(крупнее, сырой2["end_card"])["полоса"]
    assert стало["верх"] < было["верх"], "крупный кегль — полоса выше"


