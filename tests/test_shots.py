"""Склейки: детектор, контактный лист, запись на диск."""

from __future__ import annotations

import json
import subprocess

import pytest

from vertcut import layout, shots, tuning
from vertcut.errors import VertcutError


# ffmpeg зовётся ТЕМ ЖЕ ПУТЁМ, каким его зовёт сервис.
#
# Голым именем «ffmpeg» он находится только там, где лежит в PATH —
# то есть у автора, поставившего его через brew. На машине, где сервис
# поставлен как у человека, своя копия лежит РЯДОМ С СЕРВИСОМ, и в PATH
# её нет: сборочная машина ответила «не найден указанный файл»
# на пятнадцати проверках сразу.
#
# Правило проекта — «ffmpeg запускается только через run.py» — писалось
# про код сервиса, а проверки его нарушали. Не всплывало это ровно
# потому, что гонялись они на одной машине.
def ффмпег() -> str:
    from vertcut import run as дорога

    return дорога.where("ffmpeg") or "ffmpeg"


@pytest.fixture
def копия(песочница):
    """Видео из двух явно разных сцен: цветные полосы и чёрное поле."""
    файл = песочница / "proxy.mp4"
    subprocess.run([
        ффмпег(), "-v", "error", "-y",
        "-f", "lavfi", "-i", "testsrc=size=320x240:rate=25:duration=2",
        "-f", "lavfi", "-i", "color=c=black:size=320x240:rate=25:duration=2",
        "-filter_complex", "[0:v][1:v]concat=n=2:v=1[v]", "-map", "[v]",
        "-c:v", "libx264", "-crf", "20", str(файл),
    ], check=True)
    return файл


def test_склейка_между_разными_сценами_находится(копия):
    найдено = shots.detect(копия, 25.0, 4.0)
    assert len(найдено) == 2
    assert найдено[0]["end"] == pytest.approx(2.0, abs=0.1)


def test_видео_без_единой_склейки_не_поломка(песочница):
    """Для раздачи это обычный случай: разговор на одну камеру так
    и выглядит. Пустой список от детектора — законный ответ, и он
    превращается в один план на всё видео, а не в отказ."""
    файл = песочница / "ровное.mp4"
    subprocess.run([
        ффмпег(), "-v", "error", "-y", "-f", "lavfi",
        "-i", "color=c=navy:size=320x240:rate=25:duration=3",
        "-c:v", "libx264", "-crf", "20", str(файл),
    ], check=True)
    найдено = shots.detect(файл, 25.0, 3.0)
    assert len(найдено) == 1
    assert найдено[0]["start"] == 0.0


def test_края_не_обрезаются_при_разборе(копия):
    """Первый план начинается на нуле, последний доходит до конца:
    в начале видео лежит самый ценный материал для крючка."""
    найдено = shots.detect(копия, 25.0, 4.0)
    assert найдено[0]["start"] == 0.0
    assert найдено[-1]["end"] == pytest.approx(4.0, abs=0.1)


def test_длинный_план_не_рубится_пополам(песочница):
    """В библиотеке, откуда перенесена механика, план длиннее восьми
    секунд режется надвое: там это неотловленный наплыв в трейлере.
    Здесь длинный статичный план — норма, и резать в нём нечего."""
    файл = песочница / "длинный.mp4"
    subprocess.run([
        ффмпег(), "-v", "error", "-y", "-f", "lavfi",
        "-i", "color=c=gray:size=320x240:rate=25:duration=12",
        "-c:v", "libx264", "-crf", "20", str(файл),
    ], check=True)
    найдено = shots.detect(файл, 25.0, 12.0)
    assert len(найдено) == 1
    assert найдено[0]["duration"] > 8.0


def test_запись_планов_идёт_через_времянку(песочница, monkeypatch):
    """Оборванная запись оставила бы обрезанный json, а это потеря
    всего разбора планов."""
    проект = песочница / "дом" / "проба"
    проект.mkdir(parents=True)
    shots.write([{"idx": 1, "start": 0.0, "end": 1.0, "duration": 1.0}], проект)
    assert json.loads(layout.shots(проект).read_text(encoding="utf-8"))["shots"]
    assert not list(проект.glob("*.часть")), "времянка осталась лежать"


def test_нет_планов_на_диске_отказ_словами(песочница):
    проект = песочница / "дом" / "пусто"
    проект.mkdir(parents=True)
    with pytest.raises(VertcutError) as беда:
        shots.read(проект)
    assert беда.value.hint and "ingest" in беда.value.hint


def test_шрифт_подписей_не_прибит_к_одной_системе():
    """«Шрифт из моей системы» — первое, что ломается на чужой машине.

    Нет ни одного из списка — берётся шрифт самого Pillow: подписи
    станут некрасивыми, но лист соберётся. Ронять разбор из-за шрифта
    на подписи нельзя.
    """
    assert set(shots.ШРИФТЫ) == {"darwin", "win32", "linux"}
    assert shots.шрифт_подписей(20) is not None
