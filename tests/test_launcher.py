def test_без_живого_ярлыка_сервис_не_поднимается(песочница, monkeypatch):
    """Единица вместо номера родителя значит, что ярлыка уже нет.

    `works.жив(1)` отвечает «жив» — и там она права: чужой процесс,
    на который нет прав, считается живым. Здесь это значит другое,
    и без этой развилки сторож ждал бы вечно ровно в том случае, ради
    которого он и заведён. Поймано проверкой.
    """
    monkeypatch.setattr(os, "getppid", lambda: 1)
    сказано = []
    server.run(открывать=False, уйти_с_ярлыком=True, говорить=сказано.append)
    assert any("already exited" in с for с in сказано), сказано
    assert not layout.экран_хозяин().exists(), "занял хозяина и ушёл"


def test_сторож_смотрит_на_жизнь_родителя_а_не_на_его_номер():
    """`getppid` после смерти родителя отдаёт номер, который система
    успела передать другому. Спрашивать надо про жизнь запомненного,
    а не сравнивать с единицей."""
    исходник = Path(server.__file__).read_text(encoding="utf-8")
    кусок = исходник[исходник.index("def _следить_за_ярлыком"):]
    кусок = кусок[:кусок.index("\ndef ")]
    # Смотрим на САМ КОД, без объяснения над ним: в объяснении слово
    # «getppid» стоит по делу — там сказано, почему его тут нет.
    тело = кусок[кусок.index('"""', кусок.index('"""') + 3) + 3:]
    assert "works.жив(родитель)" in тело
    assert "getppid" not in тело, "сторож спрашивает номер вместо жизни"


