def _без_примечаний(файл: Path) -> str:
    """Только код, без объяснений над ним.

    **Это не придирка, а поправленная проверка.** Первый заход искал
    слова во всём файле — и не краснел, когда присмотр убрали из
    команды: слово по-прежнему стояло в примечании, где объясняется,
    зачем он нужен. Ровно та же беда, что нашлась в пятой сессии
    у заслона про полосу прокрутки.
    """
    знак = "#"
    return "\n".join(с for с in файл.read_text(encoding="utf-8").splitlines()
                      if not с.lstrip().startswith(знак))


