"""Общее для проверок.

**Главное правило проверок записано здесь, в самом начале: проверки
не трогают живые разборы.** У Нарезатора они гонялись на настоящей
папке автора, и однажды в ней пропала поставленная рукой рамка —
виновника установить не удалось. Здесь корень подменяется на временную
папку через `VERTCUT_HOME`, и подменяется автоматически, а не «когда
не забудешь».
"""

from __future__ import annotations

import pytest


@pytest.fixture(autouse=True)
def песочница(tmp_path, monkeypatch):
    monkeypatch.setenv("VERTCUT_HOME", str(tmp_path / "дом"))
    # **И ключ к модели тоже снимается — по той же причине, только
    # цена другая.** Папка стерегла работу человека; ключ стережёт
    # его деньги: проверка, случайно ушедшая в сеть с настоящим
    # ключом, стоит рублей, и узнает он об этом из счёта.
    #
    # Снимается ЗДЕСЬ, а не «когда не забудешь»: у автора ключ бывает
    # заведён в оболочке, и тогда половина проверок про «ключа нет»
    # проверяла бы не то, что написано в их именах.
    for имя in ("ANTHROPIC_API_KEY", "OPENAI_API_KEY"):
        monkeypatch.delenv(имя, raising=False)
    return tmp_path
