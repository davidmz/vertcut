"""Второй вход в укладку: текстом становится расшифровка.

Проверяется не качество распознавания — его проверить нечем, — а то,
что второй вход ведёт себя как первый везде, кроме одного места:
надёжность там называется своим именем и не врёт про сотню процентов.
"""

from __future__ import annotations

import pytest

from vertcut import align, ingest, layout, pick, speech
from vertcut.errors import VertcutError


def услышано(*слова, шаг: float = 0.5, p: float = 0.9) -> list[dict]:
    """Слова распознавания с временами и уверенностью."""
    return [{"word": w, "start": round(i * шаг, 3),
             "end": round(i * шаг + шаг / 2, 3), "p": p}
            for i, w in enumerate(слова)]


# ─── текст, собранный из услышанного ─────────────────────────────────

def test_текст_складывается_из_тех_же_слов():
    """Распознавание отдаёт слово вместе с ведущим пробелом и прилипшим
    знаком — значит текст собирается склейкой, без догадок о пробелах."""
    куски = [(" Привет", 0.0, 0.4, 0.9), (",", 0.4, 0.4, 0.9),
             (" как", 0.5, 0.7, 0.9), (" дела", 0.7, 1.0, 0.9),
             ("?", 1.0, 1.0, 0.9)]
    assert align._собрать_текст(куски)[0] == "Привет, как дела?"


def test_в_тексте_расшифровки_нет_переносов_строк():
    """Абзац здесь взять неоткуда: пауза бывает и посреди предложения.

    Перенос строки рвёт предложение всегда — значит выдуманный перенос
    выдумал бы и границу предложения.
    """
    куски = [(" Первое.", 0.0, 0.4, 0.9), ("\n", 0.4, 0.4, 0.9),
             (" Второе.", 0.5, 0.9, 0.9)]
    assert "\n" not in align._собрать_текст(куски)[0]


# ─── укладка без сценария ────────────────────────────────────────────

def test_без_сценария_время_измерено_у_всех_слов():
    """Текст взят из того же прогона, что и времена, — расходиться
    им не с чего."""
    heard = услышано("мы", "идем", "домой")
    уложено = speech.place("Мы идем домой.", heard, 10.0, speech.РАСШИФРОВКА)
    assert уложено["источник"] == speech.РАСШИФРОВКА
    assert all("a" not in w for w in уложено["words"])
    assert [w["w"] for w in уложено["words"]] == ["Мы", "идем", "домой."]


def test_без_сценария_у_слов_есть_уверенность():
    """Единственное измеренное свидетельство того, что слово вообще то."""
    heard = услышано("мы", "идем", "домой", p=0.42)
    уложено = speech.place("Мы идем домой.", heard, 10.0, speech.РАСШИФРОВКА)
    assert all(w["p"] == 0.42 for w in уложено["words"])


def test_со_сценарием_уверенности_в_словах_нет():
    """Со сценарием мнение машины о слове ни на что не влияет:
    правильным считается человек. Лишний ключ в файле — это вторая
    надёжность, про которую человеку не сказано, какая из них его.
    """
    heard = услышано("мы", "идем", "домой")
    уложено = speech.place("Мы идём домой.", heard, 10.0)
    assert all("p" not in w for w in уложено["words"])


def test_расшифровка_обязана_сойтись_сама_с_собой():
    """Текст и слова приходят из одного прогона. Разошлись — это
    поломка разбора, а не плохой звук, и говорить о ней надо так."""
    heard = услышано("мы", "идем", "домой")
    with pytest.raises(VertcutError) as беда:
        speech.place("совершенно другие слова тут", heard, 10.0,
                     speech.РАСШИФРОВКА)
    # Названо, что расшифровка разошлась САМА С СОБОЙ — это поломка
    # разбора, а не материала.
    assert "does not match itself" in беда.value.message
    assert "bug in the analysis" in беда.value.message


def test_плохой_звук_расшифровку_не_роняет():
    """На плохом звуке расшифровка будет неверной, но сама с собой
    сойдётся: порог ловит поломку разбора, а не качество материала."""
    heard = услышано("мы", "идем", "домой", p=0.11)
    уложено = speech.place("Мы идем домой.", heard, 10.0, speech.РАСШИФРОВКА)
    assert уложено["matched"] == 1.0


# ─── надёжность, которая меняет смысл ────────────────────────────────

def test_надёжность_фразы_считается_по_худшему_слову():
    """Среднее по пятнадцати словам утопит одно неверное, а в субтитре
    видно именно его."""
    heard = услышано("мы", "идем", "домой")
    heard[1]["p"] = 0.3
    уложено = speech.place("Мы идем домой.", heard, 10.0, speech.РАСШИФРОВКА)
    assert speech.phrase_confidence(уложено) == [0.3]


def test_со_сценарием_надёжности_слуха_нет_вовсе():
    """Не пропуск: там сомнение другое, и про него говорит столбец
    «край»."""
    heard = услышано("мы", "идем", "домой")
    уложено = speech.place("Мы идём домой.", heard, 10.0)
    assert speech.phrase_confidence(уложено) is None
    assert speech.confidence(уложено) is None


def test_уверенность_печатается_долями_а_не_порогом():
    """Порог «плохого» слова назвать можно только замером, а замера
    на разговорном материале ещё не было."""
    heard = услышано("раз", "два", "три", "четыре", "пять",
                     "шесть", "семь", "восемь", "девять", "десять")
    heard[0]["p"] = 0.1
    уложено = speech.place(" ".join(w["word"] for w in heard), heard, 10.0,
                           speech.РАСШИФРОВКА)
    у = speech.уверенность(уложено)
    assert у["худшее"] == 0.1 and у["медиана"] == 0.9 and у["слов"] == 10


# ─── два входа в одну стадию ─────────────────────────────────────────

def test_сценарий_сильнее_расшифровки(песочница, tmp_path):
    """У кого сценарий есть — тот получает прежнюю точность."""
    папка = tmp_path / "разбор"
    папка.mkdir()
    layout.script(папка).write_text("свой текст", encoding="utf-8")
    текст, откуда = ingest.взять_текст(папка, "машинный текст",
                                       lambda *_: None)
    assert (текст, откуда) == ("свой текст", speech.СЦЕНАРИЙ)


def test_без_сценария_расшифровка_ложится_своим_файлом(tmp_path):
    """Не в `script.txt`: через месяц не сказать, чей это текст."""
    папка = tmp_path / "разбор"
    папка.mkdir()
    текст, откуда = ingest.взять_текст(папка, "машинный текст",
                                       lambda *_: None)
    assert (текст, откуда) == ("машинный текст", speech.РАСШИФРОВКА)
    assert layout.transcript(папка).read_text(encoding="utf-8").strip() \
        == "машинный текст"
    assert not layout.script(папка).exists()


# ─── как это называется в сообщениях ─────────────────────────────────

def test_не_нашлось_говорит_про_расшифровку_а_не_про_сценарий(tmp_path):
    """«В сценарии этого нет» человеку без сценария читается как
    поломка: сценария он не давал."""
    heard = услышано("мы", "идем", "домой")
    уложено = speech.place("Мы идем домой.", heard, 10.0, speech.РАСШИФРОВКА)
    with pytest.raises(VertcutError) as беда:
        pick.by_text(уложено, "мы плывём домой")
    сказано = беда.value.message
    assert "transcript" in сказано and "script" not in сказано.replace(
        "transcript", "")


# ─── дефисное слово: времена раздаются словам, а не кускам ───────────

def test_дефисное_слово_собирается_обратно_в_одно():
    """Распознавание отдаёт «какая» и «-то» двумя кусками, а человек
    и весь остальной проект считают это одним словом.

    Пока времена лежали на кусках, такое слово не совпадало само
    с собой и получало прикинутое время вместо измеренного. Замер
    на интервью: 53 слова из 2215.
    """
    куски = [(" какая", 1.0, 1.4, 0.9), ("-то", 1.4, 1.6, 0.3),
             (" беда", 1.7, 2.0, 0.8)]
    текст, места = align._собрать_текст(куски)
    вышло = align._услышанные_слова(текст, места)
    assert текст == "какая-то беда"
    assert [w["word"] for w in вышло] == ["какая-то", "беда"]
    assert (вышло[0]["start"], вышло[0]["end"]) == (1.0, 1.6)


def test_у_склеенного_слова_берётся_худшая_уверенность():
    """В «какая-то» ошибиться можно любой половиной."""
    куски = [(" какая", 1.0, 1.4, 0.9), ("-то", 1.4, 1.6, 0.3)]
    текст, места = align._собрать_текст(куски)
    assert align._услышанные_слова(текст, места)[0]["p"] == 0.3


def test_кусок_распознавания_может_дать_несколько_слов():
    """Обратный случай: в одном куске два слова. Оба получают время
    куска, и ни одно не теряется."""
    куски = [(" мы идем", 1.0, 2.0, 0.7)]
    текст, места = align._собрать_текст(куски)
    вышло = align._услышанные_слова(текст, места)
    assert [w["word"] for w in вышло] == ["мы", "идем"]
    assert all((w["start"], w["end"]) == (1.0, 2.0) for w in вышло)


def test_расшифровка_сходится_сама_с_собой_полностью():
    """После починки — 1.000, а не 0.976. Иначе строчка «время
    измерено у всех слов» была бы враньём."""
    куски = [(" какая", 1.0, 1.4, 0.9), ("-то", 1.4, 1.6, 0.9),
             (" беда", 1.7, 2.0, 0.9), (",", 2.0, 2.0, 0.9),
             (" честно", 2.1, 2.5, 0.9), (".", 2.5, 2.5, 0.9)]
    текст, места = align._собрать_текст(куски)
    heard = align._услышанные_слова(текст, места)
    уложено = speech.place(текст, heard, 10.0, speech.РАСШИФРОВКА)
    assert уложено["matched"] == 1.0
    assert all("a" not in w for w in уложено["words"])
