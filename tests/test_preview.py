"""Предпросмотр: кадр видео с субтитром.

Проверяется главное — что геометрия здесь НЕ СВОЯ. Предпросмотр,
показывающий не то, что соберётся, хуже, чем никакого: человек
настроит стиль по нему, а в файле выйдет другое.
"""

from __future__ import annotations

import pytest

from vertcut import chain, preview, tuning


@pytest.fixture
def кадр():
    from PIL import Image
    # Полосы поперёк: по ним видно, какой кусок кадра взят.
    картинка = Image.new("RGB", (1920, 1080), (0, 0, 0))
    for x in range(0, 1920, 8):
        for y in range(1080):
            картинка.putpixel((x, y), (x % 256, 200, 60))
    return картинка


def test_колонка_режется_тем_же_окном_что_и_сборка(кадр):
    """Две геометрии разъехались бы молча, и сверка начала бы ругаться
    на исправное."""
    from PIL import Image

    вышло = preview.колонка(кадр, 0.75, 1920, 1080)
    assert вышло.size == (tuning.VERTICAL_W, tuning.VERTICAL_H)

    # Окно берётся у цепочки — той же функцией, которой она пишет
    # фильтр. Повторено здесь нарочно: проверка обязана падать, если
    # предпросмотр однажды заведёт свою арифметику.
    ждали = кадр.crop(chain.коробка_окна(1920, 1080, 0.75)).resize(
        (tuning.VERTICAL_W, tuning.VERTICAL_H), Image.LANCZOS)
    assert вышло.tobytes() == ждали.tobytes()
    assert chain.окно_для(1920, 1080, 0.75)["x"] == chain.коробка_окна(
        1920, 1080, 0.75)[0]


def test_коробка_окна_растёт_вместе_с_кадром():
    """Кадр из ffmpeg приезжает то полного размера, то уменьшенным,
    и подгонять окно на месте — это опять своя арифметика."""
    целый = chain.коробка_окна(1920, 1080, 0.5, 1.0)
    половина = chain.коробка_окна(1920, 1080, 0.5, 0.5)
    assert [x // 2 for x in целый] == list(половина)


def test_полный_кадр_вписан_по_ширине_и_стоит_по_центру(кадр):
    """Так сборка показывает планы, оставленные горизонтальными."""
    вышло = preview.полный_кадр(кадр)
    assert вышло.size == (tuning.VERTICAL_W, tuning.VERTICAL_H)
    высота_ленты = round(1080 / 1920 * tuning.VERTICAL_W)
    верх = (tuning.VERTICAL_H - высота_ленты) // 2
    # Над лентой стоит размытый фон, а не чёрное поле: чёрные полосы
    # в вертикальном ролике читаются как брак.
    сверху = вышло.getpixel((tuning.VERTICAL_W // 2, верх // 2))
    assert sum(сверху) > 30, "поле над лентой оказалось чёрным"


def test_режим_плана_решает_как_собран_кадр(кадр):
    колонкой = preview.кадр_ролика(кадр, {"mode": "crop", "cx": 0.5},
                                   1920, 1080)
    целиком = preview.кадр_ролика(кадр, {"mode": "full", "cx": 0.5},
                                  1920, 1080)
    assert колонкой.size == целиком.size
    assert колонкой.tobytes() != целиком.tobytes()


def test_время_в_видео_считается_привязкой_плана():
    """На секунде `t0` ролика стоит секунда `essay0` исходника. Своей
    арифметики времени в проекте нет нигде, и здесь её тоже нет."""
    ряд = {"t0": 2.0, "essay0": 130.0, "at": 3.0, "till": 6.0}
    assert preview.в_видео(ряд, 4.0) == 132.0


def test_план_на_секунде_находится_по_шкале_ролика():
    ряды = [{"idx": 1, "at": 0.0, "till": 2.0},
            {"idx": 2, "at": 2.0, "till": 5.0}]
    assert preview.ряд_на(ряды, 0.5)["idx"] == 1
    assert preview.ряд_на(ряды, 3.0)["idx"] == 2
    # За концом — последний план, а не пусто: пустота здесь означала бы
    # кадр без картинки, и это выглядело бы поломкой не там, где она.
    assert preview.ряд_на(ряды, 99.0)["idx"] == 2
