# Очередь — файл, и при удалении вертикалки его никто не переписывает:
# переписывать вправе только хозяин, а хозяином в эту минуту может быть
# идущая сборка. Значит вопрос «а есть ли ещё такая вертикалка»
# задаётся в момент показа.


def test_удалённая_вертикалка_помечена_и_не_ждёт(песочница):
    """Найдено автором глазами: строка выглядела сломанной.

    Дело оставалось «готово», подпись обещала файл, которого нет,
    а на месте кадра стоял серый прочерк — картинка, за которой
    пришёл отказ. Читается это как поломка сервиса, а поломки нет:
    человек сам её удалил.
    """
    import shutil

    project, _ = _видео_с_роликами(3)
    ключи = [c["id"] for c in pick.listing(project)]
    queue.поставить_один(project, ключи[0])
    queue.поставить_один(project, ключи[1])

    shutil.rmtree(layout.cut(project, ключи[0]))
    это = queue.обзор(project, {"duration": 180.0})
    ушла = next(д for д in это["дела"] if д["id"] == ключи[0])
    осталась = next(д for д in это["дела"] if д["id"] == ключи[1])

    assert ушла["удалён"] is True
    assert осталась["удалён"] is False
    # Ждать её нельзя: собирать нечего. Оставь её в «ждёт» — и она
    # попадёт в счёт работы, в оценку времени и в подпись у кнопки
    # «Собрать всё».
    assert ушла["состояние"] == works.ОТМЕНЁН
    assert осталась["состояние"] == works.ЖДЁТ
    assert это["удалено"] == 1
    # Оценка времени — про живые вертикалки: две в очереди минус
    # удалённая, плюс третья, которую в очередь ещё не ставили.
    assert это["оценка"] == осталась["оценка"] + это["ждут"][0]["оценка"]


def test_удалённая_не_считается_готовой(песочница):
    """«Готово 5» у человека, который две выбросил, — счёт того,
    чего у него нет."""
    import shutil

    project, _ = _видео_с_роликами(2)
    ключи = [c["id"] for c in pick.listing(project)]
    queue.записать(project, {"дела": [
        {"id": к, "зовут": к, "почему": "заново", "состояние": works.ГОТОВ}
        for к in ключи]})

    shutil.rmtree(layout.cut(project, ключи[0]))
    это = queue.обзор(project, {"duration": 180.0})
    assert это["готово"] == 1
    assert это["удалено"] == 1
    # Состояние у неё остаётся «готов»: файл когда-то был. Красным
    # её делает не оно, а пометка «удалён» — иначе пришлось бы врать
    # про то, чем дело кончилось.
    assert next(д for д in это["дела"]
                if д["id"] == ключи[0])["состояние"] == works.ГОТОВ


def test_сборка_не_падает_на_удалённой(песочница, monkeypatch):
    """«Упал» читается как поломка сборки, а поломки нет."""
    import shutil

    from vertcut import render

    project, _ = _видео_с_роликами(2)
    _планы_на_диске(project)
    ключи = [c["id"] for c in pick.listing(project)]
    queue.поставить_один(project, ключи[0])
    queue.поставить_один(project, ключи[1])
    shutil.rmtree(layout.cut(project, ключи[0]))

    monkeypatch.setattr(render, "проверить_исходник",
                        lambda meta: Path("/нет/такого.mp4"))
    собрано = []
    monkeypatch.setattr(
        render, "собрать_один",
        lambda *а, **к: собрано.append(а[2]["id"]) or {
            "took": 1.0, "megabytes": 1.0, "сверка": {}, "сверка_субтитров": {}})

    состояние = queue.run(project, {"duration": 180.0, "slug": project.name},
                          говорить=lambda *_: None)
    как = {д["id"]: д["состояние"] for д in состояние["дела"]}
    assert как[ключи[0]] == works.ОТМЕНЁН
    assert как[ключи[1]] == works.ГОТОВ
    assert собрано == [ключи[1]], "удалённую собирать не пытались"


