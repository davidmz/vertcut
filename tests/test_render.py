def test_штамп_без_отпечатка_фраз_считается_устаревшим():
    """Неизвестность значит «устарел», а не «свеж».

    Поймано на живом ролике: собран до того, как поменялись правила
    нарезки фраз, субтитры в нём от старой нарезки — а сервис объявлял
    его готовым и молчал.
    """
    from vertcut import layout, render, subs

    cut = {"id": "0000-0005", "файл": "ролик.mp4",
           "words": {"first": 0, "last": 5, "count": 6},
           "render": {"куски": [[0, 5]],
                      "montage": {"hand": {}},
                      "subs": {"профиль": "неважно"}}}
    # Файл на месте, границы те же, монтаж тот же, профиль тот же —
    # устареть ролику больше не от чего, кроме неизвестного текста.
    папка = layout.project("проба")
    layout.out(папка, cut).parent.mkdir(parents=True, exist_ok=True)
    layout.out(папка, cut).write_text("не пусто", encoding="utf-8")
    cut["render"]["subs"]["профиль"] = subs.отпечаток()
    причина = render.почему_устарел(папка, cut)
    assert причина == render.ТЕКСТ_НЕИЗВЕСТЕН


# ─── «Собрать» у одной вертикалки ────────────────────────────────────

def _видео_с_роликами(сколько: int = 3):
    """Разбор и несколько вертикалок на диске песочницы."""
    import json

    from tests.test_suggest import разбор

    project = layout.project("видео")
    project.mkdir(parents=True, exist_ok=True)
    laid = разбор(фраз=60)
    layout.align(project).write_text(json.dumps(laid, ensure_ascii=False),
                                     encoding="utf-8")
    layout.meta(project).write_text(json.dumps(
        {"source": "/где-то/видео.mp4", "duration": 180.0},
        ensure_ascii=False), encoding="utf-8")
    for n in range(сколько):
        куски = pick.by_ranges(laid, [(1 + n * 12, 12 + n * 12)])
        pick.save(project, pick.describe(laid, куски, "фразы", 180.0))
    return project, laid


def test_поставить_один_не_тащит_за_собой_остальных(песочница):
    """Кнопка «Собрать» на экране вертикалки — про ЭТУ вертикалку.

    Найдено автором на живом сервисе: нажатие собирало все ролики
    видео сразу.
    """
    project, _ = _видео_с_роликами(3)
    ключи = [c["id"] for c in pick.listing(project)]

    состояние = queue.поставить_один(project, ключи[1])
    assert [д["id"] for д in состояние["дела"]] == [ключи[1]]

    # А то, что уже ждёт в очереди, не теряется: человек мог поставить
    # их минуту назад с экрана сборки.
    состояние = queue.поставить_один(project, ключи[2])
    assert [д["id"] for д in состояние["дела"]] == [ключи[1], ключи[2]]

    # Тот же ключ второй раз не удваивается, а возвращается в «ждёт».
    состояние = queue.поставить_один(project, ключи[1])
    assert [д["id"] for д in состояние["дела"]] == [ключи[2], ключи[1]]
    assert all(д["состояние"] == works.ЖДЁТ for д in состояние["дела"])


def test_собрать_одну_не_говорит_очереди_заново(песочница, monkeypatch):
    """Вся беда была в одном слове.

    Ключ ставил в очередь одного, а команда шла со словом «заново» —
    и первым же делом складывала план ЗАНОВО, по всем роликам. Слово
    остаётся только у сборки всего видео.
    """
    from vertcut.web import api
    from vertcut.web import runner as работа_

    project, _ = _видео_с_роликами(3)
    ключи = [c["id"] for c in pick.listing(project)]
    поймано = {}

    def подстава(project_, что, слова_):
        поймано["слова"] = слова_
        return {"пущено": True}

    monkeypatch.setattr(работа_, "запустить", подстава)

    api.РУЧКИ[("POST", "собрать")](api.Просьба(
        тело={"слаг": project.name, "ключ": ключи[1], "заново": "1"}))
    assert "--again" not in поймано["слова"]
    assert [д["id"] for д in queue.показать(project)] == [ключи[1]]

    # А «собрать всё видео» слово «заново» по-прежнему говорит.
    api.РУЧКИ[("POST", "собрать-всё")](api.Просьба(
        тело={"слаг": project.name, "заново": "1"}))
    assert "--again" in поймано["слова"]


