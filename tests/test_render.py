def слова(текст: str, шаг: float = 0.4, с: float = 0.0) -> list[dict]:
    вышло, при = [], с
    for w in текст.split():
        вышло.append({"w": w, "s": round(при, 3), "e": round(при + шаг, 3)})
        при += шаг
    return вышло


@pytest.fixture
def уложенное():
    ws = слова("Раз два три четыре. Пять шесть семь восемь. "
               "Девять десять одиннадцать двенадцать.")
    ph = phrases.split(ws)
    return {"matched": 1.0, "words": ws, "sentences": [],
            "phrases": [{"idx": p.idx, "start": p.start, "end": p.end,
                         "text": p.text, "words": p.words}
                        for p in ph]}


