def test_окно_считается_общим_расчётом_а_не_1920_пополам():
    """Видео однажды приедет в 4K или в 4:3, и подгонка под один размер
    даст кривой кадр молча."""
    из_hd = chain.окно(1920, 1080)
    из_4k = chain.окно(3840, 2160)
    assert из_hd["w"] == 608 and из_hd["h"] == 1080
    assert из_4k["w"] == 1216 and из_4k["h"] == 2160
    узкий = chain.окно(1080, 1920)
    assert узкий["w"] == 1080, "вертикальный исходник режется по высоте"


def test_колонка_вырезается_тем_же_окном_что_посчитано():
    """Своей геометрии в строке фильтра нет: разойдись она с расчётом —
    и сверка начнёт ругаться на исправное, а кадр поедет молча."""
    # Исходник у́же вертикали 9:16 — такое приезжает со снятого
    # телефоном видео. Тогда окно режет не бока, а верх и низ.
    рамка = chain.окно(1080, 2400)
    цепь = chain.video(ряды((0.0, 4.0, 0.5, "crop")), 1080, 2400)
    assert f"crop={рамка['w']}:{рамка['h']}" in цепь
    assert f":{рамка['y']}," in цепь, "вертикальный отступ окна потерян"
    assert рамка["y"] > 0, "у слишком узкого кадра окно режет по высоте"


