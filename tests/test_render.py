# ─── шкала ролика ────────────────────────────────────────────────────

def кусок(first, last, start, end):
    return {"n": 1, "words": {"first": first, "last": last,
                              "count": last - first + 1},
            "phrases": {"first": 1, "last": 2, "count": 2},
            "start": start, "end": end, "duration": round(end - start, 3),
            "text": "текст"}


def test_длина_файла_это_речь_плюс_шторки():
    cut = {"id": "0000-0009", "куски": [кусок(0, 9, 10.0, 28.0)],
           "fade": tuning.EDGE_FADE}
    assert plans.total_of(cut, 600.0) == pytest.approx(
        18.0 + 2 * tuning.EDGE_FADE)


def test_у_края_видео_шторка_короче_и_это_не_беда():
    """Ролик, начинающийся с первого кадра видео, нарастать не из чего."""
    cut = {"id": "a", "куски": [кусок(0, 9, 0.05, 10.0)]}
    шторки = plans.fades(cut, 600.0)
    assert шторки[0]["lead"] == 0.05


def test_на_стыке_шторка_одна_на_оба_куска():
    """Врозь эти два числа однажды разъедутся, и файл выйдет не той
    длины — молча, потому что сумма кусков сойдётся."""
    cut = {"id": "a", "куски": [
        {**кусок(0, 9, 10.0, 20.0), "n": 1},
        {**кусок(20, 29, 20.1, 30.0), "n": 2}]}
    шторки = plans.fades(cut, 600.0)
    assert шторки[0]["trail"] == шторки[1]["lead"]
    # длина = речь обоих + краевые шторки + одна шторка на стык
    assert plans.total_of(cut, 600.0) == pytest.approx(
        10.0 + 9.9 + шторки[0]["lead"] + шторки[1]["trail"] + шторки[0]["trail"])


def test_карта_считает_кадры_а_не_секунды():
    cut = {"id": "a", "куски": [кусок(0, 9, 10.0, 28.0)]}
    таблица = plans.карта(cut, 600.0, 25.0)
    строка = таблица["куски"][0]
    assert строка["видео"]["кадров"] == round(таблица["всего"] * 25)
    assert строка["видео"]["кадр0"] * 1.0 == pytest.approx(
        строка["видео"]["essay0"] * 25, abs=0.001)


