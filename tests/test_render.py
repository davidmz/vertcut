"""Границы, монтаж, цепочка, заслоны, очередь.

Цепочку можно проверять здесь по-настоящему: она отдаёт СТРОКУ, а не
файл. Это и есть единственный способ поймать её поломку до того, как
она станет файлом.
"""

from __future__ import annotations

import os
