# ─── цепочка ─────────────────────────────────────────────────────────

def ряды(*тройки):
    return [{"idx": i, "at": at, "till": till, "cx": cx, "mode": режим,
             "hand": False}
            for i, (at, till, cx, режим) in enumerate(тройки, 1)]


def test_порог_стоит_посреди_между_кадрами():
    """`gte(t, n/fps)` сравнивает два числа с плавающей точкой на точное
    равенство — это монетка, и подбрасывается она на каждой склейке."""
    assert chain.порог(2.0, 25.0) == pytest.approx(1.98)


