def test_почти_ровный_кадр_сравнивается_яркостью_а_не_связью():
    """Живая беда: сквозной прогон уронил вертикалку со связью 0.5666
    при пороге 0.9. Глазами — на том стыке БЕЛАЯ ВСПЫШКА.

    После вычитания среднего в ровном кадре остаётся один шум
    пересжатия, и связь двух шумов — монетка. Раньше ветка ловила
    только идеально одноцветный кадр (`низ == 0`), то есть чёрное
    затемнение; вспышка с разбросом 0.03 проходила мимо неё.

    Ровные при этом НЕ выбрасываются из сверки: они сравниваются
    средней яркостью — белая вспышка вместо чёрного затемнения это
    всё ещё поломка, и заметить её надо.
    """
    import numpy

    rng = numpy.random.default_rng(7)
    # Два «ровных» кадра одной яркости: разный шум, одно среднее.
    один = 250.0 + rng.normal(0, 0.03, (60, 40))
    другой = 250.0 + rng.normal(0, 0.03, (60, 40))
    assert verify.связь(один, другой) == 1.0, "монетка больше не подбрасывается"

    # Ровный, но ДРУГОЙ яркости — это поломка, и она видна.
    assert verify.связь(один, один - 40) == 0.0

    # Кадр с содержанием считается по-прежнему связью.
    пёстрый = rng.normal(128, 40, (60, 40))
    assert verify.связь(пёстрый, пёстрый + 25) == pytest.approx(1.0)
    assert verify.связь(пёстрый, rng.normal(128, 40, (60, 40))) < 0.5


