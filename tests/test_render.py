# Один вопрос про все видео сразу — его задаёт значок в строке меню
# через `/апи/здоровье`, и ответ у него один: «собирает 4 из 9».


def _очередь_на_диске(песочница, имя: str, дела: list, pid: int) -> None:
    """Файл очереди с нужным хозяином. Без разбора и без сборки."""
    папка = layout.root() / имя
    папка.mkdir(parents=True, exist_ok=True)
    works.записать(layout.queue(папка),
                   {"хозяин": {"pid": pid, "что": "сборка"}, "дела": дела})


def test_идущие_считают_только_живую_очередь(песочница):
    """Мёртвый хозяин — не очередь, и врать про него нельзя.

    Недоделанные дела лежат в файле и после обрыва: они ждут
    следующего запуска, но прямо сейчас их не собирает никто.
    Скажи про них «собирает» — и человек будет ждать файл, которого
    никто не делает.
    """
    дела = [{"id": "a", "состояние": works.ГОТОВ},
            {"id": "б", "состояние": works.ИДЁТ},
            {"id": "в", "состояние": works.ЖДЁТ}]
    _очередь_на_диске(песочница, "живое", дела, os.getpid())
    _очередь_на_диске(песочница, "брошенное", дела, 999_999_999)

    идут = queue.идущие()
    assert [о["видео"] for о in идут] == ["живое"]
    # Всего три дела, осталось два — значит собирают второе из трёх.
    assert идут[0] == {"видео": "живое", "всего": 3, "осталось": 2}


