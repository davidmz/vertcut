def test_ffmpeg_рассказывает_настоящие_секунды(песочница):
    """Число в полосе — замер самого ffmpeg, а не доля от ожидаемого
    времени.

    Доля от времени показывала бы 90% у сборки, которая идёт вторую
    минуту сверх плана.
    """
    from vertcut.run import FFMPEG, run_с_ходом

    куда = песочница / "проба.mp4"
    сказано = []
    run_с_ходом([FFMPEG, "-v", "error", "-y",
                 "-f", "lavfi", "-i",
                 "testsrc2=size=160x120:rate=25:duration=3",
                 "-c:v", "libx264", "-preset", "ultrafast", str(куда)],
                3.0, lambda с, в: сказано.append(с))

    assert куда.exists() and куда.stat().st_size
    assert сказано, "ffmpeg не сказал ни слова о ходе"
    assert сказано == sorted(сказано), "ход пошёл назад"
    assert max(сказано) <= 3.0, "ход перевалил за длину ролика"
    assert max(сказано) >= 2.0, f"ход не дошёл до конца: {max(сказано)}"


