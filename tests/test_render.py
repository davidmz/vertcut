def test_ход_сборки_ложится_на_диск(песочница):
    """Читает ход другой процесс — экран. В памяти ему не место:
    сборка идёт своим процессом ровно затем, чтобы пережить закрытую
    вкладку."""
    файл = layout.queue(layout.project("видео"))
    файл.parent.mkdir(parents=True, exist_ok=True)
    дело = {"id": "0001-0010", "состояние": works.ИДЁТ}
    состояние = {"дела": [дело]}
    ход = queue._ход(файл, состояние, дело)

    ход("кодирую", 12.0, 46.6, "секунд")
    легло = works.прочитать(файл)["дела"][0]["ход"]
    assert легло == {"шаг": "кодирую", "сделано": 12.0,
                     "всего": 46.6, "единица": "секунд"}

    # Шаг, у которого считать нечего, зовётся словом и полосы
    # не рисует — правило пакета дизайна.
    ход("собираю плашку")
    легло = works.прочитать(файл)["дела"][0]["ход"]
    assert легло["шаг"] == "собираю плашку" and легло["всего"] is None


