# ─── замер: где у обводки предел ─────────────────────────────────────

def дырок(шрифт, знак: str, толщина: int) -> int:
    """Сколько замкнутых просветов внутри знака. Замер для `subtitles.yaml`."""
    from PIL import Image, ImageDraw

    к = Image.new("L", (240, 240), 0)
    ImageDraw.Draw(к).text((60, 180), знак, font=шрифт, fill=255,
                           anchor="ls", stroke_width=толщина, stroke_fill=255)
    п = к.load()
    ш, в = к.size
    снаружи = [[False] * в for _ in range(ш)]
    очередь = deque()
    for x in range(ш):
        for y in (0, в - 1):
            if п[x, y] < 128 and not снаружи[x][y]:
                снаружи[x][y] = True
                очередь.append((x, y))
    while очередь:
        x, y = очередь.popleft()
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            a, b = x + dx, y + dy
            если = 0 <= a < ш and 0 <= b < в
            if если and not снаружи[a][b] and п[a, b] < 128:
                снаружи[a][b] = True
                очередь.append((a, b))
    дыр, свои = 0, [[False] * в for _ in range(ш)]
    for x in range(ш):
        for y in range(в):
            if п[x, y] < 128 and not снаружи[x][y] and not свои[x][y]:
                дыр += 1
                оч = deque([(x, y)])
                свои[x][y] = True
                while оч:
                    a, b = оч.popleft()
                    for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                        c, d = a + dx, b + dy
                        if (0 <= c < ш and 0 <= d < в and not свои[c][d]
                                and not снаружи[c][d] and п[c, d] < 128):
                            свои[c][d] = True
                            оч.append((c, d))
    return дыр


def test_обводка_по_умолчанию_не_затягивает_просвет_буквы_о():
    """Замер из `assets/subtitles.yaml`: у Inter Tight просвет «о»
    затягивается с 0.11 кегля. Умолчание 0.06 — заметно ниже."""
    prof = профиль()
    шрифт = subs.font_of(prof).шрифт
    кегль = prof["кегль"]
    открыто = дырок(шрифт, "о", 0)
    assert открыто == 1
    assert дырок(шрифт, "о", round(кегль * 0.06)) == 1
    assert дырок(шрифт, "о", round(кегль * 0.13)) == 0


def test_обводка_по_умолчанию_не_слепляет_слова():
    """Настоящий предел: обводка растёт во все стороны, и когда её
    удвоенная толщина съедает межсловный пробел, слова слипаются."""
    основа = subs.образец()
    for имя in ("InterTight.ttf", "GolosText.ttf", "Oswald.ttf",
                "Literata.ttf"):
        prof = subs.к_пикселям({**основа, "шрифт": имя,
                                "подложка": "обводка"})
        пробел = subs.font_of(prof).шрифт.getlength(" ")
        assert 2 * prof["обводка_толщина"] < пробел, имя


# ─── четвёртый заслон знает, что при «без» он слабее ─────────────────

def test_порог_заслона_зависит_от_подложки():
    """Замер третьей сессии: при подложке «без» краска только в буквах,
    уровня там два близких, и верный файл даёт 0.572 вместо 0.999.
    Порог, ловящий сдвиг на два пикселя с плашкой, отверг бы исправное
    без неё."""
    assert tuning.SUBS_MIN_БЕЗ < tuning.SUBS_MIN
    # 0.5 стоит между худшим верным (0.572) и худшим сломанным (0.417).
    assert 0.417 < tuning.SUBS_MIN_БЕЗ < 0.572
