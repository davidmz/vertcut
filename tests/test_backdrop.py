"""Подложка: чем субтитр отделён от картинки.

Четыре рисовалки, а не настройки одной. Здесь проверяется, что они
и правда разные, что занятый субтитром прямоугольник считается теми же
числами, какими субтитр нарисован, и что цвет, слившийся с подложкой,
называется вслух, а не молча уезжает в файл.
"""

from __future__ import annotations

from collections import deque

import pytest

from vertcut import subs, tuning
from vertcut.errors import VertcutError


def профиль(**правки):
    числа = subs.образец()
    for ключ, значение in правки.items():
        где, части = числа, ключ.split("__")
        for часть in части[:-1]:
            где[часть] = dict(где[часть])
            где = где[часть]
        где[части[-1]] = значение
    return subs.к_пикселям(числа)


def страница(prof, текст="проверка связи"):
    слова = [{"w": w, "s": 0.0, "e": 0.4} for w in текст.split()]
    return subs.страницы(слова, prof, subs.font_of(prof))[0]


def нарисовать(prof, текст="проверка связи"):
    return subs.нарисовать(страница(prof, текст), 1, 1000, prof,
                           subs.font_of(prof))


# ─── четыре рисовалки ────────────────────────────────────────────────

def test_четыре_подложки_дают_четыре_разные_картинки():
    картинки = {м: нарисовать(профиль(background=м)).tobytes()
                for м in subs.ПОДЛОЖКИ}
    assert len(set(картинки.values())) == 4


def test_плашка_рисуется_только_в_своём_режиме():
    """Плашка непрозрачна, и по её пикселям видно, есть она или нет."""
    def сплошных(prof):
        альфа = нарисовать(prof).split()[3]
        return sum(1 for з in альфа.tobytes() if з >= 250)

    с_плашкой = сплошных(профиль(background="box"))
    без = сплошных(профиль(background="none"))
    assert с_плашкой > без * 3, "плашка не закрасила прямоугольник"


def test_обводка_расширяет_краску():
    тонкая = нарисовать(профиль(background="outline",
                                outline__width=0.02)).getbbox()
    толстая = нарисовать(профиль(background="outline",
                                 outline__width=0.12)).getbbox()
    assert толстая[0] < тонкая[0] and толстая[2] > тонкая[2]
    assert толстая[1] < тонкая[1] and толстая[3] > тонкая[3]


def test_тень_уходит_вправо_и_вниз():
    """Так падает свет в привычной картинке, и тень не читается
    как вторая строка."""
    prof = профиль(background="shadow")
    сдвиг = prof["тень_сдвиг"]
    без = нарисовать(профиль(background="none")).getbbox()
    с_тенью = нарисовать(prof).getbbox()
    # Краски стало ровно на сдвиг больше вширь и ввысь — то есть копия
    # ушла по диагонали, а не разбежалась во все стороны, как обводка.
    assert (с_тенью[2] - с_тенью[0]) - (без[2] - без[0]) == сдвиг
    assert (с_тенью[3] - с_тенью[1]) - (без[3] - без[1]) == сдвиг
    # И именно ВНИЗ: нижний край опустился, верхний остался на месте.
    assert с_тенью[3] == без[3] + сдвиг
    assert с_тенью[1] == без[1]


# ─── одни и те же числа у рисования и у заслона ──────────────────────

@pytest.mark.parametrize("режим", subs.ПОДЛОЖКИ)
def test_занятый_прямоугольник_накрывает_всю_краску(режим):
    """Заслон выбрасывает из сверки пиксели, занятые субтитром. Считает
    он их своими числами; разойдись они с рисованием — заслон начнёт
    спрашивать не те пиксели, и поймать это будет нечем."""
    prof = профиль(background=режим)
    стр = страница(prof)
    картинка = subs.нарисовать(стр, 1, 1000, prof, subs.font_of(prof))
    раскл = {"показы": [{"at": 0.0, "till": 1.0, "страница": стр,
                         "сказано": 1, "низ": 1000, "где": subs.ЦЕНТР,
                         "фраза": 1}]}
    x0, y0, x1, y1 = subs.занято(раскл, prof, 0.5)
    краска = картинка.getbbox()
    assert x0 <= краска[0] and y0 <= краска[1]
    assert x1 >= краска[2] and y1 >= краска[3]



def test_занятый_прямоугольник_уже_там_где_плашки_нет():
    """Лишний запас по бокам — это пиксели кадра, выброшенные из сверки
    картинки задаром: второй заслон перестанет смотреть туда, где
    субтитр ничего не закрыл. Считать поле плашки там, где плашки нет,
    и есть такой запас."""
    ширины = {}
    for режим in subs.ПОДЛОЖКИ:
        prof = профиль(background=режим)
        стр = страница(prof)
        раскл = {"показы": [{"at": 0.0, "till": 1.0, "страница": стр,
                             "сказано": 1, "низ": 1000, "где": subs.ЦЕНТР,
                             "фраза": 1}]}
        x0, _, x1, _ = subs.занято(раскл, prof, 0.5)
        ширины[режим] = x1 - x0
    assert ширины[subs.БЕЗ] < ширины[subs.ТЕНЬ] < ширины[subs.ОБВОДКА]
    assert ширины[subs.ОБВОДКА] < ширины[subs.ПЛАШКА]
    # Плашка шире ровно на своё поле с двух сторон.
    assert (ширины[subs.ПЛАШКА] - ширины[subs.БЕЗ]
            == pytest.approx(2 * профиль()["поле_сбоку"], abs=2))


def test_буквам_остаётся_меньше_места_под_плашкой():
    """У каждой подложки свой запас по краям. Держать «сколько места
    буквам» вторым числом нельзя — разъедется молча."""
    места = {м: профиль(background=м)["предел_текста"] for м in subs.ПОДЛОЖКИ}
    assert места[subs.ПЛАШКА] < места[subs.ОБВОДКА] < места[subs.БЕЗ]
    assert места[subs.ТЕНЬ] < места[subs.БЕЗ]
    # И ни одна не даёт вылезти за безопасную ширину.
    предел = профиль()["предел_плашки"]
    assert all(м <= предел for м in места.values())


