def test_поставляемый_профиль_читается():
    assert subs.жалоба_на_контраст(профиль()) is None


def test_смена_подложки_без_смены_цвета_это_жалоба():
    """Под плашку берут тёмный текст, под обводку — светлый. Поменял
    человек одно и не поменял второе — получил бы чёрное на чёрном
    и узнал об этом из собранного файла."""
    беда = subs.жалоба_на_контраст(профиль(background="outline"))
    # По смыслу: названы оба цвета и порог контраста.
    проф = профиль(background="outline")
    assert беда and проф["сказанное"] in беда and проф["обводка_цвет"] in беда
    assert str(tuning.CONTRAST_MIN) in беда


def test_светлый_текст_на_тёмной_обводке_читается():
    prof = профиль(background="outline", text_color__spoken="#FFFFFF")
    assert subs.жалоба_на_контраст(prof) is None


