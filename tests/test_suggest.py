    внутри = json.dumps({"фрагменты": [{"с": 1, "по": 10, "название": "Х",
                                        "о_чём": "х"}]}, ensure_ascii=False)
    это = разобрать(песочница, обёртка.format(текст=внутри))
    assert это["годных"] == 1


