def test_правило_языка_приклеено_к_концу_текста(песочница, monkeypatch):
    """Последнее сказанное весит больше — это и был замер."""
    from vertcut import prompts

    ответ = json.dumps({"фрагменты": []}, ensure_ascii=False)
    _, _, открывалка = весь_путь(песочница, monkeypatch, ответ)
    ушло = json.loads(открывалка.видел.data.decode("utf-8"))
    текст = ушло["messages"][0]["content"]
    assert текст.rstrip().endswith(prompts.ПРО_ЯЗЫК.strip())
