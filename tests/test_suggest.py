# ─── поддельный разбор видео ─────────────────────────────────────────

def разбор(фраз: int = 40, длина: float = 3.0, текст="фраза номер"):
    """Видео из одинаковых фраз — той же формы, что настоящий разбор.

    Форма взята с живого `align.json`, а не придумана: у слова поля
    `w`, `s`, `e`, у фразы её собственный список слов. Придуманная
    форма проверяла бы себя, а не сервис.
    """
    фразы, слова = [], []
    for n in range(1, фраз + 1):
        начало = round((n - 1) * длина, 3)
        свои = []
        for м, слово in enumerate((текст.split() + [str(n)])):
            шаг = длина / (len(текст.split()) + 1)
            свои.append({"w": слово, "s": round(начало + м * шаг, 3),
                         "e": round(начало + (м + 1) * шаг, 3), "p": 0.9})
        слова.extend(свои)
        фразы.append({"idx": n, "start": начало,
                      "end": round(начало + длина, 3),
                      "text": " ".join(w["w"] for w in свои),
                      "words": свои})
    return {"источник": "расшифровка", "matched": len(слова),
            "words": слова, "sentences": [], "phrases": фразы}


class Ответ:
    """То, что вернула бы `ai.спросить`."""

    def __init__(self, текст, вошло=100, вышло=50, деньги=0.01, секунд=1.0,
                 оборвался=False, модель="какая-то"):
        self.текст, self.модель = текст, модель
        self.вошло, self.вышло = вошло, вышло
        self.деньги, self.секунд, self.оборвался = деньги, секунд, оборвался
        self.посчитал_сам = False


def разобрать(tmp_path, ответ_текст, laid=None, **ещё):
    project = tmp_path / "видео"
    project.mkdir(exist_ok=True)
    return suggest._разобрать(project, laid or разбор(),
                              Ответ(ответ_текст, **ещё))


