"""Кандидаты во фрагменты: что сервис проверяет, а что нет.

**Ни один тест отсюда в сеть не ходит.** Модель подделывается: её
ответ — это текст, и разбор текста проверяется текстом.

Главное, что тут стережётся, — граница. Сервис проверяет механическое
(номера, длину, пересечения) и НЕ проверяет ничего про качество.
Число, которое выглядит замером, но им не является, — худший вид
самообмана.
"""

