# ─── весь путь целиком, с поддельным поставщиком ─────────────────────

def весь_путь(песочница, monkeypatch, ответ_модели: str):
    """От просьбы до файлов на диске. Сеть подделана, остальное настоящее."""
    import io
    import json as _json
    import urllib.error

    from vertcut import ai, config, ingest, works

    config.write({config.MODEL_KEY: "sk-test-0001"})
    сырое = _json.dumps({
        "model": "какая-то",
        "content": [{"type": "text", "text": ответ_модели}],
        "usage": {"input_tokens": 900, "output_tokens": 120},
        "stop_reason": "end_turn"}).encode("utf-8")

    class Открывалка:
        def open(self, просьба, timeout=None):
            Открывалка.видел = просьба

            class Ответ:
                def read(self_): return сырое
                def __enter__(self_): return self_
                def __exit__(self_, *_): return False
            return Ответ()

    monkeypatch.setattr(ai.urllib.request, "build_opener",
                        lambda *_: Открывалка())

    project = layout.project("видео")
    project.mkdir(parents=True, exist_ok=True)
    laid = разбор()
    это = suggest.спросить(project, laid, {"duration": 120.0})
    return project, это, Открывалка


def test_весь_путь_кладёт_оба_файла(песочница, monkeypatch):
    ответ = json.dumps({"фрагменты": [
        {"с": 1, "по": 10, "название": "Начало", "о_чём": "про начало"},
        {"с": 11, "по": 20, "название": "Дальше", "о_чём": "про дальше"},
    ]}, ensure_ascii=False)
    project, это, _ = весь_путь(песочница, monkeypatch, ответ)

    assert это["годных"] == 2
    assert layout.suggestions(project).exists()
    assert layout.suggestions_raw(project).exists()
    # Сырой ответ лежит КАК ПРИЕХАЛ, а не как разобрался.
    assert layout.suggestions_raw(project).read_text(
        encoding="utf-8") == ответ
    # И читается обратно тем же, чем читает экран.
    assert suggest.прочитать(project)["годных"] == 2


def test_расшифровка_уезжает_модели_целиком(песочница, monkeypatch):
    """Модель должна видеть номера фраз и их длительность.

    Порог длины сервис проверит сам, но модель, не знающая секунд,
    предложит пять кусков по восемь — и все пять окажутся негодными.
    """
    ответ = json.dumps({"фрагменты": []}, ensure_ascii=False)
    _, _, открывалка = весь_путь(песочница, monkeypatch, ответ)
    тело = json.loads(открывалка.видел.data.decode("utf-8"))
    ушло = тело["messages"][0]["content"]
    assert "1\t" in ушло and "40\t" in ушло      # все фразы
    assert "3.0s" in ушло                        # с длительностью
    assert "shorter than 15 seconds" in ушло     # и с порогом


