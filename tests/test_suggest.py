def test_метка_есть_считается_на_каждый_показ(песочница, monkeypatch):
    """Вертикалку создают ПОСЛЕ того, как совет приехал.

    Найдено автором на живом сервисе: он завёл вертикалку по совету,
    а совет остался выглядеть так, будто по нему ничего не сделано —
    в колонке пятнадцать одинаковых карточек, и какие из них уже
    отработаны, помнить надо самому.

    Метка считалась один раз, при разборе ответа, и ложилась в файл.
    Теперь она считается в момент ПОКАЗА и на диск не ложится:
    вертикалку могли и удалить, и тогда совет снова свободен.
    """
    ответ = json.dumps({"фрагменты": [
        {"с": 1, "по": 10, "название": "Начало", "о_чём": ""}]},
        ensure_ascii=False)
    project, _, _ = весь_путь(песочница, monkeypatch, ответ)
    laid = разбор()
    layout.meta(project).write_text(
        json.dumps({"source": "/где-то/видео.mp4", "duration": 120.0},
                   ensure_ascii=False), encoding="utf-8")

    # Совет уже на диске, и вертикалки по нему ещё нет.
    было = suggest.для_экрана(project, laid, {"duration": 120.0})
    assert было["было"]["предложения"][0]["есть_ключ"] is None

    # Человек создал её ровно так, как создал бы щелчками по фразам.
    куски = pick.by_ranges(laid, [(1, 10)])
    cut = pick.describe(laid, куски, "фразы 1-10", 120.0)
    pick.save(project, cut)

    стало = suggest.для_экрана(project, laid, {"duration": 120.0})
    assert стало["было"]["предложения"][0]["есть_ключ"] == cut["id"]
    # На диске при этом ничего не поменялось: показ не пишет.
    с_диска = suggest.прочитать(project)
    assert с_диска["предложения"][0]["есть_ключ"] is None

    # Удалили вертикалку — совет снова свободен.
    import shutil
    shutil.rmtree(layout.cut(project, cut["id"]))
    опять = suggest.для_экрана(project, laid, {"duration": 120.0})
    assert опять["было"]["предложения"][0]["есть_ключ"] is None


