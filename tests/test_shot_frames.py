"""Кадр плана на экране — его собственный, а не соседа.

Беда, ради которой заведён этот файл, нашлась глазами у автора и
выглядела не поломкой, а странностью разбора: два соседних плана
показывали ОДНУ картинку с разными рамками, и казалось, что детектор
склеек разрезал один план надвое. Границы были ни при чём.

Кадр плана вынимался во времянку с именем `00000.jpg` прямо в общую
папку `frames/`. Экран многопоточный: браузер, открыв список планов,
просит десяток кадров разом — десяток ffmpeg писали в один файл
и затирали друг друга. На живом видео из шестнадцати планов четыре
получили чужой кадр, а три файла оказались побайтово одним.

Ни один прежний тест этого поймать не мог: по одному вызову всё
верно. Поэтому здесь вызовы идут ОДНОВРЕМЕННО — иначе проверяется
не то, что ломалось.
"""

from __future__ import annotations

import subprocess
from concurrent.futures import ThreadPoolExecutor

import pytest

from vertcut import ingest, layout, shots


# ffmpeg зовётся ТЕМ ЖЕ ПУТЁМ, каким его зовёт сервис.
#
# Голым именем «ffmpeg» он находится только там, где лежит в PATH —
# то есть у автора, поставившего его через brew. На машине, где сервис
# поставлен как у человека, своя копия лежит РЯДОМ С СЕРВИСОМ, и в PATH
# её нет: сборочная машина ответила «не найден указанный файл»
# на пятнадцати проверках сразу.
#
# Правило проекта — «ffmpeg запускается только через run.py» — писалось
# про код сервиса, а проверки его нарушали. Не всплывало это ровно
# потому, что гонялись они на одной машине.
def ффмпег() -> str:
    from vertcut import run as дорога

    return дорога.where("ffmpeg") or "ffmpeg"

# Секунда — один сплошной цвет. Так кадр отвечает на вопрос «свой ли
# он» одним числом, а не разглядыванием: у чужого кадра цвет чужой.
ЦВЕТА = ["red", "green", "blue", "yellow", "magenta", "white"]


@pytest.fixture
def разбор(песочница):
    project = песочница / "видео"
    layout.frames(project).mkdir(parents=True, exist_ok=True)
    входы, куски = [], []
    for n, цвет in enumerate(ЦВЕТА):
        входы += ["-f", "lavfi",
                  "-i", f"color=c={цвет}:size=320x240:rate=25:duration=1"]
        куски.append(f"[{n}:v]")
    subprocess.run([
        ффмпег(), "-v", "error", "-y", *входы,
        "-filter_complex", f"{''.join(куски)}concat=n={len(ЦВЕТА)}:v=1[v]",
        "-map", "[v]", "-c:v", "libx264", "-crf", "18",
        str(layout.proxy(project)),
    ], check=True)
    return project


def цвет_кадра(путь):
    from PIL import Image
    with Image.open(путь) as кадр:
        точки = кадр.convert("RGB").resize((1, 1))
        return точки.getpixel((0, 0))


def похож(вышло, надо, допуск=40):
    return all(abs(a - b) <= допуск for a, b in zip(вышло, надо))


ОБРАЗЦЫ = {"red": (255, 0, 0), "green": (0, 128, 0), "blue": (0, 0, 255),
           "yellow": (255, 255, 0), "magenta": (255, 0, 255),
           "white": (255, 255, 255)}


def test_кадры_планов_не_путаются_при_одновременном_спросе(разбор):
    """Шесть планов, спрошенных разом, получают каждый свой кадр."""
    планы = [{"idx": n + 1, "start": float(n), "end": float(n + 1)}
             for n in range(len(ЦВЕТА))]
    with ThreadPoolExecutor(max_workers=len(планы)) as пул:
        пути = list(пул.map(lambda п: shots.кадр_плана(разбор, п), планы))
    чужие = [п["idx"] for п, путь in zip(планы, пути)
             if not похож(цвет_кадра(путь), ОБРАЗЦЫ[ЦВЕТА[п["idx"] - 1]])]
    assert not чужие, f"кадр от чужого плана у: {чужие}"


def test_кадр_плана_не_оставляет_за_собой_времянок(разбор):
    план = {"idx": 3, "start": 2.0, "end": 3.0}
    shots.кадр_плана(разбор, план)
    мусор = [п.name for п in layout.frames(разбор).iterdir() if п.is_dir()]
    assert not мусор, f"времянки остались: {мусор}"


def test_обложка_видео_тоже_своя(разбор, monkeypatch):
    """Обложка и кадры планов дрались за тот же общий файл.

    Она вынимается по своей доле длительности, поэтому проверяется
    не цвет, а то, что файл появился и лежит там, где его ищет экран.
    """
    monkeypatch.setattr(ingest, "read_meta",
                        lambda _: {"duration": len(ЦВЕТА)})
    вышло = ingest.обложка(разбор)
    assert вышло == layout.cover(разбор)
    assert вышло.exists() and вышло.stat().st_size
