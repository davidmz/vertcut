"""Правка фраз рукой: разделить, склеить, поправить текст.

Проверяется главное: правка живёт у ролика, привязана к номерам слов
и не двигает границ куска. Всё остальное — следствия.
"""

from __future__ import annotations

import pytest

from vertcut import edits
from vertcut.errors import VertcutError


def фраза(idx: int, с: int, по: int, текст: str, при: float = 0.0,
          кусок: int = 1) -> dict:
    слова = []
    шаг = 0.5
    for n, w in enumerate(текст.split()):
        слова.append({"w": w, "s": round(при + n * шаг, 3),
                      "e": round(при + n * шаг + шаг, 3)})
    return {"idx": idx, "с": с, "по": по, "кусок": кусок, "сдвиг": 0.0,
            "at": слова[0]["s"], "till": слова[-1]["e"], "words": слова,
            "целая": True}


def две_фразы() -> list[dict]:
    return [фраза(1, 0, 2, "мы идем домой.", при=0.0),
            фраза(2, 3, 5, "потом обедаем тихо.", при=2.0)]


# ─── разделить ───────────────────────────────────────────────────────

def test_разделить_режет_фразу_надвое():
    вышло = edits.наложить(две_фразы(),
                           [{"что": edits.РАЗДЕЛИТЬ, "после": 1}])
    assert len(вышло) == 3
    assert [w["w"] for w in вышло[0]["words"]] == ["мы", "идем"]
    assert [w["w"] for w in вышло[1]["words"]] == ["домой."]
    assert (вышло[0]["с"], вышло[0]["по"]) == (0, 1)
    assert (вышло[1]["с"], вышло[1]["по"]) == (2, 2)


def test_разделить_не_двигает_времён():
    """Границы ролика считаются в словах, и правка субтитра их
    не касается: та же речь, только подписана двумя субтитрами."""
    было = две_фразы()
    стало = edits.наложить(было, [{"что": edits.РАЗДЕЛИТЬ, "после": 1}])
    assert стало[0]["at"] == было[0]["at"]
    assert стало[1]["till"] == было[0]["till"]


def test_разделить_после_последнего_слова_отказывает():
    """Там фраза и так кончается — молча ничего не сделать нельзя."""
    with pytest.raises(VertcutError) as беда:
        edits.наложить(две_фразы(), [{"что": edits.РАЗДЕЛИТЬ, "после": 2}])
    assert "already ends" in беда.value.message


# ─── склеить ─────────────────────────────────────────────────────────

def test_склеить_соединяет_соседние_фразы():
    вышло = edits.наложить(две_фразы(), [{"что": edits.СКЛЕИТЬ, "после": 2}])
    assert len(вышло) == 1
    assert вышло[0]["текст" if "текст" in вышло[0] else "с"] is not None
    assert [w["w"] for w in вышло[0]["words"]][-1] == "тихо."
    assert (вышло[0]["с"], вышло[0]["по"]) == (0, 5)


def test_склеить_через_разрыв_отказывает():
    """Между кусками разрывного ролика выброшена речь: склеенный
    субтитр стоял бы поверх склейки."""
    фразы = [фраза(1, 0, 2, "мы идем домой.", при=0.0),
             фраза(2, 9, 11, "совсем другое место.", при=2.0)]
    with pytest.raises(VertcutError) as беда:
        edits.наложить(фразы, [{"что": edits.СКЛЕИТЬ, "после": 2}])
    assert "across a gap" in беда.value.message


def test_склеить_фразы_из_разных_кусков_отказывает():
    """Между ними стык монтажа, и субтитр повис бы поперёк него."""
    фразы = [фраза(1, 0, 2, "мы идем домой.", при=0.0, кусок=1),
             фраза(2, 3, 5, "потом обедаем тихо.", при=2.0, кусок=2)]
    with pytest.raises(VertcutError) as беда:
        edits.наложить(фразы, [{"что": edits.СКЛЕИТЬ, "после": 2}])
    assert "different segments" in беда.value.message


def test_склеить_последнюю_не_с_чем():
    with pytest.raises(VertcutError) as беда:
        edits.наложить(две_фразы(), [{"что": edits.СКЛЕИТЬ, "после": 5}])
    assert "last phrase" in беда.value.message


# ─── текст ───────────────────────────────────────────────────────────

def test_текст_заменяется_и_укладывается_в_прежнее_окно():
    """Правка текста НЕ двигает границ ролика: новый текст ложится
    внутрь прежнего окна фразы."""
    было = две_фразы()
    стало = edits.наложить(было, [{"что": edits.ТЕКСТ, "с": 0, "по": 2,
                                   "текст": "мы шли домой пешком."}])
    assert [w["w"] for w in стало[0]["words"]] == \
        ["мы", "шли", "домой", "пешком."]
    assert стало[0]["at"] == было[0]["at"]
    assert стало[0]["till"] == было[0]["till"]


def test_у_правленных_слов_время_помечено_прикидкой():
    """Где именно человек сказал исправленное слово, не знает никто:
    исходное было расслышано неверно, мерить нечего."""
    стало = edits.наложить(две_фразы(), [{"что": edits.ТЕКСТ, "с": 0,
                                          "по": 2, "текст": "мы шли домой."}])
    assert all(w["a"] == "правка" for w in стало[0]["words"])
    assert стало[0]["правлено"] is True


def test_текст_на_переехавшие_границы_не_ложится_молча():
    """Правка, записанная на слова, которых в ролике больше нет,
    значит что границы куска переехали. Молча её потерять — это
    субтитр не тот, и увидит это зритель."""
    with pytest.raises(VertcutError) as беда:
        edits.наложить(две_фразы(), [{"что": edits.ТЕКСТ, "с": 40, "по": 42,
                                      "текст": "что-то"}])
    # По смыслу: назван номер слова, которого нет, и что делать.
    assert "40" in беда.value.message
    assert беда.value.hint


def test_половину_разделённой_фразы_править_можно():
    """Человек правит то, что ВИДИТ, а видит он фразу уже разделённой.

    Поэтому швы накладываются первыми: иначе правка, записанная
    на половину, легла бы в пустоту.
    """
    правки = [{"что": edits.РАЗДЕЛИТЬ, "после": 1},
              {"что": edits.ТЕКСТ, "с": 0, "по": 1, "текст": "мы шли"}]
    вышло = edits.наложить(две_фразы(), правки)
    assert [w["w"] for w in вышло[0]["words"]] == ["мы", "шли"]
    assert [w["w"] for w in вышло[1]["words"]] == ["домой."]


def test_текст_целой_фразы_после_её_разделения_не_ложится_молча():
    """Обратный случай: правку записали на целую фразу, а потом её
    разделили. Гадать, какой половине она предназначалась, нельзя."""
    правки = [{"что": edits.РАЗДЕЛИТЬ, "после": 1},
              {"что": edits.ТЕКСТ, "с": 0, "по": 2, "текст": "мы шли домой."}]
    with pytest.raises(VertcutError) as беда:
        edits.наложить(две_фразы(), правки)
    # По смыслу: названы оба размаха — записанный и настоящий.
    assert "0–2" in беда.value.message
    assert "0" in беда.value.message and "1" in беда.value.message
    assert беда.value.hint


# ─── хранение ────────────────────────────────────────────────────────

def test_правок_нет_ключа_в_файле_тоже_нет():
    """Пустой список означал бы «правок нет, но кто-то тут был», а через
    полгода читался бы как забытый долг."""
    cut = {"id": "0000-0005"}
    edits.положить(cut, [])
    assert edits.КЛЮЧ not in cut


def test_правки_ложатся_по_порядку_слов():
    cut = {"id": "0000-0005"}
    edits.положить(cut, [{"что": edits.СКЛЕИТЬ, "после": 9},
                         {"что": edits.РАЗДЕЛИТЬ, "после": 2}])
    assert [п["после"] for п in cut[edits.КЛЮЧ]] == [2, 9]


def test_правка_меняет_отпечаток_фраз():
    """Иначе поправленный текст не считался бы поводом пересобрать —
    а он самый частый повод из всех."""
    from vertcut import subs

    слова = [{"w": w, "s": i * 0.5, "e": i * 0.5 + 0.4}
             for i, w in enumerate(["мы", "идем", "домой."])]
    laid = {"words": слова,
            "phrases": [{"idx": 1, "start": 0.0, "end": 1.4,
                         "text": "мы идем домой.", "words": слова}]}
    без = subs.отпечаток_фраз(laid, [[0, 2]])
    с_правкой = subs.отпечаток_фраз(
        laid, [[0, 2]], [{"что": edits.ТЕКСТ, "с": 0, "по": 2,
                          "текст": "мы шли домой."}])
    assert без != с_правкой
