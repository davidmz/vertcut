"""Укладка текста на звук и сегментация фраз.

Проверки на то, что перенеслось из чужой библиотеки: там у каждого
решения была причина, и здесь она обязана уцелеть.
"""

from __future__ import annotations

import pytest

from vertcut import align, phrases, speech, tuning
from vertcut.errors import VertcutError


# ─── что такое слово ─────────────────────────────────────────────────

def test_ё_и_е_складываются():
    """Распознавание `ё` не пишет никогда.

    Не сложи их — и «ещё» из сценария не совпадёт с услышанным «еще»
    ни разу, а доля совпавших рухнет на ровном месте.
    """
    assert align.words("Ещё раз") == align.words("Еще раз") == ["еще", "раз"]


def test_дефисное_слово_одно():
    """«какой-то» человек считает одним словом, и границы куска
    считаются в словах — значит и здесь оно одно."""
    assert align.words("какой-то день") == ["какой-то", "день"]


def test_знак_препинания_принадлежит_слову():
    """Сегментация фраз смотрит ПОСЛЕДНИЙ символ слова.

    Запятая, оставшаяся в промежутке между словами, для неё всё равно
    что её нет — и конец оборота не сработает ни разу.
    """
    вышло = align.surfaces("Слово, другое. Третье")
    assert вышло[0].endswith(",")
    assert вышло[1].endswith(".")


def test_открывающая_кавычка_уходит_к_следующему_слову():
    """Иначе у «правило. «Новый» последним символом окажется кавычка,
    и конец предложения пропадёт — ровно тот способ потерять
    пунктуацию, ради которого всё это и делается."""
    вышло = align.surfaces('правило. «Новый день')
    assert вышло[0] == "правило."
    assert вышло[1].startswith("«")


def test_сокращение_не_рвёт_предложение():
    """«т. д.» и инициалы выглядят как конец фразы, и правило это знает.

    Цена правила названа вслух и проверяется здесь же: следующее
    предложение приклеивается к сокращению. Правило простое
    и предсказуемое, а не умное, — промах видно глазами в списке фраз,
    и стоит он лишней границы предложения, а не сдвинутого времени.
    Записано в TODO.md.
    """
    одно = align.sentences("Были яблоки, груши и т. д. Потом ушли.")
    assert len(одно) == 1, "сокращение не должно рвать предложение"
    два = align.sentences("Были яблоки и груши. Потом ушли.")
    assert len(два) == 2, "обычная точка рвать обязана"


def test_абзац_рвёт_предложение_всегда():
    """Склеенные абзацы дали бы фразу, сшитую из конца одного раздела
    и начала другого."""
    assert len(align.sentences("Первый кусок\n\nВторой кусок")) == 2


# ─── откуда взялось время ────────────────────────────────────────────

def собрать(*слова):
    return [{"word": w, "start": i * 1.0, "end": i * 1.0 + 0.5}
            for i, w in enumerate(слова)]


def test_услышанное_дословно_получает_своё_время():
    времена, доля = align.map_words(["мы", "идём", "домой"],
                                    собрать("мы", "идём", "домой"))
    assert доля == 1.0
    assert all(t["kind"] == "exact" for t in времена)


def test_неуслышанное_слово_помечено_как_невзвешенное():
    """Заполнены всегда все слова, а измерены только услышанные.

    Без этой пометки не отличить измеренное время от выдуманного —
    и весь столбец «край» в списке фраз стал бы враньём.
    """
    времена, доля = align.map_words(["мы", "бежим", "домой"],
                                    собрать("мы", "летим", "домой"))
    assert доля == pytest.approx(2 / 3)
    assert времена[1]["kind"] == "spread"
    вышло = align.exchange("мы бежим домой", времена, 10_000)
    assert "a" not in вышло[0] and вышло[1]["a"] == "spread"


def test_форма_слов_берётся_из_сценария_а_не_из_услышанного():
    """В этом весь смысл укладки: имена и пунктуация авторские."""
    времена, _ = align.map_words(["мы", "бежим"], собрать("мы", "летим"))
    вышло = align.exchange("Мы бежим!", времена, 10_000)
    assert [w["w"] for w in вышло] == ["Мы", "бежим!"]


def test_не_сошлось_число_слов_отдаём_пусто_а_не_кривое():
    """Молча подставить не то слово хуже, чем не отдать ничего."""
    времена, _ = align.map_words(["мы", "бежим"], собрать("мы", "бежим"))
    assert align.exchange("Мы бежим быстро", времена, 10_000) == []


# ─── сегментация фраз ────────────────────────────────────────────────

def слова(текст: str, шаг: float = 0.3) -> list[dict]:
    вышло, при = [], 0.0
    for w in текст.split():
        вышло.append({"w": w, "s": round(при, 3), "e": round(при + шаг, 3)})
        при += шаг
    return вышло


def test_конец_предложения_рвёт_фразу():
    вышло = phrases.split(слова("Раз два три четыре. Пять шесть семь восемь."))
    assert len(вышло) == 2
    assert вышло[0].text.endswith(".")


def test_короткое_предложение_выпускается_отдельной_фразой():
    """Конец предложения — самый сильный шов, и порог длины его
    не отменяет.

    ЭТО ПЕРЕМЕНА ВТОРОЙ СЕССИИ, И У НЕЁ ЗАМЕР. Пока порог держал
    и паузу, и конец предложения, на разговорном материале каждая
    четвёртая фраза оказывалась сшита из конца одного предложения
    и начала следующего: «стол. Ну и все такое.». Числа — в
    `tuning.MIN_PHRASE`.
    """
    вышло = phrases.split(слова("Да. Теперь длинная мысль про всё на свете."))
    assert вышло[0].text == "Да."
    assert вышло[0].end - вышло[0].start < tuning.MIN_PHRASE


def test_пауза_короткую_фразу_по_прежнему_не_выпускает():
    """У порога осталась одна работа из двух: пауза посреди
    предложения не повод выпускать огрызок в четверть секунды."""
    ряд = слова("мы идем домой и дальше идем очень долго", шаг=0.3)
    ряд[1]["s"] += 1.0          # пауза после первого слова
    ряд[1]["e"] += 1.0
    вышло = phrases.split(ряд)
    assert вышло[0].text.startswith("мы идем")


def test_потолок_отступает_до_знака_а_не_рубит_посреди_оборота():
    длинный = слова("первое второе третье, четвёртое пятое шестое седьмое "
                    "восьмое девятое десятое", шаг=0.5)
    вышло = phrases.split(длинный)
    assert len(вышло) >= 2
    assert вышло[0].text.endswith(","), вышло[0].text


def test_разбор_не_делит_текст_на_строки_вовсе():
    """Черновая разбивка убрана целиком, и это главное решение сессии.

    В момент разбора стиля нет: ни шрифта, ни кегля, ни полей. Любое
    число знаков в строке здесь — выдумка, которая выглядит как ответ.
    Настоящую разбивку делает рисование субтитра, где меряется ширина
    краски настоящим шрифтом.
    """
    assert not hasattr(phrases, "wrap")
    assert not hasattr(tuning, "LINE_CHARS")
    вышло = phrases.split(слова("Раз два три."))
    assert not hasattr(вышло[0], "lines")


def test_числа_сегментации_названы_чужими_по_происхождению():
    """Единственные числа проекта, которые не мерялись ни здесь, ни
    у соседа: они лежали внутри чужого модуля, и достать их было нечем.

    Спека запрещает выдавать унаследованные числа за замеры — и она же
    требует мерить то, что можно померить. Вторая сессия их перемерила,
    и теперь у каждого написано, НА ЧЁМ: три видео, названные вслух.
    """
    from pathlib import Path
    текст = Path(tuning.__file__).read_text(encoding="utf-8")
    кусок = текст[текст.index("Сегментация фраз"):]
    assert "ПЕРЕМЕРЕНО ВО ВТОРОЙ СЕССИИ" in кусок
    assert "интервью" in кусок, "не сказано, на каком материале мерялось"
    assert "PHRASE_MAX_CHARS" in кусок


def test_знаков_в_правиле_нарезки_нет_вовсе():
    """Фразы режутся без оглядки на стиль.

    В библиотеке порог звался «предел длины строки», и там же написано,
    что имя обманывает: в строку субтитра эти 42 знака не влезали
    никогда. Первая сессия его переименовала в вес фразы, вторая убрала
    совсем: число знаков в строке — это стиль, а стиль здесь настраивает
    человек.
    """
    for имя in ("PHRASE_MAX_CHARS", "PHRASE_MAX_LINES", "LINE_CHARS",
                "MAX_LINE_CHARS"):
        assert not hasattr(tuning, имя), f"{имя} вернулось в сегментацию"
    # Длинная фраза без знаков препинания кончается по ВРЕМЕНИ,
    # а не по знакам: восемь слов по 0.3 с — это 2.4 с, потолок 4.5.
    вышло = phrases.split(слова("раз два три четыре пять шесть семь восемь"))
    assert len(вышло) == 1


# ─── чтение уложенного ───────────────────────────────────────────────

def уложенное() -> dict:
    ws = слова("Раз два три. Четыре пять шесть.")
    ph = phrases.split(ws)
    return {"matched": 1.0, "words": ws, "sentences": [],
            "phrases": [{"idx": p.idx, "start": p.start, "end": p.end,
                         "text": p.text, "words": p.words}
                        for p in ph]}


def test_спаны_фраз_проверяются_а_не_предполагаются():
    """Молча посчитанные по кривому соответствию границы выглядят
    целыми и звучат не там."""
    данные = уложенное()
    данные["words"][1]["w"] = "подменённое"
    with pytest.raises(VertcutError) as беда:
        speech.spans(данные)
    # Названа фраза, и сказано, что её слова не сходятся со списком.
    assert "do not match the word list" in беда.value.message


def test_надёжность_края_считается_числом():
    данные = уложенное()
    данные["words"][2]["a"] = "gap"
    далеко = speech.anchor_distance(данные)
    assert далеко[0] == 0
    assert далеко[2] == 1, "у слова без времени сосед измерен — значит 1"


def test_отпечаток_правил_не_роняет_разбор():
    """Подсказка не имеет права ронять то, что она стережёт.

    Настоящая поломка: чтение исходника рассыпалось на файле,
    переписанном под работающим процессом, и разбор упал трассировкой
    посреди девятиминутной работы — из-за отпечатка, который всего лишь
    отвечает на вопрос «не устарело ли».
    """
    import inspect

    было = inspect.getsource

    def падать(*_a, **_k):
        raise SyntaxError("исходник переписан под ногами")

    inspect.getsource = падать
    try:
        отп = phrases.отпечаток()
    finally:
        inspect.getsource = было
    assert отп and len(отп) == 16


# ─── дефис не участвует в споре ──────────────────────────────────────

def test_дефис_не_считается_ошибкой_распознавания():
    """Распознавание рвёт «какой-то» на два куска.

    Пока сравнивались целые слова, это считалось ошибкой слуха, и слово
    получало прикинутое время вместо измеренного. На деле это спор
    о том, где кончается слово, а не о том, какое оно.
    """
    времена, доля = align.map_words(
        ["какой-то", "день"],
        [{"word": "какой", "start": 1.0, "end": 1.4},
         {"word": "то", "start": 1.4, "end": 1.6},
         {"word": "день", "start": 1.7, "end": 2.0}])
    assert доля == 1.0
    assert времена[0]["kind"] == "exact"
    assert (времена[0]["start"], времена[0]["end"]) == (1.0, 1.6)


def test_слепленное_распознаванием_слово_тоже_не_ошибка():
    """Обратный случай, и он частый: машина слышит повтор как одно
    слово через дефис — «мертвых-мертвых». Замер на эссе: таких 17
    против 9 настоящих дефисных слов сценария."""
    времена, доля = align.map_words(
        ["мертвых", "мертвых"],
        [{"word": "мертвых-мертвых", "start": 1.0, "end": 2.0}])
    assert доля == 1.0
    assert [t["kind"] for t in времена] == ["exact", "exact"]
    # Время куска делится пополам, а не отдаётся обоим целиком.
    assert времена[0]["end"] == pytest.approx(1.5)
    assert времена[1]["start"] == pytest.approx(1.5)


def test_настоящая_ошибка_слуха_дефисом_не_прикрывается():
    """Разбор по частям не должен объявлять точным то, что расслышано
    неверно."""
    времена, доля = align.map_words(
        ["мы", "бежим"],
        [{"word": "мы", "start": 0.0, "end": 0.3},
         {"word": "летим", "start": 0.3, "end": 0.7}])
    assert доля == 0.5
    assert времена[1]["kind"] == "spread"


def test_распознавание_читает_настоящий_звук(tmp_path):
    """Проверки распознавания не слушали звук — и не увидели, что
    av 19 сломал faster-whisper у каждой свежей установки (27-я сессия:
    `open() got an unexpected keyword argument 'metadata_errors'`).
    Модель не нужна: звук читает та же функция, что и при разборе."""
    import subprocess

    from faster_whisper.audio import decode_audio
    from vertcut import run as дорога

    звук = tmp_path / "beep.wav"
    subprocess.run([дорога.where(дорога.FFMPEG) or "ffmpeg", "-loglevel", "error",
                    "-f", "lavfi", "-i", "sine=f=440:d=1", "-ar", "16000",
                    str(звук)], check=True)
    отсчёты = decode_audio(str(звук))
    assert 15000 < len(отсчёты) < 17000


def test_модель_берётся_сперва_из_кэша(monkeypatch, tmp_path):
    """Без `local_files_only` huggingface_hub на каждом разборе
    спрашивает сайт, не вышла ли модель новее (замер 27-й сессии)."""
    import faster_whisper

    вызовы, скачивание = [], []

    class Модель:
        def __init__(self, имя, **доводы):
            вызовы.append(доводы.get("local_files_only", False))
            if доводы.get("local_files_only") and not есть_в_кэше:
                raise FileNotFoundError("not in cache")

        def transcribe(self, *a, **k):
            return iter([]), None

    monkeypatch.setattr(faster_whisper, "WhisperModel", Модель)
    есть_в_кэше = True
    align.transcribe(tmp_path / "a.wav", on_download=скачивание.append)
    assert вызовы == [True] and скачивание == []

    вызовы.clear()
    есть_в_кэше = False
    align.transcribe(tmp_path / "a.wav", on_download=скачивание.append)
    assert вызовы == [True, False] and скачивание == [tuning.WHISPER_MODEL]
