def test_блок_растёт_вверх_а_не_вниз(профиль, шрифт):
    """Нижняя строка всегда на одном месте, сколько бы их ни было:
    так строка не прыгает при перелистывании."""
    одна = subs.страницы(слова("коротко"), профиль, шрифт)[0]
    две = subs.страницы(слова("одно два три четыре пять шесть семь"),
                        профиль, шрифт)[0]
    assert len(две) == 2

    def нижний_край(страница):
        картинка = subs.нарисовать(страница, 1, 1000, профиль, шрифт)
        альфа = картинка.split()[-1]
        return альфа.getbbox()[3]

    assert нижний_край(одна) == нижний_край(две)


def test_сказанное_чернеет_по_словам(профиль, шрифт):
    страница = subs.страницы(слова("раз два три"), профиль, шрифт)[0]
    import numpy as np
    было = None
    for сказано in (1, 3):
        картинка = subs.нарисовать(страница, сказано, 1000, профиль, шрифт)
        точки = np.asarray(картинка)
        тёмных = int(((точки[:, :, 3] > 0) & (точки[:, :, 0] < 40)).sum())
        if было is not None:
            assert тёмных > было, "второе слово не почернело"
        было = тёмных


def test_занятый_субтитром_прямоугольник_накрывает_плашку(профиль, шрифт):
    """Сверка выбрасывает эти пиксели. Промахнётся — сверка начнёт
    сравнивать нарисованное с кадром исходника и объявит исправный
    файл битым."""
    страница = subs.страницы(слова("проверка связи"), профиль, шрифт)[0]
    раскл = {"показы": [{"at": 0.0, "till": 2.0, "страница": страница,
                         "сказано": 1, "низ": 1000, "где": subs.ЦЕНТР,
                         "фраза": 1}]}
    угол = subs.занято(раскл, профиль, 1.0)
    картинка = subs.нарисовать(страница, 1, 1000, профиль, шрифт)
    краска = картинка.split()[-1].getbbox()
    assert угол[0] <= краска[0] and угол[1] <= краска[1]
    assert угол[2] >= краска[2] and угол[3] >= краска[3]
    assert subs.занято(раскл, профиль, 5.0) is None


