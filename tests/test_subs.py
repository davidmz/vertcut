# ─── из какого текста собран лежащий рядом файл ──────────────────────

def test_отпечаток_фраз_меняется_вместе_с_текстом():
    """Штамп сборки помнил профиль и монтаж, но не помнил сами фразы.

    Перенарезали видео другими правилами, поправили сценарий, поправили
    текст рукой — и субтитры в готовом файле стали чужими. Файл при
    этом целый, нужной длины и с субтитрами на месте: понять, что они
    старые, можно было только глазами.
    """
    from vertcut import subs

    def уложенное(текст: str) -> dict:
        слова = [{"w": w, "s": i * 0.5, "e": i * 0.5 + 0.4}
                 for i, w in enumerate(текст.split())]
        return {"words": слова,
                "phrases": [{"idx": 1, "start": слова[0]["s"],
                             "end": слова[-1]["e"], "text": текст,
                             "lines": [текст], "words": слова}]}

    было = subs.отпечаток_фраз(уложенное("мы идем домой"), [[0, 2]])
    то_же = subs.отпечаток_фраз(уложенное("мы идем домой"), [[0, 2]])
    другое = subs.отпечаток_фраз(уложенное("мы идем домой!"), [[0, 2]])
    assert было == то_же
    assert было != другое, "текст поменялся, а отпечаток тот же"


def test_отпечаток_фраз_меняется_от_сдвига_времени():
    """Слово то же, а звучит на секунду позже — субтитр встанет не там."""
    from vertcut import subs

    def уложенное(сдвиг: float) -> dict:
        слова = [{"w": w, "s": i * 0.5 + сдвиг, "e": i * 0.5 + 0.4 + сдвиг}
                 for i, w in enumerate(["мы", "идем"])]
        return {"words": слова,
                "phrases": [{"idx": 1, "start": слова[0]["s"],
                             "end": слова[-1]["e"], "text": "мы идем",
                             "lines": ["мы идем"], "words": слова}]}

    assert (subs.отпечаток_фраз(уложенное(0.0), [[0, 1]])
            != subs.отпечаток_фраз(уложенное(1.0), [[0, 1]]))


# ─── влезает или нет: считается стилем, а не разбором ────────────────

def test_влезает_ли_считается_шрифтом_а_не_знаками(профиль, шрифт):
    """Один и тот же текст в разных шрифтах даёт разную ширину,
    и на пределе это решает.

    Проверяется тем же способом, каким это решает сервис: строка
    из одинакового числа знаков латиницей и кириллицей меряется
    по-разному, а значит и страниц может выйти разное число.
    """
    предел = профиль["предел_плашки"] - 2 * профиль["поле_сбоку"]
    узкая = subs.ширина_краски(шрифт, "iiiiiiiiiiiiiiiiiiii")
    широкая = subs.ширина_краски(шрифт, "ШШШШШШШШШШШШШШШШШШШШ")
    assert len("iiiiiiiiiiiiiiiiiiii") == len("ШШШШШШШШШШШШШШШШШШШШ")
    assert узкая < широкая
    assert узкая < предел < широкая, \
        "подобрать пример, где счёт по знакам врёт, а счёт по краске нет"


def test_разбор_про_то_влезает_ли_не_знает_вовсе():
    """Фразы режутся без оглядки на стиль — это главное решение сессии.

    В записи фразы нет ни строк, ни числа знаков: в момент разбора
    стиля ещё не существует.
    """
    from vertcut import phrases

    вышло = phrases.split([
        {"w": "раз", "s": 0.0, "e": 0.3}, {"w": "два.", "s": 0.3, "e": 0.6}])
    поля = set(вышло[0].__dataclass_fields__)
    assert поля == {"idx", "start", "end", "text", "words"}
