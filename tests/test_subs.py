# ─── строки и страницы ───────────────────────────────────────────────

def test_меряется_краска_а_не_знаки(профиль, шрифт):
    """«Violet Evergarden» шире, чем столько же букв кириллицей,
    и предел в знаках тут врёт."""
    латиница = subs.ширина_краски(шрифт, "Violet Evergarden")
    кириллица = subs.ширина_краски(шрифт, "Виолет Евергарден")
    assert латиница != кириллица


def test_строки_делятся_поровну_а_не_жадно(профиль, шрифт):
    """Жадная набивка даёт длинную строку плюс огрызок из одного слова,
    и в вертикальном кадре это смотрится плохо."""
    страницы = subs.страницы(слова("одно два три четыре пять шесть семь восемь"),
                             профиль, шрифт)
    строки = страницы[0]
    assert len(строки) == 2
    assert abs(строки[0].ink - строки[1].ink) < профиль["предел_плашки"] / 3


def test_длинная_фраза_уходит_на_страницы(профиль, шрифт):
    длинная = слова(" ".join(["длинноватое"] * 14))
    страницы = subs.страницы(длинная, профиль, шрифт)
    assert len(страницы) > 1
    assert all(len(с) <= профиль["максимум_строк"] for с in страницы)


def test_слишком_длинное_слово_не_молчит(профиль, шрифт):
    """Делить слово разбивка не умеет и не должна. Но молчать нельзя:
    строка вылезет под столбик иконок соцсети, и увидит это только
    зритель."""
    страницы = subs.страницы(слова("а" * 60), профиль, шрифт)
    assert subs.слишком_широкие(страницы, профиль)


# ─── где стоит субтитр ───────────────────────────────────────────────

def test_горизонтальный_план_уводит_фразу_вниз():
    фраза = {"at": 1.0, "till": 5.0}
    ряды = [{"at": 2.0, "till": 4.0, "полный_кадр": True}]
    assert subs.где_стоит(фраза, ряды) == subs.НИЗ


def test_кадр_горизонтального_плана_не_уводит_вниз():
    """Заслон не теоретический: без него фраза уезжала вниз целиком
    из-за ОДНОГО кадра плана, попавшего под её начало. Этого кадра
    зритель не видит вовсе, а разнобой в положении субтитра видит."""
    фраза = {"at": 1.0, "till": 5.0}
    ряды = [{"at": 1.0, "till": 1.0 + tuning.STUB / 2, "полный_кадр": True}]
    assert subs.где_стоит(фраза, ряды) == subs.ЦЕНТР


def test_порог_заметности_берётся_готовый():
    """Своего числа нет и заводить его незачем: вопрос тот же самый —
    с какой длины кусок плана заметен глазу, — а два числа на один
    вопрос однажды разъедутся."""
    from pathlib import Path
    текст = Path(subs.__file__).read_text(encoding="utf-8")
    assert "tuning.STUB" in текст
    assert "STUB_SUBS" not in текст


def test_низ_под_планом_считается_от_низа_плана(профиль):
    """План однажды приедет не 16:9, его высота поедет, и субтитр
    обязан поехать за ним."""
    широкий = subs.низ_под_планом({"width": 1920, "height": 1080}, профиль)
    квадратный = subs.низ_под_планом({"width": 1440, "height": 1080}, профиль)
    assert квадратный["план_низ"] > широкий["план_низ"]


def test_субтитр_упёрся_в_поле_площадки_говорит_об_этом(профиль):
    """Не лезет под интерфейс молча."""
    почти_вертикальный = subs.низ_под_планом({"width": 1080, "height": 1900},
                                             профиль)
    assert почти_вертикальный["упёрся"]
    assert почти_вертикальный["низ"] == профиль["предел_низа"]


