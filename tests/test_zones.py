# ─── зоны видно глазами ──────────────────────────────────────────────

def test_зоны_рисуются_плёнкой_по_краям():
    """Полупрозрачные поля объясняют это без единого слова инструкции."""
    prof = профиль()
    слой = preview.нарисовать_зоны(prof)
    середина = слой.getpixel((prof["width"] // 2, prof["height"] // 2))
    угол = слой.getpixel((5, 5))
    низ = слой.getpixel((prof["width"] // 2, prof["height"] - 5))
    верх = слой.getpixel((prof["width"] // 2, 5))
    assert середина[3] == 0, "середина кадра закрашена"
    assert угол[3] > 0 and низ[3] > 0 and верх[3] > 0


def test_зоны_рисуются_даже_со_снятым_флажком():
    """Человек, который её снял, тем более должен видеть, куда лезет."""
    слой = preview.нарисовать_зоны(профиль(safe_zones__enabled=False))
    assert слой.getpixel((5, 5))[3] > 0


def test_серый_лист_рисует_зоны_даже_со_снятым_флажком(tmp_path):
    """Со снятым флажком предел строки равен всему кадру, и полосы
    пропали бы ровно тогда, когда смотреть на них важнее всего."""
    prof = профиль(safe_zones__enabled=False)
    набор = subs.font_of(prof)
    слова = [{"w": w, "s": 0.0, "e": 0.4} for w in "проверка зон".split()]
    стр = subs.страницы(слова, prof, набор)[0]
    раскл = {"показы": [{"at": 0.0, "till": 1.0, "страница": стр,
                         "сказано": 1, "низ": prof["низ_центра"],
                         "где": subs.ЦЕНТР, "фраза": 1}],
             "фразы": [{"idx": 1, "страницы": [стр]}]}
    путь = subs.лист(раскл, prof, набор, tmp_path / "лист.jpg")
    from PIL import Image
    with Image.open(путь) as картинка:
        левый = картинка.getpixel((5, 5))
        середина = картинка.getpixel((картинка.width // 2, 5))
    assert левый != середина, "полосы зон на листе не нарисованы"
