"""Безопасные зоны площадок — настройка, а не вшитое правило.

Поверх ролика площадка рисует свой интерфейс: сбоку иконки, снизу
подпись и кнопки, сверху ник. Субтитр, залезший туда, зритель просто
не прочтёт. Числа не официальные и взяты худшим случаем по трём
площадкам — значит их надо уметь двигать; а флажок стоит по умолчанию,
потому что чужой человек про иконки не знает.
"""

from __future__ import annotations

import pytest

from vertcut import preview, subs
from vertcut.errors import VertcutError


def профиль(**правки):
    числа = subs.образец()
    for ключ, значение in правки.items():
        где, части = числа, ключ.split("__")
        for часть in части[:-1]:
            где[часть] = dict(где[часть])
            где = где[часть]
        где[части[-1]] = значение
    return subs.к_пикселям(числа)


# ─── одно число, одно место ──────────────────────────────────────────

def test_ширина_строки_считается_из_зоны_а_не_лежит_числом():
    """Держать её вторым числом значит однажды подвинуть зону
    и забыть предел."""
    prof = профиль()
    assert prof["предел_плашки"] == prof["width"] - 2 * prof["зона_сбоку"]
    шире = профиль(safe_zones__side=0.08)
    assert шире["предел_плашки"] > prof["предел_плашки"]
    assert шире["предел_плашки"] == шире["width"] - 2 * шире["зона_сбоку"]


def test_предел_снизу_считается_из_зоны():
    prof = профиль()
    assert prof["предел_низа"] == prof["height"] - prof["зона_снизу"]


def test_в_профиле_нет_второго_числа_про_ширину_строки():
    """Оно жило в «строки.предел_ширины» и говорило то же самое,
    что «зоны.сбоку». Два числа на один вопрос однажды разъезжаются."""
    плоско = subs.плоско(subs.образец())
    assert "строки.предел_ширины" not in плоско
    assert "положение.низ_под_планом.предел_низа" not in плоско


# ─── флажок ──────────────────────────────────────────────────────────

def test_флажок_по_умолчанию_стоит():
    """Чужой человек про иконки соцсети не знает и утащит текст прямо
    под кнопки."""
    assert профиль()["беречь_зоны"] is True


def test_снятый_флажок_пускает_субтитр_куда_угодно():
    берегли = профиль(position__from_bottom=0.10)
    нет = профиль(position__from_bottom=0.10, safe_zones__enabled=False)
    assert берегли["низ_центра"] == берегли["предел_низа"]
    assert нет["низ_центра"] > берегли["низ_центра"]
    assert нет["предел_плашки"] == нет["width"]


def test_флажок_понимает_правду_и_слова():
    """В файле — настоящие true/false yaml; человек, правящий файл
    руками, напишет и «YES» — это тоже понимается."""
    assert профиль(safe_zones__enabled=False)["беречь_зоны"] is False
    assert профиль(safe_zones__enabled="YES")["беречь_зоны"] is True
    with pytest.raises(VertcutError) as беда:
        профиль(safe_zones__enabled="иногда")
    assert "safe_zones.enabled" in беда.value.message


# ─── положение от низа ───────────────────────────────────────────────

def test_положение_считается_от_низа_кадра():
    """Блок растёт вверх от своего низа, и низ — то единственное, что
    не двигается. Так и человек про это думает."""
    prof = профиль(position__from_bottom=0.25)
    assert prof["height"] - prof["низ_центра"] == round(0.25 * prof["height"])


def test_поставляемое_положение_то_же_что_было_замерено():
    """Число то же самое, замер тот же — поменялось только то, как оно
    записано."""
    assert профиль()["низ_центра"] == 1000


def test_упёрся_вниз_говорится_числами():
    """Человек поставил субтитр туда, куда хотел, и обязан узнать,
    что его подвинули."""
    prof = профиль(position__from_bottom=0.10)
    assert prof["упёрся_вниз"] is True
    assert prof["низ_хотели"] > prof["низ_центра"]
    assert prof["низ_центра"] == prof["предел_низа"]


def test_упёрся_вверх_опускает_блок_а_не_режет_его():
    """Две строки не помещаются между зонами — блок опускается целиком,
    а не теряет строку."""
    prof = профиль(position__from_bottom=0.95)
    assert prof["упёрся_вверх"] is True
    assert prof["верх_блока"] >= prof["зона_сверху"]


def test_верх_блока_считается_одним_местом():
    """По этому числу рисование ставит краску, заслон считает занятый
    прямоугольник, а предпросмотр — кадр."""
    prof = профиль()
    полоса = subs.полоса(prof)
    assert полоса["верх"] == prof["верх_блока"]
    assert полоса["низ"] == prof["низ_центра"]


