"""Шрифты: набор в поставке, свой файл, какие знаки шрифт знает.

Шрифт ломается тихо, и почти всё здесь — про то, чтобы он ломался
громко: не знает кириллицы, не выставился вес, нет лицензии рядом.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from vertcut import fonts, layout, subs
from vertcut.errors import VertcutError

# Что субтитр обязан уметь нарисовать на любом поставляемом шрифте.
АЛФАВИТ = ("абвгдежзийклмнопрстуфхцчшщъыьэюяё"
           "АБВГДЕЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯЁ"
           "abcdefghijklmnopqrstuvwxyz"
           "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
           "0123456789.,!?:;—–-«»\"'()…%№")


# ─── поставка ────────────────────────────────────────────────────────

@pytest.mark.parametrize("шрифт", fonts.НАБОР, ids=lambda ш: ш["файл"])
def test_у_каждого_поставляемого_шрифта_лежит_его_лицензия(шрифт):
    """Раздача чужого шрифта без его лицензии — не мелочь, а нарушение,
    и заметят его позже всех."""
    файл = layout.fonts() / шрифт["файл"]
    лицензия = layout.fonts() / шрифт["лицензия"]
    assert файл.exists(), "шрифта нет в поставке"
    assert лицензия.exists(), "лицензии нет рядом"
    текст = лицензия.read_text(encoding="utf-8")
    assert "SIL Open Font License" in текст


@pytest.mark.parametrize("шрифт", fonts.НАБОР, ids=lambda ш: ш["файл"])
def test_каждый_поставляемый_знает_кириллицу_и_латиницу(шрифт):
    """Чужой шрифт может не знать кириллицы. Поставляемый — не может:
    сервис раздаётся русскоязычным людям, и «работает сразу» значит
    именно это."""
    нет = fonts.чего_нет(АЛФАВИТ, layout.fonts() / шрифт["файл"])
    assert not нет, f"не знает знаков: {нет}"


def test_откуда_взяты_шрифты_записано():
    """Число без причины через месяц выглядит произволом; файл
    в поставке без причины — тем более."""
    откуда = layout.fonts() / "ORIGIN.md"
    assert откуда.exists()
    текст = откуда.read_text(encoding="utf-8")
    for шрифт in fonts.НАБОР:
        assert шрифт["файл"] in текст


# ─── какие знаки шрифт знает ─────────────────────────────────────────

def test_чего_нет_называет_знаки_по_одному():
    """Golos Text не знает греческих букв — на них он нарисовал бы
    квадратики."""
    нет = fonts.чего_нет("альфа α и бета β",
                         layout.fonts() / "GolosText.ttf")
    assert нет == ["α", "β"]


def test_пробелы_не_спрашиваются():
    """Их рисует не глиф, а продвижение пера."""
    assert fonts.чего_нет("а б\nв\tг", layout.fonts() / "GolosText.ttf") == []


def test_разбор_знаков_понимает_сборники_шрифтов():
    """Человек вправе показать на системный .ttc — отказ «не понимаю
    файл» там был бы неправдой."""
    сборник = Path("/System/Library/Fonts/Helvetica.ttc")
    if not сборник.exists():
        pytest.skip("на этой системе нет такого сборника")
    assert len(fonts.знаки(сборник)) > 200


def test_не_шрифт_это_отказ_словами(tmp_path):
    подделка = tmp_path / "как_бы.ttf"
    подделка.write_bytes("вовсе не шрифт".encode("utf-8"))
    with pytest.raises(VertcutError):
        fonts.знаки(подделка)


# ─── где шрифт ищется ────────────────────────────────────────────────

def test_шрифт_ищется_в_трёх_местах_по_порядку(tmp_path):
    """Порядок тот же, что у профиля: видео, свои, поставка."""
    видео = layout.project("проба")
    видео.mkdir(parents=True)
    свои = layout.my_fonts()
    свои.mkdir(parents=True)

    поставочный = fonts.найти("InterTight.ttf")
    assert поставочный.parent == layout.fonts()

    (свои / "InterTight.ttf").write_bytes(
        (layout.fonts() / "InterTight.ttf").read_bytes())
    assert fonts.найти("InterTight.ttf").parent == свои

    (видео / "InterTight.ttf").write_bytes(
        (layout.fonts() / "InterTight.ttf").read_bytes())
    assert fonts.найти("InterTight.ttf", видео).parent == видео


def test_свой_шрифт_копируется_а_не_запоминается_путём(tmp_path):
    """Путь на рабочий стол через месяц ведёт в пустоту, и ролик
    соберётся без букв."""
    чужой = tmp_path / "рабочий стол" / "МойШрифт.ttf"
    чужой.parent.mkdir(parents=True)
    чужой.write_bytes((layout.fonts() / "GolosText.ttf").read_bytes())

    куда = fonts.поставить(чужой)
    assert куда == layout.my_fonts() / "МойШрифт.ttf"
    assert куда.read_bytes() == чужой.read_bytes()

    чужой.unlink()
    assert fonts.найти("МойШрифт.ttf").exists()


